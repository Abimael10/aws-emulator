//! An execution that outlives the allowance its definition declares ends `TIMED_OUT`, and
//! that status change reaches the default EventBridge bus like every other one.
//!
//! The RULE under test: **a state machine's top-level `TimeoutSeconds` bounds the WHOLE
//! execution — once that span has passed since the execution started, the execution is
//! `TIMED_OUT` whatever it was doing or waiting on at that instant, with no `error` and no
//! `cause` of its own — and the status it moves into is published onto the account's
//! default bus as `source` `aws.states` / `detail-type`
//! `Step Functions Execution Status Change`, so a rule matching that envelope delivers it
//! to the rule's targets.** An execution whose definition declares no allowance is bounded
//! by nothing and keeps running.
//!
//! The rows span what the rule generalises over — WHAT the execution is doing when the
//! allowance runs out: computing (a `Wait` longer than the allowance), suspended at an
//! ACTIVITY task no worker answers, and suspended at a CALLBACK task nobody answers — with
//! the control row that declares no allowance at all asserted to keep running.
//!
//! Nothing here calls Step Functions again after the start: every envelope asserted is read
//! off the SQS queue the rule targets, so a status that arrives was published by Step
//! Functions itself as the clock made it due, and not as a side effect of a client reading
//! the execution back.
//!
//! Assembling the whole router costs stack (see `boot_serve.rs`), so it is built — and the
//! requests driven — on an explicitly sized thread.

use std::sync::Arc;
use std::time::{Duration, Instant};

use bytes::Bytes;
use serde_json::{json, Value};
use smithy_server_runtime::MultiServiceRouter;

use crate::query_wire::{element, form_encode};

/// Keep this at or above the size `boot_serve.rs` uses: the same assembly runs here.
const BOOT_STACK_SIZE: usize = 64 * 1024 * 1024;

/// The Region every request below is addressed in.
const REGION: &str = "us-east-1";

/// The `source` and `detail-type` Step Functions publishes an execution's status changes
/// under, spelled out here rather than imported from the service crate, so a wrong constant
/// in the implementation cannot make this suite pass.
const SFN_SOURCE: &str = "aws.states";
const EXECUTION_STATUS_CHANGE: &str = "Step Functions Execution Status Change";

/// The bus an Amazon Web Services service's own events go to: "events generated by Amazon
/// Web Services services go to your account's default event bus".
const DEFAULT_BUS: &str = "default";

/// The service principal EventBridge delivers to an SQS target as, which is what the
/// queue's resource policy admits ("for Amazon SQS queues, EventBridge relies on
/// resource-based policies").
const EVENTS_PRINCIPAL: &str = "events.amazonaws.com";

/// The service principal a state machine's execution role is trusted by, which is the
/// identity its `Task` states' integration calls are made as.
const STATES_PRINCIPAL: &str = "states.amazonaws.com";

/// The IAM API version every call below names.
const IAM_API_VERSION: &str = "2010-05-08";

/// The status an execution rests in while it runs, and the one it reaches when its own
/// allowance runs out (`ExecutionStatus`).
const RUNNING: &str = "RUNNING";
const TIMED_OUT: &str = "TIMED_OUT";

/// The allowance each timing-out row's definition declares, in seconds: short, because what
/// is under test is that the allowance is HONOURED and not how long one is.
const ALLOWANCE_SECONDS: u64 = 1;

/// How long this suite waits for something the clock owes — an envelope reaching a queue —
/// before giving up. Generous: it waits for the CONDITION, so a host running this beside
/// the rest of the workspace's tests spends the span instead of failing on it.
const DELIVERY_DEADLINE: Duration = Duration::from_secs(120);

/// One poll of a queue inside [`DELIVERY_DEADLINE`].
const POLL_INTERVAL: Duration = Duration::from_millis(25);

/// How long the control row watches the queue of an execution that must keep running: well
/// past the allowance the other rows declare and past the span one transition of theirs took
/// to arrive, so an empty read is evidence that nothing was published rather than evidence of
/// having looked too early.
const QUIET_SPAN: Duration = Duration::from_secs(5);

/// The whole emulator over one engine, exactly as `core/router/src/lib.rs` assembles it for
/// the binary: Step Functions publishes through the in-process callback, so WHICH mounted
/// model claims that `events`-scoped call is the one a client reaches too.
fn router() -> MultiServiceRouter {
    let engine = aws_emulator_router::new_engine();
    let mut router = aws_emulator_router::build_router(Arc::clone(&engine));
    router.set_request_authentication(false);
    router
}

/// A SigV4 `Authorization` whose credential scope names `service`, which is what routes the
/// request. The signature is never checked: the router above runs with request
/// authentication off.
fn authorization(service: &str) -> String {
    format!(
        "AWS4-HMAC-SHA256 Credential=AKIDEXAMPLE/20260101/{REGION}/{service}/aws4_request, \
         SignedHeaders=host, Signature=0000"
    )
}

/// One `X-Amz-Target` RPC call against the service whose signing name is `signing_name`,
/// which must answer 200.
async fn rpc(
    router: &MultiServiceRouter,
    case: &str,
    signing_name: &str,
    target_prefix: &str,
    json_version: &str,
    operation: &str,
    body: &Value,
) -> Value {
    let request = http::Request::builder()
        .method("POST")
        .uri("/")
        .header("host", format!("{signing_name}.{REGION}.amazonaws.com"))
        .header("authorization", authorization(signing_name))
        .header("content-type", format!("application/x-amz-json-{json_version}"))
        .header("x-amz-target", format!("{target_prefix}.{operation}"))
        .body(Bytes::from(body.to_string()))
        .expect("the test request is well formed");
    let response = router.dispatch(request).await;
    let status = response.status().as_u16();
    let parsed = if response.body().is_empty() {
        Value::Null
    } else {
        serde_json::from_slice(response.body()).unwrap_or(Value::Null)
    };
    assert_eq!(
        status, 200,
        "case {case:?}: expected HTTP 200 from {signing_name} {operation}, got {status} with \
         {parsed}"
    );
    parsed
}

/// One Step Functions call (`awsJson1_0`, `AWSStepFunctions.<Operation>`).
async fn sfn(router: &MultiServiceRouter, case: &str, operation: &str, body: &Value) -> Value {
    rpc(
        router,
        case,
        "states",
        "AWSStepFunctions",
        "1.0",
        operation,
        body,
    )
    .await
}

/// One EventBridge call (`awsJson1_1`, `AWSEvents.<Operation>`).
async fn events(router: &MultiServiceRouter, case: &str, operation: &str, body: &Value) -> Value {
    rpc(router, case, "events", "AWSEvents", "1.1", operation, body).await
}

/// One Amazon SQS call (`awsJson1_0`, `AmazonSQS.<Operation>`).
async fn sqs(router: &MultiServiceRouter, case: &str, operation: &str, body: &Value) -> Value {
    rpc(router, case, "sqs", "AmazonSQS", "1.0", operation, body).await
}

/// One IAM call (`awsQuery`), which must answer 200; answers its XML body.
async fn iam(
    router: &MultiServiceRouter,
    case: &str,
    action: &str,
    members: &[(&str, &str)],
) -> String {
    let mut body = format!("Action={action}&Version={IAM_API_VERSION}");
    for (name, value) in members {
        body.push('&');
        body.push_str(&form_encode(name));
        body.push('=');
        body.push_str(&form_encode(value));
    }
    let host = format!("iam.{REGION}.amazonaws.com");
    let request = http::Request::builder()
        .method("POST")
        .uri(format!("https://{host}/"))
        .header("host", host)
        .header("content-type", "application/x-www-form-urlencoded")
        .header("authorization", authorization("iam"))
        .body(Bytes::from(body))
        .expect("the test request is well formed");
    let response = router.dispatch(request).await;
    let status = response.status().as_u16();
    let answered = String::from_utf8_lossy(response.body()).to_string();
    assert_eq!(
        status, 200,
        "case {case:?}: expected HTTP 200 from IAM {action}, got {status} with {answered}"
    );
    answered
}

/// A role Step Functions may assume, allowed the message send a callback task's own
/// integration makes; answers its ARN.
///
/// A `Task` state's integration call is made as a session of the state machine's execution
/// role, so a role that exists and admits both is what lets such a state hand its work over
/// at all.
async fn given_role(router: &MultiServiceRouter, case: &str, name: &str) -> String {
    let trust = json!({
        "Version": "2012-10-17",
        "Statement": [{
            "Effect": "Allow",
            "Principal": {"Service": STATES_PRINCIPAL},
            "Action": "sts:AssumeRole",
        }],
    })
    .to_string();
    let created = iam(
        router,
        case,
        "CreateRole",
        &[("RoleName", name), ("AssumeRolePolicyDocument", &trust)],
    )
    .await;
    let arn = element(&created, "Arn");
    let document = json!({
        "Version": "2012-10-17",
        "Statement": [{"Effect": "Allow", "Action": "sqs:SendMessage", "Resource": "*"}],
    })
    .to_string();
    iam(
        router,
        case,
        "PutRolePolicy",
        &[
            ("RoleName", name),
            ("PolicyName", "inline"),
            ("PolicyDocument", &document),
        ],
    )
    .await;
    arn
}

/// A string member of a response, or a panic naming the case and what came back.
fn member(case: &str, body: &Value, pointer: &str) -> String {
    body.pointer(pointer)
        .and_then(Value::as_str)
        .unwrap_or_else(|| panic!("case {case:?}: expected {pointer} in {body}"))
        .to_string()
}

/// An SQS queue called `name`; answers its url and the ARN a rule names it by.
async fn queue(router: &MultiServiceRouter, case: &str, name: &str) -> (String, String) {
    let created = sqs(router, case, "CreateQueue", &json!({"QueueName": name})).await;
    let url = member(case, &created, "/QueueUrl");
    let attributes = sqs(
        router,
        case,
        "GetQueueAttributes",
        &json!({"QueueUrl": &url, "AttributeNames": ["QueueArn"]}),
    )
    .await;
    let arn = member(case, &attributes, "/Attributes/QueueArn");
    (url, arn)
}

/// Let EventBridge send to the queue at `url`, the way a client admits it: a resource policy
/// naming EventBridge's service principal.
async fn admit_events(router: &MultiServiceRouter, case: &str, url: &str, queue_arn: &str) {
    let policy = json!({
        "Version": "2012-10-17",
        "Statement": [{
            "Sid": "AllowEventBridge",
            "Effect": "Allow",
            "Principal": {"Service": EVENTS_PRINCIPAL},
            "Action": "sqs:SendMessage",
            "Resource": queue_arn,
        }],
    })
    .to_string();
    sqs(
        router,
        case,
        "SetQueueAttributes",
        &json!({"QueueUrl": url, "Attributes": {"Policy": policy}}),
    )
    .await;
}

/// An ENABLED rule called `name` on the default bus matching every Step Functions execution
/// status change, with the queue `queue_arn` as its one target.
async fn status_change_rule(
    router: &MultiServiceRouter,
    case: &str,
    name: &str,
    queue_arn: &str,
) {
    events(
        router,
        case,
        "PutRule",
        &json!({
            "Name": name,
            "EventBusName": DEFAULT_BUS,
            "EventPattern": json!({
                "source": [SFN_SOURCE],
                "detail-type": [EXECUTION_STATUS_CHANGE],
            })
            .to_string(),
            "State": "ENABLED",
        }),
    )
    .await;
    let targeted = events(
        router,
        case,
        "PutTargets",
        &json!({
            "Rule": name,
            "EventBusName": DEFAULT_BUS,
            "Targets": [{"Id": "t1", "Arn": queue_arn}],
        }),
    )
    .await;
    assert_eq!(
        targeted["FailedEntryCount"],
        json!(0),
        "case {case:?}: every target must be accepted, got {targeted}"
    );
}

/// Every envelope now waiting on the queue at `url`, each taken out of the queue.
async fn drain(router: &MultiServiceRouter, case: &str, url: &str) -> Vec<Value> {
    let received = sqs(
        router,
        case,
        "ReceiveMessage",
        &json!({"QueueUrl": url, "MaxNumberOfMessages": 10}),
    )
    .await;
    let messages = received["Messages"].as_array().cloned().unwrap_or_default();
    let mut envelopes = Vec::new();
    for message in &messages {
        if let Some(handle) = message["ReceiptHandle"].as_str() {
            sqs(
                router,
                case,
                "DeleteMessage",
                &json!({"QueueUrl": url, "ReceiptHandle": handle}),
            )
            .await;
        }
        let raw = message["Body"].as_str().unwrap_or_default();
        envelopes.push(serde_json::from_str::<Value>(raw).unwrap_or(Value::Null));
    }
    envelopes
}

/// Collect envelopes off the queue at `url` until one reports `wanted` for `execution` or
/// [`DELIVERY_DEADLINE`] passes; answers everything that arrived along the way.
async fn collect_until(
    router: &MultiServiceRouter,
    case: &str,
    url: &str,
    execution: &str,
    wanted: &str,
) -> Vec<Value> {
    let started = Instant::now();
    let mut arrived: Vec<Value> = Vec::new();
    while started.elapsed() < DELIVERY_DEADLINE {
        arrived.extend(drain(router, case, url).await);
        if arrived.iter().any(|envelope| {
            envelope["detail"]["executionArn"].as_str() == Some(execution)
                && envelope["detail"]["status"].as_str() == Some(wanted)
        }) {
            return arrived;
        }
        tokio::time::sleep(POLL_INTERVAL).await;
    }
    arrived
}

/// The `detail.status` of each envelope about `execution`, in arrival order.
fn statuses(envelopes: &[Value], execution: &str) -> Vec<String> {
    envelopes
        .iter()
        .filter(|envelope| envelope["detail"]["executionArn"].as_str() == Some(execution))
        .map(|envelope| {
            envelope["detail"]["status"]
                .as_str()
                .unwrap_or_default()
                .to_string()
        })
        .collect()
}

/// What one row runs: the definition the state machine carries, whether that definition
/// declares an allowance, and whether the row has to create an activity for the definition
/// to name.
struct Row {
    case: &'static str,
    /// The definition, built over the ARN of the activity this row created (empty when the
    /// row created none) and over the url of the queue a callback task publishes to.
    definition: fn(&str, &str) -> Value,
    /// Whether the row's definition names an activity, which has to exist to be scheduled.
    needs_activity: bool,
    /// The status the row's execution must reach, or `None` for a row that must keep
    /// running.
    reaches: Option<&'static str>,
}

/// RULE: the allowance a definition declares bounds the whole execution, whatever it is
/// waiting on, and the status it then moves into is published to the default bus.
#[test]
fn an_execution_past_its_declared_allowance_times_out_and_publishes_that_status() {
    std::thread::Builder::new()
        .name("sfn-execution-allowance-status-change".to_string())
        .stack_size(BOOT_STACK_SIZE)
        .spawn(|| {
            let runtime = tokio::runtime::Builder::new_current_thread()
                .enable_time()
                .build()
                .expect("build a current-thread runtime");
            runtime.block_on(drive());
        })
        .expect("spawn the sized thread")
        .join()
        .expect("the suite thread runs to completion");
}

/// Every row, against ONE assembled router per row.
async fn drive() {
    let rows = [
        Row {
            case: "a Wait longer than the allowance",
            definition: |_activity, _url| {
                json!({
                    "TimeoutSeconds": ALLOWANCE_SECONDS,
                    "StartAt": "Hold",
                    "States": {
                        "Hold": {"Type": "Wait", "Seconds": 600, "Next": "Done"},
                        "Done": {"Type": "Pass", "End": true},
                    },
                })
            },
            needs_activity: false,
            reaches: Some(TIMED_OUT),
        },
        Row {
            case: "an activity task no worker answers",
            definition: |activity, _url| {
                json!({
                    "TimeoutSeconds": ALLOWANCE_SECONDS,
                    "StartAt": "Work",
                    "States": {"Work": {"Type": "Task", "Resource": activity, "End": true}},
                })
            },
            needs_activity: true,
            reaches: Some(TIMED_OUT),
        },
        Row {
            case: "a callback task nobody answers",
            definition: |_activity, url| {
                json!({
                    "TimeoutSeconds": ALLOWANCE_SECONDS,
                    "StartAt": "Hand over",
                    "States": {
                        "Hand over": {
                            "Type": "Task",
                            "Resource": "arn:aws:states:::sqs:sendMessage.waitForTaskToken",
                            "Parameters": {
                                "QueueUrl": url,
                                "MessageBody": {"token.$": "$$.Task.Token"},
                            },
                            "End": true,
                        },
                    },
                })
            },
            needs_activity: false,
            reaches: Some(TIMED_OUT),
        },
        Row {
            case: "an activity task under a definition declaring no allowance",
            definition: |activity, _url| {
                json!({
                    "StartAt": "Work",
                    "States": {"Work": {"Type": "Task", "Resource": activity, "End": true}},
                })
            },
            needs_activity: true,
            reaches: None,
        },
    ];

    for (index, row) in rows.iter().enumerate() {
        let case = row.case;
        let router = router();

        // The consumer: one queue admitting EventBridge behind a rule on every execution
        // status change.
        let (url, queue_arn) = queue(&router, case, &format!("status-{index}")).await;
        admit_events(&router, case, &url, &queue_arn).await;
        status_change_rule(&router, case, &format!("status-{index}"), &queue_arn).await;
        // The queue a callback task hands its token to, which is not the one under watch.
        let (handover_url, _handover_arn) = queue(&router, case, &format!("hand-{index}")).await;

        let activity = if row.needs_activity {
            let created = sfn(
                &router,
                case,
                "CreateActivity",
                &json!({"name": format!("work-{index}")}),
            )
            .await;
            member(case, &created, "/activityArn")
        } else {
            String::new()
        };

        let role_arn = given_role(&router, case, &format!("states-{index}")).await;
        let machine = sfn(
            &router,
            case,
            "CreateStateMachine",
            &json!({
                "name": format!("machine-{index}"),
                "definition": (row.definition)(&activity, &handover_url).to_string(),
                "roleArn": role_arn,
                "type": "STANDARD",
            }),
        )
        .await;
        let machine_arn = member(case, &machine, "/stateMachineArn");
        let started = sfn(
            &router,
            case,
            "StartExecution",
            &json!({
                "stateMachineArn": &machine_arn,
                "name": format!("run-{index}"),
                "input": r#"{"who":"world"}"#,
            }),
        )
        .await;
        let execution_arn = member(case, &started, "/executionArn");

        match row.reaches {
            // The row's execution ends on its own: the start has already answered, so the
            // transition is owed by this service rather than by a client.
            Some(wanted) => {
                let arrived =
                    collect_until(&router, case, &url, &execution_arn, wanted).await;
                let found = statuses(&arrived, &execution_arn);
                assert_eq!(
                    found,
                    vec![RUNNING.to_string(), wanted.to_string()],
                    "case {case:?}: expected the rule's queue to receive {RUNNING} and then \
                     {wanted}, got {found:?} from {arrived:?}"
                );
                let terminal = arrived
                    .iter()
                    .find(|envelope| envelope["detail"]["status"].as_str() == Some(wanted))
                    .unwrap_or_else(|| {
                        panic!("case {case:?}: no {wanted} envelope in {arrived:?}")
                    });
                for (pointer, expected) in [
                    ("/source", json!(SFN_SOURCE)),
                    ("/detail-type", json!(EXECUTION_STATUS_CHANGE)),
                    ("/resources", json!([&execution_arn])),
                    ("/detail/executionArn", json!(&execution_arn)),
                    ("/detail/stateMachineArn", json!(&machine_arn)),
                    // What ran out is the execution's own allowance rather than anything a
                    // state did, so there is no failure to name.
                    ("/detail/error", Value::Null),
                    ("/detail/cause", Value::Null),
                ] {
                    let actual = terminal.pointer(pointer).cloned().unwrap_or(Value::Null);
                    assert_eq!(
                        actual, expected,
                        "case {case:?}: expected {pointer} to be {expected}, got {actual} in \
                         {terminal}"
                    );
                }
                let (start_date, stop_date) = (
                    terminal["detail"]["startDate"].as_i64().unwrap_or_default(),
                    terminal["detail"]["stopDate"].as_i64().unwrap_or_default(),
                );
                assert!(
                    stop_date >= start_date && start_date > 0,
                    "case {case:?}: expected whole epoch milliseconds bracketing the run, got \
                     startDate {start_date} and stopDate {stop_date} in {terminal}"
                );
            }
            // The control row: a definition that declares no allowance bounds its execution
            // by nothing, so the only status published for it is the one the start wrote.
            None => {
                let mut arrived = collect_until(&router, case, &url, &execution_arn, RUNNING).await;
                tokio::time::sleep(QUIET_SPAN).await;
                arrived.extend(drain(&router, case, &url).await);
                let found = statuses(&arrived, &execution_arn);
                assert_eq!(
                    found,
                    vec![RUNNING.to_string()],
                    "case {case:?}: expected the rule's queue to receive {RUNNING} and nothing \
                     further, got {found:?} from {arrived:?}"
                );
            }
        }
    }
}
