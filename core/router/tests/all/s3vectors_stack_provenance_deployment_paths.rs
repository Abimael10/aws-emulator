/// Call one CloudFormation operation with owned members, which is the form the rows build.
async fn call(
    router: &MultiServiceRouter,
    region: &str,
    action: &str,
    members: &[(String, String)],
) -> (u16, String) {
    let borrowed: Vec<(&str, &str)> = members
        .iter()
        .map(|(name, value)| (name.as_str(), value.as_str()))
        .collect();
    cloudformation(router, region, action, &borrowed).await
}

/// One member of a CloudFormation request.
fn member(name: &str, value: &str) -> (String, String) {
    (name.to_string(), value.to_string())
}

/// Read the stack until it reports a status that is not `*_IN_PROGRESS`, and answer with that
/// status and the body it was read from.
async fn settled(
    case: &str,
    router: &MultiServiceRouter,
    region: &str,
    stack: &str,
) -> (String, String) {
    let started = Instant::now();
    loop {
        let (http_status, body) =
            cloudformation(router, region, "DescribeStacks", &[("StackName", stack)]).await;
        assert_eq!(
            http_status, 200,
            "case {case:?}: DescribeStacks({stack}) must answer 200, got {http_status} {body}"
        );
        let reported = opt_element(&body, "StackStatus").unwrap_or_default();
        if !reported.ends_with(IN_PROGRESS) {
            return (reported, body);
        }
        assert!(
            started.elapsed() < SETTLE_DEADLINE,
            "case {case:?}: the stack {stack} is still {reported:?} after waiting for it to \
             settle: {body}"
        );
        tokio::time::sleep(SETTLE_POLL_INTERVAL).await;
    }
}

/// Read the change set until it reports itself executable (`ExecutionStatus: AVAILABLE`),
/// which is what says the plan may be executed.
async fn executable(case: &str, router: &MultiServiceRouter, region: &str, stack: &str) {
    let started = Instant::now();
    loop {
        let (http_status, body) = cloudformation(
            router,
            region,
            "DescribeChangeSet",
            &[("ChangeSetName", CHANGE_SET), ("StackName", stack)],
        )
        .await;
        assert_eq!(
            http_status, 200,
            "case {case:?}: DescribeChangeSet({CHANGE_SET}) must answer 200, got {http_status} \
             {body}"
        );
        let reported = opt_element(&body, "ExecutionStatus").unwrap_or_default();
        if reported == execution_status::AVAILABLE {
            return;
        }
        assert!(
            started.elapsed() < SETTLE_DEADLINE,
            "case {case:?}: the change set {CHANGE_SET} is still {reported:?} after waiting for \
             it to become executable: {body}"
        );
        tokio::time::sleep(SETTLE_POLL_INTERVAL).await;
    }
}

/// Deploy one row's stack by the operation the row names, and answer with the stack id
/// `DescribeStacks` reports for it.
async fn deployed(router: &MultiServiceRouter, row: &Row, stack: &str) -> String {
    let case = row.case;
    let region = row.region;
    let tags = tag_members(row.stack_tags);
    match row.deployed_by {
        DeployedBy::CreateStack | DeployedBy::CreateThenUpdate => {
            let mut members = vec![
                member("StackName", stack),
                member("TemplateBody", row.template),
            ];
            members.extend(tags.clone());
            let (http_status, body) = call(router, region, "CreateStack", &members).await;
            assert_eq!(
                http_status, 200,
                "case {case:?}: CreateStack must be accepted, got {http_status} {body}"
            );
        }
        DeployedBy::ExecutedChangeSet => {
            let mut members = vec![
                member("StackName", stack),
                member("ChangeSetName", CHANGE_SET),
                member("ChangeSetType", "CREATE"),
                member("TemplateBody", row.template),
            ];
            members.extend(tags.clone());
            let (http_status, body) = call(router, region, "CreateChangeSet", &members).await;
            assert_eq!(
                http_status, 200,
                "case {case:?}: CreateChangeSet must be accepted, got {http_status} {body}"
            );
            // A change set is executable once its own creation has completed; until it is
            // executed the stack it created rests in review, with no deployment of its own.
            executable(case, router, region, stack).await;
            let (http_status, reviewed) =
                cloudformation(router, region, "DescribeStacks", &[("StackName", stack)]).await;
            assert_eq!(
                (http_status, opt_element(&reviewed, "StackStatus").as_deref()),
                (200, Some(status::REVIEW_IN_PROGRESS)),
                "case {case:?}: a change set that has not been executed leaves the stack in \
                 review, got {http_status} {reviewed}"
            );
            let (http_status, body) = call(
                router,
                region,
                "ExecuteChangeSet",
                &[
                    member("ChangeSetName", CHANGE_SET),
                    member("StackName", stack),
                ],
            )
            .await;
            assert_eq!(
                http_status, 200,
                "case {case:?}: ExecuteChangeSet must be accepted, got {http_status} {body}"
            );
        }
    }
    let (reported, body) = settled(case, router, region, stack).await;
    assert_eq!(
        reported,
        status::CREATE_COMPLETE,
        "case {case:?}: expected the create to complete, got {reported:?} {body}"
    );

    if let Some(updated) = row.updated_template {
        let mut members = vec![member("StackName", stack), member("TemplateBody", updated)];
        members.extend(tags);
        let (http_status, body) = call(router, region, "UpdateStack", &members).await;
        assert_eq!(
            http_status, 200,
            "case {case:?}: UpdateStack must be accepted, got {http_status} {body}"
        );
        let (reported, body) = settled(case, router, region, stack).await;
        assert_eq!(
            reported,
            status::UPDATE_COMPLETE,
            "case {case:?}: expected the update to complete, got {reported:?} {body}"
        );
    }

    let (http_status, described) =
        cloudformation(router, region, "DescribeStacks", &[("StackName", stack)]).await;
    assert_eq!(
        http_status, 200,
        "case {case:?}: the deployed stack must be readable, got {http_status} {described}"
    );
    opt_element(&described, "StackId").unwrap_or_else(|| {
        panic!("case {case:?}: the stack must report a StackId, got {described}")
    })
}

/// The handles the stack publishes for its resources, as the logical-id to physical-id map.
async fn published_handles(
    case: &str,
    router: &MultiServiceRouter,
    region: &str,
    stack: &str,
) -> BTreeMap<String, String> {
    let (http_status, resources) = cloudformation(
        router,
        region,
        "DescribeStackResources",
        &[("StackName", stack)],
    )
    .await;
    assert_eq!(
        http_status, 200,
        "case {case:?}: DescribeStackResources({stack}) must answer 200, got {http_status} \
         {resources}"
    );
    physical_ids_of(&resources)
}

/// The tag set the rule says the resource `logical_id` of this row ends up carrying, in the
/// stack `stack` whose id is `stack_id` — stated once for every suite that checks the rule
/// (`expected_resource_tags`), with this row's declaration read out of it.
fn expected_tags(
    row: &Row,
    logical_id: &str,
    stack: &str,
    stack_id: &str,
) -> BTreeMap<String, String> {
    let declared: Vec<(&str, &str)> = row
        .resources
        .iter()
        .filter(|resource| resource.logical_id == logical_id)
        .flat_map(|resource| resource.declared.iter().copied())
        .collect();
    expected_resource_tags(&declared, row.stack_tags, stack, stack_id, logical_id)
}

/// `POST /tags/{resourceArn}` — S3 Vectors' `TagResource`, as a CLIENT makes it, with the ARN
/// percent-encoded into the one path segment its `@httpLabel` binds.
async fn tag_vector_resource(
    router: &MultiServiceRouter,
    region: &str,
    arn: &str,
    tags: &Value,
) -> (u16, Value) {
    let request = http::Request::builder()
        .method("POST")
        .uri(format!("/tags/{}", form_encode(arn)))
        .header("host", format!("s3vectors.{region}.amazonaws.com"))
        .header("content-type", "application/json")
        .header("authorization", authorization("s3vectors", region))
        .body(Bytes::from(
            serde_json::to_vec(&json!({ "tags": tags })).expect("the request body serializes"),
        ))
        .expect("a well-formed request");
    let response = router.dispatch(request).await;
    let http_status = response.status().as_u16();
    let payload: Value = serde_json::from_slice(response.body()).unwrap_or(Value::Null);
    (http_status, payload)
}

/// `DELETE /tags/{resourceArn}?tagKeys=…` — S3 Vectors' `UntagResource`, as a CLIENT makes
/// it. `tagKeys` is an `@httpQuery` list, so each key is one repetition of the parameter.
async fn untag_vector_resource(
    router: &MultiServiceRouter,
    region: &str,
    arn: &str,
    tag_keys: &[&str],
) -> (u16, Value) {
    let query = tag_keys
        .iter()
        .map(|key| format!("tagKeys={}", form_encode(key)))
        .collect::<Vec<String>>()
        .join("&");
    let request = http::Request::builder()
        .method("DELETE")
        .uri(format!("/tags/{}?{query}", form_encode(arn)))
        .header("host", format!("s3vectors.{region}.amazonaws.com"))
        .header("content-type", "application/json")
        .header("authorization", authorization("s3vectors", region))
        .body(Bytes::new())
        .expect("a well-formed request");
    let response = router.dispatch(request).await;
    let http_status = response.status().as_u16();
    let payload: Value = serde_json::from_slice(response.body()).unwrap_or(Value::Null);
    (http_status, payload)
}

/// The wire error code (`__type`) of an error response, or `""`.
fn error_code(body: &Value) -> String {
    body.get("__type")
        .and_then(Value::as_str)
        .unwrap_or_default()
        .to_string()
}

/// Every row: the S3 Vectors resource the stack published carries the stack's own tags, its
/// declaration's own tags and the three CloudFormation records — whichever stack operation
/// provisioned it.
#[tokio::test]
async fn every_provisioning_path_stamps_the_reserved_stack_tags_onto_the_vector_resource() {
    for (index, row) in ROWS.iter().enumerate() {
        let case = row.case;
        let region = row.region;
        // One router per row, so a bucket name one row spells cannot collide with another's.
        let router = build_router();
        let stack = format!("s3vectors-paths-{index}");
        let stack_id = deployed(&router, row, &stack).await;
        let handles = published_handles(case, &router, region, &stack).await;

        for resource in row.resources {
            let logical_id = resource.logical_id;
            // The handle the stack publishes for the resource, which for both S3 Vectors
            // types is that resource's own ARN.
            let arn = handles.get(logical_id).cloned().unwrap_or_else(|| {
                panic!("case {case:?}: the stack must publish a physical id for {logical_id:?}")
            });

            let (http_status, held) = vector_resource_tags(&router, region, &arn).await;
            assert_eq!(
                http_status, 200,
                "case {case:?}: ListTagsForResource({arn}) must answer 200, got {http_status} \
                 with {held:?}"
            );
            let expected = expected_tags(row, logical_id, &stack, &stack_id);
            assert_eq!(
                held, expected,
                "case {case:?}: expected {logical_id} to carry {expected:?}, got {held:?}"
            );
        }
    }
}

/// A vector bucket a CLIENT created belongs to no stack, so its tag map carries none of the
/// three — which is what distinguishes a stack-managed bucket from a hand-made one — and a
/// client naming one of the three is refused with the service's own sentence.
///
/// The rows differ along whether the client's create names tags at all and along the key it
/// names, including one that merely resembles the reserved prefix.
#[tokio::test]
async fn a_vector_bucket_created_outside_a_stack_carries_none_of_the_reserved_keys() {
    let region = "us-east-2";
    for (case, declared, expected) in [
        ("a create naming no tags at all", json!(null), json!({})),
        (
            "a create naming the client's own tags",
            json!({ "team": "platform", "Service": "search" }),
            json!({ "team": "platform", "Service": "search" }),
        ),
        (
            "a create naming a key that merely resembles the reserved prefix",
            json!({ "not-aws:cloudformation:stack-id": "forged" }),
            json!({ "not-aws:cloudformation:stack-id": "forged" }),
        ),
    ] {
        let router = build_router();
        let name = "outside-a-stack";
        let mut request = json!({ "vectorBucketName": name });
        if !declared.is_null() {
            request["tags"] = declared.clone();
        }
        let (http_status, body) = s3vectors(&router, region, "CreateVectorBucket", &request).await;
        assert_eq!(
            http_status, 200,
            "case {case:?}: CreateVectorBucket must answer 200, got {http_status} {body}"
        );
        let arn = body
            .get("vectorBucketArn")
            .and_then(Value::as_str)
            .unwrap_or_default()
            .to_string();

        let (http_status, held) = vector_resource_tags(&router, region, &arn).await;
        assert_eq!(
            http_status, 200,
            "case {case:?}: ListTagsForResource({arn}) must answer 200, got {http_status} \
             with {held:?}"
        );
        let expected: BTreeMap<String, String> = expected
            .as_object()
            .expect("the expected tag map is an object")
            .iter()
            .map(|(key, value)| {
                (
                    key.clone(),
                    value.as_str().unwrap_or_default().to_string(),
                )
            })
            .collect();
        assert_eq!(
            held, expected,
            "case {case:?}: expected a bucket no stack owns to carry {expected:?}, got {held:?}"
        );
        for reserved in [STACK_NAME_TAG, STACK_ID_TAG, LOGICAL_ID_TAG] {
            assert!(
                !held.contains_key(reserved),
                "case {case:?}: expected no {reserved:?} on a bucket no stack created, got \
                 {held:?}"
            );
        }
    }

    // And a client cannot put one there by naming it: each of the three is refused on the
    // create, so the only way into the map is CloudFormation's own provisioning call.
    for reserved in [STACK_NAME_TAG, STACK_ID_TAG, LOGICAL_ID_TAG] {
        let router = build_router();
        let (http_status, body) = s3vectors(
            &router,
            region,
            "CreateVectorBucket",
            &json!({
                "vectorBucketName": "forged-provenance",
                "tags": { reserved: "forged" },
            }),
        )
        .await;
        assert_eq!(
            (http_status, error_code(&body).as_str()),
            (400, "ValidationException"),
            "case {reserved:?}: a client's create must refuse the reserved key, got \
             {http_status} {body}"
        );
        assert_eq!(
            body.get("message").and_then(Value::as_str),
            Some(RESERVED_KEY_SENTENCE),
            "case {reserved:?}: the refusal must be the service's own sentence, got {body}"
        );
    }
}

/// The reverse lookup SURVIVES a caller's own tag writes: a client may add and remove keys of
/// its own, and may neither overwrite nor remove one of the three — so a stack-provisioned
/// bucket still names its stack after any sequence of client tagging calls.
#[tokio::test]
async fn a_callers_tag_writes_cannot_displace_the_stamped_stack_provenance() {
    let region = "eu-central-1";
    let stack = "s3vectors-provenance-writes";
    let router = build_router();
    let row = &Row {
        case: "a client's tag writes around the stamped provenance",
        region,
        deployed_by: DeployedBy::CreateStack,
        stack_tags: &[("Tier", "prod")],
        template: CONFIGURED_BUCKET_TEMPLATE,
        updated_template: None,
        resources: &[Declared {
            logical_id: "EmbeddingStore",
            declared: &[("Service", "search")],
        }],
    };
    let stack_id = deployed(&router, row, stack).await;
    let handles = published_handles(row.case, &router, region, stack).await;
    let arn = handles
        .get("EmbeddingStore")
        .cloned()
        .unwrap_or_else(|| panic!("the stack must publish a physical id, got {handles:?}"));
    let stamped = expected_tags(row, "EmbeddingStore", stack, &stack_id);

    // A key of the client's own joins the set; the three are untouched.
    let (http_status, body) =
        tag_vector_resource(&router, region, &arn, &json!({ "Reviewed": "yes" })).await;
    assert_eq!(
        http_status, 200,
        "TagResource with a client's own key must answer 200, got {http_status} {body}"
    );
    let mut expected = stamped.clone();
    expected.insert("Reviewed".to_string(), "yes".to_string());
    let (_, held) = vector_resource_tags(&router, region, &arn).await;
    assert_eq!(
        held, expected,
        "expected the client's key beside the stamped set {expected:?}, got {held:?}"
    );

    // Each of the three is refused to a client, whether it tries to overwrite it or remove
    // it, and the map is left exactly as it was either way.
    for reserved in [STACK_NAME_TAG, STACK_ID_TAG, LOGICAL_ID_TAG] {
        let (http_status, body) =
            tag_vector_resource(&router, region, &arn, &json!({ reserved: "forged" })).await;
        assert_eq!(
            (http_status, error_code(&body).as_str()),
            (400, "ValidationException"),
            "case {reserved:?}: TagResource must refuse a client's write of it, got \
             {http_status} {body}"
        );
        assert_eq!(
            body.get("message").and_then(Value::as_str),
            Some(RESERVED_KEY_SENTENCE),
            "case {reserved:?}: the refusal must be the service's own sentence, got {body}"
        );

        let (http_status, body) = untag_vector_resource(&router, region, &arn, &[reserved]).await;
        assert_eq!(
            (http_status, error_code(&body).as_str()),
            (400, "ValidationException"),
            "case {reserved:?}: UntagResource must refuse a client's removal of it, got \
             {http_status} {body}"
        );
        assert_eq!(
            body.get("message").and_then(Value::as_str),
            Some(RESERVED_KEY_SENTENCE),
            "case {reserved:?}: the refusal must be the service's own sentence, got {body}"
        );

        let (_, held) = vector_resource_tags(&router, region, &arn).await;
        assert_eq!(
            held, expected,
            "case {reserved:?}: a refused write must leave {expected:?}, got {held:?}"
        );
    }

    // Removing the client's own key leaves the stamped set whole, so the reverse lookup is
    // still there once the client has taken back everything it put on.
    let (http_status, body) = untag_vector_resource(&router, region, &arn, &["Reviewed"]).await;
    assert_eq!(
        http_status, 200,
        "UntagResource of a client's own key must answer 200, got {http_status} {body}"
    );
    let (_, held) = vector_resource_tags(&router, region, &arn).await;
    assert_eq!(
        held, stamped,
        "expected the stamped set {stamped:?} to remain, got {held:?}"
    );
}
