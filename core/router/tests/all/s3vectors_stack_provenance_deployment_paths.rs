//! The three `aws:cloudformation:*` tags on an Amazon S3 Vectors resource a CloudFormation
//! stack provisioned, read back through S3 Vectors' own wire — whichever STACK OPERATION
//! provisioned it, and with a caller's own tag writes going on around them.
//!
//! RULE: every resource CloudFormation provisions carries, in the service that OWNS it, the
//! stack-level `Tags` in force PLUS the three tags CloudFormation records itself —
//! `aws:cloudformation:stack-name` (the owning stack's name), `aws:cloudformation:stack-id`
//! (its id) and `aws:cloudformation:logical-id` (the resource's logical id in the template) —
//! and nothing a caller can send writes or removes one of those three. The rule is about
//! PROVISIONING rather than about one request, so it holds for every stack operation that
//! provisions a resource, and the owning service's own tag read on the handle the stack
//! published answers with the whole set however the resource came to exist. That set IS the
//! resource-to-stack reverse lookup a client holding only a vector-bucket ARN has, and the
//! absence of the three is what tells a hand-made bucket from a stack-managed one.
//!
//! What `cloudformation_stamps_s3vectors_stack_provenance.rs` varies — how many stack tags,
//! how many resources, whether the declaration states tags of its own, whether a key
//! collides, which of the two S3 Vectors types — this suite holds light and varies the OTHER
//! half of the same rule:
//!
//! * the stack operation that provisioned the resource: `CreateStack`, an executed `CREATE`
//!   change set, and an `UpdateStack` that ADDS a resource to a stack that already exists;
//! * whether the resource is a vector bucket or an index inside one, and whether its name is
//!   spelled by the template or generated by CloudFormation;
//! * what a CALLER does to the tag map afterwards: adding a key of its own, removing one of
//!   its own, and trying to overwrite or remove one of the three;
//! * and the control: a vector bucket created straight through
//!   `s3vectors CreateVectorBucket`, which belongs to no stack and therefore carries none of
//!   the three.
//!
//! Two crates have to agree for the rule to hold (CloudFormation stamps the tags, S3 Vectors
//! stores and reports them), so the suite lives here rather than in either crate. Every
//! expected value is computed here from what the row declares plus the stack id
//! `DescribeStacks` reports — never read back out of the tag answer being checked.

