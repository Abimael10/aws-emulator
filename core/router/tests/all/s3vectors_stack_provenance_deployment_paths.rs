/// The change set name every row that deploys through one uses.
const CHANGE_SET: &str = "s3vectors-provenance-plan";

/// How long a case waits for a stack operation, or a change set, to settle before it gives
/// up.
///
/// The CONDITION is what the loops below wait for, never a span: a stack operation's terminal
/// status is owed a moment after the call that started it, and this deadline is deliberately
/// far past any span the emulator owes, so a loaded or slow machine cannot turn a settled
/// stack into a failed assertion.
const SETTLE_DEADLINE: Duration = Duration::from_secs(120);

/// How long a poll pauses between two reads of the status it is waiting on.
const SETTLE_POLL_INTERVAL: Duration = Duration::from_millis(25);

/// The suffix of every status CloudFormation reports while an operation is still running.
const IN_PROGRESS: &str = "_IN_PROGRESS";

/// The sentence Amazon S3 Vectors answers a request that names a tag key in AWS's reserved
/// namespace, spelled out so this suite pins the WORDING rather than whatever the
/// implementation's own constant happens to hold.
///
/// Source: the fixed text that service answers such a request with, which this emulator's S3
/// Vectors crate carries as `state::SYSTEM_TAG_REFUSED`. It names neither the key nor the
/// operation, so the one sentence is the answer on every call that takes tag keys.
const RESERVED_KEY_SENTENCE: &str = "System tags cannot be added/updated by requester";

/// Which stack operation provisioned the resources a row reads back.
#[derive(Debug, Clone, Copy)]
enum DeployedBy {
    /// `CreateStack` with the row's template.
    CreateStack,
    /// `CreateChangeSet` with `ChangeSetType=CREATE`, then `ExecuteChangeSet` — the plan
    /// path, which brings the stack into existence in review and then deploys it.
    ExecutedChangeSet,
    /// `CreateStack` with the row's first template, then `UpdateStack` with its second, which
    /// ADDS a resource to a stack that already exists.
    CreateThenUpdate,
}

/// One resource a row reads back: its logical id in the template and the `Tags` that
/// declaration asks for.
struct Declared {
    logical_id: &'static str,
    declared: &'static [(&'static str, &'static str)],
}

/// One row: the deployment path, the Region, the stack-level tags in force, the template(s)
/// the path deploys and the resources whose tag sets the rule decides.
struct Row {
    case: &'static str,
    region: &'static str,
    deployed_by: DeployedBy,
    /// The `Tags` the stack operation supplies, propagated to every resource.
    stack_tags: &'static [(&'static str, &'static str)],
    /// The template the path deploys first.
    template: &'static str,
    /// The template an `UpdateStack` deploys afterwards, for the row whose path is an update.
    updated_template: Option<&'static str>,
    resources: &'static [Declared],
}

