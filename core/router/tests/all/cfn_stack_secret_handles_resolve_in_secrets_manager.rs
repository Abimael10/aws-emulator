//! What a secret a CloudFormation stack created is ADDRESSABLE BY, and what a refusal of a
//! read of it names — end to end over the emulator's own assembled service set.
//!
//! Two rules, one deployment:
//!
//! * **A stack's `AWS::SecretsManager::Secret` is created in Secrets Manager itself, under the
//!   name CloudFormation names it and the ARN that service minted — so EVERY handle the
//!   deployment hands out resolves there.** The handles are the ones AWS publishes for the
//!   type ("Ref returns the ARN of the secret", and `Fn::GetAtt … Id` the same ARN) and the
//!   ones `SecretId` accepts for any secret ("the ARN or name of the secret", with "a partial
//!   ARN" naming it too — `smithy_query(query="operation",operation="GetSecretValue")`). A
//!   read on any of them answers that secret's own `ARN`, `Name`, `VersionId`,
//!   `VersionStages` and the `SecretString` the template declared; none of them is
//!   `ResourceNotFoundException`, which the model states for a secret that does not exist.
//! * **A read nothing in force allows is refused `AccessDeniedException` naming the handle the
//!   REQUEST supplied, verbatim** — the sentence `User: <session> is not authorized to
//!   perform: <action> on resource: <the id as requested> because no identity-based policy
//!   allows the <action> action` — so the clause a client matches against what it asked for
//!   carries that, not an identifier the service resolved for it.
//!
//! The two are one picture: the grant on the stack's secret is scoped to the ARN the stack
//! published, and the SAME handle is served when the role carries that grant and refused,
//! naming itself, when the role carries nothing of this service. A client that fixes a missing
//! policy therefore sees the read succeed on the identifier the stack handed its function, and
//! a client that has not sees a denial it can correlate with the identifier it sent.
//!
//! Five crates have to agree for that to hold — CloudFormation creates the secret and archives
//! the inline handler, Secrets Manager holds the secret and takes the decision, IAM holds the
//! two roles and the inline grant, STS mints the session a function's own call is signed as,
//! Lambda runs the handler — so the suite lives here rather than in any one of them. Every
//! observation is made where a client makes one: `DescribeStacks`,
//! `DescribeStackResources`, `Invoke`, and Secrets Manager's own `DescribeSecret`.
//!
//! The rows differ along what the rules generalise over: the FORM of the handle (the ARN a
//! `Ref` published, the ARN `Fn::GetAtt … Id` published, that ARN without the six characters
//! Secrets Manager draws per secret, and the secret's name), WHERE the name came from (stated
//! by the declaration, or generated by CloudFormation for a declaration that states none), and
//! the SHAPE of the value the secret holds (plain text, a JSON credential document). Each row
//! is probed twice over, through the function whose role carries the grant and through the one
//! whose role carries none.
//!
//! `cloudformation_condition_gated_secrets_policy` pins what a `Condition` on the grant
//! decides, with the one handle a `Ref` publishes;
//! `cloudformation_provisions_secrets_manager_secrets` pins what the type's own properties
//! deploy; `lambda_in_function_secretsmanager_grant_revocation` pins the decision being taken
//! afresh as the role's document is rewritten. What only this suite reaches is the SET of
//! handles one stack-created secret answers for, and the refusal naming each of them.

use std::collections::BTreeMap;
use std::sync::Arc;
use std::time::Duration;

use bytes::Bytes;
use serde_json::{json, Value};
