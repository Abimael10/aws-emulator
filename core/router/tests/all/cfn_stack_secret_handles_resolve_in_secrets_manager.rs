/// The Region every request here is signed for, and so the Region the stack's resources
/// belong to.
const REGION: &str = "us-east-1";

/// The account this emulator serves, which every ARN and every session's ARN carries.
const ACCOUNT: &str = ::engine::EMULATOR_ACCOUNT_ID;

/// The terminal `StackStatus` a create that succeeded settles to, and the statuses a create
/// can settle to at all: the deploy waits for a terminal one and then says which it was.
const CREATE_COMPLETE: &str = "CREATE_COMPLETE";
const TERMINAL_STATUSES: [&str; 4] = [
    CREATE_COMPLETE,
    "CREATE_FAILED",
    "ROLLBACK_COMPLETE",
    "ROLLBACK_FAILED",
];

/// The logical ids the template declares.
const NAMED_SECRET: &str = "NamedSecret";
const GENERATED_SECRET: &str = "GeneratedSecret";
const GRANTED_ROLE: &str = "GrantedRole";
const REFUSED_ROLE: &str = "RefusedRole";
const READ_POLICY: &str = "ReadPolicy";
const GRANTED_FUNCTION: &str = "GrantedProbe";
const REFUSED_FUNCTION: &str = "RefusedProbe";

/// The output keys the template publishes the two handles of each secret under.
const NAMED_REF_OUTPUT: &str = "NamedSecretRef";
const NAMED_ID_OUTPUT: &str = "NamedSecretId";
const GENERATED_REF_OUTPUT: &str = "GeneratedSecretRef";
const GENERATED_ID_OUTPUT: &str = "GeneratedSecretId";

/// The name the first secret's declaration STATES, so the handle a row supplies as its name is
/// one the template carried rather than one read back out of the answer being checked.
const DECLARED_NAME: &str = "xsvc-stack-handles-declared-secret";

/// The value each secret is declared with: plain text, and a JSON credential document —
/// `SecretString` is free text whose only constraint is a length of at least one
/// (`smithy_query(query="shape", shape="SecretStringType")`).
const DECLARED_VALUE: &str = "the-value-the-template-declared";
const GENERATED_SECRET_VALUE: &str = r#"{"username":"appuser","password":"an-example-password"}"#;

/// The IAM action the handler's read performs, which the grant names and the refusal blames
/// ("Required permissions: secretsmanager:GetSecretValue", `GetSecretValue`, that service's
/// own model).
const READ_ACTION: &str = "secretsmanager:GetSecretValue";

/// The code and status Secrets Manager refuses a call nothing in force allows with: the
/// AWS-common `AccessDeniedException`, carried at this service's client-error status because
/// awsJson1_1 discriminates a failure by the error type in the body.
const ACCESS_DENIED: &str = "AccessDeniedException";
const ACCESS_DENIED_STATUS: u16 = 400;

/// The staging label the version a read resolves by default carries: "If you don't specify
/// either a VersionStage or VersionId, Secrets Manager returns the AWSCURRENT version."
/// (`GetSecretValue`, that service's Smithy model.)
const STAGE_CURRENT: &str = "AWSCURRENT";

/// How many characters Secrets Manager draws per secret and ends its ARN with
/// (`arn:aws:secretsmanager:<region>:<account>:secret:<name>-<suffix>`), which is what a
/// PARTIAL ARN leaves off.
const ARN_SUFFIX_LEN: usize = 6;

/// The runtime, handler and per-invocation budget every probe function declares. The budget is
/// well past what a run needs on any host, because what is under test is the addressing and
/// the decision rather than how fast an interpreter gets through a handler.
const RUNTIME: &str = "python3.12";
const HANDLER: &str = "index.handler";
const FUNCTION_TIMEOUT: u64 = 120;

/// How often to look while waiting for work another service owes — the stack settling, a
/// created function reaching `Active` — and how many looks to take. The spans are those
/// services' own, so no fixed sleep names the instant one ends, and the deadline is generous
/// so a loaded host cannot decide the outcome.
const LOOK: Duration = Duration::from_millis(100);
const LOOKS: usize = 1_200;

/// The handler every probe runs: it reads the secret the EVENT names, through the SDK the
/// runtime supplies, and reports either the members that read answered or the refusal Secrets
/// Manager answered it with. It computes nothing: the handle it asks about is the one the
/// invocation handed it.
const PROBE_HANDLER: &str = r#"
import boto3
from botocore.exceptions import ClientError


def handler(event, context):
    client = boto3.client("secretsmanager")
    try:
        answered = client.get_secret_value(SecretId=event["secret_id"])
    except ClientError as refused:
        return {
            "ok": False,
            "code": refused.response["Error"]["Code"],
            "message": refused.response["Error"]["Message"],
            "status": refused.response["ResponseMetadata"]["HTTPStatusCode"],
        }
    return {
        "ok": True,
        "arn": answered["ARN"],
        "name": answered["Name"],
        "secret": answered["SecretString"],
        "version_id": answered["VersionId"],
        "stages": answered["VersionStages"],
    }
"#;

/// The emulator as it is ASSEMBLED, on one engine (`aws_emulator_router::build_router`): a
/// handler's own SDK call is dispatched back into this same router, so the secret it reads is
/// the secret this stack deployed.
fn build_router() -> MultiServiceRouter {
    let engine: Arc<engine::InMemoryEngine> = Arc::new(engine::InMemoryEngine::new());
    let mut router = aws_emulator_router::build_router(engine);
    // The signature is never checked here, as in every other suite of this crate; the
    // credential scope is what routes a request.
    router.set_request_authentication(false);
    router
}

/// A SigV4 `Authorization` header whose credential scope names `service`, which is what routes
/// the request and what each handler reads its Region from.
fn authorization(service: &str) -> String {
    format!(
        "AWS4-HMAC-SHA256 Credential=AKIAIOSFODNN7EXAMPLE/20260101/{REGION}/{service}/\
         aws4_request, SignedHeaders=host, Signature=0000"
    )
}

/// Call one CloudFormation operation over its awsQuery wire.
async fn cloudformation(
    router: &MultiServiceRouter,
    action: &str,
    members: &[(&str, &str)],
) -> (u16, String) {
    let mut body = format!("Action={action}&Version=2010-05-15");
    for (key, value) in members {
        body.push('&');
        body.push_str(&form_encode(key));
        body.push('=');
        body.push_str(&form_encode(value));
    }
    let request = http::Request::builder()
        .method("POST")
        .uri("/")
        .header("host", format!("cloudformation.{REGION}.amazonaws.com"))
        .header("content-type", "application/x-www-form-urlencoded")
        .header("authorization", authorization("cloudformation"))
        .body(Bytes::from(body))
        .expect("a well-formed request");
    let response = router.dispatch(request).await;
    let status = response.status().as_u16();
    (status, String::from_utf8_lossy(response.body()).to_string())
}

/// One Lambda `restJson1` call, as its status, its headers and its parsed body.
async fn lambda(
    router: &MultiServiceRouter,
    method: &str,
    uri: &str,
    body: &[u8],
) -> (u16, http::HeaderMap, Value) {
    let request = http::Request::builder()
        .method(method)
        .uri(uri)
        .header("host", format!("lambda.{REGION}.amazonaws.com"))
        .header("content-type", "application/json")
        .header("authorization", authorization("lambda"))
        .body(Bytes::from(body.to_vec()))
        .expect("a well-formed request");
    let response = router.dispatch(request).await;
    let (parts, body) = response.into_parts();
    let parsed = if body.is_empty() {
        Value::Null
    } else {
        serde_json::from_slice(&body)
            .unwrap_or_else(|_| Value::String(String::from_utf8_lossy(&body).to_string()))
    };
    (parts.status.as_u16(), parts.headers, parsed)
}

/// Call one Secrets Manager operation over its `awsJson1_1` wire.
async fn secretsmanager(
    router: &MultiServiceRouter,
    operation: &str,
    body: &Value,
) -> (u16, Value) {
    let request = http::Request::builder()
        .method("POST")
        .uri("/")
        .header("host", format!("secretsmanager.{REGION}.amazonaws.com"))
        .header("content-type", "application/x-amz-json-1.1")
        .header("x-amz-target", format!("secretsmanager.{operation}"))
        .header("authorization", authorization("secretsmanager"))
        .body(Bytes::from(body.to_string()))
        .expect("a well-formed request");
    let response = router.dispatch(request).await;
    let status = response.status().as_u16();
    let parsed: Value = if response.body().is_empty() {
        Value::Null
    } else {
        serde_json::from_slice(response.body()).unwrap_or(Value::Null)
    };
    (status, parsed)
}

/// The trust policy a Lambda execution role needs, so Lambda can be handed either role.
fn trust_policy() -> Value {
    json!({
        "Version": "2012-10-17",
        "Statement": [{
            "Effect": "Allow",
            "Principal": {"Service": "lambda.amazonaws.com"},
            "Action": "sts:AssumeRole",
        }],
    })
}

/// The role and function names one stack declares, so the session a refusal names —
/// `arn:aws:sts::<account>:assumed-role/<role>/<function>` — is known from the declaration.
fn granted_role_name(stack: &str) -> String {
    format!("{stack}-granted-role")
}
fn refused_role_name(stack: &str) -> String {
    format!("{stack}-refused-role")
}
fn granted_function_name(stack: &str) -> String {
    format!("{stack}-granted-probe")
}
fn refused_function_name(stack: &str) -> String {
    format!("{stack}-refused-probe")
}

/// One probe function's declaration: the inline handler, archived into a deployment package by
/// CloudFormation, running as `role`.
fn probe_function(name: String, role: &str) -> Value {
    json!({
        "Type": "AWS::Lambda::Function",
        "Properties": {
            "FunctionName": name,
            "Runtime": RUNTIME,
            "Handler": HANDLER,
            "Timeout": FUNCTION_TIMEOUT,
            "Role": {"Fn::GetAtt": [role, "Arn"]},
            "Code": {"ZipFile": PROBE_HANDLER},
        },
    })
}

/// The template the suite deploys: the two secrets, the two execution roles, the grant one of
/// them carries on both secrets, a probe function per role, and the handles each secret
/// publishes as outputs.
fn template(stack: &str) -> String {
    json!({
        "AWSTemplateFormatVersion": "2010-09-09",
        "Resources": {
            NAMED_SECRET: {
                "Type": "AWS::SecretsManager::Secret",
                "Properties": {"Name": DECLARED_NAME, "SecretString": DECLARED_VALUE},
            },
            // No `Name`, so the name is CloudFormation's own generated one.
            GENERATED_SECRET: {
                "Type": "AWS::SecretsManager::Secret",
                "Properties": {"SecretString": GENERATED_SECRET_VALUE},
            },
            GRANTED_ROLE: {
                "Type": "AWS::IAM::Role",
                "Properties": {
                    "RoleName": granted_role_name(stack),
                    "AssumeRolePolicyDocument": trust_policy(),
                },
            },
            REFUSED_ROLE: {
                "Type": "AWS::IAM::Role",
                "Properties": {
                    "RoleName": refused_role_name(stack),
                    "AssumeRolePolicyDocument": trust_policy(),
                },
            },
            // The grant is SCOPED to the ARNs the stack published for its two secrets, which
            // is what a template writes; the handles a row supplies are every form of those
            // secrets' ids.
            READ_POLICY: {
                "Type": "AWS::IAM::Policy",
                "Properties": {
                    "PolicyName": format!("{stack}-read-the-secrets"),
                    "Roles": [{"Ref": GRANTED_ROLE}],
                    "PolicyDocument": {
                        "Version": "2012-10-17",
                        "Statement": [{
                            "Effect": "Allow",
                            "Action": READ_ACTION,
                            "Resource": [{"Ref": NAMED_SECRET}, {"Ref": GENERATED_SECRET}],
                        }],
                    },
                },
            },
            GRANTED_FUNCTION: probe_function(granted_function_name(stack), GRANTED_ROLE),
            REFUSED_FUNCTION: probe_function(refused_function_name(stack), REFUSED_ROLE),
        },
        "Outputs": {
            NAMED_REF_OUTPUT: {"Value": {"Ref": NAMED_SECRET}},
            NAMED_ID_OUTPUT: {"Value": {"Fn::GetAtt": [NAMED_SECRET, "Id"]}},
            GENERATED_REF_OUTPUT: {"Value": {"Ref": GENERATED_SECRET}},
            GENERATED_ID_OUTPUT: {"Value": {"Fn::GetAtt": [GENERATED_SECRET, "Id"]}},
        },
    })
    .to_string()
}

/// Poll `DescribeStacks` until the stack first reports a TERMINAL status, and answer it with
/// the answer it was read from.
async fn wait_for_terminal_status(router: &MultiServiceRouter, stack: &str) -> (String, String) {
    let mut last = stack_status(router, stack).await;
    for _ in 0..LOOKS {
        if TERMINAL_STATUSES.contains(&last.0.as_str()) {
            return last;
        }
        tokio::time::sleep(LOOK).await;
        last = stack_status(router, stack).await;
    }
    last
}

/// Deploy the stack and answer `(its outputs, its logical -> physical id map)`.
async fn deploy(
    router: &MultiServiceRouter,
    stack: &str,
) -> (BTreeMap<String, String>, BTreeMap<String, String>) {
    let body = template(stack);
    let (status, answered) = cloudformation(
        router,
        "CreateStack",
        &[
            ("StackName", stack),
            ("TemplateBody", &body),
            // The template declares IAM resources, two of them NAMED, which is what these
            // two capabilities acknowledge.
            ("Capabilities.member.1", "CAPABILITY_IAM"),
            ("Capabilities.member.2", "CAPABILITY_NAMED_IAM"),
        ],
    )
    .await;
    assert_eq!(
        status, 200,
        "setup: expected HTTP 200 from CreateStack({stack:?}), got {status} with {answered}"
    );

    let (reached, described) = wait_for_terminal_status(router, stack).await;
    let failures = if reached == CREATE_COMPLETE {
        Vec::new()
    } else {
        let (_, events) =
            cloudformation(router, "DescribeStackEvents", &[("StackName", stack)]).await;
        elements(&events, "ResourceStatusReason")
    };
    assert_eq!(
        reached, CREATE_COMPLETE,
        "setup: expected the stack to reach {CREATE_COMPLETE}, got {described} with resource \
         failures {failures:?}"
    );

    let (status, resources) =
        cloudformation(router, "DescribeStackResources", &[("StackName", stack)]).await;
    assert_eq!(
        status, 200,
        "setup: expected HTTP 200 from DescribeStackResources, got {status} with {resources}"
    );
    (outputs_of(&described), physical_ids_of(&resources))
}

/// Wait until Lambda reports `name` `Active` — "the function is ready to be invoked"
/// (`FunctionConfiguration$State`) — which is the state an invocation needs.
async fn wait_until_active(router: &MultiServiceRouter, name: &str) {
    let mut last = Value::Null;
    for _ in 0..LOOKS {
        let (status, _, configuration) = lambda(
            router,
            "GET",
            &format!("/2015-03-31/functions/{name}/configuration"),
            &[],
        )
        .await;
        assert_eq!(
            status, 200,
            "setup: expected HTTP 200 from GetFunctionConfiguration({name:?}), got {status} \
             with {configuration}"
        );
        if configuration.get("State").and_then(Value::as_str) == Some("Active") {
            return;
        }
        last = configuration;
        tokio::time::sleep(LOOK).await;
    }
    panic!("setup: Lambda never reported {name:?} Active, last configuration {last}");
}

/// Invoke `function` with the handle `supplied` as the secret to read, and answer the result
/// the handler itself reported.
async fn probe(
    router: &MultiServiceRouter,
    case: &str,
    function: &str,
    supplied: &str,
) -> Value {
    let event = json!({"secret_id": supplied}).to_string();
    let (status, headers, payload) = lambda(
        router,
        "POST",
        &format!("/2015-03-31/functions/{function}/invocations"),
        event.as_bytes(),
    )
    .await;
    assert_eq!(
        status, 200,
        "case {case:?}: expected HTTP 200 from Invoke, got {status} with payload {payload}"
    );
    let signal = headers
        .get("x-amz-function-error")
        .and_then(|value| value.to_str().ok())
        .map(str::to_string);
    assert_eq!(
        signal, None,
        "case {case:?}: expected no function error, got {signal:?} with payload {payload}"
    );
    payload
}

/// The output `key` carries, which the stack must have published.
fn published(outputs: &BTreeMap<String, String>, key: &str) -> String {
    outputs
        .get(key)
        .cloned()
        .unwrap_or_else(|| panic!("setup: no {key} output in {outputs:?}"))
}

/// The PARTIAL ARN of `arn`: the full ARN without the characters Secrets Manager draws per
/// secret, which names the secret too ("a partial ARN", `GetSecretValue$SecretId`).
fn partial_arn(arn: &str) -> String {
    let dropped = arn.len().saturating_sub(ARN_SUFFIX_LEN + 1);
    arn[..dropped].to_string()
}

/// Assert `arn` is the ARN form Secrets Manager mints for a secret named `name`:
/// `arn:aws:secretsmanager:<region>:<account>:secret:<name>-<six characters>`.
fn assert_arn_form(case: &str, arn: &str, name: &str) {
    let prefix = format!("arn:aws:secretsmanager:{REGION}:{ACCOUNT}:secret:{name}-");
    assert!(
        arn.starts_with(&prefix) && arn.len() == prefix.len() + ARN_SUFFIX_LEN,
        "case {case:?}: expected an ARN of {prefix:?} plus {ARN_SUFFIX_LEN} characters, got \
         {arn:?}"
    );
}

/// One secret of the deployment, as the handles it is addressable by and what a served read of
/// it must answer.
struct Deployed {
    /// What the row varies: where the secret's name came from.
    origin: &'static str,
    /// The name Secrets Manager holds it under.
    name: String,
    /// The ARN that service minted for it, which is what both published handles carry.
    arn: String,
    /// The value the template declared for it.
    value: &'static str,
}

/// One probe: the handle it supplies, and the secret that handle addresses.
struct Probe<'a> {
    case: String,
    supplied: String,
    secret: &'a Deployed,
}

/// Read the two secrets the stack deployed back through Secrets Manager's own `DescribeSecret`
/// on the handles the stack published, and answer what each is addressable by.
///
/// The NAME of the declaration that states none is CloudFormation's own generated one, so it
/// is taken from the owning service's report of the secret rather than computed here; its
/// SHAPE — `<stack>-<logical id>-<random>` — is asserted against the declaration.
async fn deployed_secrets(
    router: &MultiServiceRouter,
    stack: &str,
    outputs: &BTreeMap<String, String>,
) -> Vec<Deployed> {
    // (what the row varies, the Ref output, the GetAtt Id output, the declared value)
    let declared: [(&'static str, &str, &str, &'static str); 2] = [
        (
            "a name the declaration stated",
            NAMED_REF_OUTPUT,
            NAMED_ID_OUTPUT,
            DECLARED_VALUE,
        ),
        (
            "a name CloudFormation generated",
            GENERATED_REF_OUTPUT,
            GENERATED_ID_OUTPUT,
            GENERATED_SECRET_VALUE,
        ),
    ];
    let mut deployed = Vec::new();
    for (origin, ref_output, id_output, value) in declared {
        let arn = published(outputs, ref_output);
        // "Ref returns the ARN of the secret", and `Fn::GetAtt … Id` is the same ARN: the two
        // handles a template can hand out are one identifier.
        assert_eq!(
            published(outputs, id_output),
            arn,
            "case {origin:?}: expected {id_output} to carry the same ARN as {ref_output} \
             ({arn:?}), got {outputs:?}"
        );
        // The secret is one Secrets Manager really holds, and it answers for the ARN the
        // stack published: the name it holds it under comes from that answer.
        let (status, described) =
            secretsmanager(router, "DescribeSecret", &json!({"SecretId": &arn})).await;
        assert_eq!(
            status, 200,
            "case {origin:?}: expected HTTP 200 from DescribeSecret on the published ARN \
             {arn:?}, got {status} with {described}"
        );
        let name = described["Name"]
            .as_str()
            .unwrap_or_else(|| panic!("case {origin:?}: expected a Name, got {described}"))
            .to_string();
        assert_arn_form(origin, &arn, &name);
        deployed.push(Deployed {
            origin,
            name,
            arn,
            value,
        });
    }
    // The name of the declaration that stated one is that name; the generated one has
    // CloudFormation's own shape for a physical name it draws, `<stack>-<logical id>-<random>`.
    assert_eq!(
        deployed[0].name, DECLARED_NAME,
        "expected the declared name to be the one Secrets Manager holds the secret under, got \
         {:?}",
        deployed[0].name
    );
    let generated_prefix = format!("{stack}-{GENERATED_SECRET}-");
    assert!(
        deployed[1].name.starts_with(&generated_prefix)
            && deployed[1].name.len() > generated_prefix.len(),
        "expected a generated name of {generated_prefix:?} plus a drawn part, got {:?}",
        deployed[1].name
    );
    deployed
}

/// Every handle each deployed secret is addressable by: the ARN the stack published, that ARN
/// without the characters Secrets Manager drew, and the secret's name.
fn probes(deployed: &[Deployed]) -> Vec<Probe<'_>> {
    let mut rows = Vec::new();
    for secret in deployed {
        for (form, supplied) in [
            ("the full ARN the stack published", secret.arn.clone()),
            ("the partial ARN of it", partial_arn(&secret.arn)),
            ("the secret's own name", secret.name.clone()),
        ] {
            rows.push(Probe {
                case: format!("{form}, for a secret with {}", secret.origin),
                supplied,
                secret,
            });
        }
    }
    rows
}

/// RULE 1: every handle the deployment hands out for a secret its stack created resolves in
/// Secrets Manager, so the stack's own function — whose role carries the grant scoped to the
/// ARN the stack published — is SERVED that secret's own members on each of them.
#[tokio::test]
async fn every_handle_a_stack_published_resolves_for_its_granted_function() {
    let stack = "xsvc-stack-secret-handles-served";
    let router = build_router();
    let (outputs, physical) = deploy(&router, stack).await;
    for logical in [
        NAMED_SECRET,
        GENERATED_SECRET,
        GRANTED_ROLE,
        READ_POLICY,
        GRANTED_FUNCTION,
    ] {
        assert!(
            physical.contains_key(logical),
            "setup: expected a physical id for {logical}, got {physical:?}"
        );
    }
    let deployed = deployed_secrets(&router, stack, &outputs).await;
    let function = granted_function_name(stack);
    wait_until_active(&router, &function).await;

    for row in probes(&deployed) {
        let case = &row.case;
        let payload = probe(&router, case, &function, &row.supplied).await;
        assert_eq!(
            payload["ok"],
            json!(true),
            "case {case:?}: expected the granted read to be served, got {payload}"
        );
        // Whichever handle addressed it, the answer is the ONE secret the stack created: its
        // own ARN, the name it is held under, the value the template declared, and the version
        // a read with no selector resolves.
        assert_eq!(
            payload["arn"].as_str(),
            Some(row.secret.arn.as_str()),
            "case {case:?}: expected the ARN {:?}, got {payload}",
            row.secret.arn
        );
        assert_eq!(
            payload["name"].as_str(),
            Some(row.secret.name.as_str()),
            "case {case:?}: expected the name {:?}, got {payload}",
            row.secret.name
        );
        assert_eq!(
            payload["secret"].as_str(),
            Some(row.secret.value),
            "case {case:?}: expected the declared SecretString {:?}, got {payload}",
            row.secret.value
        );
        assert_eq!(
            payload["stages"],
            json!([STAGE_CURRENT]),
            "case {case:?}: expected the read to resolve {STAGE_CURRENT}, got {payload}"
        );
        assert!(
            payload["version_id"].as_str().is_some_and(|id| !id.is_empty()),
            "case {case:?}: expected the version's own id, got {payload}"
        );
    }
}

/// RULE 2: the refusal of a read nothing in force allows names the handle the REQUEST
/// supplied, verbatim — whichever form of the secret's id that was, and whether or not the
/// account holds a secret under it.
#[tokio::test]
async fn the_refusal_names_the_handle_the_function_supplied() {
    let stack = "xsvc-stack-secret-handles-refused";
    let router = build_router();
    let (outputs, physical) = deploy(&router, stack).await;
    for logical in [REFUSED_ROLE, REFUSED_FUNCTION] {
        assert!(
            physical.contains_key(logical),
            "setup: expected a physical id for {logical}, got {physical:?}"
        );
    }
    let deployed = deployed_secrets(&router, stack, &outputs).await;
    let function = refused_function_name(stack);
    wait_until_active(&router, &function).await;

    // The session a function's own call is signed as:
    // `arn:aws:sts::<account>:assumed-role/<role>/<function>`.
    let session = format!(
        "arn:aws:sts::{ACCOUNT}:assumed-role/{}/{function}",
        refused_role_name(stack)
    );
    // Beside every handle of a secret the account HOLDS, one it holds no secret under at all:
    // the clause reads the same either way, so it says nothing about which it was.
    let unheld = Deployed {
        origin: "no secret of this account",
        name: format!("{stack}-no-such-secret"),
        arn: format!(
            "arn:aws:secretsmanager:{REGION}:{ACCOUNT}:secret:{stack}-no-such-secret-AbCdEf"
        ),
        value: "",
    };
    let mut rows = probes(&deployed);
    rows.extend(probes(std::slice::from_ref(&unheld)));

    for row in rows {
        let case = &row.case;
        let payload = probe(&router, case, &function, &row.supplied).await;
        assert_eq!(
            payload["ok"],
            json!(false),
            "case {case:?}: expected the ungranted read to be refused, got {payload}"
        );
        assert_eq!(
            payload["code"].as_str(),
            Some(ACCESS_DENIED),
            "case {case:?}: expected an {ACCESS_DENIED}, got {payload}"
        );
        assert_eq!(
            payload["status"].as_u64(),
            Some(u64::from(ACCESS_DENIED_STATUS)),
            "case {case:?}: expected HTTP {ACCESS_DENIED_STATUS} for the refusal, got {payload}"
        );
        let expected = format!(
            "User: {session} is not authorized to perform: {READ_ACTION} on resource: {} \
             because no identity-based policy allows the {READ_ACTION} action",
            row.supplied
        );
        assert_eq!(
            payload["message"].as_str(),
            Some(expected.as_str()),
            "case {case:?}: expected {expected:?}, got {payload}"
        );
    }
}
