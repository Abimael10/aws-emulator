//! What a `.waitForTaskToken` Lambda callback's own settlement is authorized against: the
//! identity-based policies in force on the invoked function's EXECUTION ROLE at the instant of
//! the call.
//!
//! RULE: a `SendTask*` call names no ARN of its own, so it is judged against the resource the
//! task token it carries belongs to — for a callback (`.waitForTaskToken`) task, the STATE
//! MACHINE whose execution is waiting at it — and a call made from inside a running function
//! is made as a session of that function's execution role; a settlement no identity-based
//! policy in force on that role allows is refused HTTP 400 `AccessDeniedException` naming the
//! assumed-role session, `states:<OperationName>` and that state machine, the token is NOT
//! redeemed and the parked execution stays `RUNNING`, while the identical settlement made once
//! the grant is in force is answered HTTP 200 and carries the execution to the terminal status
//! its answer dictates — `SUCCEEDED` with the `output` a success sent, `FAILED` with the
//! `error` and `cause` a failure named.
//!
//! "The execution role grants the function permission to use Amazon Web Services services"
//! (`FunctionConfiguration$Role`), and the identity such a call speaks for is the session
//! `arn:aws:sts::<account>:assumed-role/<role>/<function>`; with neither an identity-based nor
//! a resource-based allow a request is denied, and an explicit deny wins over any allow (IAM
//! User Guide, *Policy evaluation logic*). The token is "generated by Step Functions when
//! tasks are assigned to a worker, or in the context object when a workflow enters a task
//! state" (`SendTaskSuccessInput$taskToken`), and the decision is taken per request, so a
//! statement attached between two settlements refuses the first and serves the second.
//!
//! Four crates have to agree for that to hold — IAM holds the role and its inline document,
//! STS mints the session the function's calls are signed with, Lambda runs the handler the
//! callback task hands the token to, and Step Functions takes the decision and resumes the
//! parked execution — so the suite lives here. What the neighbours pin and this one does not
//! repeat: `lambda_in_function_step_functions_authorization` pins the decision for operations
//! that name an ARN of their own (a start, a read, a list), and
//! `cfn_deployed_sfn_lambda_callback_and_task_stacks` pins the callback pattern itself under a
//! role that grants it. What only this suite reaches is the decision taken on the SETTLEMENT a
//! `lambda:invoke.waitForTaskToken` task's own invocation makes — the call that is addressed
//! by nothing but its token — and what the parked execution does either way.
//!
//! The rows differ along what the rule generalises over: WHICH settlement the handler calls
//! (`SendTaskSuccess`, `SendTaskFailure`), WHAT the role's document allows (nothing of this
//! service, the other settlement's action, this one's, every action of the service), WHICH
//! resource that statement names (the state machine the parked execution runs on, another
//! state machine of the account, every resource), whether that document also DENIES the
//! action, WHEN it says it (before the first settlement, changed between two of them), and
//! WHERE the settlement is made from (inside the invocation the hand-over made, and a later
//! invocation holding the same token). Every attempt asserts both halves — what the handler
//! reports of the call, and what THIS SERVICE then holds for the parked execution — so a
//! refusal that still redeemed the token, and a grant that answered without resuming the
//! execution, both fail here.

