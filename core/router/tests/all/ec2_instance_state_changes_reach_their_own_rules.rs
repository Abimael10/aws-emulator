//! Which EventBridge rule each state an instance moves into reaches, over the WHOLE mounted
//! service set — the one `core/router/src/lib.rs` assembles for the binary.
//!
//! RULE: Amazon EC2 publishes every state an instance moves INTO onto the account's default
//! event bus IN THE INSTANCE'S OWN REGION, as `source` `aws.ec2` / `detail-type`
//! `EC2 Instance State-change Notification`, naming the instance in the envelope's `resources`
//! and carrying in the event `detail` the instance's id and that state; EventBridge then
//! routes each envelope by its CONTENT, so a rule whose `EventPattern` names ONE state
//! receives that state's envelope and none of the other states' — a state-scoped rule is
//! distinguishable from a broken one.
//!
//! The rows span what the rule generalises over: every state an instance's own lifecycle
//! passes through, each with a rule and a queue of its own; the REGION the instance runs in,
//! together with who chose its Availability Zone (the request, or the service for a subnet
//! that named none); and the SHAPE of the pattern a client scopes a state by (the state branch
//! on its own, and that branch as one arm of an `$or`). The states are the `InstanceStateName`
//! values a launch, a stop, a start and a termination move an instance into (`smithy_query`
//! query="shape" shape="com.amazonaws.ec2#InstanceStateName"), so the table is the catalog
//! rather than one recorded transition.
//!
//! Every `$or` rule's second arm is a BARRIER branch of the caller's own source, which is how
//! a client proves its rule, its target and the queue's resource policy deliver at all before
//! it provokes any instance activity: a queue that then receives nothing is one whose PATTERN
//! withheld the envelope, not a rule that was never live.
//!
//! What only this suite reaches, beside the crate-local
//! `services/service-com-amazonaws-ec2-amazonec2/tests/all/instance_state_change_notifications.rs`
//! (which pins WHICH moves are published, over a table of launches and calls): the per-state
//! ROUTING of those publications over the production service set, where more than one mounted
//! model resolves the `events` and `ssm` keys, and where the image the instance is launched
//! from is the one Systems Manager resolves for a client.
//! `ec2_instance_state_changes_on_a_started_emulator.rs` drives the same chain against the
//! binary a client starts.

use std::collections::BTreeMap;
use std::time::{Duration, Instant};

use bytes::Bytes;
use serde_json::{json, Value};
use smithy_server_runtime::MultiServiceRouter;

// The ONE percent-encoder and element readers this test crate keeps for form-wire suites
// (`all/query_wire.rs`: "Nothing new should write another one — call this module").
use crate::query_wire::{element, elements, form_encode};

/// The EC2 API version an ec2Query body carries.
const EC2_API_VERSION: &str = "2016-11-15";

/// The public Systems Manager parameter a client resolves the Amazon Linux 2023 image id
/// through, which is the image every instance here is launched from.
const AL2023_PARAMETER: &str =
    "/aws/service/ami-amazon-linux-latest/al2023-ami-kernel-default-x86_64";

/// The instance type every launch asks for.
const INSTANCE_TYPE: &str = "t3.micro";

/// The `source` and `detail-type` an instance's state change is published under, spelled out
/// here rather than imported from the service crate, so a wrong constant in the implementation
/// cannot make this suite pass.
const EC2_SOURCE: &str = "aws.ec2";
const INSTANCE_STATE_CHANGE: &str = "EC2 Instance State-change Notification";

/// The bus an Amazon Web Services service's own events go to: "events generated by Amazon Web
/// Services services go to your account's default event bus".
const DEFAULT_BUS: &str = "default";

/// The service principal EventBridge delivers to an SQS target as, which is what a queue's
/// resource policy admits ("for Amazon SQS queues, EventBridge relies on resource-based
/// policies").
const EVENTS_PRINCIPAL: &str = "events.amazonaws.com";

/// The caller's own source a barrier event carries, and the detail type it goes under.
const BARRIER_SOURCE: &str = "ec2statechange.barrier";
const BARRIER_DETAIL_TYPE: &str = "Barrier";

/// The states one instance's lifecycle passes through, each the subject of a rule of its own:
/// the `pending` and `running` of a launch and of a start, the `stopping` and `stopped` of a
/// stop, and the `shutting-down` and `terminated` of a termination. They are
/// `InstanceStateName` values (`smithy_query` query="shape"
/// shape="com.amazonaws.ec2#InstanceStateName"), spelled as that enum spells them.
const STATES: [&str; 6] = [
    "pending",
    "running",
    "stopping",
    "stopped",
    "shutting-down",
    "terminated",
];

/// How long a wait looks for a condition another component's clock owes — a move, or the
/// publication that reports it — and how often it looks. Generous on purpose: every wait looks
/// for its CONDITION, so machine load decides when a leg finishes and never whether it passes.
const DEADLINE: Duration = Duration::from_secs(120);
const POLL: Duration = Duration::from_millis(50);

/// How many times a leg re-reads the queues when asserting that nothing FURTHER arrives: the
/// absence is asserted over a run of reads rather than over one, so a delivery that arrives
/// late still fails the leg.
const HELD_READS: usize = 5;

/// The whole emulator over one engine, exactly as `core/router/src/lib.rs` assembles it for
/// the binary.
fn router() -> MultiServiceRouter {
    let engine = aws_emulator_router::new_engine();
    let mut router = aws_emulator_router::build_router(engine);
    // Signature verification is the front door's concern, not this suite's.
    router.set_request_authentication(false);
    router
}

/// A SigV4 `Authorization` whose credential scope names `service` and `region`, which is what
/// routes the request and where its Region comes from. The signature is never checked: the
/// router above runs with request authentication off.
fn authorization(service: &str, region: &str) -> String {
    format!(
        "AWS4-HMAC-SHA256 Credential=AKIDEXAMPLE/20260101/{region}/{service}/aws4_request, \
         SignedHeaders=host, Signature=0000"
    )
}

/// What addresses one RPC call: the signing name that routes it, the `X-Amz-Target` prefix its
/// operations are named under and the version of the awsJson wire it speaks.
struct Wire {
    signing_name: &'static str,
    target_prefix: &'static str,
    json_version: &'static str,
}

/// The three services a client reaches over an awsJson wire here.
const EVENTS_WIRE: Wire = Wire {
    signing_name: "events",
    target_prefix: "AWSEvents",
    json_version: "1.1",
};
const SQS_WIRE: Wire = Wire {
    signing_name: "sqs",
    target_prefix: "AmazonSQS",
    json_version: "1.0",
};
const SSM_WIRE: Wire = Wire {
    signing_name: "ssm",
    target_prefix: "AmazonSSM",
    json_version: "1.1",
};

/// One `X-Amz-Target` RPC call against the service `wire` addresses, which must answer 200.
async fn rpc(
    router: &MultiServiceRouter,
    case: &str,
    region: &str,
    wire: &Wire,
    operation: &str,
    body: &Value,
) -> Value {
    let Wire {
        signing_name,
        target_prefix,
        json_version,
    } = wire;
    let request = http::Request::builder()
        .method("POST")
        .uri("/")
        .header("host", format!("{signing_name}.{region}.amazonaws.com"))
        .header("authorization", authorization(signing_name, region))
        .header(
            "content-type",
            format!("application/x-amz-json-{json_version}"),
        )
        .header("x-amz-target", format!("{target_prefix}.{operation}"))
        .body(Bytes::from(body.to_string()))
        .expect("the test request is well formed");
    let response = router.dispatch(request).await;
    let status = response.status().as_u16();
    let parsed: Value = if response.body().is_empty() {
        Value::Null
    } else {
        serde_json::from_slice(response.body()).unwrap_or(Value::Null)
    };
    assert_eq!(
        status, 200,
        "case {case:?}: expected HTTP 200 from {signing_name} {operation}, got {status} with \
         {parsed}"
    );
    parsed
}

/// One EventBridge call.
async fn events(
    router: &MultiServiceRouter,
    case: &str,
    region: &str,
    operation: &str,
    body: &Value,
) -> Value {
    rpc(router, case, region, &EVENTS_WIRE, operation, body).await
}

/// One Amazon SQS call.
async fn sqs(
    router: &MultiServiceRouter,
    case: &str,
    region: &str,
    operation: &str,
    body: &Value,
) -> Value {
    rpc(router, case, region, &SQS_WIRE, operation, body).await
}

/// One Systems Manager call.
async fn ssm(
    router: &MultiServiceRouter,
    case: &str,
    region: &str,
    operation: &str,
    body: &Value,
) -> Value {
    rpc(router, case, region, &SSM_WIRE, operation, body).await
}

/// One `ec2Query` call: an `application/x-www-form-urlencoded` POST answered with XML.
async fn ec2(
    router: &MultiServiceRouter,
    case: &str,
    region: &str,
    action: &str,
    params: &[(&str, &str)],
) -> String {
    let mut body = format!("Action={action}&Version={EC2_API_VERSION}");
    for (name, value) in params {
        body.push('&');
        body.push_str(&form_encode(name));
        body.push('=');
        body.push_str(&form_encode(value));
    }
    let request = http::Request::builder()
        .method("POST")
        .uri("/")
        .header("host", format!("ec2.{region}.amazonaws.com"))
        .header("authorization", authorization("ec2", region))
        .header("content-type", "application/x-www-form-urlencoded")
        .body(Bytes::from(body))
        .expect("the test request is well formed");
    let response = router.dispatch(request).await;
    let status = response.status().as_u16();
    let text = String::from_utf8_lossy(response.body()).to_string();
    assert_eq!(
        status, 200,
        "case {case:?}: expected HTTP 200 from EC2 {action}, got {status} with {text}"
    );
    text
}

/// A string member of a JSON response, or a panic naming the case and what came back.
fn member(case: &str, body: &Value, pointer: &str) -> String {
    body.pointer(pointer)
        .and_then(Value::as_str)
        .unwrap_or_else(|| panic!("case {case:?}: expected {pointer} in {body}"))
        .to_string()
}

/// An SQS queue called `name`, created through SQS itself and admitting EventBridge's service
/// principal for calls made on behalf of `rule_arn`; answers its url and its ARN.
async fn queue(
    router: &MultiServiceRouter,
    case: &str,
    region: &str,
    name: &str,
    rule_arn: &str,
) -> (String, String) {
    let created = sqs(router, case, region, "CreateQueue", &json!({"QueueName": name})).await;
    let url = member(case, &created, "/QueueUrl");
    let attributes = sqs(
        router,
        case,
        region,
        "GetQueueAttributes",
        &json!({"QueueUrl": &url, "AttributeNames": ["QueueArn"]}),
    )
    .await;
    let arn = member(case, &attributes, "/Attributes/QueueArn");
    let policy = json!({
        "Version": "2012-10-17",
        "Statement": [{
            "Sid": "AllowEventBridge",
            "Effect": "Allow",
            "Principal": {"Service": EVENTS_PRINCIPAL},
            "Action": "sqs:SendMessage",
            "Resource": &arn,
            "Condition": {"ArnEquals": {"aws:SourceArn": rule_arn}},
        }],
    })
    .to_string();
    sqs(
        router,
        case,
        region,
        "SetQueueAttributes",
        &json!({"QueueUrl": &url, "Attributes": {"Policy": policy}}),
    )
    .await;
    (url, arn)
}

/// The state branch of a pattern: the `source`, the `detail-type` and the one state it scopes
/// the rule to.
fn state_branch(state: &str) -> Value {
    json!({
        "source": [EC2_SOURCE],
        "detail-type": [INSTANCE_STATE_CHANGE],
        "detail": {"state": [state]},
    })
}

/// The pattern one rule of a row carries: the state branch ON ITS OWN, or that branch as one
/// arm of an `$or` whose other arm is the barrier branch a client proves the rule with.
fn pattern_for(state: &str, nonce: &str, with_barrier: bool) -> Value {
    if with_barrier {
        json!({
            "$or": [
                state_branch(state),
                {"source": [BARRIER_SOURCE], "detail": {"nonce": [nonce]}},
            ],
        })
    } else {
        state_branch(state)
    }
}

/// An ENABLED rule on the default bus scoped to `state`, with a queue of its own as its one
/// target; answers that queue's url.
async fn rule_for(
    router: &MultiServiceRouter,
    case: &str,
    region: &str,
    name: &str,
    state: &str,
    nonce: &str,
    with_barrier: bool,
) -> String {
    let created = events(
        router,
        case,
        region,
        "PutRule",
        &json!({
            "Name": name,
            "EventBusName": DEFAULT_BUS,
            "EventPattern": pattern_for(state, nonce, with_barrier).to_string(),
            "State": "ENABLED",
        }),
    )
    .await;
    let rule_arn = member(case, &created, "/RuleArn");
    let (url, queue_arn) = queue(router, case, region, name, &rule_arn).await;
    let targeted = events(
        router,
        case,
        region,
        "PutTargets",
        &json!({
            "Rule": name,
            "EventBusName": DEFAULT_BUS,
            "Targets": [{"Id": "sqs-target", "Arn": queue_arn}],
        }),
    )
    .await;
    assert_eq!(
        targeted["FailedEntryCount"],
        json!(0),
        "case {case:?}: every target must be accepted, got {targeted}"
    );
    url
}

/// Every envelope waiting on the queue at `url` right now, DELETING what it hands over.
async fn drain(
    router: &MultiServiceRouter,
    case: &str,
    region: &str,
    url: &str,
) -> Vec<Value> {
    let received = sqs(
        router,
        case,
        region,
        "ReceiveMessage",
        &json!({"QueueUrl": url, "MaxNumberOfMessages": 10, "WaitTimeSeconds": 0}),
    )
    .await;
    let messages = received["Messages"].as_array().cloned().unwrap_or_default();
    let mut envelopes = Vec::with_capacity(messages.len());
    for message in &messages {
        if let Some(handle) = message["ReceiptHandle"].as_str() {
            sqs(
                router,
                case,
                region,
                "DeleteMessage",
                &json!({"QueueUrl": url, "ReceiptHandle": handle}),
            )
            .await;
        }
        let raw = message["Body"].as_str().unwrap_or_default();
        envelopes.push(serde_json::from_str::<Value>(raw).unwrap_or(Value::Null));
    }
    envelopes
}

/// Look at `instance_id` until it reports `state`, so the call that acts on it next is made
/// then and not before.
async fn until_state(
    router: &MultiServiceRouter,
    case: &str,
    region: &str,
    instance_id: &str,
    state: &str,
) {
    let deadline = Instant::now() + DEADLINE;
    loop {
        let body = ec2(
            router,
            case,
            region,
            "DescribeInstances",
            &[("InstanceId.1", instance_id)],
        )
        .await;
        if elements(&body, "name").iter().any(|name| name == state) {
            return;
        }
        assert!(
            Instant::now() < deadline,
            "case {case:?}: {instance_id} must reach {state}, got {body}"
        );
        tokio::time::sleep(POLL).await;
    }
}

/// One envelope of the FORM Amazon EC2 publishes an instance state change as, written here so
/// a client can ask EventBridge whether its rule's pattern matches such an event at all
/// (`TestEventPattern`) before it provokes any instance activity.
fn sample_state_change(region: &str, state: &str) -> Value {
    json!({
        "version": "0",
        "id": "00000000-0000-0000-0000-000000000000",
        "detail-type": INSTANCE_STATE_CHANGE,
        "source": EC2_SOURCE,
        "account": "000000000000",
        "time": "2026-01-01T00:00:00Z",
        "region": region,
        "resources": [format!("arn:aws:ec2:{region}:000000000000:instance/i-0123456789abcdef0")],
        "detail": {"instance-id": "i-0123456789abcdef0", "state": state},
    })
}

/// RULE: the wiring a client wrote READS BACK as it wrote it, and the pattern it scoped a
/// state by is the one EventBridge judges an instance state change by — so a client can prove
/// its rule, its target and its pattern before it drives an instance anywhere.
#[tokio::test]
async fn a_state_scoped_rule_reads_back_and_judges_the_envelope_it_scopes() {
    let case = "the wiring a client reads back";
    let region = "us-east-2";
    let router = router();

    let name = "ec2-state-readback";
    let state = "stopping";
    let pattern = pattern_for(state, state, false);
    let url = rule_for(&router, case, region, name, state, state, false).await;
    let queue_arn = member(
        case,
        &sqs(
            &router,
            case,
            region,
            "GetQueueAttributes",
            &json!({"QueueUrl": &url, "AttributeNames": ["QueueArn"]}),
        )
        .await,
        "/Attributes/QueueArn",
    );

    // The rule itself, as a client reads it back.
    let described = events(
        &router,
        case,
        region,
        "DescribeRule",
        &json!({"Name": name, "EventBusName": DEFAULT_BUS}),
    )
    .await;
    assert_eq!(
        described["Name"],
        json!(name),
        "case {case:?}: the rule reports the name it was created under, got {described}"
    );
    assert_eq!(
        described["State"],
        json!("ENABLED"),
        "case {case:?}: the rule reports the state it was created in, got {described}"
    );
    assert_eq!(
        described["EventBusName"],
        json!(DEFAULT_BUS),
        "case {case:?}: the rule reports the bus it was created on, got {described}"
    );
    let read_back: Value = described["EventPattern"]
        .as_str()
        .and_then(|text| serde_json::from_str(text).ok())
        .unwrap_or(Value::Null);
    assert_eq!(
        read_back, pattern,
        "case {case:?}: the rule reports the pattern it was created with, got {described}"
    );

    // Its targets, as a client reads them back.
    let targets = events(
        &router,
        case,
        region,
        "ListTargetsByRule",
        &json!({"Rule": name, "EventBusName": DEFAULT_BUS}),
    )
    .await;
    assert_eq!(
        targets["Targets"],
        json!([{"Id": "sqs-target", "Arn": queue_arn}]),
        "case {case:?}: the rule reports the one target it was given, got {targets}"
    );

    // And the listing a client finds the rule in.
    let listed = events(
        &router,
        case,
        region,
        "ListRules",
        &json!({"NamePrefix": name, "EventBusName": DEFAULT_BUS}),
    )
    .await;
    let found = listed["Rules"]
        .as_array()
        .map(|rules| rules.iter().any(|rule| rule["Name"] == json!(name)))
        .unwrap_or_default();
    assert!(
        found,
        "case {case:?}: the rule is in the listing of its own name prefix, got {listed}"
    );

    // The pattern's own verdict on an envelope of the form Amazon EC2 publishes: the state it
    // scopes matches, and every other state of the catalog does not.
    for candidate in STATES {
        let answered = events(
            &router,
            case,
            region,
            "TestEventPattern",
            &json!({
                "EventPattern": pattern.to_string(),
                "Event": sample_state_change(region, candidate).to_string(),
            }),
        )
        .await;
        assert_eq!(
            answered["Result"],
            json!(candidate == state),
            "case {case:?}: a pattern scoped to {state} must judge a {candidate} envelope \
             {}, got {answered}",
            candidate == state
        );
    }
}

/// One row: the Region the whole leg is addressed in, whether the subnet NAMES its
/// Availability Zone or leaves the choice to the service, and the shape of the pattern each of
/// its rules carries.
struct Row {
    case: &'static str,
    /// The Region every call of this row is signed for.
    region: &'static str,
    /// The zone the row's subnet asks for, or `None` to let Amazon EC2 place it.
    zone: Option<&'static str>,
    /// The address block the row's VPC is created with, so two rows never collide.
    vpc_cidr: &'static str,
    /// The block its subnet takes out of that.
    subnet_cidr: &'static str,
    /// Whether this row's rules carry the barrier arm beside their state branch.
    with_barrier: bool,
}

/// THE RULE: each state an instance moves into reaches the rule scoped to that state, and no
/// other state's rule — in the Region the instance runs in, whichever shape the rule's pattern
/// takes.
#[tokio::test]
async fn each_state_an_instance_enters_reaches_the_rule_scoped_to_it() {
    let router = router();

    let rows = [
        Row {
            case: "a zone the request names, behind rules a barrier proves",
            region: "us-east-1",
            zone: Some("us-east-1a"),
            vpc_cidr: "10.90.0.0/16",
            subnet_cidr: "10.90.1.0/24",
            with_barrier: true,
        },
        Row {
            case: "another Region, a zone the service chooses, and bare state patterns",
            region: "eu-west-1",
            zone: None,
            vpc_cidr: "10.92.0.0/16",
            subnet_cidr: "10.92.1.0/24",
            with_barrier: false,
        },
    ];

    for row in &rows {
        let case = row.case;
        let region = row.region;

        // The network the instance is placed in, created through Amazon EC2 itself.
        let vpc = element(
            &ec2(
                &router,
                case,
                region,
                "CreateVpc",
                &[("CidrBlock", row.vpc_cidr)],
            )
            .await,
            "vpcId",
        );
        let mut subnet_params: Vec<(&str, &str)> =
            vec![("VpcId", &vpc), ("CidrBlock", row.subnet_cidr)];
        if let Some(zone) = row.zone {
            subnet_params.push(("AvailabilityZone", zone));
        }
        let subnet = element(
            &ec2(&router, case, region, "CreateSubnet", &subnet_params).await,
            "subnetId",
        );
        let group = element(
            &ec2(
                &router,
                case,
                region,
                "CreateSecurityGroup",
                &[
                    ("VpcId", &vpc),
                    ("GroupName", "ec2-state-changes"),
                    ("GroupDescription", "the instance under test"),
                ],
            )
            .await,
            "groupId",
        );

        // The image, resolved the way a client resolves it: the published parameter.
        let resolved = ssm(
            &router,
            case,
            region,
            "GetParameter",
            &json!({"Name": AL2023_PARAMETER}),
        )
        .await;
        let image = member(case, &resolved, "/Parameter/Value");

        // One rule and one queue per state.
        let mut urls: BTreeMap<&str, String> = BTreeMap::new();
        for state in STATES {
            let name = format!("ec2-state-{state}-{region}");
            let url = rule_for(
                &router,
                case,
                region,
                &name,
                state,
                state,
                row.with_barrier,
            )
            .await;
            urls.insert(state, url);
        }

        // Where the rules carry one, the barrier: a client's own event on each rule's own
        // branch, so a queue that receives no state change later is one whose pattern
        // withheld it rather than a rule that was never live.
        if row.with_barrier {
            for state in STATES {
                events(
                    &router,
                    case,
                    region,
                    "PutEvents",
                    &json!({"Entries": [{
                        "EventBusName": DEFAULT_BUS,
                        "Source": BARRIER_SOURCE,
                        "DetailType": BARRIER_DETAIL_TYPE,
                        "Detail": json!({"nonce": state}).to_string(),
                    }]}),
                )
                .await;
                let url = urls[state].clone();
                let deadline = Instant::now() + DEADLINE;
                loop {
                    let held = drain(&router, case, region, &url).await;
                    if held
                        .iter()
                        .any(|envelope| envelope["detail"]["nonce"] == json!(state))
                    {
                        break;
                    }
                    assert!(
                        Instant::now() < deadline,
                        "case {case:?}: the barrier event must reach the {state} rule's queue \
                         before the instance is launched, got {held:?}"
                    );
                    tokio::time::sleep(POLL).await;
                }
            }
        }

        // The instance, and the whole lifecycle a client drives it through: a launch, a stop,
        // a start and a termination — between them, every state of the table above.
        let launched = ec2(
            &router,
            case,
            region,
            "RunInstances",
            &[
                ("ImageId", &image),
                ("InstanceType", INSTANCE_TYPE),
                ("SubnetId", &subnet),
                ("SecurityGroupId.1", &group),
                ("MinCount", "1"),
                ("MaxCount", "1"),
            ],
        )
        .await;
        let instance = element(&launched, "instanceId");

        until_state(&router, case, region, &instance, "running").await;
        ec2(
            &router,
            case,
            region,
            "StopInstances",
            &[("InstanceId.1", &instance)],
        )
        .await;
        until_state(&router, case, region, &instance, "stopped").await;
        ec2(
            &router,
            case,
            region,
            "StartInstances",
            &[("InstanceId.1", &instance)],
        )
        .await;
        until_state(&router, case, region, &instance, "running").await;
        ec2(
            &router,
            case,
            region,
            "TerminateInstances",
            &[("InstanceId.1", &instance)],
        )
        .await;
        until_state(&router, case, region, &instance, "terminated").await;

        // What each state's rule received for THIS instance, filed as it arrives.
        let mut taken: BTreeMap<&str, Vec<Value>> = BTreeMap::new();
        let deadline = Instant::now() + DEADLINE;
        loop {
            for state in STATES {
                let url = urls[state].clone();
                for envelope in drain(&router, case, region, &url).await {
                    if envelope["detail-type"] == json!(INSTANCE_STATE_CHANGE)
                        && envelope["detail"]["instance-id"] == json!(&instance)
                    {
                        taken.entry(state).or_default().push(envelope);
                    }
                }
            }
            let missing: Vec<&str> = STATES
                .into_iter()
                .filter(|state| {
                    taken.get(state).is_none_or(|envelopes| {
                        !envelopes
                            .iter()
                            .any(|envelope| envelope["detail"]["state"] == json!(state))
                    })
                })
                .collect();
            if missing.is_empty() {
                break;
            }
            assert!(
                Instant::now() < deadline,
                "case {case:?}: every state of {instance} must reach its own rule's queue; \
                 {missing:?} never arrived, and what did arrive is {taken:?}"
            );
            tokio::time::sleep(POLL).await;
        }

        // And nothing else: a rule scoped to one state receives no other state's envelope,
        // over a run of reads, so one that arrives late still fails the leg.
        for read in 0..HELD_READS {
            for state in STATES {
                let url = urls[state].clone();
                for envelope in drain(&router, case, region, &url).await {
                    if envelope["detail-type"] == json!(INSTANCE_STATE_CHANGE)
                        && envelope["detail"]["instance-id"] == json!(&instance)
                    {
                        taken.entry(state).or_default().push(envelope);
                    }
                }
                let foreign: Vec<String> = taken
                    .get(state)
                    .map(|envelopes| {
                        envelopes
                            .iter()
                            .map(|envelope| {
                                envelope["detail"]["state"]
                                    .as_str()
                                    .unwrap_or_default()
                                    .to_string()
                            })
                            .filter(|got| got != state)
                            .collect()
                    })
                    .unwrap_or_default();
                assert!(
                    foreign.is_empty(),
                    "case {case:?}, read {read}: the rule scoped to {state} receives only that \
                     state's envelopes for {instance}, got {foreign:?}"
                );
            }
            tokio::time::sleep(POLL).await;
        }

        // Every envelope's own members, read off the instance and the Region the calls were
        // addressed in.
        for state in STATES {
            let envelopes = taken.get(state).cloned().unwrap_or_default();
            assert!(
                !envelopes.is_empty(),
                "case {case:?}: the {state} rule holds at least one envelope for {instance}"
            );
            for envelope in &envelopes {
                assert_eq!(
                    envelope["source"],
                    json!(EC2_SOURCE),
                    "case {case:?}: every state change carries the EC2 source, got {envelope}"
                );
                assert_eq!(
                    envelope["region"],
                    json!(region),
                    "case {case:?}: every state change is published in the instance's Region, \
                     got {envelope}"
                );
                let names_instance = envelope["resources"].as_array().is_some_and(|resources| {
                    resources.iter().any(|resource| {
                        resource.as_str().is_some_and(|arn| {
                            arn.ends_with(&format!("instance/{instance}"))
                                && arn.contains(&format!(":{region}:"))
                        })
                    })
                });
                assert!(
                    names_instance,
                    "case {case:?}: every state change names {instance} in its resources, under \
                     the Region it runs in, got {envelope}"
                );
            }
        }
    }
}
