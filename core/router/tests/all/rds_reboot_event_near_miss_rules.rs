//! The documented RDS -> EventBridge -> SQS near-miss routing scenario, end to end over the
//! whole assembled emulator.
//!
//! RULE: a lifecycle change Amazon RDS records for a DB instance is published once onto the
//! account's DEFAULT event bus in that instance's Region, and EventBridge delivers that one
//! envelope to the targets of EVERY rule whose pattern agrees with each field it pins and to
//! no rule that differs from the envelope in any one field — the pattern a rule is matched
//! by being the one it holds now, so a rule rewritten to the agreeing pattern is delivered
//! the next publication.
//!
//! Only a cross-service suite can pin this over the WHOLE mounted service set: the flow is
//! served by four services over one engine (EC2 for the network the DB subnet group is over,
//! Amazon RDS for the control plane that records and publishes the change, EventBridge for
//! the routing, Amazon SQS for what arrived), and three mounted models resolve to the `rds`
//! signing key and three more to `events`, so WHICH model claims the in-process publication
//! has to be the one a client's own call reaches.
//!
//! The rows span what the rule generalises over — WHICH ONE field of the agreeing pattern a
//! rule differs in: the event identifier inside `detail`, the source ARN inside `detail`, and
//! the `detail-type`. Each row's rule has its own queue, which must stay empty while the
//! agreeing rule's queue receives the publication, and must then receive the NEXT publication
//! once `PutRule` rewrites its pattern to the agreeing one — so a queue that was empty
//! because the emulator delivers nothing at all could not pass. The whole scenario is driven
//! twice over, on a router that VERIFIES every request's signature (the configuration the
//! emulator serves traffic in, so the one the in-process publication has to be accepted on)
//! and on one that does not.
//!
//! Every step of the scenario must also CONVERGE: the catalog reads, the network, the DB
//! instance's progression to `available`, the reboot's return to `available` and each
//! delivery are waited for by polling for the condition, under one generous deadline each.
//! [`crate::rds_reboot_event_near_miss_on_a_started_emulator`] drives the same scenario
//! against the started binary over TLS.
//!
//! Assembling the whole router costs stack (see `boot_serve.rs`), so it is built — and the
//! requests driven — on an explicitly sized thread.

use std::collections::BTreeSet;
use std::sync::Arc;
use std::time::{Duration, Instant};

use aws_emulator_router::{build_router, InMemoryEngine};
use bytes::Bytes;
use serde_json::{json, Value};
use smithy_server_runtime::MultiServiceRouter;

use super::query_wire::{element, elements, form_encode, opt_element};

/// Keep this at or above `boot_serve.rs`'s stack: the same assembly runs here.
const BOOT_STACK_SIZE: usize = 64 * 1024 * 1024;

/// The Region every call below is signed for and addressed in.
const REGION: &str = "us-west-2";

/// The account id every generated emulator presents, which the ARNs a pattern pins carry.
const ACCOUNT: &str = "000000000000";

/// The `source` and `detail-type` Amazon RDS publishes a DB instance change under, and the
/// detail-type of another RDS source type a near-miss row pins instead. Spelled out here
/// rather than imported from the service crate, so a wrong constant in the implementation
/// cannot make this suite pass. Source: Amazon RDS publishes `aws.rds` events, one
/// detail-type per event source type, spelled `RDS <the source type, in words> Event`.
const EVENT_SOURCE: &str = "aws.rds";
const DB_INSTANCE_EVENT: &str = "RDS DB Instance Event";
const DB_SNAPSHOT_EVENT: &str = "RDS DB Snapshot Event";

/// `detail.EventID` of the change a reboot records, and of ANOTHER change of the same source
/// type (the stop of a DB instance) a near-miss row pins instead.
///
/// Source: the per-source-type tables of "Amazon RDS event categories and event messages"
/// (Amazon RDS User Guide) — the DB instance rows whose messages are `DB instance restarted`
/// and `DB instance stopped`.
const RESTART_EVENT_ID: &str = "RDS-EVENT-0006";
const STOP_EVENT_ID: &str = "RDS-EVENT-0087";

/// The bus an Amazon Web Services service's own events go to: "events generated by Amazon
/// Web Services services go to your account's default event bus".
const DEFAULT_BUS: &str = "default";

/// The service principal EventBridge delivers to an SQS target as, which is what the queue's
/// resource policy admits ("for Amazon SQS queues, EventBridge relies on resource-based
/// policies").
const EVENTS_PRINCIPAL: &str = "events.amazonaws.com";

/// The DB instance the scenario provisions, reboots and writes every pattern for.
const INSTANCE: &str = "emu-near-miss-db";

/// An identifier the account holds no DB instance for, so a row can pin an ARN that resolves
/// to nothing.
const ABSENT_INSTANCE: &str = "emu-near-miss-absent";

/// The engine and class the scenario orders, and the storage it asks for.
const ENGINE: &str = "postgres";
const INSTANCE_CLASS: &str = "db.t4g.micro";
const ALLOCATED_STORAGE: &str = "20";

/// How long any one condition the scenario waits for is given: far above the span this
/// emulator's own transitions and in-process deliveries take, so a loaded machine delays the
/// suite instead of breaking it.
const DEADLINE: Duration = Duration::from_secs(60);

/// The gap between two reads of the same poll loop.
const POLL_INTERVAL: Duration = Duration::from_millis(50);

/// How many pages of a paginated catalog read the suite walks before calling the pagination
/// non-terminating: far more than a filtered catalog holds.
const MAX_PAGES: usize = 50;

/// What one call answered.
struct Answer {
    status: u16,
    body: String,
}

impl Answer {
    /// Assert the call was served, and hand back its body.
    fn served(self, case: &str) -> String {
        assert_eq!(
            self.status, 200,
            "case {case:?}: the call must be served, got HTTP {} with {}",
            self.status, self.body
        );
        self.body
    }

    /// Assert the call was served and read its body as JSON.
    fn json(self, case: &str) -> Value {
        let body = self.served(case);
        serde_json::from_str(&body)
            .unwrap_or_else(|error| panic!("case {case:?}: {body} must be JSON: {error}"))
    }
}

/// The whole emulator over one engine, and the runtime every call is driven on.
struct Emulator {
    router: MultiServiceRouter,
    runtime: tokio::runtime::Runtime,
    /// The key pair every call signs with on a router that VERIFIES signatures, or `None`
    /// on one that does not.
    credentials: Option<(String, String)>,
}

impl Emulator {
    /// The whole emulator, with request authentication as `authenticated` says.
    fn build(authenticated: bool) -> Self {
        let engine: Arc<InMemoryEngine> = Arc::new(InMemoryEngine::new());
        let mut router = build_router(engine);
        router.set_request_authentication(authenticated);
        let credentials = authenticated.then(|| {
            let published = ::emulator_server::SigV4Authenticator::minted_credentials()
                .expect("turning authentication on publishes this process's keys");
            (
                published.access_key_id.clone(),
                published.secret_access_key.clone(),
            )
        });
        // `enable_all`, which is what the emulator's own boot path builds: a DB instance
        // create opens the instance's engine listener through the core, and binding a socket
        // needs the runtime's I/O driver.
        let runtime = tokio::runtime::Builder::new_current_thread()
            .enable_all()
            .build()
            .expect("a current-thread runtime");
        Self {
            router,
            runtime,
            credentials,
        }
    }

    /// One call of `method` to the service `signing_name` at `path`, with `body`.
    fn dispatch(
        &self,
        signing_name: &str,
        method: &str,
        path: &str,
        headers: &[(&str, &str)],
        body: String,
    ) -> Answer {
        let host = format!("{signing_name}.{REGION}.amazonaws.com");
        let mut builder = ::http::Request::builder()
            .method(method)
            .uri(format!("https://{host}{path}"))
            .header("host", host);
        for (name, value) in headers {
            builder = builder.header(*name, *value);
        }
        let request = match &self.credentials {
            // The credential this process publishes once authentication is on: the router
            // verifies the signature, as it does for the traffic the emulator serves.
            Some((key_id, secret)) => {
                let built = builder
                    .body(body.into_bytes())
                    .expect("a well-formed request");
                let signed = sign_request(built, key_id, secret, signing_name);
                let (parts, payload) = signed.into_parts();
                ::http::Request::from_parts(parts, Bytes::from(payload))
            }
            // No signature is checked; what the scope carries is the Region and the service
            // a handler reads.
            None => builder
                .header(
                    "authorization",
                    format!(
                        "AWS4-HMAC-SHA256 \
                         Credential=AKIDEXAMPLE/20260101/{REGION}/{signing_name}/aws4_request, \
                         SignedHeaders=host, Signature=not-verified"
                    ),
                )
                .body(Bytes::from(body))
                .expect("a well-formed request"),
        };
        let response = self.runtime.block_on(self.router.dispatch(request));
        let (parts, body) = response.into_parts();
        Answer {
            status: parts.status.as_u16(),
            body: String::from_utf8_lossy(&body).to_string(),
        }
    }

    /// One awsQuery (or ec2Query) call, as an SDK client sends one.
    fn query(
        &self,
        signing_name: &str,
        version: &str,
        action: &str,
        params: &[(&str, String)],
    ) -> Answer {
        let mut body = format!("Action={action}&Version={version}");
        for (name, value) in params {
            body.push('&');
            body.push_str(name);
            body.push('=');
            body.push_str(&form_encode(value));
        }
        self.dispatch(
            signing_name,
            "POST",
            "/",
            &[("content-type", "application/x-www-form-urlencoded")],
            body,
        )
    }

    /// One Amazon RDS call.
    fn rds(&self, action: &str, params: &[(&str, String)]) -> String {
        self.query("rds", "2014-10-31", action, params)
            .served(action)
    }

    /// One Amazon EC2 call.
    fn ec2(&self, action: &str, params: &[(&str, String)]) -> String {
        self.query("ec2", "2016-11-15", action, params)
            .served(action)
    }

    /// One `X-Amz-Target` RPC call.
    fn rpc(
        &self,
        signing_name: &str,
        target_prefix: &str,
        json_version: &str,
        operation: &str,
        body: &Value,
    ) -> Value {
        self.dispatch(
            signing_name,
            "POST",
            "/",
            &[
                (
                    "content-type",
                    &format!("application/x-amz-json-{json_version}"),
                ),
                ("x-amz-target", &format!("{target_prefix}.{operation}")),
            ],
            body.to_string(),
        )
        .json(operation)
    }

    /// One EventBridge call.
    fn events(&self, operation: &str, body: &Value) -> Value {
        self.rpc("events", "AWSEvents", "1.1", operation, body)
    }
    /// One gap of a poll loop, awaited INSIDE the runtime so the timer has its driver.
    fn pause(&self) {
        self.runtime
            .block_on(async { tokio::time::sleep(POLL_INTERVAL).await });
    }

    /// One Amazon SQS call.
    fn sqs(&self, operation: &str, body: &Value) -> Value {
        self.rpc("sqs", "AmazonSQS", "1.0", operation, body)
    }
}

/// Sign `request` for `signing_name` in [`REGION`], in the `Authorization` header an SDK
/// request carries.
fn sign_request(
    mut request: ::http::Request<Vec<u8>>,
    key_id: &str,
    secret: &str,
    signing_name: &str,
) -> ::http::Request<Vec<u8>> {
    let identity =
        ::aws_credential_types::Credentials::new(key_id, secret, None, None, "test").into();
    let params = ::aws_sigv4::sign::v4::SigningParams::builder()
        .identity(&identity)
        .region(REGION)
        .name(signing_name)
        .time(::std::time::SystemTime::now())
        .settings(::aws_sigv4::http_request::SigningSettings::default())
        .build()
        .expect("the signing parameters are complete")
        .into();
    let (method, uri) = (request.method().to_string(), request.uri().to_string());
    let headers: Vec<(String, String)> = request
        .headers()
        .iter()
        .map(|(name, value)| {
            (
                name.as_str().to_string(),
                value.to_str().expect("a text header").to_string(),
            )
        })
        .collect();
    let signable = ::aws_sigv4::http_request::SignableRequest::new(
        &method,
        &uri,
        headers
            .iter()
            .map(|(name, value)| (name.as_str(), value.as_str())),
        ::aws_sigv4::http_request::SignableBody::Bytes(request.body()),
    )
    .expect("the request is signable");
    let (instructions, _) = ::aws_sigv4::http_request::sign(signable, &params)
        .expect("the request signs")
        .into_parts();
    instructions.apply_to_request_http1x(&mut request);
    request
}

/// `[(name, value.to_string()), ..]` — the parameters of one call.
macro_rules! params {
    ($($name:expr => $value:expr),* $(,)?) => {
        [$(($name, $value.to_string())),*]
    };
}

/// A string member of a JSON answer, or a panic naming the case and what came back.
fn member(case: &str, body: &Value, pointer: &str) -> String {
    body.pointer(pointer)
        .and_then(Value::as_str)
        .unwrap_or_else(|| panic!("case {case:?}: expected {pointer} in {body}"))
        .to_string()
}

/// The ARN Amazon RDS gives the DB instance `identifier` of this account and Region.
fn instance_arn(identifier: &str) -> String {
    format!("arn:aws:rds:{REGION}:{ACCOUNT}:db:{identifier}")
}

/// The pattern that agrees with the restart of the instance at `arn` in every field it pins.
fn agreeing_pattern(arn: &str) -> Value {
    json!({
        "source": [EVENT_SOURCE],
        "detail-type": [DB_INSTANCE_EVENT],
        "detail": { "EventID": [RESTART_EVENT_ID], "SourceArn": [arn] },
    })
}

/// One rule whose pattern is the agreeing one with a single field changed.
struct NearMiss {
    /// What this row changes, for the assertion messages.
    case: &'static str,
    /// The name of this row's rule and of the queue it targets.
    slug: &'static str,
    /// The pattern itself, over the rebooted instance's own ARN.
    pattern: fn(&str) -> Value,
}

/// The table: one row per field of the agreeing pattern, each differing in that field alone.
const NEAR_MISSES: &[NearMiss] = &[
    NearMiss {
        case: "another event identifier of the same source type",
        slug: "emu-near-miss-event-id",
        pattern: |arn| {
            json!({
                "source": [EVENT_SOURCE],
                "detail-type": [DB_INSTANCE_EVENT],
                "detail": { "EventID": [STOP_EVENT_ID], "SourceArn": [arn] },
            })
        },
    },
    NearMiss {
        case: "the source ARN of an instance the account holds no record of",
        slug: "emu-near-miss-source-arn",
        pattern: |_| agreeing_pattern(&instance_arn(ABSENT_INSTANCE)),
    },
    NearMiss {
        case: "the detail-type of another RDS source type",
        slug: "emu-near-miss-detail-type",
        pattern: |arn| {
            json!({
                "source": [EVENT_SOURCE],
                "detail-type": [DB_SNAPSHOT_EVENT],
                "detail": { "EventID": [RESTART_EVENT_ID], "SourceArn": [arn] },
            })
        },
    },
];

/// The queue `name`, created through Amazon SQS, admitting EventBridge's send on behalf of
/// the rule `rule_arn`; answers its URL.
fn queue_for_rule(emulator: &Emulator, name: &str, rule_arn: &str) -> String {
    let created = emulator.sqs("CreateQueue", &json!({ "QueueName": name }));
    let url = member(name, &created, "/QueueUrl");
    let attributes = emulator.sqs(
        "GetQueueAttributes",
        &json!({ "QueueUrl": &url, "AttributeNames": ["QueueArn"] }),
    );
    let queue_arn = member(name, &attributes, "/Attributes/QueueArn");
    let document = json!({
        "Version": "2012-10-17",
        "Statement": [{
            "Effect": "Allow",
            "Principal": { "Service": EVENTS_PRINCIPAL },
            "Action": "sqs:SendMessage",
            "Resource": queue_arn,
            "Condition": { "ArnEquals": { "aws:SourceArn": rule_arn } },
        }],
    });
    emulator.sqs(
        "SetQueueAttributes",
        &json!({
            "QueueUrl": &url,
            "Attributes": { "Policy": document.to_string() },
        }),
    );
    let targeted = emulator.events(
        "PutTargets",
        &json!({
            "Rule": name,
            "EventBusName": DEFAULT_BUS,
            "Targets": [{ "Id": "the-queue", "Arn": queue_arn }],
        }),
    );
    assert_eq!(
        targeted["FailedEntryCount"].as_i64(),
        Some(0),
        "case {name:?}: the queue target must be accepted, got {targeted}"
    );
    url
}

/// Put the ENABLED rule `name` on the default bus with `pattern`; answers its ARN.
fn put_rule(emulator: &Emulator, name: &str, pattern: &Value) -> String {
    let put = emulator.events(
        "PutRule",
        &json!({
            "Name": name,
            "EventBusName": DEFAULT_BUS,
            "EventPattern": pattern.to_string(),
            "State": "ENABLED",
        }),
    );
    member(name, &put, "/RuleArn")
}

/// Every envelope now waiting on the queue at `url`.
fn drain(emulator: &Emulator, url: &str) -> Vec<Value> {
    let received = emulator.sqs(
        "ReceiveMessage",
        &json!({ "QueueUrl": url, "MaxNumberOfMessages": 10 }),
    );
    received["Messages"]
        .as_array()
        .cloned()
        .unwrap_or_default()
        .iter()
        .map(|message| {
            let raw = message["Body"].as_str().unwrap_or_default();
            serde_json::from_str::<Value>(raw).unwrap_or(Value::Null)
        })
        .collect()
}

/// Collect envelopes off the queue at `url` until `wanted` have arrived or [`DEADLINE`]
/// passes; answers everything that did arrive.
fn collect(emulator: &Emulator, case: &str, url: &str, wanted: usize) -> Vec<Value> {
    let started = Instant::now();
    let mut arrived: Vec<Value> = Vec::new();
    while arrived.len() < wanted && started.elapsed() < DEADLINE {
        arrived.extend(drain(emulator, url));
        if arrived.len() < wanted {
            emulator.pause();
        }
    }
    assert!(
        arrived.len() >= wanted,
        "case {case:?}: expected {wanted} envelope(s) on the queue, got {arrived:?}"
    );
    arrived
}

/// Poll `DescribeDBInstances` until the instance reports `status`, or [`DEADLINE`] passes.
fn wait_for_status(emulator: &Emulator, case: &str, identifier: &str, status: &str) {
    let started = Instant::now();
    let mut seen = String::new();
    while started.elapsed() < DEADLINE {
        let described = emulator.rds(
            "DescribeDBInstances",
            &params!["DBInstanceIdentifier" => identifier],
        );
        seen = element(&described, "DBInstanceStatus");
        if seen == status {
            return;
        }
        emulator.pause();
    }
    panic!("case {case:?}: expected the instance to report {status:?}, last saw {seen:?}");
}

/// The default engine version of [`ENGINE`], read off the service's own catalog.
fn default_engine_version(emulator: &Emulator) -> String {
    let described = emulator.rds(
        "DescribeDBEngineVersions",
        &params!["Engine" => ENGINE, "DefaultOnly" => "true"],
    );
    element(&described, "EngineVersion")
}

/// Every Availability Zone the orderable-options catalog offers [`ENGINE`] /
/// [`INSTANCE_CLASS`] in, walked over EVERY page the catalog pages the answer into.
fn orderable_zones(emulator: &Emulator, version: &str) -> BTreeSet<String> {
    let mut zones = BTreeSet::new();
    let mut marker: Option<String> = None;
    for page in 0..MAX_PAGES {
        let mut request = params![
            "Engine" => ENGINE,
            "EngineVersion" => version,
            "DBInstanceClass" => INSTANCE_CLASS,
        ]
        .to_vec();
        if let Some(token) = &marker {
            request.push(("Marker", token.clone()));
        }
        let described = emulator.rds("DescribeOrderableDBInstanceOptions", &request);
        // `AvailabilityZone$Name` is the only `Name` an orderable option carries, so every
        // one of them in the page is a zone the option is offered in.
        zones.extend(elements(&described, "Name"));
        marker = opt_element(&described, "Marker");
        if marker.is_none() {
            return zones;
        }
        assert!(
            page + 1 < MAX_PAGES,
            "the orderable-options catalog must page to an end, still paging after \
             {MAX_PAGES} pages"
        );
    }
    zones
}

/// RULE: one published DB instance change is delivered to every rule whose pattern agrees
/// with each field it pins and to no rule differing in any one field — and to a rule whose
/// pattern is REWRITTEN to the agreeing one, on the next publication.
///
/// The rows are the two router configurations: one that verifies every request's signature,
/// which is how the emulator serves traffic and so the one the in-process publication has to
/// be accepted on, and one that does not.
#[test]
fn a_reboot_reaches_the_agreeing_rule_and_only_a_repointed_near_miss() {
    for authenticated in [true, false] {
        std::thread::Builder::new()
            .name("rds-near-miss-routing".to_string())
            .stack_size(BOOT_STACK_SIZE)
            .spawn(move || scenario(authenticated))
            .expect("the scenario thread starts")
            .join()
            .unwrap_or_else(|_| {
                panic!("case \"request authentication {authenticated}\": the scenario fails")
            });
    }
}

fn scenario(authenticated: bool) {
    let emulator = Emulator::build(authenticated);

    // ---- the catalogs a client orders from, each of which has to converge ----
    let version = default_engine_version(&emulator);
    let zones = orderable_zones(&emulator, &version);
    let described = emulator.ec2("DescribeAvailabilityZones", &params![]);
    let states = elements(&described, "zoneState");
    assert!(
        !states.is_empty() && states.iter().all(|state| state == "available"),
        "every zone of the Region is reported available, got {states:?} in {described}"
    );
    let available: Vec<String> = elements(&described, "zoneName")
        .into_iter()
        .filter(|zone| zones.contains(zone))
        .collect();
    assert!(
        available.len() >= 2,
        "the orderable catalog and EC2 must agree on at least two available zones, got \
         {available:?} out of {zones:?} and {described}"
    );

    // ---- the network the DB subnet group is over ----
    let vpc = emulator.ec2("CreateVpc", &params!["CidrBlock" => "10.71.0.0/16"]);
    let vpc_id = element(&vpc, "vpcId");
    let mut subnets = Vec::new();
    for (index, zone) in available.iter().take(2).enumerate() {
        let subnet = emulator.ec2(
            "CreateSubnet",
            &params![
                "VpcId" => vpc_id,
                "CidrBlock" => format!("10.71.{index}.0/24"),
                "AvailabilityZone" => zone,
            ],
        );
        subnets.push(element(&subnet, "subnetId"));
    }
    emulator.rds(
        "CreateDBSubnetGroup",
        &params![
            "DBSubnetGroupName" => "emu-near-miss-subnets",
            "DBSubnetGroupDescription" => "the near-miss scenario's subnets",
            "SubnetIds.SubnetIdentifier.1" => subnets[0],
            "SubnetIds.SubnetIdentifier.2" => subnets[1],
        ],
    );

    // ---- the DB instance, polled to the status the next step waits for ----
    let created = emulator.rds(
        "CreateDBInstance",
        &params![
            "DBInstanceIdentifier" => INSTANCE,
            "Engine" => ENGINE,
            "DBInstanceClass" => INSTANCE_CLASS,
            "AllocatedStorage" => ALLOCATED_STORAGE,
            "DBSubnetGroupName" => "emu-near-miss-subnets",
        ],
    );
    let arn = element(&created, "DBInstanceArn");
    assert_eq!(
        arn,
        instance_arn(INSTANCE),
        "the instance's ARN is the one a client writes its rule patterns over"
    );
    wait_for_status(&emulator, "the created instance", INSTANCE, "available");

    // ---- the agreeing rule and the near-miss rules, each with its own queue ----
    let agreeing_rule = put_rule(&emulator, "emu-near-miss-agreeing", &agreeing_pattern(&arn));
    let agreeing_queue = queue_for_rule(&emulator, "emu-near-miss-agreeing", &agreeing_rule);
    let near: Vec<(&NearMiss, String)> = NEAR_MISSES
        .iter()
        .map(|row| {
            let rule = put_rule(&emulator, row.slug, &(row.pattern)(&arn));
            let url = queue_for_rule(&emulator, row.slug, &rule);
            (row, url)
        })
        .collect();

    // ---- the reboot, which records and publishes the restart ----
    emulator.rds(
        "RebootDBInstance",
        &params!["DBInstanceIdentifier" => INSTANCE],
    );

    // The agreeing rule's queue is the positive control AND the witness for the rows below:
    // ONE publication is matched against every rule of the bus, so once it has arrived here
    // every other rule has been decided against the same event.
    let delivered = collect(&emulator, "the agreeing pattern", &agreeing_queue, 1);
    assert_eq!(
        delivered.len(),
        1,
        "the agreeing rule receives the restart exactly once, got {delivered:?}"
    );
    let first_date = assert_restart_of("the agreeing pattern", &delivered[0], &arn);

    for (row, url) in &near {
        assert_holds_nothing(&emulator, row.case, url);
    }

    // ---- the repair: each near-miss rule repointed at the agreeing pattern ----
    wait_for_status(&emulator, "the rebooted instance", INSTANCE, "available");
    for (row, _) in &near {
        put_rule(&emulator, row.slug, &agreeing_pattern(&arn));
        // The rewrite leaves the rule's own target in place: it is the SAME rule and the
        // same queue that was silent above.
        let targets = emulator.events("ListTargetsByRule", &json!({ "Rule": row.slug }));
        assert_eq!(
            targets["Targets"]
                .as_array()
                .map(|targets| targets.len())
                .unwrap_or_default(),
            1,
            "case {:?}: the rewritten rule keeps its target, got {targets}",
            row.case
        );
    }
    emulator.rds(
        "RebootDBInstance",
        &params!["DBInstanceIdentifier" => INSTANCE],
    );
    for (row, url) in &near {
        let delivered = collect(&emulator, row.case, url, 1);
        let dated = assert_restart_of(row.case, &delivered[0], &arn);
        // The envelope a repointed rule receives is the SECOND restart's own record, dated
        // when that restart happened: a publication is rendered from the record the change
        // was written into, so a consumer filtering on `detail.Date` sees each restart as
        // its own event rather than the first one again.
        assert_ne!(
            dated, first_date,
            "case {:?}: expected the second restart's own date, got the first one \
             ({first_date:?}) in {:?}",
            row.case, delivered[0]
        );
    }
}

/// Assert `envelope` is the envelope of the restart of the instance at `arn`, and answer the
/// `detail.Date` it carries.
fn assert_restart_of(case: &str, envelope: &Value, arn: &str) -> String {
    for (pointer, expected) in [
        ("/source", json!(EVENT_SOURCE)),
        ("/detail-type", json!(DB_INSTANCE_EVENT)),
        ("/account", json!(ACCOUNT)),
        ("/region", json!(REGION)),
        ("/resources", json!([arn])),
        ("/detail/EventID", json!(RESTART_EVENT_ID)),
        ("/detail/SourceArn", json!(arn)),
    ] {
        let actual = envelope.pointer(pointer).cloned().unwrap_or(Value::Null);
        assert_eq!(
            actual, expected,
            "case {case:?}: expected {pointer} to be {expected}, got {actual} in {envelope}"
        );
    }
    let dated = envelope
        .pointer("/detail/Date")
        .and_then(Value::as_str)
        .unwrap_or_default()
        .to_string();
    assert!(
        dated.ends_with('Z') && dated.contains('T'),
        "case {case:?}: expected the detail to state when the change happened, got \
         {dated:?} in {envelope}"
    );
    dated
}

/// Assert the queue holds nothing: both depth attributes report zero, and a read of it hands
/// over no message at all.
fn assert_holds_nothing(emulator: &Emulator, case: &str, url: &str) {
    let reported = emulator.sqs(
        "GetQueueAttributes",
        &json!({
            "QueueUrl": url,
            "AttributeNames": [
                "ApproximateNumberOfMessages",
                "ApproximateNumberOfMessagesNotVisible",
            ],
        }),
    );
    for attribute in [
        "ApproximateNumberOfMessages",
        "ApproximateNumberOfMessagesNotVisible",
    ] {
        assert_eq!(
            reported["Attributes"][attribute],
            json!("0"),
            "case {case:?}: expected {attribute} \"0\", got {reported}"
        );
    }
    let held = drain(emulator, url);
    assert!(
        held.is_empty(),
        "case {case:?}: expected no message on the queue, got {held:?}"
    );
}
