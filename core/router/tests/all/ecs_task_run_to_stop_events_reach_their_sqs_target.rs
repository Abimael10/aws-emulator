//! A standalone Amazon ECS task's WHOLE unattended run reaches the Amazon SQS target of the
//! EventBridge rule that matches it.
//!
//! The RULE under test: **every status a task moves into is published once onto the account's
//! default EventBridge bus as `source` `aws.ecs` / `detail-type` `ECS Task State Change`,
//! stamped in the envelope's `time` with the instant of that move, naming the task in
//! `resources` and carrying in `detail` the task Amazon ECS holds at that instant — at least
//! its `taskArn`, the `clusterArn` of the cluster it runs in, the `lastStatus` it moved into
//! and the `desiredStatus` it is heading for; so a rule whose `EventPattern` names that
//! source, that detail type and that cluster delivers a task placed by `RunTask` its whole
//! run — a `RUNNING` envelope and a later `STOPPED` one, the `STOPPED` one `desiredStatus`
//! `STOPPED` because the work the task was placed to do is over — in chronological order by
//! `time`, with NO further call to Amazon ECS, while a rule that cannot match the cluster
//! receives none of them; and `DescribeTasks` afterwards reports the task that last envelope
//! reported.**
//!
//! Sources: `smithy_query(query="operation", operation="RunTask,DescribeTasks")` for the task
//! projection an event's `detail` is read off (`taskArn`, `clusterArn`, `taskDefinitionArn`,
//! `lastStatus`, `desiredStatus`, `stopCode`, `stoppedReason`) and for `RunTask$count`, and
//! `smithy_query(query="shape", shape="PutEventsRequestEntry")` for the envelope members a
//! publication fills (`Source`, `DetailType`, `Time`, `Resources`, `Detail`).
//!
//! This suite lives here because the path is cross-service: Amazon ECS publishes through the
//! in-process callback, EventBridge routes the envelope by its CONTENT, and Amazon SQS holds
//! what arrived — so what is asserted is what each of the three services persisted, and
//! nothing reads the publisher's own queue.
//!
//! The rows differ along what the rule generalises over: the launch type and network mode the
//! task was placed with — a Fargate task allocated its own elastic network interface in a
//! subnet with a public address against a task sharing its host's networking, and so WHICH
//! statuses it passes through on the way — what its essential container runs (a program that
//! waits, a program that ends at once, and no program of its own at all), and how many tasks
//! ONE call placed, since each placed task has a run of its own to report.
//!
//! Every wait below looks again for the CONDITION it is waiting on until a generous deadline
//! passes, so a loaded machine polls more often instead of failing.

use std::sync::Arc;
use std::time::{Duration, Instant};

use bytes::Bytes;
use serde_json::{json, Value};
use smithy_server_runtime::MultiServiceRouter;

/// The Region every request below is signed for, and so the Region of every ARN minted for
/// them.
const REGION: &str = "us-west-2";

/// The account every emulator ARN carries, which a container-instance registration's identity
/// document has to name.
const ACCOUNT: &str = engine::EMULATOR_ACCOUNT_ID;

/// The `source` and `detail-type` Amazon ECS publishes a task's state changes under, spelled
/// out here rather than imported from the service crate, so a wrong constant in the
/// implementation cannot make this suite pass.
const EVENT_SOURCE: &str = "aws.ecs";
const TASK_STATE_CHANGE: &str = "ECS Task State Change";

/// The two statuses of a whole run this suite asserts on, and the `desiredStatus` each of them
/// carries. Source: `smithy_query(query="operation", operation="DescribeTasks")` for
/// `Task$lastStatus`/`Task$desiredStatus`.
const RUNNING: &str = "RUNNING";
const STOPPED: &str = "STOPPED";

/// The bus an Amazon Web Services service's own events go to: "events generated by Amazon Web
/// Services services go to your account's default event bus".
const DEFAULT_BUS: &str = "default";

/// The service principal EventBridge delivers to an SQS target as, which is what the target
/// queue's own resource policy admits ("for Amazon SQS queues, EventBridge relies on
/// resource-based policies").
const EVENTS_PRINCIPAL: &str = "events.amazonaws.com";

/// The `X-Amz-Target` prefix of the Amazon ECS model, whose `sigv4Name` is `ecs`; it speaks
/// awsJson1.1.
const ECS_TARGET_PREFIX: &str = "AmazonEC2ContainerServiceV20141113";

/// The cluster every task below runs in, and the cluster the rule that cannot match names.
const CLUSTER: &str = "taskrunevents";
const OTHER_CLUSTER: &str = "elsewhere";

/// The container instance the EC2 row's task is placed on: "The EC2 launch type runs your
/// tasks on Amazon EC2 instances registered to your cluster."
const CAPACITY_INSTANCE: &str = "i-0c0ffee0c0ffee0c0";

/// The network a Fargate row's task is placed in. The ids are fixed, because the requests and
/// the records have to name the same ones, so they are written into the account's Amazon EC2
/// records rather than minted ([`crate::ec2_network`]).
const VPC: &str = "vpc-0ec50000000000001";
const SUBNET: &str = "subnet-0ec50000000000001";

/// The security group a Fargate placement names beside its subnet. Nothing resolves it — what
/// a row is about is the run, not the group — so one value does.
const SECURITY_GROUP: &str = "sg-0ec50000000000001";

/// The image every container names. Nothing here is about the registry, so one value does; the
/// VPC the tasks are placed in has a route to it ([`crate::ec2_network::register_internet_route`])
/// and the Fargate placements take a public address, so the fetch is reachable. An image this
/// emulator holds no program for, so a task of it runs through to `STOPPED` on its own, which
/// is the whole run a row below follows: an image whose own command is a server in the
/// foreground would hold such a task `RUNNING`
/// (`container_servers::image_declared_command`).
const IMAGE: &str = "public.ecr.aws/amazonlinux/amazonlinux:2023";

/// How often a poll re-reads a target queue.
const POLL_INTERVAL: Duration = Duration::from_millis(50);

/// How long a poll keeps trying before it gives up. Generous: a task crosses its launch steps,
/// its start and then the end of the work it was placed to do, and each poll stops the instant
/// its own condition holds — so the budget costs nothing when the envelopes arrive and a loaded
/// machine only polls more often.
const POLL_BUDGET: Duration = Duration::from_secs(90);

/// How long a row waits before reading both queues one last time: long enough that a delivery
/// which was going to happen would have — so a late duplicate counts against the once-only
/// assertions, and a rule that cannot match has had its chance to receive something.
const QUIET_STRETCH: Duration = Duration::from_secs(2);

/// Amazon ECS, EventBridge and Amazon SQS over ONE shared engine — the three services a
/// published task event travels through, mounted the way the production router mounts them —
/// with the network the Fargate rows place into in the account's Amazon EC2 records.
fn emulator() -> MultiServiceRouter {
    let engine: Arc<engine::InMemoryEngine> = Arc::new(engine::InMemoryEngine::new());
    crate::ec2_network::register_network(&engine, VPC, &[SUBNET], &format!("{REGION}a"));
    crate::ec2_network::register_internet_route(&engine, VPC);
    let mut router = MultiServiceRouter::new();
    router.set_request_authentication(false);
    router.register_service(
        service_com_amazonaws_ecs_amazonec2containerservicev20141113::EmulatedService::new(
            Arc::clone(&engine),
        ),
    );
    router.register_service(
        service_com_amazonaws_eventbridge_awsevents::EmulatedService::new(Arc::clone(&engine)),
    );
    router.register_service(service_com_amazonaws_sqs_amazonsqs::EmulatedService::new(
        engine,
    ));
    router
}

/// A SigV4 `Authorization` whose credential scope names `signing_name`, which is what routes
/// the request. The signature is never checked: the router above runs with request
/// authentication off.
fn authorization(signing_name: &str) -> String {
    format!(
        "AWS4-HMAC-SHA256 Credential=AKIDEXAMPLE/20260101/{REGION}/{signing_name}\
         /aws4_request, SignedHeaders=host, Signature=0000"
    )
}

/// One `X-Amz-Target` RPC call, answered with its HTTP status and parsed body.
async fn json_call(
    router: &MultiServiceRouter,
    signing_name: &str,
    target: &str,
    json_version: &str,
    body: &Value,
) -> (u16, Value) {
    let request = http::Request::builder()
        .method("POST")
        .uri("/")
        .header("host", format!("{signing_name}.{REGION}.amazonaws.com"))
        .header(
            "content-type",
            format!("application/x-amz-json-{json_version}"),
        )
        .header("x-amz-target", target)
        .header("authorization", authorization(signing_name))
        .body(Bytes::from(body.to_string()))
        .expect("a well-formed request");
    let response = router.dispatch(request).await;
    let status = response.status().as_u16();
    let payload = response.into_body();
    let parsed: Value = if payload.is_empty() {
        json!({})
    } else {
        serde_json::from_slice(&payload)
            .unwrap_or_else(|_| json!({ "unparsed": String::from_utf8_lossy(&payload) }))
    };
    (status, parsed)
}

/// One Amazon ECS call that must succeed, answered with its body.
async fn ecs(router: &MultiServiceRouter, case: &str, operation: &str, body: &Value) -> Value {
    let target = format!("{ECS_TARGET_PREFIX}.{operation}");
    let (status, parsed) = json_call(router, "ecs", &target, "1.1", body).await;
    assert_eq!(
        status, 200,
        "case {case:?}: expected 200 from ECS {operation}, got {status} with {parsed}"
    );
    parsed
}

/// One EventBridge call that must succeed.
async fn events(router: &MultiServiceRouter, case: &str, operation: &str, body: &Value) -> Value {
    let target = format!("AWSEvents.{operation}");
    let (status, parsed) = json_call(router, "events", &target, "1.1", body).await;
    assert_eq!(
        status, 200,
        "case {case:?}: expected 200 from EventBridge {operation}, got {status} with {parsed}"
    );
    parsed
}

/// One Amazon SQS call that must succeed.
async fn sqs(router: &MultiServiceRouter, case: &str, operation: &str, body: &Value) -> Value {
    let target = format!("AmazonSQS.{operation}");
    let (status, parsed) = json_call(router, "sqs", &target, "1.0", body).await;
    assert_eq!(
        status, 200,
        "case {case:?}: expected 200 from SQS {operation}, got {status} with {parsed}"
    );
    parsed
}

/// A string member at `pointer`, or a panic naming the case and what came back.
fn member(case: &str, body: &Value, pointer: &str) -> String {
    body.pointer(pointer)
        .and_then(Value::as_str)
        .unwrap_or_else(|| panic!("case {case:?}: expected {pointer} in {body}"))
        .to_string()
}

/// An SQS queue called `name`, created through Amazon SQS itself and admitting EventBridge's
/// own service principal; answers its url and the ARN a rule names it by.
async fn queue(router: &MultiServiceRouter, case: &str, name: &str) -> (String, String) {
    let created = sqs(router, case, "CreateQueue", &json!({ "QueueName": name })).await;
    let url = member(case, &created, "/QueueUrl");
    let attributes = sqs(
        router,
        case,
        "GetQueueAttributes",
        &json!({ "QueueUrl": &url, "AttributeNames": ["QueueArn"] }),
    )
    .await;
    let arn = member(case, &attributes, "/Attributes/QueueArn");
    let policy = json!({
        "Version": "2012-10-17",
        "Statement": [{
            "Sid": "AllowEventBridge",
            "Effect": "Allow",
            "Principal": { "Service": EVENTS_PRINCIPAL },
            "Action": "sqs:SendMessage",
            "Resource": arn,
        }],
    })
    .to_string();
    sqs(
        router,
        case,
        "SetQueueAttributes",
        &json!({ "QueueUrl": &url, "Attributes": { "Policy": policy } }),
    )
    .await;
    (url, arn)
}

/// An ENABLED rule called `name` on the default bus carrying `pattern`, with the queue
/// `queue_arn` as its one target.
async fn rule(
    router: &MultiServiceRouter,
    case: &str,
    name: &str,
    pattern: &Value,
    queue_arn: &str,
) {
    events(
        router,
        case,
        "PutRule",
        &json!({
            "Name": name,
            "EventBusName": DEFAULT_BUS,
            "EventPattern": pattern.to_string(),
            "State": "ENABLED",
        }),
    )
    .await;
    let targeted = events(
        router,
        case,
        "PutTargets",
        &json!({
            "Rule": name,
            "EventBusName": DEFAULT_BUS,
            "Targets": [{ "Id": "sqs-target", "Arn": queue_arn }],
        }),
    )
    .await;
    assert_eq!(
        targeted["FailedEntryCount"],
        json!(0),
        "case {case:?}: every target must be accepted, got {targeted}"
    );
}

/// The ARN of the cluster named `name` in this account and Region.
fn cluster_arn(name: &str) -> String {
    format!("arn:aws:ecs:{REGION}:{ACCOUNT}:cluster/{name}")
}

/// The pattern of a rule matching the task state changes of ONE cluster: the identity Amazon
/// ECS publishes them under, narrowed through the event's own `detail`.
fn task_events_of(cluster: &str) -> Value {
    json!({
        "source": [EVENT_SOURCE],
        "detail-type": [TASK_STATE_CHANGE],
        "detail": { "clusterArn": [cluster_arn(cluster)] },
    })
}

/// Every message now waiting on the queue at `url`, as the parsed event envelopes their bodies
/// carry — each one DELETED as it is taken, the way a consumer of a queue reads it.
///
/// "Because Amazon SQS is a distributed system ... the message remains in the queue" until the
/// consumer deletes it, and it becomes visible again when its visibility timeout runs out
/// (`DeleteMessage`, `ReceiveMessage$VisibilityTimeout`): a reader that never deleted would be
/// handed what it already has a second time, so the handle each message carries is used.
async fn drain(router: &MultiServiceRouter, case: &str, url: &str) -> Vec<Value> {
    let received = sqs(
        router,
        case,
        "ReceiveMessage",
        &json!({ "QueueUrl": url, "MaxNumberOfMessages": 10 }),
    )
    .await;
    let messages = received["Messages"]
        .as_array()
        .cloned()
        .unwrap_or_default();
    let mut envelopes: Vec<Value> = Vec::new();
    for message in &messages {
        let raw = message["Body"].as_str().unwrap_or_default();
        envelopes.push(serde_json::from_str::<Value>(raw).unwrap_or(Value::Null));
        let handle = member(case, message, "/ReceiptHandle");
        sqs(
            router,
            case,
            "DeleteMessage",
            &json!({ "QueueUrl": url, "ReceiptHandle": handle }),
        )
        .await;
    }
    envelopes
}

/// Poll the queue at `url` — and ONLY the queue — until what it has delivered satisfies
/// `arrived`, or [`POLL_BUDGET`] passes; answers everything that did arrive.
///
/// Nothing in this loop calls Amazon ECS, which is the point: a client watching a task through
/// EventBridge makes no further call to the service that publishes.
async fn collect_until(
    router: &MultiServiceRouter,
    case: &str,
    url: &str,
    arrived: impl Fn(&[Value]) -> bool,
) -> Vec<Value> {
    let deadline = Instant::now() + POLL_BUDGET;
    let mut collected: Vec<Value> = Vec::new();
    loop {
        collected.extend(drain(router, case, url).await);
        if arrived(&collected) || Instant::now() >= deadline {
            return collected;
        }
        tokio::time::sleep(POLL_INTERVAL).await;
    }
}

/// The envelopes of `delivered` that report `status` for the task `task_arn`.
fn reporting<'a>(delivered: &'a [Value], task_arn: &str, status: &str) -> Vec<&'a Value> {
    delivered
        .iter()
        .filter(|envelope| {
            envelope["detail"]["taskArn"] == json!(task_arn)
                && envelope["detail"]["lastStatus"] == json!(status)
        })
        .collect()
}

/// The `detail.lastStatus` of every envelope of `delivered` about `task_arn`, for a failure
/// message that says what DID arrive.
fn statuses(delivered: &[Value], task_arn: &str) -> Vec<String> {
    delivered
        .iter()
        .filter(|envelope| envelope["detail"]["taskArn"] == json!(task_arn))
        .map(|envelope| {
            envelope["detail"]["lastStatus"]
                .as_str()
                .unwrap_or_default()
                .to_string()
        })
        .collect()
}

/// The envelope's `time` as the second it names.
///
/// An event envelope carries `time` as an RFC 3339 instant in UTC, which is the one form every
/// consumer reads it with, so a value that is not one is itself a failure.
fn instant_of(case: &str, envelope: &Value) -> i64 {
    let text = envelope["time"]
        .as_str()
        .unwrap_or_else(|| {
            panic!("case {case:?}: expected a time in the envelope, got {envelope}")
        });
    ::aws_smithy_types::DateTime::from_str(text, ::aws_smithy_types::date_time::Format::DateTime)
        .unwrap_or_else(|error| {
            panic!(
                "case {case:?}: expected an RFC 3339 UTC instant in time, got {text:?} ({error})"
            )
        })
        .secs()
}

/// An EC2 instance identity document, as the container agent reads it from the instance
/// metadata service: it carries the `accountId` and the `instanceId` a registration supplies.
fn identity_document(instance_id: &str) -> String {
    json!({
        "accountId": ACCOUNT,
        "instanceId": instance_id,
        "region": REGION,
        "instanceType": "m5.large",
        "availabilityZone": format!("{REGION}a"),
    })
    .to_string()
}

/// Register one revision of `family` with a single essential container, in `network_mode`,
/// running `command` when the row gives one; answers its ARN.
async fn register(
    router: &MultiServiceRouter,
    case: &str,
    family: &str,
    network_mode: &str,
    fargate: bool,
    command: Option<&[&str]>,
) -> String {
    let mut container = json!({
        "name": "app",
        "image": IMAGE,
        "memory": 128,
        "essential": true,
    });
    if let Some(command) = command {
        container["command"] = json!(command);
    }
    let mut body = json!({
        "family": family,
        "networkMode": network_mode,
        "containerDefinitions": [container],
    });
    if fargate {
        body["requiresCompatibilities"] = json!(["FARGATE"]);
        // A Fargate revision states the task size its tasks take; these are the smallest
        // documented pair (`RegisterTaskDefinition$cpu`: "256 (.25 vCPU) - Available memory
        // values: 512 (0.5 GB)").
        body["cpu"] = json!("256");
        body["memory"] = json!("512");
    }
    let registered = ecs(router, case, "RegisterTaskDefinition", &body).await;
    member(case, &registered, "/taskDefinition/taskDefinitionArn")
}

/// `RunTask` one row's placement and answer the ARN of every task it placed.
async fn run_task(router: &MultiServiceRouter, case: &str, row: &Row, family: &str) -> Vec<String> {
    let mut body = json!({
        "cluster": CLUSTER,
        "taskDefinition": family,
        "launchType": row.launch_type,
        "count": row.count,
    });
    if row.network_mode == "awsvpc" {
        body["networkConfiguration"] = json!({
            "awsvpcConfiguration": {
                "subnets": [SUBNET],
                "securityGroups": [SECURITY_GROUP],
                "assignPublicIp": "ENABLED",
            }
        });
    }
    let placed = ecs(router, case, "RunTask", &body).await;
    let tasks = placed["tasks"].as_array().cloned().unwrap_or_default();
    assert_eq!(
        tasks.len() as i64,
        row.count,
        "case {case:?}: expected RunTask to place {} task(s), got {placed}",
        row.count
    );
    tasks
        .iter()
        .map(|task| member(case, task, "/taskArn"))
        .collect()
}

/// The task `DescribeTasks` reports for `task_arn`.
async fn describe(router: &MultiServiceRouter, case: &str, task_arn: &str) -> Value {
    let body = ecs(
        router,
        case,
        "DescribeTasks",
        &json!({ "cluster": CLUSTER, "tasks": [task_arn] }),
    )
    .await;
    body["tasks"]
        .as_array()
        .and_then(|tasks| tasks.first())
        .cloned()
        .unwrap_or_else(|| panic!("case {case:?}: expected the task {task_arn} back, got {body}"))
}

/// One row: a placement of this suite's cluster.
struct Row {
    case: &'static str,
    /// The task-definition family the row registers and places.
    family: &'static str,
    /// `RunTask$launchType` the placement names.
    launch_type: &'static str,
    /// `RegisterTaskDefinition$networkMode` the revision is registered in.
    network_mode: &'static str,
    /// What the essential container runs, and `None` for a container whose launch names no
    /// argument vector of its own.
    command: Option<&'static [&'static str]>,
    /// `RunTask$count`: "The number of instantiations of the specified task to place".
    count: i64,
}

