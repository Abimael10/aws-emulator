//! An ECS service DEPLOYMENT's state changes reach the EventBridge rules that match them.
//!
//! The RULE under test: **a service deployment is a three-state machine
//! (`Deployment$rolloutState`: "When a service deployment is started, it begins in an
//! `IN_PROGRESS` state. When the service reaches a steady state, the deployment transitions
//! to a `COMPLETED` state. If the service fails to reach a steady state and circuit breaker
//! is turned on, the deployment transitions to a `FAILED` state"), and every state it moves
//! into is published once onto the account's DEFAULT EventBridge bus as `source` `aws.ecs` /
//! `detail-type` `ECS Deployment State Change`, whose `detail` names the transition in
//! `eventName`, its severity in `eventType` (`INFO` for progress, `ERROR` for the failure),
//! the rollout that moved in `deploymentId`, the instant it moved at in `updatedAt` and why
//! it is in that state in `reason`, and whose `resources` names the SERVICE the rollout
//! belongs to; EventBridge then routes it by its CONTENT, so a rule whose `EventPattern`
//! matches delivers the envelope to that rule's targets and a rule that cannot match
//! receives none of them.** Source: the Amazon ECS Developer Guide's service deployment
//! state change events (`ecs_service_deployment_events.html`), and
//! `smithy_query(query="shape", shape="com.amazonaws.ecs#DeploymentRolloutState")` ->
//! COMPLETED, FAILED, IN_PROGRESS for the states a rollout takes.
//!
//! This suite lives here because the path is cross-service: Amazon ECS publishes through the
//! in-process callback, EventBridge routes, and Amazon SQS holds what arrived — so what is
//! asserted is what each of the three services persisted, with nothing reading the
//! publisher's own queue.
//!
//! The rows of the first test differ along what the rule generalises over: WHICH door started
//! the rollout (a create, and an update that releases another revision of the same family),
//! and how many tasks the rollout places — none, one, and two — which is what decides how
//! long the scheduler takes to settle it. The second test is the other end of the same state
//! machine: the rollout the deployment circuit breaker FAILS, whose transition is an `ERROR`
//! naming that deployment, together with the rule scoped to that `eventName` — which receives
//! the failed rollout's transition and none of the healthy one's.
//!
//! Nothing in the polling loops calls Amazon ECS: the transitions are owed by the CLOCK, and a
//! client that watches a deployment through EventBridge makes no further call to the service
//! that publishes.

use std::sync::Arc;
use std::time::{Duration, Instant};

use bytes::Bytes;
use serde_json::{json, Value};
use smithy_server_runtime::MultiServiceRouter;

/// The Region every request below is signed for.
const REGION: &str = "us-west-2";

/// The account every emulator ARN carries, which a container-instance registration's identity
/// document has to name (`engine::EMULATOR_ACCOUNT_ID`).
const ACCOUNT: &str = "000000000000";

/// The `source` and `detail-type` Amazon ECS publishes a deployment's state changes under,
/// spelled out here rather than imported from the service crate, so a wrong constant in the
/// implementation cannot make this suite pass.
const EVENT_SOURCE: &str = "aws.ecs";
const DEPLOYMENT_STATE_CHANGE: &str = "ECS Deployment State Change";

/// The `eventName` of each transition of the deployment state machine, and the two
/// `eventType` values they carry.
const IN_PROGRESS: &str = "SERVICE_DEPLOYMENT_IN_PROGRESS";
const COMPLETED: &str = "SERVICE_DEPLOYMENT_COMPLETED";
const FAILED: &str = "SERVICE_DEPLOYMENT_FAILED";
const INFO: &str = "INFO";
const ERROR: &str = "ERROR";

/// The bus an Amazon Web Services service's own events go to: "events generated by Amazon Web
/// Services services go to your account's default event bus".
const DEFAULT_BUS: &str = "default";

/// The service principal EventBridge delivers to an SQS target as, which is what a queue's
/// resource policy admits ("for Amazon SQS queues, EventBridge relies on resource-based
/// policies").
const EVENTS_PRINCIPAL: &str = "events.amazonaws.com";

/// The `X-Amz-Target` prefix of the Amazon ECS model (`AmazonEC2ContainerServiceV20141113`),
/// whose `sigv4Name` is `ecs`; it speaks awsJson1.1.
const ECS_TARGET_PREFIX: &str = "AmazonEC2ContainerServiceV20141113";

/// The cluster every service below runs in.
const CLUSTER: &str = "deployevents";

/// The container instance the scheduler places this suite's EC2 tasks on: "The EC2 launch type
/// runs your tasks on Amazon EC2 instances registered to your cluster."
const CAPACITY_INSTANCE: &str = "i-0c0ffee0c0ffee0c0";

/// The image every container names. Nothing is fetched from it; what a row is about is the
/// rollout, not the registry.
const IMAGE: &str = "public.ecr.aws/nginx/nginx:latest";

/// The command of the container that CANNOT stay up: its essential container ends at once,
/// which is a task the rollout that placed it lost (`Deployment$failedTasks`: "A task is
/// considered a failure if ... the task doesn't transition to a RUNNING state"), so the
/// circuit breaker counts it.
const EXITS_AT_ONCE: [&str; 3] = ["sh", "-c", "exit 1"];

/// How often a poll re-reads a target queue.
const POLL_INTERVAL: Duration = Duration::from_millis(50);

/// How long a poll keeps trying before it gives up. Generous: a rollout settles one span after
/// the tasks it placed are running, a failing rollout spends a span losing a task and another
/// having the breaker count it, and every poll stops the instant its own condition holds — so
/// the budget costs nothing when the transitions arrive and a loaded machine only polls more
/// often.
const POLL_BUDGET: Duration = Duration::from_secs(90);

/// Amazon ECS, EventBridge and Amazon SQS over ONE shared engine — the three services a
/// published deployment event travels through, mounted the way the production router mounts
/// them.
fn emulator() -> MultiServiceRouter {
    let engine: Arc<engine::InMemoryEngine> = Arc::new(engine::InMemoryEngine::new());
    let mut router = MultiServiceRouter::new();
    router.set_request_authentication(false);
    router.register_service(
        service_com_amazonaws_ecs_amazonec2containerservicev20141113::EmulatedService::new(
            Arc::clone(&engine),
        ),
    );
    router.register_service(
        service_com_amazonaws_eventbridge_awsevents::EmulatedService::new(Arc::clone(&engine)),
    );
    router.register_service(service_com_amazonaws_sqs_amazonsqs::EmulatedService::new(
        engine,
    ));
    router
}

/// The WHOLE emulator over one engine, exactly as `core/router/src/lib.rs` assembles it for
/// the binary: Amazon ECS publishes through the in-process callback, so WHICH mounted model
/// claims that `events`-scoped call has to be the one a client reaches too — several models
/// resolve to the `events` signing key.
fn whole_emulator() -> MultiServiceRouter {
    let engine = aws_emulator_router::new_engine();
    let mut router = aws_emulator_router::build_router(engine);
    router.set_request_authentication(false);
    router
}

/// A SigV4 `Authorization` whose credential scope names `signing_name`, which is what routes
/// the request. The signature is never checked: the router above runs with request
/// authentication off.
fn authorization(signing_name: &str) -> String {
    format!(
        "AWS4-HMAC-SHA256 Credential=AKIDEXAMPLE/20260101/{REGION}/{signing_name}\
         /aws4_request, SignedHeaders=host, Signature=0000"
    )
}

/// One `X-Amz-Target` RPC call, answered with its HTTP status and parsed body.
async fn json_call(
    router: &MultiServiceRouter,
    signing_name: &str,
    target: &str,
    json_version: &str,
    body: &Value,
) -> (u16, Value) {
    let request = http::Request::builder()
        .method("POST")
        .uri("/")
        .header("host", format!("{signing_name}.{REGION}.amazonaws.com"))
        .header(
            "content-type",
            format!("application/x-amz-json-{json_version}"),
        )
        .header("x-amz-target", target)
        .header("authorization", authorization(signing_name))
        .body(Bytes::from(body.to_string()))
        .expect("a well-formed request");
    let response = router.dispatch(request).await;
    let status = response.status().as_u16();
    let payload = response.into_body();
    let parsed: Value = if payload.is_empty() {
        json!({})
    } else {
        serde_json::from_slice(&payload)
            .unwrap_or_else(|_| json!({ "unparsed": String::from_utf8_lossy(&payload) }))
    };
    (status, parsed)
}

/// One Amazon ECS call that must succeed, answered with its body.
async fn ecs(router: &MultiServiceRouter, case: &str, operation: &str, body: &Value) -> Value {
    let target = format!("{ECS_TARGET_PREFIX}.{operation}");
    let (status, parsed) = json_call(router, "ecs", &target, "1.1", body).await;
    assert_eq!(
        status, 200,
        "case {case:?}: expected 200 from ECS {operation}, got {status} with {parsed}"
    );
    parsed
}

/// One EventBridge call that must succeed.
async fn events(router: &MultiServiceRouter, case: &str, operation: &str, body: &Value) -> Value {
    let target = format!("AWSEvents.{operation}");
    let (status, parsed) = json_call(router, "events", &target, "1.1", body).await;
    assert_eq!(
        status, 200,
        "case {case:?}: expected 200 from EventBridge {operation}, got {status} with {parsed}"
    );
    parsed
}

/// One Amazon SQS call that must succeed.
async fn sqs(router: &MultiServiceRouter, case: &str, operation: &str, body: &Value) -> Value {
    let target = format!("AmazonSQS.{operation}");
    let (status, parsed) = json_call(router, "sqs", &target, "1.0", body).await;
    assert_eq!(
        status, 200,
        "case {case:?}: expected 200 from SQS {operation}, got {status} with {parsed}"
    );
    parsed
}

/// A string member at `pointer`, or a panic naming the case and what came back.
fn member(case: &str, body: &Value, pointer: &str) -> String {
    body.pointer(pointer)
        .and_then(Value::as_str)
        .unwrap_or_else(|| panic!("case {case:?}: expected {pointer} in {body}"))
        .to_string()
}

/// An SQS queue called `name`, created through Amazon SQS itself and admitting EventBridge's
/// own service principal; answers its url and the ARN a rule names it by.
async fn queue(router: &MultiServiceRouter, case: &str, name: &str) -> (String, String) {
    let created = sqs(router, case, "CreateQueue", &json!({ "QueueName": name })).await;
    let url = member(case, &created, "/QueueUrl");
    let attributes = sqs(
        router,
        case,
        "GetQueueAttributes",
        &json!({ "QueueUrl": &url, "AttributeNames": ["QueueArn"] }),
    )
    .await;
    let arn = member(case, &attributes, "/Attributes/QueueArn");
    let policy = json!({
        "Version": "2012-10-17",
        "Statement": [{
            "Sid": "AllowEventBridge",
            "Effect": "Allow",
            "Principal": { "Service": EVENTS_PRINCIPAL },
            "Action": "sqs:SendMessage",
            "Resource": arn,
        }],
    })
    .to_string();
    sqs(
        router,
        case,
        "SetQueueAttributes",
        &json!({ "QueueUrl": &url, "Attributes": { "Policy": policy } }),
    )
    .await;
    (url, arn)
}

/// An ENABLED rule called `name` on the default bus carrying `pattern`, with the queue
/// `queue_arn` as its one target.
async fn rule(
    router: &MultiServiceRouter,
    case: &str,
    name: &str,
    pattern: &Value,
    queue_arn: &str,
) {
    events(
        router,
        case,
        "PutRule",
        &json!({
            "Name": name,
            "EventBusName": DEFAULT_BUS,
            "EventPattern": pattern.to_string(),
            "State": "ENABLED",
        }),
    )
    .await;
    let targeted = events(
        router,
        case,
        "PutTargets",
        &json!({
            "Rule": name,
            "EventBusName": DEFAULT_BUS,
            "Targets": [{ "Id": "sqs-target", "Arn": queue_arn }],
        }),
    )
    .await;
    assert_eq!(
        targeted["FailedEntryCount"],
        json!(0),
        "case {case:?}: every target must be accepted, got {targeted}"
    );
}

/// The pattern of a rule matching EVERY deployment state change of this bus.
fn every_deployment_event() -> Value {
    json!({
        "source": [EVENT_SOURCE],
        "detail-type": [DEPLOYMENT_STATE_CHANGE],
    })
}

/// The pattern of a rule matching only the FAILED transition — a rule narrowed through the
/// event's own `detail`, which is what makes a correctly-scoped rule distinguishable from a
/// broken one.
fn failed_deployment_event() -> Value {
    json!({
        "source": [EVENT_SOURCE],
        "detail-type": [DEPLOYMENT_STATE_CHANGE],
        "detail": { "eventName": [FAILED] },
    })
}

/// Every message now waiting on the queue at `url`, as the parsed event envelopes their
/// bodies carry.
async fn drain(router: &MultiServiceRouter, case: &str, url: &str) -> Vec<Value> {
    let received = sqs(
        router,
        case,
        "ReceiveMessage",
        &json!({ "QueueUrl": url, "MaxNumberOfMessages": 10 }),
    )
    .await;
    received["Messages"]
        .as_array()
        .cloned()
        .unwrap_or_default()
        .iter()
        .map(|message| {
            let raw = message["Body"].as_str().unwrap_or_default();
            serde_json::from_str::<Value>(raw).unwrap_or(Value::Null)
        })
        .collect()
}

/// Poll the queue at `url` — and ONLY the queue — until what it has delivered satisfies
/// `arrived`, or [`POLL_BUDGET`] passes; answers everything that did arrive.
async fn collect_until(
    router: &MultiServiceRouter,
    case: &str,
    url: &str,
    arrived: impl Fn(&[Value]) -> bool,
) -> Vec<Value> {
    let deadline = Instant::now() + POLL_BUDGET;
    let mut collected: Vec<Value> = Vec::new();
    loop {
        collected.extend(drain(router, case, url).await);
        if arrived(&collected) || Instant::now() >= deadline {
            return collected;
        }
        tokio::time::sleep(POLL_INTERVAL).await;
    }
}

/// Whether `envelopes` holds the transition `event_name` of the rollout `deployment_id`.
fn holds(envelopes: &[Value], deployment_id: &str, event_name: &str) -> bool {
    envelopes.iter().any(|envelope| {
        envelope["detail"]["deploymentId"] == json!(deployment_id)
            && envelope["detail"]["eventName"] == json!(event_name)
    })
}

/// The envelopes of `delivered` that are about the rollout `deployment_id`.
fn about(delivered: &[Value], deployment_id: &str) -> Vec<Value> {
    delivered
        .iter()
        .filter(|envelope| envelope["detail"]["deploymentId"] == json!(deployment_id))
        .cloned()
        .collect()
}

/// The `detail.eventName` of each of `envelopes`, SORTED: an SQS standard queue makes "a
/// best-effort to preserve order", so what is asserted is WHICH transitions arrived, once
/// each.
fn names(envelopes: &[Value]) -> Vec<String> {
    let mut found: Vec<String> = envelopes
        .iter()
        .map(|envelope| {
            envelope["detail"]["eventName"]
                .as_str()
                .unwrap_or_default()
                .to_string()
        })
        .collect();
    found.sort();
    found
}

/// The two transitions a healthy rollout publishes, in the order [`names`] answers them.
fn started_and_completed() -> Vec<String> {
    let mut expected = vec![IN_PROGRESS.to_string(), COMPLETED.to_string()];
    expected.sort();
    expected
}

/// The two transitions a rollout the breaker failed publishes.
fn started_and_failed() -> Vec<String> {
    let mut expected = vec![IN_PROGRESS.to_string(), FAILED.to_string()];
    expected.sort();
    expected
}

/// The `detail.reason` of the one delivered `event_name` of `envelopes`.
fn reason(envelopes: &[Value], event_name: &str) -> String {
    envelopes
        .iter()
        .find(|envelope| envelope["detail"]["eventName"] == json!(event_name))
        .and_then(|envelope| envelope["detail"]["reason"].as_str())
        .unwrap_or_default()
        .to_string()
}

/// Assert the envelope of each of `envelopes`: the bus identity a deployment transition is
/// published under, the service the rollout belongs to in `resources`, the severity the
/// transition carries, and the instant it moved at.
fn assert_envelopes(envelopes: &[Value], service_arn: &str, case: &str) {
    for envelope in envelopes {
        assert_eq!(
            envelope["source"],
            json!(EVENT_SOURCE),
            "case {case:?}: expected source {EVENT_SOURCE}, got {envelope}"
        );
        assert_eq!(
            envelope["detail-type"],
            json!(DEPLOYMENT_STATE_CHANGE),
            "case {case:?}: expected detail-type {DEPLOYMENT_STATE_CHANGE}, got {envelope}"
        );
        assert_eq!(
            envelope["resources"],
            json!([service_arn]),
            "case {case:?}: expected {service_arn} in resources, got {envelope}"
        );
        let expected_type = if envelope["detail"]["eventName"] == json!(FAILED) {
            ERROR
        } else {
            INFO
        };
        assert_eq!(
            envelope["detail"]["eventType"],
            json!(expected_type),
            "case {case:?}: expected eventType {expected_type}, got {envelope}"
        );
        let updated_at = envelope["detail"]["updatedAt"].as_str().unwrap_or_default();
        assert!(
            updated_at.contains('T') && updated_at.ends_with('Z'),
            "case {case:?}: expected a UTC date-time in detail.updatedAt, got {envelope}"
        );
    }
}

/// An EC2 instance identity document, as the container agent reads it from the instance
/// metadata service: it carries the `accountId` and the `instanceId` a registration supplies.
fn identity_document(instance_id: &str) -> String {
    json!({
        "accountId": ACCOUNT,
        "instanceId": instance_id,
        "region": REGION,
        "instanceType": "m5.large",
        "availabilityZone": format!("{REGION}a"),
    })
    .to_string()
}

/// The cluster of this suite, with one container instance registered into it through the
/// agent's own operation.
async fn cluster_with_capacity(router: &MultiServiceRouter, case: &str) {
    ecs(
        router,
        case,
        "CreateCluster",
        &json!({ "clusterName": CLUSTER }),
    )
    .await;
    ecs(
        router,
        case,
        "RegisterContainerInstance",
        &json!({
            "cluster": CLUSTER,
            "instanceIdentityDocument": identity_document(CAPACITY_INSTANCE),
            // Base64 text beside the document; nothing here signs anything, and what a
            // signature is OF cannot be checked without the key that produced it.
            "instanceIdentityDocumentSignature": "ZXhhbXBsZQ".repeat(35),
        }),
    )
    .await;
}

/// Register one revision of `family` whose single container runs `command` when it is given
/// one, and answer its ARN.
async fn register(
    router: &MultiServiceRouter,
    case: &str,
    family: &str,
    command: Option<&[&str]>,
) -> String {
    let mut container = json!({
        "name": "app",
        "image": IMAGE,
        "memory": 128,
        "essential": true,
    });
    if let Some(command) = command {
        container["command"] = json!(command);
    }
    let registered = ecs(
        router,
        case,
        "RegisterTaskDefinition",
        &json!({ "family": family, "containerDefinitions": [container] }),
    )
    .await;
    member(case, &registered, "/taskDefinition/taskDefinitionArn")
}

/// The id of the service's CURRENT (`PRIMARY`) deployment, as a service view reports it.
fn current_deployment_id(case: &str, service: &Value) -> String {
    member(case, service, "/deployments/0/id")
}

/// The service `DescribeServices` reports for `name`.
async fn describe(router: &MultiServiceRouter, case: &str, name: &str) -> Value {
    let body = ecs(
        router,
        case,
        "DescribeServices",
        &json!({ "cluster": CLUSTER, "services": [name] }),
    )
    .await;
    body["services"]
        .as_array()
        .and_then(|services| services.first())
        .cloned()
        .unwrap_or_else(|| panic!("case {case:?}: expected the service back, got {body}"))
}

/// The deployment of `service` whose id is `deployment_id`.
fn deployment_of(case: &str, service: &Value, deployment_id: &str) -> Value {
    service["deployments"]
        .as_array()
        .and_then(|deployments| {
            deployments
                .iter()
                .find(|deployment| deployment["id"] == json!(deployment_id))
        })
        .cloned()
        .unwrap_or_else(|| {
            panic!("case {case:?}: expected the rollout {deployment_id} back, got {service}")
        })
}

/// One row: a service of this suite's cluster, and whether a second rollout is released over
/// its first by an update.
struct Row {
    case: &'static str,
    service: &'static str,
    family: &'static str,
    /// `Service$desiredCount` the service is created with.
    desired: i64,
    /// Whether an `UpdateService` then releases another revision of the same family.
    updates: bool,
}

/// The table spans the rule: which door starts the rollout, and how many tasks it places.
const ROWS: &[Row] = &[
    Row {
        case: "a rollout that places one task",
        service: "one-task",
        family: "deployone",
        desired: 1,
        updates: false,
    },
    Row {
        case: "a rollout that places no task at all",
        service: "no-task",
        family: "deploynone",
        desired: 0,
        updates: false,
    },
    Row {
        case: "a rollout that places two tasks",
        service: "two-tasks",
        family: "deploytwo",
        desired: 2,
        updates: false,
    },
    Row {
        case: "a second rollout released over the first by an update",
        service: "updated",
        family: "deployupdated",
        desired: 1,
        updates: true,
    },
];

#[tokio::test]
async fn every_state_a_healthy_service_deployment_moves_into_reaches_the_matching_rule() {
    let setup = "the estate every row runs in";
    let router = emulator();
    let (url, queue_arn) = queue(&router, setup, "ecs-deployment-events").await;
    rule(
        &router,
        setup,
        "ecs-deployment-state-change",
        &every_deployment_event(),
        &queue_arn,
    )
    .await;
    // The negative half of the same rule: a rule scoped to the FAILED transition can match
    // nothing a healthy rollout publishes, so its own queue must stay empty.
    let (failures_url, failures_arn) = queue(&router, setup, "ecs-deployment-failures").await;
    rule(
        &router,
        setup,
        "ecs-deployment-failed",
        &failed_deployment_event(),
        &failures_arn,
    )
    .await;
    cluster_with_capacity(&router, setup).await;

    for row in ROWS {
        let case = row.case;
        let first = register(&router, case, row.family, None).await;
        let created = ecs(
            &router,
            case,
            "CreateService",
            &json!({
                "cluster": CLUSTER,
                "serviceName": row.service,
                "taskDefinition": first,
                "desiredCount": row.desired,
                "launchType": "EC2",
                "deploymentController": { "type": "ECS" },
            }),
        )
        .await;
        let service_arn = member(case, &created, "/service/serviceArn");
        let first_deployment = current_deployment_id(case, &created["service"]);

        let delivered = collect_until(&router, case, &url, |envelopes| {
            holds(envelopes, &first_deployment, COMPLETED)
        })
        .await;
        let about_first = about(&delivered, &first_deployment);
        assert_eq!(
            names(&about_first),
            started_and_completed(),
            "case {case:?}: expected the rollout {first_deployment} to publish its start and \
             its completion, got {delivered:?}"
        );
        assert_envelopes(&about_first, &service_arn, case);

        // ROUND TRIP: the state the event reports is the state the control plane reports for
        // the same rollout, with the same reason — the event and `DescribeServices` cannot
        // disagree about where a deployment stands.
        let service = describe(&router, case, row.service).await;
        let deployment = deployment_of(case, &service, &first_deployment);
        assert_eq!(
            deployment["rolloutState"],
            json!("COMPLETED"),
            "case {case:?}: expected the rollout to report its completion, got {deployment}"
        );
        assert_eq!(
            deployment["rolloutStateReason"],
            json!(reason(&about_first, COMPLETED)),
            "case {case:?}: expected the event's reason to be the rollout's own, got \
             {deployment}"
        );

        if row.updates {
            // An update that releases ANOTHER revision is a rollout of its own, with its own
            // deployment id, and it travels the same two states.
            let second = register(&router, case, row.family, None).await;
            let updated = ecs(
                &router,
                case,
                "UpdateService",
                &json!({
                    "cluster": CLUSTER,
                    "service": row.service,
                    "taskDefinition": second,
                }),
            )
            .await;
            let second_deployment = current_deployment_id(case, &updated["service"]);
            assert_ne!(
                second_deployment, first_deployment,
                "case {case:?}: an update that releases a revision is a new rollout, got \
                 {updated}"
            );
            let delivered = collect_until(&router, case, &url, |envelopes| {
                holds(envelopes, &second_deployment, COMPLETED)
            })
            .await;
            let about_second = about(&delivered, &second_deployment);
            assert_eq!(
                names(&about_second),
                started_and_completed(),
                "case {case:?}: expected the rollout {second_deployment} to publish its start \
                 and its completion, got {delivered:?}"
            );
            assert_envelopes(&about_second, &service_arn, case);
        }
    }

    // Nothing failed, so the rule scoped to failures received nothing: a client cannot
    // mistake a healthy deployment for a failed one. What makes that absence assertable
    // without waiting on the clock is a BARRIER — one more service, created after every row,
    // whose own completion travels the bus behind anything the rows could have published:
    // once it has arrived, a FAILED transition any row had published would have arrived too.
    let barrier_definition = register(&router, setup, "deploybarrier", None).await;
    let barrier = ecs(
        &router,
        setup,
        "CreateService",
        &json!({
            "cluster": CLUSTER,
            "serviceName": "healthy-barrier",
            "taskDefinition": barrier_definition,
            "desiredCount": 0,
            "launchType": "EC2",
            "deploymentController": { "type": "ECS" },
        }),
    )
    .await;
    let barrier_deployment = current_deployment_id(setup, &barrier["service"]);
    let delivered = collect_until(&router, setup, &url, |envelopes| {
        holds(envelopes, &barrier_deployment, COMPLETED)
    })
    .await;
    assert_eq!(
        names(&about(&delivered, &barrier_deployment)),
        started_and_completed(),
        "expected the barrier rollout's own two transitions, got {delivered:?}"
    );
    let failures = drain(&router, "the failure-scoped rule", &failures_url).await;
    assert!(
        failures.is_empty(),
        "expected the rule scoped to failures to receive nothing, got {failures:?}"
    );
}

#[tokio::test]
async fn a_rollout_the_circuit_breaker_fails_publishes_an_error_naming_that_deployment() {
    let case = "a rollout whose task cannot stay up, watched by the circuit breaker";
    let router = emulator();
    let (url, queue_arn) = queue(&router, case, "ecs-deployment-events").await;
    rule(
        &router,
        case,
        "ecs-deployment-state-change",
        &every_deployment_event(),
        &queue_arn,
    )
    .await;
    let (failures_url, failures_arn) = queue(&router, case, "ecs-deployment-failures").await;
    rule(
        &router,
        case,
        "ecs-deployment-failed",
        &failed_deployment_event(),
        &failures_arn,
    )
    .await;
    cluster_with_capacity(&router, case).await;

    let family = "deploybreaker";
    let healthy = register(&router, case, family, None).await;
    let failing = register(&router, case, family, Some(&EXITS_AT_ONCE)).await;

    let service_name = "breaking";
    let created = ecs(
        &router,
        case,
        "CreateService",
        &json!({
            "cluster": CLUSTER,
            "serviceName": service_name,
            "taskDefinition": healthy,
            "desiredCount": 1,
            "launchType": "EC2",
            "deploymentController": { "type": "ECS" },
            "deploymentConfiguration": {
                "deploymentCircuitBreaker": {
                    "enable": true,
                    "rollback": false,
                    // "COUNT - Uses value as the threshold": one lost task is enough, so the
                    // breaker fires on the first launch this rollout loses.
                    "thresholdConfiguration": { "type": "COUNT", "value": 1 },
                },
            },
        }),
    )
    .await;
    let service_arn = member(case, &created, "/service/serviceArn");
    let healthy_deployment = current_deployment_id(case, &created["service"]);

    // The first rollout completes: its task stays up, so the service reaches the steady state
    // it was rolling out.
    let delivered = collect_until(&router, case, &url, |envelopes| {
        holds(envelopes, &healthy_deployment, COMPLETED)
    })
    .await;
    assert_eq!(
        names(&about(&delivered, &healthy_deployment)),
        started_and_completed(),
        "case {case:?}: expected the healthy rollout to complete, got {delivered:?}"
    );

    // The rollout that cannot: its task's essential container ends at once, the breaker counts
    // it, and the threshold is reached on that first loss.
    let updated = ecs(
        &router,
        case,
        "UpdateService",
        &json!({
            "cluster": CLUSTER,
            "service": service_name,
            "taskDefinition": failing,
        }),
    )
    .await;
    let failed_deployment = current_deployment_id(case, &updated["service"]);
    assert_ne!(
        failed_deployment, healthy_deployment,
        "case {case:?}: the update releases a rollout of its own, got {updated}"
    );

    let delivered = collect_until(&router, case, &url, |envelopes| {
        holds(envelopes, &failed_deployment, FAILED)
    })
    .await;
    let about_failed = about(&delivered, &failed_deployment);
    assert_eq!(
        names(&about_failed),
        started_and_failed(),
        "case {case:?}: expected the failing rollout to publish its start and its failure, got \
         {delivered:?}"
    );
    assert_envelopes(&about_failed, &service_arn, case);
    let failure_reason = reason(&about_failed, FAILED);
    assert!(
        failure_reason.contains("circuit breaker"),
        "case {case:?}: expected the failure's reason to name the breaker, got {failure_reason:?}"
    );

    // ROUND TRIP: the rollout the event names as failed is the one the control plane reports
    // as failed, for the same reason.
    let service = describe(&router, case, service_name).await;
    let deployment = deployment_of(case, &service, &failed_deployment);
    assert_eq!(
        deployment["rolloutState"],
        json!("FAILED"),
        "case {case:?}: expected the rollout to report its failure, got {deployment}"
    );
    assert_eq!(
        deployment["rolloutStateReason"],
        json!(failure_reason),
        "case {case:?}: expected the event's reason to be the rollout's own, got {deployment}"
    );

    // The rule scoped to failures receives exactly that one transition, and none of the
    // healthy rollout's — which is what tells a correctly-scoped rule from a broken one.
    let failures = collect_until(&router, case, &failures_url, |envelopes| {
        holds(envelopes, &failed_deployment, FAILED)
    })
    .await;
    assert_eq!(
        names(&failures),
        vec![FAILED.to_string()],
        "case {case:?}: expected the failure-scoped rule to receive only the failed rollout's \
         transition, got {failures:?}"
    );
}

/// The INVARIANT of the same state machine: a transition is published when the rollout MOVES,
/// so a deployment that is settled again — a scale-out gives the scheduler the same rollout's
/// task set to settle afresh, without releasing a revision — announces no second completion.
#[tokio::test]
async fn a_rollout_settled_again_by_a_scale_out_publishes_no_second_completion() {
    let case = "a settled rollout the scheduler settles again";
    let router = emulator();
    let (url, queue_arn) = queue(&router, case, "ecs-deployment-events").await;
    rule(
        &router,
        case,
        "ecs-deployment-state-change",
        &every_deployment_event(),
        &queue_arn,
    )
    .await;
    cluster_with_capacity(&router, case).await;

    let definition = register(&router, case, "deployscaled", None).await;
    let created = ecs(
        &router,
        case,
        "CreateService",
        &json!({
            "cluster": CLUSTER,
            "serviceName": "scaled",
            "taskDefinition": &definition,
            "desiredCount": 1,
            "launchType": "EC2",
            "deploymentController": { "type": "ECS" },
        }),
    )
    .await;
    let deployment_id = current_deployment_id(case, &created["service"]);
    let delivered = collect_until(&router, case, &url, |envelopes| {
        holds(envelopes, &deployment_id, COMPLETED)
    })
    .await;
    assert_eq!(
        names(&about(&delivered, &deployment_id)),
        started_and_completed(),
        "case {case:?}: expected the rollout to complete, got {delivered:?}"
    );

    // A count change is work for the scheduler, not a release: the service leaves its steady
    // state and reaches it again on the SAME deployment.
    let updated = ecs(
        &router,
        case,
        "UpdateService",
        &json!({ "cluster": CLUSTER, "service": "scaled", "desiredCount": 2 }),
    )
    .await;
    assert_eq!(
        current_deployment_id(case, &updated["service"]),
        deployment_id,
        "case {case:?}: a count change releases no new rollout, got {updated}"
    );
    // The scale really happened, so the scheduler really did settle the rollout again.
    let deadline = Instant::now() + POLL_BUDGET;
    let service = loop {
        let service = describe(&router, case, "scaled").await;
        let deployment = deployment_of(case, &service, &deployment_id);
        if service["runningCount"] == json!(2) && deployment["rolloutState"] == json!("COMPLETED") {
            break service;
        }
        assert!(
            Instant::now() < deadline,
            "case {case:?}: expected the scaled-out rollout to settle again, got {service}"
        );
        tokio::time::sleep(POLL_INTERVAL).await;
    };

    // A BARRIER, so the absence asserted below is not merely the absence of having looked
    // early enough: a second service, created after the scale-out, whose own completion
    // travels the same queue behind anything the scale-out could have published.
    let barrier = ecs(
        &router,
        case,
        "CreateService",
        &json!({
            "cluster": CLUSTER,
            "serviceName": "barrier",
            "taskDefinition": &definition,
            "desiredCount": 0,
            "launchType": "EC2",
            "deploymentController": { "type": "ECS" },
        }),
    )
    .await;
    let barrier_deployment = current_deployment_id(case, &barrier["service"]);
    let delivered = collect_until(&router, case, &url, |envelopes| {
        holds(envelopes, &barrier_deployment, COMPLETED)
    })
    .await;
    assert!(
        about(&delivered, &deployment_id).is_empty(),
        "case {case:?}: a rollout settled again announces no further transition, got {:?} \
         ({service})",
        about(&delivered, &deployment_id)
    );
    assert_eq!(
        names(&about(&delivered, &barrier_deployment)),
        started_and_completed(),
        "case {case:?}: expected the barrier rollout's own two transitions, got {delivered:?}"
    );
}

