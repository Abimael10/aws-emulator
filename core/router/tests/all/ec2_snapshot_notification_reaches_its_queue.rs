//! An EBS snapshot's outcome reaches the queue an EventBridge rule delivers it to — through
//! the WHOLE mounted service set, the one `core/router/src/lib.rs` assembles for the binary.
//!
//! The RULE under test: **a snapshot action is not finished when the API answers it, so
//! Amazon EC2 publishes the OUTCOME of that action once per snapshot it was asked for onto
//! the account's DEFAULT EventBridge bus as `source` `aws.ec2` / `detail-type` `EBS Snapshot
//! Notification`, naming the snapshot in the envelope's `resources` and carrying in the event
//! `detail` the action it is the outcome of (`createSnapshot`, `copySnapshot`), the `state`
//! the snapshot settled in, the `result` saying whether that is the state the action set out
//! to reach, the `cause` of a result that failed, and the snapshot and its source.**
//! EventBridge then routes it by its CONTENT, so a rule whose `EventPattern` names the failed
//! result delivers only the envelopes that carry it.
//!
//! Three services have to agree for that to hold — Amazon EC2 publishes, EventBridge routes,
//! Amazon SQS holds what arrived — and the publication Amazon EC2 makes is an in-process call
//! addressed the way a client's own `events`-scoped call is addressed, so WHICH mounted model
//! claims it is only decidable with every service mounted. The crate-local suite
//! `services/service-com-amazonaws-ec2-amazonec2/tests/all/snapshot_notifications.rs` pins
//! the same rule over the table of actions and outcomes; what only this suite can reach is
//! that same path over the production service set, where more than one model resolves to the
//! `events` key.
//!
//! The rows differ along what the rule generalises over: WHICH action started the snapshot
//! and the OUTCOME it reached — a create that completes, a copy of a snapshot that is there,
//! and a copy whose source is not there, which EC2 accepts and then fails ASYNCHRONOUSLY.

use std::sync::Arc;
use std::time::{Duration, Instant};

use bytes::Bytes;
use serde_json::{json, Value};
use smithy_server_runtime::MultiServiceRouter;

use crate::query_wire::{element, form_encode};

/// The Region every request below is signed for.
const REGION: &str = "us-west-2";

/// The zone the volume below is created in.
const ZONE: &str = "us-west-2a";

/// The `source`, `detail-type` and `detail.event` values Amazon EC2 publishes a snapshot's
/// outcome under, spelled out here rather than imported from the service crate, so a wrong
/// constant in the implementation cannot make this suite pass.
const EC2_SOURCE: &str = "aws.ec2";
const SNAPSHOT_NOTIFICATION: &str = "EBS Snapshot Notification";
const CREATE_SNAPSHOT_EVENT: &str = "createSnapshot";
const COPY_SNAPSHOT_EVENT: &str = "copySnapshot";

/// The states a snapshot settles in and the results they report.
const COMPLETED: &str = "completed";
const ERROR: &str = "error";
const SUCCEEDED: &str = "succeeded";
const FAILED: &str = "failed";

/// A snapshot id of the long form EC2 issues that no snapshot of the account carries: the
/// copy of a source that is not there is what makes an asynchronous failure observable.
const MISSING_SNAPSHOT_ID: &str = "snap-0123456789abcdef0";

/// The sentence a copy whose source could not be resolved reports as the `cause` of its
/// failure, in AWS's own words: it names neither the id nor the Region.
const MISSING_SOURCE_CAUSE: &str = "Source snapshot is not found";

/// The bus an Amazon Web Services service's own events go to: "events generated by Amazon
/// Web Services services go to your account's default event bus".
const DEFAULT_BUS: &str = "default";

/// The service principal EventBridge delivers to an SQS target as, which is what a queue's
/// resource policy admits ("for Amazon SQS queues, EventBridge relies on resource-based
/// policies").
const EVENTS_PRINCIPAL: &str = "events.amazonaws.com";

/// The EC2 API version an ec2Query body carries.
const EC2_API_VERSION: &str = "2016-11-15";

/// How long a row waits for the publication to arrive on a queue before it gives up: far
/// above the work one action makes, and driven off what has ARRIVED rather than off a fixed
/// sleep, so a slow machine delays a row instead of breaking it.
const DELIVERY_DEADLINE: Duration = Duration::from_secs(30);

/// One poll of a queue inside [`DELIVERY_DEADLINE`].
const POLL_INTERVAL: Duration = Duration::from_millis(25);

/// The whole emulator over one engine, exactly as `core/router/src/lib.rs` assembles it for
/// the binary: Amazon EC2 publishes through the in-process callback, so WHICH mounted model
/// claims that `events`-scoped call has to be the one a client reaches too.
fn router() -> MultiServiceRouter {
    let engine = aws_emulator_router::new_engine();
    let mut router = aws_emulator_router::build_router(Arc::clone(&engine));
    router.set_request_authentication(false);
    router
}

/// A SigV4 `Authorization` whose credential scope names `service`, which is what routes the
/// request. The signature is never checked: the router above runs with request
/// authentication off.
fn authorization(service: &str) -> String {
    format!(
        "AWS4-HMAC-SHA256 Credential=AKIDEXAMPLE/20260101/{REGION}/{service}/aws4_request, \
         SignedHeaders=host, Signature=0000"
    )
}

/// One `X-Amz-Target` RPC call against the service whose signing name is `signing_name`,
/// which must answer 200.
async fn rpc(
    router: &MultiServiceRouter,
    case: &str,
    signing_name: &str,
    target_prefix: &str,
    json_version: &str,
    operation: &str,
    body: &Value,
) -> Value {
    let request = http::Request::builder()
        .method("POST")
        .uri("/")
        .header("host", format!("{signing_name}.{REGION}.amazonaws.com"))
        .header("authorization", authorization(signing_name))
        .header("content-type", format!("application/x-amz-json-{json_version}"))
        .header("x-amz-target", format!("{target_prefix}.{operation}"))
        .body(Bytes::from(body.to_string()))
        .expect("the test request is well formed");
    let response = router.dispatch(request).await;
    let status = response.status().as_u16();
    let parsed: Value = if response.body().is_empty() {
        Value::Null
    } else {
        serde_json::from_slice(response.body()).unwrap_or(Value::Null)
    };
    assert_eq!(
        status, 200,
        "case {case:?}: expected HTTP 200 from {signing_name} {operation}, got {status} with \
         {parsed}"
    );
    parsed
}

/// One EventBridge call (`awsJson1_1`, `AWSEvents.<Operation>`).
async fn events(router: &MultiServiceRouter, case: &str, operation: &str, body: &Value) -> Value {
    rpc(router, case, "events", "AWSEvents", "1.1", operation, body).await
}

/// One Amazon SQS call (`awsJson1_0`, `AmazonSQS.<Operation>`).
async fn sqs(router: &MultiServiceRouter, case: &str, operation: &str, body: &Value) -> Value {
    rpc(router, case, "sqs", "AmazonSQS", "1.0", operation, body).await
}

/// One `ec2Query` call: an `application/x-www-form-urlencoded` POST answered with XML.
async fn ec2(
    router: &MultiServiceRouter,
    case: &str,
    action: &str,
    params: &[(&str, &str)],
) -> String {
    let mut body = format!("Action={action}&Version={EC2_API_VERSION}");
    for (name, value) in params {
        body.push('&');
        body.push_str(&form_encode(name));
        body.push('=');
        body.push_str(&form_encode(value));
    }
    let request = http::Request::builder()
        .method("POST")
        .uri("/")
        .header("host", format!("ec2.{REGION}.amazonaws.com"))
        .header("authorization", authorization("ec2"))
        .header("content-type", "application/x-www-form-urlencoded")
        .body(Bytes::from(body))
        .expect("the test request is well formed");
    let response = router.dispatch(request).await;
    let status = response.status().as_u16();
    let text = String::from_utf8_lossy(response.body()).to_string();
    assert_eq!(
        status, 200,
        "case {case:?}: expected HTTP 200 from EC2 {action}, got {status} with {text}"
    );
    text
}

/// A string member of a JSON response, or a panic naming the case and what came back.
fn member(case: &str, body: &Value, pointer: &str) -> String {
    body.pointer(pointer)
        .and_then(Value::as_str)
        .unwrap_or_else(|| panic!("case {case:?}: expected {pointer} in {body}"))
        .to_string()
}

/// An SQS queue called `name`, created through SQS itself and admitting EventBridge's
/// service principal; answers its url and the ARN a rule names it by.
async fn queue(router: &MultiServiceRouter, case: &str, name: &str) -> (String, String) {
    let created = sqs(router, case, "CreateQueue", &json!({"QueueName": name})).await;
    let url = member(case, &created, "/QueueUrl");
    let attributes = sqs(
        router,
        case,
        "GetQueueAttributes",
        &json!({"QueueUrl": &url, "AttributeNames": ["QueueArn"]}),
    )
    .await;
    let arn = member(case, &attributes, "/Attributes/QueueArn");
    let policy = json!({
        "Version": "2012-10-17",
        "Statement": [{
            "Sid": "AllowEventBridge",
            "Effect": "Allow",
            "Principal": {"Service": EVENTS_PRINCIPAL},
            "Action": "sqs:SendMessage",
            "Resource": &arn,
        }],
    })
    .to_string();
    sqs(
        router,
        case,
        "SetQueueAttributes",
        &json!({"QueueUrl": &url, "Attributes": {"Policy": policy}}),
    )
    .await;
    (url, arn)
}

/// An ENABLED rule called `name` on the default bus carrying `pattern`, with the queue
/// `queue_arn` as its one target.
async fn rule(
    router: &MultiServiceRouter,
    case: &str,
    name: &str,
    pattern: &Value,
    queue_arn: &str,
) {
    events(
        router,
        case,
        "PutRule",
        &json!({
            "Name": name,
            "EventBusName": DEFAULT_BUS,
            "EventPattern": pattern.to_string(),
            "State": "ENABLED",
        }),
    )
    .await;
    let targeted = events(
        router,
        case,
        "PutTargets",
        &json!({
            "Rule": name,
            "EventBusName": DEFAULT_BUS,
            "Targets": [{"Id": "t1", "Arn": queue_arn}],
        }),
    )
    .await;
    assert_eq!(
        targeted["FailedEntryCount"],
        json!(0),
        "case {case:?}: every target must be accepted, got {targeted}"
    );
}

/// Every envelope now waiting on the queue at `url`, taken off it.
async fn drain(router: &MultiServiceRouter, case: &str, url: &str) -> Vec<Value> {
    let received = sqs(
        router,
        case,
        "ReceiveMessage",
        &json!({"QueueUrl": url, "MaxNumberOfMessages": 10}),
    )
    .await;
    let messages = received["Messages"].as_array().cloned().unwrap_or_default();
    let mut envelopes = Vec::new();
    for message in messages {
        if let Some(handle) = message["ReceiptHandle"].as_str() {
            sqs(
                router,
                case,
                "DeleteMessage",
                &json!({"QueueUrl": url, "ReceiptHandle": handle}),
            )
            .await;
        }
        let raw = message["Body"].as_str().unwrap_or_default();
        envelopes.push(serde_json::from_str::<Value>(raw).unwrap_or(Value::Null));
    }
    envelopes
}

/// Whether `envelope` names `snapshot_arn` among its `resources`.
fn names_snapshot(envelope: &Value, snapshot_arn: &str) -> bool {
    envelope["resources"].as_array().is_some_and(|resources| {
        resources
            .iter()
            .any(|resource| resource.as_str() == Some(snapshot_arn))
    })
}

/// The envelopes among `seen` and on the queue at `url` that name `snapshot_arn`, looked for
/// until [`DELIVERY_DEADLINE`] passes rather than waited out — so the answer is the one the
/// service published however fast the host runs.
///
/// Every envelope drained on the way is KEPT in `seen`, because one drain takes whatever has
/// arrived: a row's own envelope must not be lost to another row's poll.
async fn delivered_for(
    router: &MultiServiceRouter,
    case: &str,
    url: &str,
    snapshot_arn: &str,
    seen: &mut Vec<Value>,
) -> Vec<Value> {
    let deadline = Instant::now() + DELIVERY_DEADLINE;
    loop {
        seen.extend(drain(router, case, url).await);
        let mine: Vec<Value> = seen
            .iter()
            .filter(|envelope| names_snapshot(envelope, snapshot_arn))
            .cloned()
            .collect();
        if !mine.is_empty() {
            seen.retain(|envelope| !names_snapshot(envelope, snapshot_arn));
            return mine;
        }
        assert!(
            Instant::now() < deadline,
            "case {case:?}: an EBS snapshot notification for {snapshot_arn} must reach the \
             rule's queue, got {seen:?}"
        );
        tokio::time::sleep(POLL_INTERVAL).await;
    }
}

/// The ARN the account knows the snapshot `snapshot_id` by, as EC2 addresses a snapshot:
/// `arn:aws:ec2:<region>:<account>:snapshot/<id>`.
fn snapshot_arn(snapshot_id: &str) -> String {
    format!(
        "arn:aws:ec2:{REGION}:{account}:snapshot/{snapshot_id}",
        account = engine::emulator_account_id()
    )
}

/// What one row asks for and must therefore see.
struct Row {
    case: &'static str,
    /// The snapshot the outcome is about.
    snapshot_id: String,
    /// The ARN of what it was made from: a volume for a create, a snapshot for a copy.
    source_arn: String,
    /// The action the outcome is the outcome of.
    event: &'static str,
    /// The state the snapshot settles in, which is also what `DescribeSnapshots` reports.
    state: &'static str,
    /// The result that state reports.
    result: &'static str,
    /// The cause a failed outcome states, and empty for one that did not fail.
    cause: &'static str,
}

/// THE RULE over the actions that start a snapshot, routed by the result each outcome
/// reports.
#[tokio::test]
async fn an_ebs_snapshot_outcome_reaches_the_rule_that_matches_it() {
    let case = "the snapshot notification wiring";
    let router = router();

    // The two rules: one for every outcome, one pinned to the FAILED result — so an
    // envelope's routing is evidence of what it carried.
    let (every_url, every_arn) = queue(&router, case, "ec2-snapshot-outcomes").await;
    rule(
        &router,
        case,
        "ec2-snapshot-outcomes",
        &json!({"source": [EC2_SOURCE], "detail-type": [SNAPSHOT_NOTIFICATION]}),
        &every_arn,
    )
    .await;
    let (failed_url, failed_arn) = queue(&router, case, "ec2-snapshot-failures").await;
    rule(
        &router,
        case,
        "ec2-snapshot-failures",
        &json!({
            "source": [EC2_SOURCE],
            "detail-type": [SNAPSHOT_NOTIFICATION],
            "detail": {"result": [FAILED]},
        }),
        &failed_arn,
    )
    .await;

    // The create: one volume of the account, and one snapshot of it.
    let created_volume = ec2(
        &router,
        case,
        "CreateVolume",
        &[("AvailabilityZone", ZONE), ("VolumeType", "gp3"), ("Size", "4")],
    )
    .await;
    let volume_id = element(&created_volume, "volumeId");
    let volume_arn = element(&created_volume, "volumeArn");
    let created = ec2(
        &router,
        case,
        "CreateSnapshot",
        &[("VolumeId", volume_id.as_str())],
    )
    .await;
    let snapshot_id = element(&created, "snapshotId");

    // The copy of a snapshot that IS there, and the copy of one that is NOT: both are
    // accepted, and only the second fails.
    let copied = ec2(
        &router,
        case,
        "CopySnapshot",
        &[
            ("SourceSnapshotId", snapshot_id.as_str()),
            ("SourceRegion", REGION),
        ],
    )
    .await;
    let copy_id = element(&copied, "snapshotId");
    let failing = ec2(
        &router,
        case,
        "CopySnapshot",
        &[
            ("SourceSnapshotId", MISSING_SNAPSHOT_ID),
            ("SourceRegion", REGION),
        ],
    )
    .await;
    let failed_copy_id = element(&failing, "snapshotId");

    let rows = vec![
        Row {
            case: "a create of a volume of the account",
            snapshot_id: snapshot_id.clone(),
            source_arn: volume_arn,
            event: CREATE_SNAPSHOT_EVENT,
            state: COMPLETED,
            result: SUCCEEDED,
            cause: "",
        },
        Row {
            case: "a copy of a snapshot that is there",
            snapshot_id: copy_id,
            source_arn: snapshot_arn(&snapshot_id),
            event: COPY_SNAPSHOT_EVENT,
            state: COMPLETED,
            result: SUCCEEDED,
            cause: "",
        },
        Row {
            case: "a copy of a snapshot that is not there",
            snapshot_id: failed_copy_id,
            source_arn: snapshot_arn(MISSING_SNAPSHOT_ID),
            event: COPY_SNAPSHOT_EVENT,
            state: ERROR,
            result: FAILED,
            cause: MISSING_SOURCE_CAUSE,
        },
    ];

    // What each queue has handed over so far: a drain takes whatever has arrived, so the
    // envelopes of the rows that are not being waited for are kept rather than discarded.
    let mut every_seen: Vec<Value> = Vec::new();
    let mut failed_seen: Vec<Value> = Vec::new();
    for row in &rows {
        let case = row.case;
        let arn = snapshot_arn(&row.snapshot_id);
        let delivered = delivered_for(&router, case, &every_url, &arn, &mut every_seen).await;
        assert_eq!(
            delivered.len(),
            1,
            "case {case:?}: exactly one notification is published for {}, got {delivered:?}",
            row.snapshot_id
        );
        let envelope = &delivered[0];
        let checks: [(&str, &str); 2] = [
            ("/source", EC2_SOURCE),
            ("/detail-type", SNAPSHOT_NOTIFICATION),
        ];
        for (pointer, expected) in checks {
            assert_eq!(
                envelope.pointer(pointer).and_then(Value::as_str),
                Some(expected),
                "case {case:?}: expected {pointer} {expected:?}, got {envelope}"
            );
        }
        let detail: [(&str, &str); 5] = [
            ("event", row.event),
            ("state", row.state),
            ("result", row.result),
            ("cause", row.cause),
            ("source", row.source_arn.as_str()),
        ];
        for (name, expected) in detail {
            assert_eq!(
                envelope["detail"][name].as_str(),
                Some(expected),
                "case {case:?}: expected the detail {name} {expected:?}, got {envelope}"
            );
        }
        assert_eq!(
            envelope["detail"]["snapshot_id"].as_str(),
            Some(arn.as_str()),
            "case {case:?}: the detail names the snapshot it is about, got {envelope}"
        );

        // The rule pinned to the failed result sees this snapshot's envelope only when that
        // is what it carried — the negative half of the same rule.
        if row.result == FAILED {
            let routed = delivered_for(&router, case, &failed_url, &arn, &mut failed_seen).await;
            assert_eq!(
                routed.len(),
                1,
                "case {case:?}: the rule on the failed result takes this envelope, got {routed:?}"
            );
        } else {
            failed_seen.extend(drain(&router, case, &failed_url).await);
            assert!(
                failed_seen
                    .iter()
                    .all(|envelope| !names_snapshot(envelope, &arn)),
                "case {case:?}: the rule on the failed result takes no envelope of a snapshot \
                 that completed, got {failed_seen:?}"
            );
        }

        // The event and the API agree: the state the outcome reported is the one a read of
        // the snapshot reports once it has settled.
        let described = ec2(
            &router,
            case,
            "DescribeSnapshots",
            &[("SnapshotId.1", row.snapshot_id.as_str())],
        )
        .await;
        assert_eq!(
            element(&described, "status"),
            row.state,
            "case {case:?}: DescribeSnapshots must report {:?} for {}, got {described}",
            row.state,
            row.snapshot_id
        );
    }
}
