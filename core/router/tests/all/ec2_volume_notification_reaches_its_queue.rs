//! An EBS volume's create outcome reaches the queue an EventBridge rule delivers it to —
//! through the WHOLE mounted service set, the one `core/router/src/lib.rs` assembles for
//! the binary.
//!
//! The RULE under test: **a volume create is not finished when the API answers it, so
//! Amazon EC2 publishes the OUTCOME of that create once onto the account's DEFAULT
//! EventBridge bus as `source` `aws.ec2` / `detail-type` `EBS Volume Notification`, naming
//! the volume in the envelope's `resources` and carrying in the event `detail` the call it
//! is the outcome of (`createVolume`), the `result` that call reached — the state a volume
//! that comes into being reaches, or `failed` for one that cannot be created at all — and
//! the `cause` of a failure, in the words of the service that refused it.** EventBridge
//! then routes it by its CONTENT, so a rule whose `EventPattern` names that result delivers
//! it to that rule's queue and a rule naming the other result receives none of it.
//!
//! Four services have to agree for that to hold — Amazon EC2 publishes, AWS KMS decides
//! whether the volume's key will produce its data key, EventBridge routes, Amazon SQS holds
//! what arrived — and the publication Amazon EC2 makes is an in-process call addressed the
//! way a client's own `events`-scoped call is addressed, so WHICH mounted model claims it is
//! only decidable with every service mounted. The crate-local suite
//! `services/service-com-amazonaws-ec2-amazonec2/tests/all/volume_create_notifications.rs`
//! pins the same rule over a table of key states and the one-event-per-created-volume
//! guarantee; what only this suite can reach is that same path over the production service
//! set, where more than one model resolves to the `events` key.
//!
//! The rows differ along what the rule generalises over: the OUTCOME the create reaches (a
//! volume that is created, one whose key is disabled, one whose key is scheduled for
//! deletion), and with it the `cause` the event carries and WHICH of the two rules the
//! envelope is routed to.

use std::sync::Arc;
use std::time::{Duration, Instant};

use bytes::Bytes;
use serde_json::{json, Value};
use smithy_server_runtime::MultiServiceRouter;

use crate::query_wire::{element, form_encode};

/// The Region every request below is signed for.
const REGION: &str = "us-west-2";

/// The zone every volume below is created in.
const ZONE: &str = "us-west-2a";

/// The `source`, `detail-type` and `detail.event` Amazon EC2 publishes a volume create's
/// outcome under, spelled out here rather than imported from the service crate, so a wrong
/// constant in the implementation cannot make this suite pass.
const EC2_SOURCE: &str = "aws.ec2";
const VOLUME_NOTIFICATION: &str = "EBS Volume Notification";
const CREATE_VOLUME_EVENT: &str = "createVolume";

/// The two results a create reaches.
const AVAILABLE: &str = "available";
const FAILED: &str = "failed";

/// The bus an Amazon Web Services service's own events go to: "events generated by Amazon
/// Web Services services go to your account's default event bus".
const DEFAULT_BUS: &str = "default";

/// The service principal EventBridge delivers to an SQS target as, which is what a queue's
/// resource policy admits ("for Amazon SQS queues, EventBridge relies on resource-based
/// policies").
const EVENTS_PRINCIPAL: &str = "events.amazonaws.com";

/// The EC2 API version an ec2Query body carries.
const EC2_API_VERSION: &str = "2016-11-15";

/// How long a row waits for the publication to arrive on a queue before it gives up: far
/// above the work one create makes, and driven off what has ARRIVED rather than off a fixed
/// sleep, so a slow machine delays a row instead of breaking it.
const DELIVERY_DEADLINE: Duration = Duration::from_secs(30);

/// One poll of a queue inside [`DELIVERY_DEADLINE`].
const POLL_INTERVAL: Duration = Duration::from_millis(25);

/// The whole emulator over one engine, exactly as `core/router/src/lib.rs` assembles it for
/// the binary: Amazon EC2 publishes through the in-process callback, so WHICH mounted model
/// claims that `events`-scoped call has to be the one a client reaches too.
fn router() -> MultiServiceRouter {
    let engine = aws_emulator_router::new_engine();
    let mut router = aws_emulator_router::build_router(Arc::clone(&engine));
    router.set_request_authentication(false);
    router
}

/// A SigV4 `Authorization` whose credential scope names `service`, which is what routes the
/// request. The signature is never checked: the router above runs with request
/// authentication off.
fn authorization(service: &str) -> String {
    format!(
        "AWS4-HMAC-SHA256 Credential=AKIDEXAMPLE/20260101/{REGION}/{service}/aws4_request, \
         SignedHeaders=host, Signature=0000"
    )
}

/// One `X-Amz-Target` RPC call against the service whose signing name is `signing_name`,
/// which must answer 200.
async fn rpc(
    router: &MultiServiceRouter,
    case: &str,
    signing_name: &str,
    target_prefix: &str,
    json_version: &str,
    operation: &str,
    body: &Value,
) -> Value {
    let request = http::Request::builder()
        .method("POST")
        .uri("/")
        .header("host", format!("{signing_name}.{REGION}.amazonaws.com"))
        .header("authorization", authorization(signing_name))
        .header("content-type", format!("application/x-amz-json-{json_version}"))
        .header("x-amz-target", format!("{target_prefix}.{operation}"))
        .body(Bytes::from(body.to_string()))
        .expect("the test request is well formed");
    let response = router.dispatch(request).await;
    let status = response.status().as_u16();
    let parsed: Value = if response.body().is_empty() {
        Value::Null
    } else {
        serde_json::from_slice(response.body()).unwrap_or(Value::Null)
    };
    assert_eq!(
        status, 200,
        "case {case:?}: expected HTTP 200 from {signing_name} {operation}, got {status} with \
         {parsed}"
    );
    parsed
}

/// One EventBridge call (`awsJson1_1`, `AWSEvents.<Operation>`).
async fn events(router: &MultiServiceRouter, case: &str, operation: &str, body: &Value) -> Value {
    rpc(router, case, "events", "AWSEvents", "1.1", operation, body).await
}

/// One Amazon SQS call (`awsJson1_0`, `AmazonSQS.<Operation>`).
async fn sqs(router: &MultiServiceRouter, case: &str, operation: &str, body: &Value) -> Value {
    rpc(router, case, "sqs", "AmazonSQS", "1.0", operation, body).await
}

/// One AWS KMS call (`awsJson1_1`, `TrentService.<Operation>`).
async fn kms(router: &MultiServiceRouter, case: &str, operation: &str, body: &Value) -> Value {
    rpc(router, case, "kms", "TrentService", "1.1", operation, body).await
}

/// One `ec2Query` call: an `application/x-www-form-urlencoded` POST answered with XML.
async fn ec2(
    router: &MultiServiceRouter,
    case: &str,
    action: &str,
    params: &[(&str, &str)],
) -> String {
    let mut body = format!("Action={action}&Version={EC2_API_VERSION}");
    for (name, value) in params {
        body.push('&');
        body.push_str(&form_encode(name));
        body.push('=');
        body.push_str(&form_encode(value));
    }
    let request = http::Request::builder()
        .method("POST")
        .uri("/")
        .header("host", format!("ec2.{REGION}.amazonaws.com"))
        .header("authorization", authorization("ec2"))
        .header("content-type", "application/x-www-form-urlencoded")
        .body(Bytes::from(body))
        .expect("the test request is well formed");
    let response = router.dispatch(request).await;
    let status = response.status().as_u16();
    let text = String::from_utf8_lossy(response.body()).to_string();
    assert_eq!(
        status, 200,
        "case {case:?}: expected HTTP 200 from EC2 {action}, got {status} with {text}"
    );
    text
}

/// A string member of a JSON response, or a panic naming the case and what came back.
fn member(case: &str, body: &Value, pointer: &str) -> String {
    body.pointer(pointer)
        .and_then(Value::as_str)
        .unwrap_or_else(|| panic!("case {case:?}: expected {pointer} in {body}"))
        .to_string()
}

/// An SQS queue called `name`, created through SQS itself and admitting EventBridge's
/// service principal; answers its url and the ARN a rule names it by.
async fn queue(router: &MultiServiceRouter, case: &str, name: &str) -> (String, String) {
    let created = sqs(router, case, "CreateQueue", &json!({"QueueName": name})).await;
    let url = member(case, &created, "/QueueUrl");
    let attributes = sqs(
        router,
        case,
        "GetQueueAttributes",
        &json!({"QueueUrl": &url, "AttributeNames": ["QueueArn"]}),
    )
    .await;
    let arn = member(case, &attributes, "/Attributes/QueueArn");
    let policy = json!({
        "Version": "2012-10-17",
        "Statement": [{
            "Sid": "AllowEventBridge",
            "Effect": "Allow",
            "Principal": {"Service": EVENTS_PRINCIPAL},
            "Action": "sqs:SendMessage",
            "Resource": &arn,
        }],
    })
    .to_string();
    sqs(
        router,
        case,
        "SetQueueAttributes",
        &json!({"QueueUrl": &url, "Attributes": {"Policy": policy}}),
    )
    .await;
    (url, arn)
}

/// An ENABLED rule called `name` on the default bus carrying `pattern`, with the queue
/// `queue_arn` as its one target.
async fn rule(
    router: &MultiServiceRouter,
    case: &str,
    name: &str,
    pattern: &Value,
    queue_arn: &str,
) {
    events(
        router,
        case,
        "PutRule",
        &json!({
            "Name": name,
            "EventBusName": DEFAULT_BUS,
            "EventPattern": pattern.to_string(),
            "State": "ENABLED",
        }),
    )
    .await;
    let targeted = events(
        router,
        case,
        "PutTargets",
        &json!({
            "Rule": name,
            "EventBusName": DEFAULT_BUS,
            "Targets": [{"Id": "t1", "Arn": queue_arn}],
        }),
    )
    .await;
    assert_eq!(
        targeted["FailedEntryCount"],
        json!(0),
        "case {case:?}: every target must be accepted, got {targeted}"
    );
}

/// Every envelope now waiting on the queue at `url`, taken off it.
async fn drain(router: &MultiServiceRouter, case: &str, url: &str) -> Vec<Value> {
    let received = sqs(
        router,
        case,
        "ReceiveMessage",
        &json!({"QueueUrl": url, "MaxNumberOfMessages": 10}),
    )
    .await;
    let messages = received["Messages"].as_array().cloned().unwrap_or_default();
    let mut envelopes = Vec::new();
    for message in messages {
        if let Some(handle) = message["ReceiptHandle"].as_str() {
            sqs(
                router,
                case,
                "DeleteMessage",
                &json!({"QueueUrl": url, "ReceiptHandle": handle}),
            )
            .await;
        }
        let raw = message["Body"].as_str().unwrap_or_default();
        envelopes.push(serde_json::from_str::<Value>(raw).unwrap_or(Value::Null));
    }
    envelopes
}

/// The envelopes on the queue at `url` that name `volume_arn`, looked for until
/// [`DELIVERY_DEADLINE`] passes rather than waited out — so the answer is the one the
/// service published however fast the host runs.
async fn delivered_for(
    router: &MultiServiceRouter,
    case: &str,
    url: &str,
    volume_arn: &str,
) -> Vec<Value> {
    let deadline = Instant::now() + DELIVERY_DEADLINE;
    let mut arrived: Vec<Value> = Vec::new();
    loop {
        arrived.extend(drain(router, case, url).await);
        let mine: Vec<Value> = arrived
            .iter()
            .filter(|envelope| {
                envelope["resources"].as_array().is_some_and(|resources| {
                    resources
                        .iter()
                        .any(|resource| resource.as_str() == Some(volume_arn))
                })
            })
            .cloned()
            .collect();
        if !mine.is_empty() {
            return mine;
        }
        assert!(
            Instant::now() < deadline,
            "case {case:?}: an EBS volume notification for {volume_arn} must reach the rule's \
             queue, got {arrived:?}"
        );
        tokio::time::sleep(POLL_INTERVAL).await;
    }
}

/// One customer managed key AWS KMS minted, answering its key id and its ARN.
async fn key(router: &MultiServiceRouter, case: &str) -> (String, String) {
    let created = kms(router, case, "CreateKey", &json!({})).await;
    (
        member(case, &created, "/KeyMetadata/KeyId"),
        member(case, &created, "/KeyMetadata/Arn"),
    )
}

/// What one row asks for and must therefore see.
struct Row {
    case: &'static str,
    /// The members this row adds to the create, beyond the zone, type and size.
    extra: Vec<(&'static str, String)>,
    /// The `result` the published event must report.
    result: &'static str,
    /// The `cause` it must carry: the sentence the service that refused the volume stated,
    /// and empty for an outcome that did not fail.
    cause: String,
}

/// THE RULE over the outcomes of a create, routed by the result each one reports.
#[tokio::test]
async fn an_ebs_volume_create_outcome_reaches_the_rule_that_matches_it() {
    let case = "the volume notification wiring";
    let router = router();

    // The two rules: one for every outcome, one pinned to the FAILED result — so an
    // envelope's routing is evidence of what it carried.
    let (every_url, every_arn) = queue(&router, case, "ec2-volume-outcomes").await;
    rule(
        &router,
        case,
        "ec2-volume-outcomes",
        &json!({"source": [EC2_SOURCE], "detail-type": [VOLUME_NOTIFICATION]}),
        &every_arn,
    )
    .await;
    let (failed_url, failed_arn) = queue(&router, case, "ec2-volume-failures").await;
    rule(
        &router,
        case,
        "ec2-volume-failures",
        &json!({
            "source": [EC2_SOURCE],
            "detail-type": [VOLUME_NOTIFICATION],
            "detail": {"result": [FAILED]},
        }),
        &failed_arn,
    )
    .await;

    // Each key is minted by AWS KMS itself and then moved into the state its row is about,
    // through KMS's own API.
    let (enabled, _) = key(&router, "an enabled key").await;
    let (disabled, disabled_arn) = key(&router, "a disabled key").await;
    kms(
        &router,
        "a disabled key",
        "DisableKey",
        &json!({"KeyId": &disabled}),
    )
    .await;
    let (pending, pending_arn) = key(&router, "a key pending deletion").await;
    kms(
        &router,
        "a key pending deletion",
        "ScheduleKeyDeletion",
        &json!({"KeyId": &pending, "PendingWindowInDays": 7}),
    )
    .await;

    let rows = vec![
        Row {
            case: "a volume under a key KMS will produce a data key under",
            extra: vec![("Encrypted", "true".to_string()), ("KmsKeyId", enabled)],
            result: AVAILABLE,
            cause: String::new(),
        },
        Row {
            case: "a volume under a disabled key",
            extra: vec![("Encrypted", "true".to_string()), ("KmsKeyId", disabled)],
            result: FAILED,
            cause: format!("{disabled_arn} is disabled."),
        },
        Row {
            case: "a volume under a key scheduled for deletion",
            extra: vec![("Encrypted", "true".to_string()), ("KmsKeyId", pending)],
            result: FAILED,
            cause: format!("{pending_arn} is pending deletion."),
        },
    ];

    for row in &rows {
        let case = row.case;
        let mut params: Vec<(&str, &str)> = vec![
            ("AvailabilityZone", ZONE),
            ("VolumeType", "gp3"),
            ("Size", "4"),
        ];
        for (name, value) in &row.extra {
            params.push((name, value.as_str()));
        }
        let created = ec2(&router, case, "CreateVolume", &params).await;
        let volume_id = element(&created, "volumeId");
        let volume_arn = element(&created, "volumeArn");

        let delivered = delivered_for(&router, case, &every_url, &volume_arn).await;
        assert_eq!(
            delivered.len(),
            1,
            "case {case:?}: exactly one notification is published for {volume_id}, got \
             {delivered:?}"
        );
        let envelope = &delivered[0];
        assert_eq!(
            envelope["source"].as_str(),
            Some(EC2_SOURCE),
            "case {case:?}: expected the source {EC2_SOURCE}, got {envelope}"
        );
        assert_eq!(
            envelope["detail-type"].as_str(),
            Some(VOLUME_NOTIFICATION),
            "case {case:?}: expected the detail-type {VOLUME_NOTIFICATION}, got {envelope}"
        );
        assert_eq!(
            envelope["detail"]["event"].as_str(),
            Some(CREATE_VOLUME_EVENT),
            "case {case:?}: expected the event {CREATE_VOLUME_EVENT}, got {envelope}"
        );
        assert_eq!(
            envelope["detail"]["result"].as_str(),
            Some(row.result),
            "case {case:?}: expected the result {:?}, got {envelope}",
            row.result
        );
        assert_eq!(
            envelope["detail"]["cause"].as_str(),
            Some(row.cause.as_str()),
            "case {case:?}: expected the cause {:?}, got {envelope}",
            row.cause
        );

        // The rule pinned to the failed result sees this volume's envelope only when that
        // is what it carried — the negative half of the same rule.
        if row.result == FAILED {
            let routed = delivered_for(&router, case, &failed_url, &volume_arn).await;
            assert_eq!(
                routed.len(),
                1,
                "case {case:?}: the rule on the failed result takes this envelope, got \
                 {routed:?}"
            );
        } else {
            let routed = drain(&router, case, &failed_url).await;
            assert!(
                routed.is_empty(),
                "case {case:?}: the rule on the failed result takes no envelope of a volume \
                 that was created, got {routed:?}"
            );
        }
    }
}
