/// The namespace an Application Load Balancer's metrics live in, and the series this suite reads —
/// spelled out here rather than imported, so a wrong constant in the implementation cannot make a
/// test pass.
const APPLICATION_NAMESPACE: &str = "AWS/ApplicationELB";
const REQUEST_COUNT: &str = "RequestCount";
const TARGET_RESPONSE_TIME: &str = "TargetResponseTime";
const TARGET_2XX_COUNT: &str = "HTTPCode_Target_2XX_Count";
const TARGET_4XX_COUNT: &str = "HTTPCode_Target_4XX_Count";
const ELB_5XX_COUNT: &str = "HTTPCode_ELB_5XX_Count";

/// The dimensions an Elastic Load Balancing series carries, and the units these series are
/// published in.
const LOAD_BALANCER_DIMENSION: &str = "LoadBalancer";
const TARGET_GROUP_DIMENSION: &str = "TargetGroup";
const COUNT_UNIT: &str = "Count";
const SECONDS_UNIT: &str = "Seconds";

/// How an Elastic Load Balancing dimension names an Application Load Balancer and a target group:
/// the ARN from the resource type onwards, whose first segment is the family code for a load
/// balancer (`app/my-load-balancer/50dc6c495c0c9188`) and the resource type for a group
/// (`targetgroup/my-targets/73e2d6bc24d8a067`), as the Application Load Balancer metric reference
/// writes both.
const APPLICATION_FAMILY_CODE: &str = "app";
const TARGET_GROUP_PREFIX: &str = "targetgroup";

/// The names the metered topology's resources take, and the names the quiet one's take: each test
/// drives an engine of its own, and distinct names keep a failure's message unambiguous.
const FAMILY: &str = "meteredfamily";
const GROUP_NAME: &str = "metered-group";
const LOAD_BALANCER_NAME: &str = "metered-lb";
const SERVICE_NAME: &str = "meteredsvc";
const QUIET_GROUP_NAME: &str = "quiet-group";
const QUIET_LOAD_BALANCER_NAME: &str = "quiet-lb";

/// The port the container's server listens on, which is the `containerPort` the revision declares,
/// the port the binding names and the target group's own.
const PORT: i64 = 80;

/// The marker the container's own program writes into the document it serves, so a body anything
/// else produced fails the row.
const MARKER: &str = "ALB-METERED-TASK";

/// The paths the rows ask for: the page the container wrote, and a path its document root holds
/// nothing at.
const ROOT_PATH: &str = "/";
const MISSING_PATH: &str = "/nothing-here";

/// The status the target answers the document it holds with, and the one its own static server
/// answers a path its document root holds nothing at.
const SERVED_STATUS: u16 = 200;
const NOT_FOUND_STATUS: u16 = 404;

/// How long one wait keeps looking before it gives up, and how often it looks again. Each wait gets
/// this budget of its OWN: the deadline is here so a failure is a failure rather than a hang, and
/// nothing below asserts on elapsed time.
const DEADLINE: Duration = Duration::from_secs(120);
const POLL: Duration = Duration::from_millis(100);

/// How many further looks the assertion of EMPTINESS takes. Together with [`POLL`] a window far
/// longer than the spacing a publisher that is catching up writes at, so an emptiness the test
/// asserts is one that HELD rather than one read too early.
const QUIET_LOOKS: usize = 20;

/// How a client ADDRESSES the load balancer, which is one dimension the rows differ along.
#[derive(Debug, Clone, Copy)]
enum Addressing {
    /// A real connection to the authority the control plane published, which is what the client
    /// that was handed that address opens.
    Dialled,
    /// The published authority sent as the request's `Host`.
    HostStyle,
}

/// One batch: how the client addresses the load balancer, what it asks for, what it must be
/// answered with, and how many requests the batch drives.
struct Row {
    case: &'static str,
    addressing: Addressing,
    path: &'static str,
    status: u16,
    requests: usize,
}

const ROWS: &[Row] = &[
    Row {
        case: "one request dialled on the published address for the page the container wrote",
        addressing: Addressing::Dialled,
        path: ROOT_PATH,
        status: SERVED_STATUS,
        requests: 1,
    },
    Row {
        case: "three further requests dialled on the published address for the same page",
        addressing: Addressing::Dialled,
        path: ROOT_PATH,
        status: SERVED_STATUS,
        requests: 3,
    },
    Row {
        case: "two requests sending the published authority as the Host for the same page",
        addressing: Addressing::HostStyle,
        path: ROOT_PATH,
        status: SERVED_STATUS,
        requests: 2,
    },
    Row {
        case: "one request dialled for a path the container holds nothing at",
        addressing: Addressing::Dialled,
        path: MISSING_PATH,
        status: NOT_FOUND_STATUS,
        requests: 1,
    },
    Row {
        case: "two requests sending the authority as the Host for a path held nothing at",
        addressing: Addressing::HostStyle,
        path: MISSING_PATH,
        status: NOT_FOUND_STATUS,
        requests: 2,
    },
];

/// One emulator carrying Amazon EC2, Elastic Load Balancing v2, Amazon ECS and CloudWatch — which
/// owns the metric store both publishers write into — over ONE shared engine, exactly as the
/// production router builds them.
fn emulator() -> MultiServiceRouter {
    let engine: Arc<engine::InMemoryEngine> = Arc::new(engine::InMemoryEngine::new());
    let mut router = MultiServiceRouter::new();
    router.set_request_authentication(false);
    router.register_service(service_com_amazonaws_ec2_amazonec2::EmulatedService::new(
        Arc::clone(&engine),
    ));
    router.register_service(
        service_com_amazonaws_elasticloadbalancingv2_elasticloadbalancing_v10::EmulatedService::new(
            Arc::clone(&engine),
        ),
    );
    router.register_service(
        service_com_amazonaws_ecs_amazonec2containerservicev20141113::EmulatedService::new(
            Arc::clone(&engine),
        ),
    );
    router.register_service(
        service_com_amazonaws_cloudwatch_graniteserviceversion20100801::EmulatedService::new(engine),
    );
    router
}

/// Epoch seconds, for the window a statistics read asks about.
fn epoch_seconds() -> f64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_secs_f64()
}

/// Every datapoint CloudWatch holds for `metric` of `namespace` on exactly `dimensions`.
async fn datapoints(
    router: &MultiServiceRouter,
    namespace: &str,
    metric: &str,
    dimensions: &Value,
) -> Vec<Value> {
    let now = epoch_seconds();
    let stats = cloudwatch(
        router,
        "GetMetricStatistics",
        json!({
            "Namespace": namespace,
            "MetricName": metric,
            "Dimensions": dimensions,
            // Wide enough to hold the whole run-up a series opens with.
            "StartTime": now - 1_800.0,
            "EndTime": now + 600.0,
            "Period": 60,
            "Statistics": ["Sum", "Minimum", "Maximum", "SampleCount"],
        }),
    )
    .await;
    stats["Datapoints"].as_array().cloned().unwrap_or_default()
}

/// The `Sum` of every datapoint a series holds, which is 0.0 for a series holding none.
fn total(points: &[Value]) -> f64 {
    points
        .iter()
        .filter_map(|point| point["Sum"].as_f64())
        .sum()
}

/// How many observations the datapoints of a series stand for.
fn samples(points: &[Value]) -> f64 {
    points
        .iter()
        .filter_map(|point| point["SampleCount"].as_f64())
        .sum()
}

/// Every `Unit` the datapoints of a series report.
fn reported_units(points: &[Value]) -> BTreeSet<String> {
    points
        .iter()
        .map(|point| point["Unit"].as_str().unwrap_or_default().to_string())
        .collect()
}

/// Wait until the `Sum` of `metric` on `dimensions` reaches `expected`, and assert it is exactly
/// that — so a request counted twice fails as loudly as one counted not at all.
///
/// A series with nothing to report holds no datapoint, whose `Sum` is the sum of nothing: an
/// `expected` of 0.0 is satisfied by that, and is broken by any datapoint at all.
async fn counted(
    router: &MultiServiceRouter,
    case: &str,
    metric: &str,
    dimensions: &Value,
    expected: f64,
) -> Vec<Value> {
    let deadline = Instant::now() + DEADLINE;
    loop {
        let points = datapoints(router, APPLICATION_NAMESPACE, metric, dimensions).await;
        let sum = total(&points);
        if sum >= expected {
            assert_eq!(
                sum, expected,
                "case {case:?}: expected the {metric} Sum on {dimensions} to be exactly \
                 {expected}, got {sum} over {points:?}"
            );
            return points;
        }
        assert!(
            Instant::now() < deadline,
            "case {case:?}: expected the {metric} Sum on {dimensions} to reach {expected}, got \
             {sum} over {points:?}"
        );
        ::tokio::time::sleep(POLL).await;
    }
}

/// Assert that `metric` on `dimensions` holds NO datapoint, looked at again and again over a
/// window far longer than the spacing a publisher that is catching up writes at — so the
/// emptiness asserted is one that HELD rather than one read before a lagging publisher wrote.
///
/// A count of nothing is not a datapoint of zero: that is the reporting criteria these series
/// carry, and it is what makes the split between what the LOAD BALANCER produced and what the
/// TARGET produced readable at all.
async fn stays_empty(router: &MultiServiceRouter, case: &str, metric: &str, dimensions: &Value) {
    for look in 0..QUIET_LOOKS {
        let points = datapoints(router, APPLICATION_NAMESPACE, metric, dimensions).await;
        assert!(
            points.is_empty(),
            "case {case:?}: look {look}: no request of {metric} was answered, so that series \
             holds no datapoint at all, got {points:?}"
        );
        ::tokio::time::sleep(POLL).await;
    }
}

/// Wait until `metric` of `namespace` holds at least one datapoint on `dimensions`, and answer
/// every datapoint it then holds.
async fn published(
    router: &MultiServiceRouter,
    case: &str,
    namespace: &str,
    metric: &str,
    dimensions: &Value,
) -> Vec<Value> {
    let deadline = Instant::now() + DEADLINE;
    loop {
        let points = datapoints(router, namespace, metric, dimensions).await;
        if !points.is_empty() {
            return points;
        }
        assert!(
            Instant::now() < deadline,
            "case {case:?}: expected {namespace} {metric} datapoints on {dimensions}, got none"
        );
        ::tokio::time::sleep(POLL).await;
    }
}

/// Wait until some datapoint of `metric` reports a POSITIVE maximum, and answer it.
///
/// What a MEASUREMENT of a running container looks like, as against a placeholder: the figure is
/// read off the run this emulator performs for that container, so it is positive once that run is
/// holding anything at all. Polls the CONDITION rather than waiting a fixed time.
async fn measured_positive(
    router: &MultiServiceRouter,
    case: &str,
    metric: &str,
    dimensions: &Value,
) -> f64 {
    let deadline = Instant::now() + DEADLINE;
    loop {
        let points = datapoints(router, ECS_NAMESPACE, metric, dimensions).await;
        let highest = points
            .iter()
            .filter_map(|point| point["Maximum"].as_f64())
            .fold(f64::NEG_INFINITY, f64::max);
        if highest > 0.0 {
            return highest;
        }
        assert!(
            Instant::now() < deadline,
            "case {case:?}: expected a positive {metric} maximum on {dimensions}, got \
             {points:?}"
        );
        ::tokio::time::sleep(POLL).await;
    }
}

/// The dimension set of every `metric` series the Application namespace holds, as `ListMetrics`
/// lists them.
async fn listed_dimension_sets(
    router: &MultiServiceRouter,
    metric: &str,
) -> Vec<Vec<(String, String)>> {
    let listed = cloudwatch(
        router,
        "ListMetrics",
        json!({ "Namespace": APPLICATION_NAMESPACE, "MetricName": metric }),
    )
    .await;
    listed["Metrics"]
        .as_array()
        .cloned()
        .unwrap_or_default()
        .iter()
        .map(|metric| {
            metric["Dimensions"]
                .as_array()
                .cloned()
                .unwrap_or_default()
                .iter()
                .map(|dimension| {
                    (
                        dimension["Name"].as_str().unwrap_or_default().to_string(),
                        dimension["Value"].as_str().unwrap_or_default().to_string(),
                    )
                })
                .collect()
        })
        .collect()
}

/// Wait until `ListMetrics` lists a `RequestCount` series carrying the `LoadBalancer` dimension
/// ALONE, and answer the value that dimension holds — the name the load balancer's own counts are
/// keyed by, which no caller states and only the publisher can have written.
async fn published_load_balancer_dimension(router: &MultiServiceRouter, case: &str) -> String {
    let deadline = Instant::now() + DEADLINE;
    loop {
        let sets = listed_dimension_sets(router, REQUEST_COUNT).await;
        let own = sets
            .iter()
            .find(|set| set.len() == 1 && set[0].0 == LOAD_BALANCER_DIMENSION);
        if let Some(set) = own {
            return set[0].1.clone();
        }
        assert!(
            Instant::now() < deadline,
            "case {case:?}: expected a {REQUEST_COUNT} series on the {LOAD_BALANCER_DIMENSION} \
             dimension alone, got {sets:?}"
        );
        ::tokio::time::sleep(POLL).await;
    }
}

/// How an Elastic Load Balancing dimension names the resource `arn` identifies: that ARN from the
/// resource type onwards.
fn dimension_value_of(arn: &str) -> String {
    arn.splitn(6, ':').nth(5).unwrap_or_default().to_string()
}

/// RULE: every request answered on the address the load balancer published is metered into its
/// family's own namespace, on its own dimension and on the pair naming the group that answered —
/// and the service behind it publishes its own utilization while it holds a running task.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn the_traffic_driven_at_the_published_address_is_metered_into_both_namespaces() {
    let router = emulator();
    let network = seed_network(&router).await;
    ecs_ok(&router, "CreateCluster", json!({ "clusterName": CLUSTER })).await;
    let program = serving_command(MARKER);
    let command: Vec<&str> = program.iter().map(String::as_str).collect();
    let revision = register_revision(&router, FAMILY, PORT, &command).await;
    let setup = "an ALB forwarding to the ip target of one awsvpc ECS task";
    let (group, dns_name) = front_door(
        &router,
        &network,
        setup,
        GROUP_NAME,
        LOAD_BALANCER_NAME,
        PORT,
    )
    .await;
    create_service(&router, &network, SERVICE_NAME, &revision, &group, PORT).await;
    // The registration's health comes first: the rule is about the requests a target the load
    // balancer's own checks found healthy ANSWERED.
    healthy_target(&router, setup, &group, SERVICE_NAME).await;

    // The group's own dimension is read off the ARN the control plane minted for it, and the load
    // balancer's off the series the publisher wrote: the one value no call of this test states.
    let group_dimension = dimension_value_of(&group);
    assert!(
        group_dimension.starts_with(&format!("{TARGET_GROUP_PREFIX}/{GROUP_NAME}/")),
        "case {setup:?}: expected the group's dimension to be its ARN from \
         {TARGET_GROUP_PREFIX:?} onwards, got {group_dimension:?} for {group:?}"
    );

    let mut requests = 0.0_f64;
    let mut served = 0.0_f64;
    let mut missing = 0.0_f64;
    let mut load_balancer_dimension = String::new();
    for row in ROWS {
        for _ in 0..row.requests {
            let answered = match row.addressing {
                Addressing::Dialled => dialled(row.case, &dns_name, row.path).await,
                Addressing::HostStyle => get(&router, &dns_name, row.path).await,
            };
            assert_eq!(
                answered.status, row.status,
                "case {:?}: expected the target's own HTTP {}, got {} with body {:?}",
                row.case, row.status, answered.status, answered.body
            );
            let carries_marker = answered.body.contains(MARKER);
            assert_eq!(
                carries_marker,
                row.status == SERVED_STATUS,
                "case {:?}: only the document the container's program wrote carries {MARKER:?}, \
                 got {:?}",
                row.case,
                answered.body
            );
        }
        requests += row.requests as f64;
        if row.status == SERVED_STATUS {
            served += row.requests as f64;
        } else {
            missing += row.requests as f64;
        }

        if load_balancer_dimension.is_empty() {
            load_balancer_dimension = published_load_balancer_dimension(&router, row.case).await;
            let segments: Vec<&str> = load_balancer_dimension.split('/').collect();
            assert!(
                segments.len() == 3
                    && segments[0] == APPLICATION_FAMILY_CODE
                    && segments[1] == LOAD_BALANCER_NAME
                    && !segments[2].is_empty(),
                "case {:?}: expected the load balancer's dimension to be \
                 {APPLICATION_FAMILY_CODE}/{LOAD_BALANCER_NAME}/<id>, got \
                 {load_balancer_dimension:?}",
                row.case
            );
        }
        let own = json!([
            { "Name": LOAD_BALANCER_DIMENSION, "Value": load_balancer_dimension },
        ]);
        let pair = json!([
            { "Name": TARGET_GROUP_DIMENSION, "Value": group_dimension },
            { "Name": LOAD_BALANCER_DIMENSION, "Value": load_balancer_dimension },
        ]);

        // Every request the load balancer answered is one request processed, counted once on its
        // own dimension and once on the pair naming the group it forwarded to.
        let counts = counted(&router, row.case, REQUEST_COUNT, &own, requests).await;
        assert_eq!(
            reported_units(&counts),
            BTreeSet::from([COUNT_UNIT.to_string()]),
            "case {:?}: a number of requests is published in {COUNT_UNIT}, got {counts:?}",
            row.case
        );
        counted(&router, row.case, REQUEST_COUNT, &pair, requests).await;
        // The status class is counted to the end that PRODUCED it: both of these statuses are the
        // target's own, so each goes to the target's class series and to none of the load
        // balancer's (asserted of the load balancer's own series after the loop, where the
        // emptiness can be read over a window rather than at one instant).
        counted(&router, row.case, TARGET_2XX_COUNT, &own, served).await;
        counted(&router, row.case, TARGET_4XX_COUNT, &own, missing).await;
    }

    // The time the TARGET took, for the requests a target was called for: ONE observation per
    // request, in seconds, each of them a span that elapsed rather than nothing at all. A health
    // check is not among them — it is not a request the load balancer answered for a client, which
    // the exact `RequestCount` sums above establish.
    let own = json!([
        { "Name": LOAD_BALANCER_DIMENSION, "Value": load_balancer_dimension },
    ]);
    let timings = published(
        &router,
        setup,
        APPLICATION_NAMESPACE,
        TARGET_RESPONSE_TIME,
        &own,
    )
    .await;
    assert_eq!(
        reported_units(&timings),
        BTreeSet::from([SECONDS_UNIT.to_string()]),
        "case {setup:?}: a response time is published in {SECONDS_UNIT}, got {timings:?}"
    );
    let timed = samples(&timings);
    assert_eq!(
        timed, requests,
        "case {setup:?}: expected one {TARGET_RESPONSE_TIME} observation for each of the \
         {requests} requests a target answered, got {timed} over {timings:?}"
    );
    for point in &timings {
        let least = point["Minimum"].as_f64().unwrap_or(f64::NAN);
        assert!(
            least > 0.0,
            "case {setup:?}: a {TARGET_RESPONSE_TIME} is the span the call to the target took, so \
             it is positive, got {least} in {point:?}"
        );
    }

    // Both statuses these rows were answered with are the TARGET's own, so the load balancer
    // generated no status of its own and its own class series holds nothing — read over a window,
    // because an emptiness is only worth asserting if it HELD.
    stays_empty(&router, setup, ELB_5XX_COUNT, &own).await;

    // The SERVICE behind that load balancer meters itself while it holds a running task: its own
    // two percentages, on exactly the pair that names it.
    let service_dimensions = json!([
        { "Name": CLUSTER_DIMENSION, "Value": CLUSTER },
        { "Name": SERVICE_DIMENSION, "Value": SERVICE_NAME },
    ]);
    for metric in [CPU_UTILIZATION, MEMORY_UTILIZATION] {
        let points = published(&router, setup, ECS_NAMESPACE, metric, &service_dimensions).await;
        assert_eq!(
            reported_units(&points),
            BTreeSet::from([PERCENT.to_string()]),
            "case {setup:?}: {metric} is a share of what the service was given, so it is \
             published in {PERCENT}, got {points:?}"
        );
        for point in &points {
            let least = point["Minimum"].as_f64().unwrap_or(f64::NAN);
            let most = point["Maximum"].as_f64().unwrap_or(f64::NAN);
            assert!(
                (0.0..=100.0).contains(&least) && (0.0..=100.0).contains(&most),
                "case {setup:?}: every {metric} figure is a percentage of a reservation, so none \
                 is negative or past 100, got {least} to {most} in {point:?}"
            );
        }
    }

    // And one of those two is a MEASUREMENT of the running task rather than a placeholder: the
    // containers of a running task occupy memory, so the memory share they are reported at is
    // positive. (The CPU share legitimately idles at zero — a container that waits is using none of
    // the CPU it was given — so only the memory series carries this.)
    let occupied = measured_positive(&router, setup, MEMORY_UTILIZATION, &service_dimensions).await;
    assert!(
        occupied <= 100.0,
        "case {setup:?}: a memory share is a percentage of what the task definition reserves, got \
         {occupied}"
    );
}

/// RULE (the negative half): a count of nothing is not a datapoint of zero, so a load balancer no
/// client has sent a request to publishes no request series at all.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn a_load_balancer_that_answered_nothing_publishes_no_request_series() {
    let router = emulator();
    let network = seed_network(&router).await;
    let case = "an ALB and its listener that no client has sent a request to";
    front_door(&router, &network, case, QUIET_GROUP_NAME, QUIET_LOAD_BALANCER_NAME, PORT).await;

    // Looked at again and again over a window far longer than a publisher catching up writes at,
    // so the emptiness asserted is one that HELD rather than one read too early.
    for look in 0..QUIET_LOOKS {
        for metric in [REQUEST_COUNT, TARGET_RESPONSE_TIME, TARGET_2XX_COUNT] {
            let sets = listed_dimension_sets(&router, metric).await;
            assert!(
                sets.is_empty(),
                "case {case:?}: look {look}: no request of {metric} has been answered, so the \
                 namespace holds no such series, got {sets:?}"
            );
        }
        ::tokio::time::sleep(POLL).await;
    }
}
