//! The traffic a client drives through the ADDRESS an Application Load Balancer published, and
//! the two namespaces that traffic is metered into.
//!
//! RULE: **a load balancer meters every request it ANSWERED into the series of its own family's
//! namespace — one `RequestCount` on the `LoadBalancer` dimension that names it and one on the
//! `TargetGroup` + `LoadBalancer` pair that names the group which answered, each status class
//! counted to the end that PRODUCED it, and a positive `TargetResponseTime` in seconds for a
//! request a target was called for — whatever address a client used to reach it and however many
//! requests that client sent; a series with nothing to report holds no datapoint at all rather
//! than a zero. And while the Amazon ECS service behind that load balancer holds a running task,
//! that service publishes its own `CPUUtilization` and `MemoryUtilization` in `Percent` on
//! exactly the `ClusterName` + `ServiceName` pair that names it.**
//!
//! The grounds. `LoadBalancer$DNSName` is "the public DNS name of the load balancer", which is
//! the address a client is handed and sends its traffic to — so a load balancer that publishes a
//! name no client on this machine can reach is one whose request series can never be observed at
//! all. `RequestCount` is "the number of requests processed over IPv4 and IPv6" and
//! `TargetResponseTime` "the time elapsed, in seconds, after the request leaves the load balancer
//! until a response from the target is received", both of the Application Load Balancer's own
//! namespace, dimensioned by the load balancer (`app/<name>/<id>`) and, for what one group's
//! targets did, by that group beside it (`targetgroup/<name>/<id>`); `HTTPCode_Target_4XX_Count`
//! counts a status the TARGET answered and "does not include any response codes generated by the
//! load balancer", which the load balancer's own `HTTPCode_ELB_5XX_Count` does. The Amazon ECS
//! service utilization of the ECS developer guide divides what the tasks of one service use by
//! what that service's task definition reserves, which is why each of those two figures is a
//! percentage dimensioned on the one service it measures.
//!
//! Four crates have to agree for that to hold, which is why this suite lives here: Amazon ECS runs
//! the container and meters the service, Amazon EC2 owns the network the load balancer reaches it
//! over, Elastic Load Balancing v2 publishes the address and answers the client, and CloudWatch
//! owns the ONE metric store both publishers write into and a client reads back. Everything is
//! driven through the real operations on ONE shared engine, through the fixtures the suite that owns
//! this topology already keeps ([`crate::ecs_alb_serves_its_awsvpc_tasks_container`]: the network,
//! the revision, the front door, the service, the health poll and the one raw HTTP/1.1 exchange on a
//! published address) and the CloudWatch caller the suite that owns the `AWS/ECS` series keeps
//! ([`crate::ecs_service_utilization_metrics`]), so no fixture of either is copied here. What this
//! suite does keep of its own is the mounting \u2014 the rule spans FOUR services, so the emulator below
//! mounts CloudWatch beside the three that suite's own fixture needs \u2014 and the metric-store reader,
//! which this suite needs parameterised by namespace where the sibling's is private and `AWS/ECS`'s
//! alone.
//!
//! What is NEW here is that topology, not the metering rule: the owning crate already drives the
//! cumulative request series on its own
//! (`services/service-com-amazonaws-elasticloadbalancingv2-elasticloadbalancing-v10/tests/all/alb_request_metrics.rs`),
//! and the `AWS/ECS` series' own suite drives that half
//! ([`crate::ecs_service_utilization_metrics`]). Neither can see what a client that was handed
//! `LoadBalancer$DNSName` and DIALLED it is metered as, with real ECS tasks behind the group \u2014 which
//! is what the recorded checks this suite stands for do.
//!
//! The rows differ along what the rule generalises over: HOW the client addressed the published
//! load balancer (a real connection DIALLED to the published authority, and the same authority sent
//! as a `Host`), WHICH document it asked for (the page the container's program wrote, and a path
//! that container holds nothing at — the TARGET's own `404`, counted to the target's class series
//! and to none of the load balancer's) and HOW MANY requests one batch drove (one, two and three),
//! with the counts asserted cumulatively after every batch so each batch is counted exactly once.
//! The second test is the negative half: a load balancer nothing has sent a request to publishes no
//! request series at all.
//!
//! Every clock-owed move — the task's start, the registration it owes, the health its checks
//! determine, the datapoints the publishers owe — is POLLED for until it holds, never slept for,
//! and each deadline is generous: a row asserts that the move HAPPENS, not how fast this host runs.

