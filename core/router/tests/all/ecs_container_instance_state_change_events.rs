/// A string member at `pointer`, or a panic naming the case and what came back.
fn member(case: &str, body: &Value, pointer: &str) -> String {
    body.pointer(pointer)
        .and_then(Value::as_str)
        .unwrap_or_else(|| panic!("case {case:?}: expected {pointer} in {body}"))
        .to_string()
}

/// The ARN of the cluster named `name` in this account and Region.
fn cluster_arn(name: &str) -> String {
    format!("arn:aws:ecs:{REGION}:{ACCOUNT}:cluster/{name}")
}

/// The pattern of a rule matching the container-instance changes of ONE cluster that left the
/// instance in ONE status: the identity Amazon ECS publishes them under, narrowed through the
/// event's own `detail`.
fn container_instance_events_in(status: &str) -> Value {
    json!({
        "source": [EVENT_SOURCE],
        "detail-type": [CONTAINER_INSTANCE_STATE_CHANGE],
        "detail": { "clusterArn": [cluster_arn(CLUSTER)], "status": [status] },
    })
}

/// An SQS queue called `name`, created through Amazon SQS itself and admitting EventBridge's own
/// service principal; answers its url and the ARN a rule names it by.
async fn queue(router: &MultiServiceRouter, case: &str, name: &str) -> (String, String) {
    let created = sqs(router, case, "CreateQueue", &json!({ "QueueName": name })).await;
    let url = member(case, &created, "/QueueUrl");
    let attributes = sqs(
        router,
        case,
        "GetQueueAttributes",
        &json!({ "QueueUrl": &url, "AttributeNames": ["QueueArn"] }),
    )
    .await;
    let arn = member(case, &attributes, "/Attributes/QueueArn");
    let policy = json!({
        "Version": "2012-10-17",
        "Statement": [{
            "Sid": "AllowEventBridge",
            "Effect": "Allow",
            "Principal": { "Service": EVENTS_PRINCIPAL },
            "Action": "sqs:SendMessage",
            "Resource": arn,
        }],
    })
    .to_string();
    sqs(
        router,
        case,
        "SetQueueAttributes",
        &json!({ "QueueUrl": &url, "Attributes": { "Policy": policy } }),
    )
    .await;
    (url, arn)
}

/// An ENABLED rule called `name` on the default bus carrying `pattern`, with the queue
/// `queue_arn` as its one target.
async fn rule(
    router: &MultiServiceRouter,
    case: &str,
    name: &str,
    pattern: &Value,
    queue_arn: &str,
) {
    events(
        router,
        case,
        "PutRule",
        &json!({
            "Name": name,
            "EventBusName": DEFAULT_BUS,
            "EventPattern": pattern.to_string(),
            "State": "ENABLED",
        }),
    )
    .await;
    let targeted = events(
        router,
        case,
        "PutTargets",
        &json!({
            "Rule": name,
            "EventBusName": DEFAULT_BUS,
            "Targets": [{ "Id": "sqs-target", "Arn": queue_arn }],
        }),
    )
    .await;
    assert_eq!(
        targeted["FailedEntryCount"],
        json!(0),
        "case {case:?}: every target must be accepted, got {targeted}"
    );
}

/// Every message now waiting on the queue at `url`, as the parsed event envelopes their bodies
/// carry — each one DELETED as it is taken, the way a consumer of a queue reads it.
async fn drain(router: &MultiServiceRouter, case: &str, url: &str) -> Vec<Value> {
    let received = sqs(
        router,
        case,
        "ReceiveMessage",
        &json!({ "QueueUrl": url, "MaxNumberOfMessages": 10 }),
    )
    .await;
    let messages = received["Messages"]
        .as_array()
        .cloned()
        .unwrap_or_default();
    let mut envelopes: Vec<Value> = Vec::new();
    for message in &messages {
        let raw = message["Body"].as_str().unwrap_or_default();
        envelopes.push(serde_json::from_str::<Value>(raw).unwrap_or(Value::Null));
        let handle = member(case, message, "/ReceiptHandle");
        sqs(
            router,
            case,
            "DeleteMessage",
            &json!({ "QueueUrl": url, "ReceiptHandle": handle }),
        )
        .await;
    }
    envelopes
}

/// Stand the account's network up — a VPC, a public subnet, an internet gateway with a route to
/// it and an egress-only security group — and answer the subnet and the group a launch names.
async fn network(router: &MultiServiceRouter, case: &str) -> (String, String) {
    let vpc = element(
        &ec2(router, case, "CreateVpc", &[("CidrBlock", "10.90.0.0/16")]).await,
        "vpcId",
    );
    let zone = format!("{REGION}a");
    let subnet = element(
        &ec2(
            router,
            case,
            "CreateSubnet",
            &[
                ("VpcId", &vpc),
                ("CidrBlock", "10.90.1.0/24"),
                ("AvailabilityZone", &zone),
            ],
        )
        .await,
        "subnetId",
    );
    let gateway = element(
        &ec2(router, case, "CreateInternetGateway", &[]).await,
        "internetGatewayId",
    );
    ec2(
        router,
        case,
        "AttachInternetGateway",
        &[("InternetGatewayId", &gateway), ("VpcId", &vpc)],
    )
    .await;
    let tables = elements(
        &ec2(
            router,
            case,
            "DescribeRouteTables",
            &[("Filter.1.Name", "vpc-id"), ("Filter.1.Value.1", &vpc)],
        )
        .await,
        "routeTableId",
    );
    let table = tables.first().cloned().unwrap_or_else(|| {
        panic!("case {case:?}: expected the VPC to hold a route table, got {tables:?}")
    });
    ec2(
        router,
        case,
        "CreateRoute",
        &[
            ("RouteTableId", &table),
            ("DestinationCidrBlock", "0.0.0.0/0"),
            ("GatewayId", &gateway),
        ],
    )
    .await;
    let group = element(
        &ec2(
            router,
            case,
            "CreateSecurityGroup",
            &[
                ("GroupName", "capacityevents-egress"),
                ("GroupDescription", "egress only"),
                ("VpcId", &vpc),
            ],
        )
        .await,
        "groupId",
    );
    (subnet, group)
}

