/// Launch ONE host from the ECS-optimized image, with a public address, the instance profile and
/// the user data the documented way of joining a cluster carries; answers the Amazon EC2
/// instance id.
async fn launch_host(
    router: &MultiServiceRouter,
    case: &str,
    subnet: &str,
    group: &str,
    profile_arn: &str,
) -> String {
    let image = ssm_parameter(router, case, ECS_OPTIMIZED_AMI_PARAMETER).await;
    // "User data must be base64-encoded" (`RunInstancesRequest$UserData`), which is what an SDK
    // does to the shell line that appends the agent's configuration.
    let user_data = ::aws_smithy_types::base64::encode(format!(
        "#!/bin/bash\necho ECS_CLUSTER={CLUSTER} >> /etc/ecs/ecs.config\n"
    ));
    let launched = ec2(
        router,
        case,
        "RunInstances",
        &[
            ("ImageId", &image),
            ("InstanceType", INSTANCE_TYPE),
            ("MinCount", "1"),
            ("MaxCount", "1"),
            ("UserData", &user_data),
            ("IamInstanceProfile.Arn", profile_arn),
            ("NetworkInterface.1.DeviceIndex", "0"),
            ("NetworkInterface.1.SubnetId", subnet),
            ("NetworkInterface.1.AssociatePublicIpAddress", "true"),
            ("NetworkInterface.1.SecurityGroupId.1", group),
        ],
    )
    .await;
    element(&launched, "instanceId")
}

/// The container instance of the cluster whose `ec2InstanceId` is `instance_id`, as
/// `DescribeContainerInstances` reports it — reached through the listing a client walks first —
/// and `None` while the cluster holds no such capacity.
///
/// The default filter of the listing "includes container instances set to all states other than
/// INACTIVE", so a deregistered host is read back by naming its ARN instead.
async fn registered_host(
    router: &MultiServiceRouter,
    case: &str,
    instance_id: &str,
) -> Option<Value> {
    let listed = ecs(
        router,
        case,
        "ListContainerInstances",
        &json!({ "cluster": CLUSTER }),
    )
    .await;
    let arns: Vec<Value> = listed["containerInstanceArns"]
        .as_array()
        .cloned()
        .unwrap_or_default();
    if arns.is_empty() {
        return None;
    }
    let described = ecs(
        router,
        case,
        "DescribeContainerInstances",
        &json!({ "cluster": CLUSTER, "containerInstances": arns }),
    )
    .await;
    described["containerInstances"]
        .as_array()
        .into_iter()
        .flatten()
        .find(|host| host["ec2InstanceId"] == json!(instance_id))
        .cloned()
}

/// The container instance `arn` names, whatever status it is in.
async fn described_host(router: &MultiServiceRouter, case: &str, arn: &str) -> Value {
    let described = ecs(
        router,
        case,
        "DescribeContainerInstances",
        &json!({ "cluster": CLUSTER, "containerInstances": [arn] }),
    )
    .await;
    described["containerInstances"]
        .as_array()
        .and_then(|hosts| hosts.first())
        .cloned()
        .unwrap_or_else(|| panic!("case {case:?}: expected the host {arn} back, got {described}"))
}

/// The envelopes of `delivered` that report `version` for the instance `arn`.
fn reporting<'a>(delivered: &'a [Value], arn: &str, version: i64) -> Vec<&'a Value> {
    delivered
        .iter()
        .filter(|envelope| {
            envelope["detail"]["containerInstanceArn"] == json!(arn)
                && envelope["detail"]["version"] == json!(version)
        })
        .collect()
}

/// The `(status, version)` pair of every envelope of `delivered`, for a failure message that
/// says what DID arrive.
fn arrived(delivered: &[Value]) -> Vec<(String, i64)> {
    delivered
        .iter()
        .map(|envelope| {
            (
                envelope["detail"]["status"]
                    .as_str()
                    .unwrap_or_default()
                    .to_string(),
                envelope["detail"]["version"].as_i64().unwrap_or_default(),
            )
        })
        .collect()
}

/// WHICH change a row has the registered host experience.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Change {
    /// `UpdateContainerInstancesState` to `DRAINING`: the host is taken out of service.
    Drain,
    /// `DeregisterContainerInstance`: the host is taken out of the cluster.
    Deregister,
    /// `PutAttributes`: a custom attribute is written on the host, which moves no status.
    WriteAttribute,
}

/// One row: the change the host experiences and the status it leaves the host reporting.
struct Row {
    case: &'static str,
    change: Change,
    status: &'static str,
}

/// The table spans the rule: the KIND of change a container instance experiences.
const ROWS: &[Row] = &[
    Row {
        case: "a host drained out of service",
        change: Change::Drain,
        status: DRAINING,
    },
    Row {
        case: "a host deregistered out of the cluster",
        change: Change::Deregister,
        status: INACTIVE,
    },
    Row {
        case: "a custom attribute written on an in-service host",
        change: Change::WriteAttribute,
        status: ACTIVE,
    },
];

/// Make the row's change to the host `arn`.
async fn apply(router: &MultiServiceRouter, case: &str, change: Change, arn: &str) {
    match change {
        Change::Drain => {
            let answered = ecs(
                router,
                case,
                "UpdateContainerInstancesState",
                &json!({
                    "cluster": CLUSTER,
                    "containerInstances": [arn],
                    "status": DRAINING,
                }),
            )
            .await;
            let failures = answered["failures"].as_array().cloned().unwrap_or_default();
            assert!(
                failures.is_empty(),
                "case {case:?}: expected the drain to report no failures, got {failures:?}"
            );
        }
        Change::Deregister => {
            ecs(
                router,
                case,
                "DeregisterContainerInstance",
                &json!({ "cluster": CLUSTER, "containerInstance": arn }),
            )
            .await;
        }
        Change::WriteAttribute => {
            ecs(
                router,
                case,
                "PutAttributes",
                &json!({
                    "cluster": CLUSTER,
                    "attributes": [{
                        "name": CUSTOM_ATTRIBUTE,
                        "value": CUSTOM_ATTRIBUTE_VALUE,
                        "targetType": "container-instance",
                        "targetId": arn,
                    }],
                }),
            )
            .await;
        }
    }
}

/// RULE: an Amazon EC2 instance launched into a cluster becomes one of its container instances,
/// and every change that instance then experiences is published once as an `ECS Container
/// Instance State Change` event — so the rule narrowed to the status the change left the
/// instance in delivers it to its SQS target, the rules narrowed to the other statuses receive
/// none of it, and the control plane agrees with what the envelope reported.
#[tokio::test]
async fn every_change_a_container_instance_experiences_reaches_the_matching_rules_queue() {
    for row in ROWS {
        let case = row.case;
        // A fresh emulator per row, so one row's host, rules and queues cannot decide another's.
        let router = emulator();

        // One queue and one status-scoped rule per status, created BEFORE the capacity exists,
        // which is what an operator watching a cluster's capacity has in place.
        let mut queues: Vec<(&str, String)> = Vec::new();
        for status in STATUSES {
            let (url, arn) = queue(&router, case, &format!("capacity-{status}")).await;
            rule(
                &router,
                case,
                &format!("container-instance-{status}"),
                &container_instance_events_in(status),
                &arn,
            )
            .await;
            queues.push((status, url));
        }
        let url_of = |wanted: &str| -> String {
            queues
                .iter()
                .find(|(status, _)| *status == wanted)
                .map(|(_, url)| url.clone())
                .unwrap_or_else(|| panic!("case {case:?}: no queue for {wanted}"))
        };

        ecs(
            &router,
            case,
            "CreateCluster",
            &json!({ "clusterName": CLUSTER }),
        )
        .await;
        let (subnet, group) = network(&router, case).await;
        let profile_arn = instance_profile(&router, case).await;
        let instance_id = launch_host(&router, case, &subnet, &group, &profile_arn).await;

        // The registration is owed by the CLOCK — the agent on the instance registers it, with
        // no client request between the launch and the cluster reporting the capacity — so the
        // row waits for the condition a client polls for.
        let deadline = Instant::now() + DEADLINE;
        let mut host = registered_host(&router, case, &instance_id).await;
        while host.is_none() && Instant::now() < deadline {
            ::tokio::time::sleep(LOOK_AGAIN_AFTER).await;
            host = registered_host(&router, case, &instance_id).await;
        }
        let host = host.unwrap_or_else(|| {
            panic!(
                "case {case:?}: expected the host {instance_id} to register as a container \
                 instance of {CLUSTER}"
            )
        });
        let host_arn = member(case, &host, "/containerInstanceArn");
        assert_eq!(
            (host["status"].as_str(), host["agentConnected"].as_bool()),
            (Some(ACTIVE), Some(true)),
            "case {case:?}: expected the registered host {instance_id} {ACTIVE} with its agent \
             connected, got {host}"
        );
        let registered_version = host["version"].as_i64().unwrap_or_default();

        // The REGISTRATION is a change of its own, and it is owed by the CLOCK rather than by
        // any call: capacity joining a cluster is what an operator watches for, so the rule
        // scoped to `ACTIVE` receives it with nothing calling Amazon ECS again — this loop
        // reads only the queue.
        let joining = url_of(ACTIVE);
        let deadline = Instant::now() + DEADLINE;
        let mut joined: Vec<Value> = Vec::new();
        loop {
            joined.extend(drain(&router, case, &joining).await);
            if !reporting(&joined, &host_arn, registered_version).is_empty()
                || Instant::now() >= deadline
            {
                break;
            }
            ::tokio::time::sleep(LOOK_AGAIN_AFTER).await;
        }
        let registration = reporting(&joined, &host_arn, registered_version);
        assert_eq!(
            registration.len(),
            1,
            "case {case:?}: expected exactly one envelope reporting the registration (version \
             {registered_version}) of {host_arn} on the {ACTIVE} rule's queue, got {:?}",
            arrived(&joined)
        );
        assert_eq!(
            (
                registration[0]["detail"]["ec2InstanceId"].clone(),
                registration[0]["detail"]["status"].clone(),
                registration[0]["detail"]["agentConnected"].clone(),
            ),
            (json!(&instance_id), json!(ACTIVE), json!(true)),
            "case {case:?}: expected the registration envelope to report the host {instance_id} \
             {ACTIVE} with its agent connected, got {}",
            registration[0]
        );

        apply(&router, case, row.change, &host_arn).await;

        // What the control plane now holds for the host, which is what the event reporting the
        // change has to carry.
        let changed = described_host(&router, case, &host_arn).await;
        let changed_version = changed["version"].as_i64().unwrap_or_default();
        assert_eq!(
            changed["status"].as_str(),
            Some(row.status),
            "case {case:?}: expected the change to leave the host {}, got {changed}",
            row.status
        );
        assert!(
            changed_version > registered_version,
            "case {case:?}: expected the change to move the host's version past \
             {registered_version}, got {changed}"
        );

        // From here ONLY the queues are read: the change has to arrive without anybody calling
        // Amazon ECS again.
        let matching = url_of(row.status);
        let deadline = Instant::now() + DEADLINE;
        let mut delivered: Vec<Value> = Vec::new();
        loop {
            delivered.extend(drain(&router, case, &matching).await);
            if !reporting(&delivered, &host_arn, changed_version).is_empty()
                || Instant::now() >= deadline
            {
                break;
            }
            ::tokio::time::sleep(LOOK_AGAIN_AFTER).await;
        }
        let change_events = reporting(&delivered, &host_arn, changed_version);
        assert_eq!(
            change_events.len(),
            1,
            "case {case:?}: expected exactly one envelope reporting version \
             {changed_version} of {host_arn} on the {} rule's queue, got {:?}",
            row.status,
            arrived(&delivered)
        );
        let envelope = change_events[0];
        assert_eq!(
            envelope["source"],
            json!(EVENT_SOURCE),
            "case {case:?}: expected source {EVENT_SOURCE}, got {envelope}"
        );
        assert_eq!(
            envelope["detail-type"],
            json!(CONTAINER_INSTANCE_STATE_CHANGE),
            "case {case:?}: expected detail-type {CONTAINER_INSTANCE_STATE_CHANGE}, got \
             {envelope}"
        );
        assert_eq!(
            envelope["resources"],
            json!([&host_arn]),
            "case {case:?}: expected the host's ARN in resources, got {envelope}"
        );
        assert_eq!(
            envelope["detail"]["clusterArn"],
            json!(cluster_arn(CLUSTER)),
            "case {case:?}: expected detail.clusterArn {}, got {envelope}",
            cluster_arn(CLUSTER)
        );
        // The event reports the instance the control plane holds at that instant, so the three
        // members a client acts on have to be the described host's own.
        assert_eq!(
            (
                envelope["detail"]["ec2InstanceId"].clone(),
                envelope["detail"]["status"].clone(),
                envelope["detail"]["agentConnected"].clone(),
            ),
            (
                json!(&instance_id),
                changed["status"].clone(),
                changed["agentConnected"].clone(),
            ),
            "case {case:?}: expected the envelope to report the described host {changed}, got \
             {envelope}"
        );

        // The REGISTRATION the agent made arrived before this change, on the rule scoped to
        // `ACTIVE`, and was taken off that queue above — so a queue this change must not reach
        // is one that holds nothing of it, however long it keeps looking.
        for (status, url) in &queues {
            if *status == row.status {
                continue;
            }
            let mut other: Vec<Value> = Vec::new();
            for _ in 0..QUIET_LOOKS {
                ::tokio::time::sleep(LOOK_AGAIN_AFTER).await;
                other.extend(drain(&router, case, url).await);
                assert!(
                    reporting(&other, &host_arn, changed_version).is_empty(),
                    "case {case:?}: the rule narrowed to {status} must receive nothing of the \
                     change that left the host {}, got {:?}",
                    row.status,
                    arrived(&other)
                );
            }
            // Whatever such a queue did receive is a change of ITS own status: a rule narrowed
            // on the event's `detail` delivers only what matches it.
            for envelope in &other {
                assert_eq!(
                    envelope["detail"]["status"],
                    json!(status),
                    "case {case:?}: the {status} rule's queue must hold only {status} changes, \
                     got {envelope}"
                );
            }
        }
    }
}
