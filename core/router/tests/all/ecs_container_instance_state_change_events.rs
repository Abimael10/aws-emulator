//! Every change a CONTAINER INSTANCE experiences reaches the Amazon SQS target of the
//! EventBridge rule that matches it.
//!
//! The RULE under test: **an Amazon EC2 instance of the account whose user data configures the
//! container agent with a cluster of the account becomes a container instance of that cluster,
//! and every change that container instance then experiences is published once onto the
//! account's default EventBridge bus as `source` `aws.ecs` / `detail-type` `ECS Container
//! Instance State Change`, naming the instance in the envelope's `resources` and carrying in
//! `detail` the instance Amazon ECS holds at that instant — its `containerInstanceArn`, the
//! `clusterArn` of the cluster whose capacity it is, its `ec2InstanceId`, the `status` it is
//! in, whether its agent is `agentConnected` and the `version` counter Amazon ECS bumps for
//! every change it experiences — so a rule whose `EventPattern` narrows that identity to ONE
//! status delivers only the changes that left the instance in that status, and a rule narrowed
//! to another receives none of them.**
//!
//! Sources: `smithy_query(query="operation",
//! operation="RegisterContainerInstance,DescribeContainerInstances,UpdateContainerInstancesState")`
//! for the `ContainerInstance` projection an event's `detail` is read off
//! (`containerInstanceArn`, `ec2InstanceId`, `status`, `agentConnected`, `version`,
//! `registeredAt`, `registeredResources`) and for the statuses
//! `UpdateContainerInstancesState$status` moves an instance between, and
//! `smithy_query(query="shape", shape="PutEventsRequestEntry")` for the envelope members a
//! publication fills (`Source`, `DetailType`, `Time`, `Resources`, `Detail`).
//!
//! This suite lives beside the router because the path is cross-service: the host is Amazon
//! EC2's, launched through that service's own `RunInstances` into a VPC it minted, from the
//! ECS-optimized image AWS Systems Manager publishes the id of, under an AWS IAM instance
//! profile, with the user data the documented way of joining a cluster carries ("echo
//! ECS_CLUSTER=<cluster> >> /etc/ecs/ecs.config"); the registration it earns is Amazon ECS's,
//! the envelope is routed by EventBridge on its CONTENT and Amazon SQS holds what arrived — so
//! what is asserted is what each service persisted, and nothing reads the publisher's own
//! queue.
//!
//! The rows differ along what the rule generalises over: WHICH change the instance experiences
//! — a drain that takes it out of service, a deregistration that takes it out of the cluster,
//! and an attribute written on it, which moves no status at all and is still a change the
//! instance's version counter records.
//!
//! Every wait below looks again for the CONDITION it is waiting on until a generous deadline
//! passes, so a loaded machine polls more often instead of failing.

