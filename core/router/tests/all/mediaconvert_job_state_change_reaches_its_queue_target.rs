//! The `MediaConvert Job State Change` events a job's run publishes, observed where a client
//! observes them: on the Amazon SQS queue an EventBridge rule on the account's default bus
//! delivers to, with NO MediaConvert call made while waiting.
//!
//! The rule pinned here: **once a job has begun processing, every status it moves into is
//! published onto the account's default event bus as `source` `aws.mediaconvert` /
//! `detail-type` `MediaConvert Job State Change`, carrying that job's own id and its new status
//! in `detail`, because the move HAPPENED — so a client that submits a job and then only listens
//! on a rule observes the whole run without asking MediaConvert about it again. A job that never
//! begins is not a run and publishes nothing.** Sources: `CreateJob$StatusUpdateInterval` ("how
//! often MediaConvert sends STATUS_UPDATE events to Amazon CloudWatch Events"), which is the
//! model's own statement that this service publishes a job's progress, and `QueueStatus` ("if
//! you pause a queue, jobs in that queue won't begin") for the half that publishes nothing.
//!
//! Three crates have to agree for that to hold — MediaConvert publishes, EventBridge matches
//! each event against the bus's rules and hands it to their targets, and Amazon SQS holds what
//! was delivered — so the suite lives here rather than in any one of them, it is driven over the
//! WHOLE assembled router, and every observation is a client call: nothing is asserted on an
//! emulator internal. The router AUTHENTICATES every request, which is how the emulator serves
//! traffic, so the publication MediaConvert makes through the emulator's own callback — from a
//! task that outlives the request that armed the clock — is made against a router that verifies
//! signatures, exactly as it is in a served emulator.
//!
//! The rows differ along what the rule generalises over: what left the clock owing the run (a
//! submit onto an `ACTIVE` queue, the activation of the `PAUSED` queue a job was already waiting
//! in), how many jobs are owed one at once, and whether the job ever began (held by its queue,
//! and taken out of it by a cancel). The consumer behaves like the documented one: it receives
//! and DELETES what it received, so a redelivery would show up here as a repeat.
//!
//! Nothing here waits on the wall clock: the queue is drained again until the events a row
//! expects are on it — bounded by a WITNESS job's own terminal event for the rows that expect
//! silence — under a deadline that is a safety net rather than a measurement.
//!
//! Assembling the whole router costs stack (see `boot_serve.rs`), so it is built — and the
//! requests driven — on an explicitly sized thread.

use std::sync::Arc;
use std::time::{Duration, Instant, SystemTime};

use aws_credential_types::Credentials;
use aws_emulator_router::{build_router, InMemoryEngine};
use aws_sigv4::http_request::{sign, SignableBody, SignableRequest, SigningSettings};
use aws_sigv4::sign::v4::SigningParams;
use serde_json::{json, Value};
use smithy_server_runtime::MultiServiceRouter;

/// Keep this at or above the size `boot_serve.rs` uses: the same assembly runs here.
const BOOT_STACK_SIZE: usize = 64 * 1024 * 1024;

/// The Region every call below is signed for, which is the Region the jobs belong to and the
/// Region their events are published in.
const REGION: &str = "us-west-2";

/// The `source` MediaConvert publishes under, spelled out here rather than imported, so a wrong
/// constant in the implementation cannot make this suite pass.
const SOURCE: &str = "aws.mediaconvert";

/// The `detail-type` a JOB's state changes are published under.
const JOB_STATE_CHANGE: &str = "MediaConvert Job State Change";

/// The bus an Amazon Web Services service's own events go to: "events generated by Amazon Web
/// Services services go to your account's default event bus".
const DEFAULT_BUS: &str = "default";

/// The service principal EventBridge delivers to an SQS target as, which is what the queue's
/// resource policy admits ("for Amazon SQS queues, EventBridge relies on resource-based
/// policies").
const EVENTS_PRINCIPAL: &str = "events.amazonaws.com";

/// The IAM role ARN shape `CreateJob$Role` documents. MediaConvert stores it on the job; it is
/// not what decides anything about the events.
const ROLE: &str = "arn:aws:iam::123456789012:role/MediaConvertRole";

/// The status a job moves into when it has BEGUN processing, which is the first event of a run.
const BEGUN: &str = "PROGRESSING";

/// The statuses a RUN ends in, which is where a job's event stream stops.
///
/// `JobStatus` is "a job's status can be SUBMITTED, PROGRESSING, COMPLETE, CANCELED, or ERROR",
/// of which `SUBMITTED` is where a submit leaves a job and `CANCELED` is what a cancel writes —
/// so a run that was neither held nor cancelled ends in one of these two. WHICH one is the
/// service's own to decide, so the rows below assert the SHAPE of the stream and then its
/// agreement with `GetJob`, never one of the two literals.
const RUN_ENDS_IN: [&str; 2] = ["COMPLETE", "ERROR"];

/// What a job's own event stream must look like.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Expected {
    /// A job that RUNS: it begins processing, and then its run ends.
    Runs,
    /// A job that never begins is not a run, so it publishes nothing at all.
    Nothing,
}

impl Expected {
    /// How many events this stream is, which is what a drain waits for.
    fn events(self) -> usize {
        match self {
            Self::Runs => 2,
            Self::Nothing => 0,
        }
    }
}

/// Whether `statuses` is the whole stream of a job whose run has ENDED: it began, and then
/// stopped in one of the statuses a run ends in.
fn ran(statuses: &[&str]) -> bool {
    statuses.len() == 2
        && statuses.first() == Some(&BEGUN)
        && statuses
            .last()
            .is_some_and(|status| RUN_ENDS_IN.contains(status))
}

/// Whether a run's terminal status has been announced among `statuses`, which is what bounds a
/// wait on the queue.
fn ended(statuses: &[&str]) -> bool {
    statuses.iter().any(|status| RUN_ENDS_IN.contains(status))
}

/// How long a drain keeps LOOKING. Generous: a safety net so a broken emulator fails instead of
/// hanging, never a measurement — what is asserted is what arrived, and every loop stops the
/// instant its condition holds.
const BUDGET: Duration = Duration::from_secs(120);

/// How long one look pauses before the queue is drained again.
const LOOK_INTERVAL: Duration = Duration::from_millis(50);

/// The credential every call below signs with: the pair this process publishes once request
/// authentication is on.
struct Signer {
    key_id: String,
    secret: String,
}

impl Signer {
    /// Sign `request` for `signing_name` in [`REGION`], in the `Authorization` header an SDK
    /// request carries.
    fn sign(
        &self,
        mut request: http::Request<Vec<u8>>,
        signing_name: &str,
    ) -> http::Request<Vec<u8>> {
        let identity = Credentials::new(&self.key_id, &self.secret, None, None, "test").into();
        let params = SigningParams::builder()
            .identity(&identity)
            .region(REGION)
            .name(signing_name)
            .time(SystemTime::now())
            .settings(SigningSettings::default())
            .build()
            .expect("the signing parameters are complete")
            .into();
        let (method, uri) = (request.method().to_string(), request.uri().to_string());
        let headers: Vec<(String, String)> = request
            .headers()
            .iter()
            .map(|(name, value)| {
                (
                    name.as_str().to_string(),
                    value.to_str().expect("a text header").to_string(),
                )
            })
            .collect();
        let signable = SignableRequest::new(
            &method,
            &uri,
            headers
                .iter()
                .map(|(name, value)| (name.as_str(), value.as_str())),
            SignableBody::Bytes(request.body()),
        )
        .expect("the request is signable");
        let (instructions, _) = sign(signable, &params)
            .expect("the request signs")
            .into_parts();
        instructions.apply_to_request_http1x(&mut request);
        request
    }
}

/// What routes one call: the signing name whose credential scope the request carries, the
/// content type that service's protocol uses, and the `X-Amz-Target` an RPC protocol routes on.
struct Wire<'a> {
    signing_name: &'a str,
    content_type: &'a str,
    target: Option<&'a str>,
}

/// One signed call on the regional endpoint of `wire.signing_name`, as the status it answered
/// and its parsed body.
async fn call(
    router: &MultiServiceRouter,
    signer: &Signer,
    wire: &Wire<'_>,
    method: &str,
    path: &str,
    body: Option<&Value>,
) -> (u16, Value) {
    let signing_name = wire.signing_name;
    let host = format!("{signing_name}.{REGION}.amazonaws.com");
    let mut builder = http::Request::builder()
        .method(method)
        .uri(format!("https://{host}{path}"))
        .header("host", &host)
        .header("content-type", wire.content_type);
    if let Some(target) = wire.target {
        builder = builder.header("x-amz-target", target);
    }
    let payload = body.map(Value::to_string).unwrap_or_default();
    let built = builder
        .body(payload.into_bytes())
        .expect("the test request is well formed");
    let signed = signer.sign(built, signing_name);
    let (parts, payload) = signed.into_parts();
    let request = http::Request::from_parts(parts, bytes::Bytes::from(payload));
    let response = router.dispatch(request).await;
    let status = response.status().as_u16();
    let parsed = if response.body().is_empty() {
        Value::Null
    } else {
        serde_json::from_slice(response.body()).unwrap_or(Value::Null)
    };
    (status, parsed)
}

/// One EventBridge call (`awsJson1_1`, `AWSEvents.<Operation>`), which must answer 200.
async fn events(
    router: &MultiServiceRouter,
    signer: &Signer,
    case: &str,
    operation: &str,
    body: &Value,
) -> Value {
    let (status, parsed) = call(
        router,
        signer,
        &Wire {
            signing_name: "events",
            content_type: "application/x-amz-json-1.1",
            target: Some(&format!("AWSEvents.{operation}")),
        },
        "POST",
        "/",
        Some(body),
    )
    .await;
    assert_eq!(
        status, 200,
        "case {case:?}: expected HTTP 200 from EventBridge {operation}, got {status} with \
         {parsed}"
    );
    parsed
}

