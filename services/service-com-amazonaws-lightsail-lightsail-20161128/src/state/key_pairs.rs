//! The stored SSH key pair: the public half this service holds for the account,
//! under the name an instance's key pair member names it by — and, for the
//! account's DEFAULT key pair alone, the material of the pair this service
//! minted itself, which is downloaded again on every call.

use super::*;

/// One stored SSH key pair: the PUBLIC half Lightsail holds for the account,
/// under the name an instance's `sshKeyName` names it by.
///
/// Lightsail holds only the public half — the modelled `DeleteKeyPair`
/// documentation deletes a key pair "by removing the public key from Amazon
/// Lightsail" — so that is all a record here holds beside what the service
/// assigned it. The private half is handed to the caller by the call that
/// created the pair and is never stored.
#[derive(Debug, Clone)]
pub struct StoredKeyPair {
    /// The key pair name the request named, kept verbatim — it is this record's
    /// store key and the `name` every read reports.
    pub name: String,
    pub arn: String,
    pub support_code: String,
    pub created_at_ms: i64,
    pub location: StoredLocation,
    pub tags: Vec<Tag>,
    /// The fingerprint of the public half: "The RSA fingerprint of the key pair"
    /// (`KeyPair$fingerprint`). It is what a delete's `expectedFingerprint`
    /// states it expects to be deleting.
    pub fingerprint: String,
}

impl StoredKeyPair {
    /// This record as the modelled `KeyPair`.
    pub fn view(&self) -> KeyPair {
        KeyPair {
            name: Some(self.name.clone()),
            arn: Some(self.arn.clone()),
            support_code: Some(self.support_code.clone()),
            created_at: Some(timestamp(self.created_at_ms)),
            location: Some(self.location.view()),
            resource_type: Some(RESOURCE_TYPE_KEY_PAIR.to_string()),
            tags: Some(self.tags.clone()),
            fingerprint: Some(self.fingerprint.clone()),
        }
    }

    /// Whether this is the account's Lightsail DEFAULT key pair — the one
    /// [`DEFAULT_SSH_KEY_NAME`] names, which an instance created without a key
    /// pair of its own is launched with.
    ///
    /// The record's NAME is what decides, because that name is how every
    /// Lightsail operation addresses the default pair.
    pub fn is_default(&self) -> bool {
        self.name == DEFAULT_SSH_KEY_NAME
    }
}

/// The SSH key material this service minted for one key pair: the two halves the
/// call that minted it answers, and the fingerprint the stored record keeps.
///
/// Real RSA key material, generated by the cryptography library this workspace
/// already generates RSA key pairs with, and encoded by the crates that
/// implement each published encoding — so nothing here is a string shaped like a
/// key. Only the private half's holder can use it: it is handed to the caller by
/// the call that minted it and never stored, exactly as the modelled `KeyPair`
/// carries no key material and keeps the fingerprint alone.
/// Not `Clone`: the private half is handed to the caller by the call that minted
/// it, so a second copy of it has no reason to exist.
pub struct MintedKeyPairMaterial {
    /// The public half as "a base64-encoded public key of the ssh-rsa type"
    /// (`CreateKeyPairResult$publicKeyBase64`): the base64 of the key's own
    /// `ssh-rsa` encoding and nothing else — one base64 token, with no algorithm
    /// label, no separating space and no surrounding whitespace.
    ///
    /// A member documented as base64-encoded carries base64, so what a caller
    /// decodes is the key blob itself: the RFC 4253 `ssh-rsa` public key, which
    /// names its own algorithm inside itself, so nothing of the key is lost by
    /// leaving the OpenSSH line's text prefix off. The label and the space
    /// belong to the `authorized_keys` LINE a caller composes from this value,
    /// not to the value.
    ///
    /// It is the same rendering an instance's SSH host key is reported with
    /// ([`witness_ssh_host_key`]): the key blob's base64, with the algorithm
    /// named apart from it.
    pub public_key: String,
    /// The private half as an `RSA PRIVATE KEY` PEM — the PKCS#1 encoding
    /// `privateKeyBase64` documents ("A base64-encoded RSA private key"), which
    /// is what an SSH client reads from the file a caller saves it to.
    pub private_key: String,
    /// "The RSA fingerprint of the key pair" (`KeyPair$fingerprint`): the MD5
    /// digest of the DER-encoded PUBLIC half, in the colon-separated hex an AWS
    /// key pair fingerprint is published in — the digest `openssl rsa -pubout
    /// -outform DER | openssl md5 -c` prints for this key.
    ///
    /// Computed from the PUBLIC half alone, because that is all this service
    /// holds once the call returns: the fingerprint of a stored key pair has to
    /// be derivable from the record, whether the pair was minted here or
    /// imported with its public half alone.
    pub fingerprint: String,
}

/// Redacts the private half, for the reason [`TemporarySshKeys`]' own `Debug`
/// redacts the key it grants: a derived `Debug` would carry the minted private
/// key into any formatter, including a log line.
impl std::fmt::Debug for MintedKeyPairMaterial {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("MintedKeyPairMaterial")
            .field("public_key", &self.public_key)
            .field("fingerprint", &self.fingerprint)
            .finish_non_exhaustive()
    }
}

impl MintedKeyPairMaterial {
    /// Mint a fresh RSA key pair of [`KEY_PAIR_MODULUS_BITS`].
    ///
    /// `None` only when the key does not generate or does not encode, which a
    /// caller reports no key pair for rather than storing a record with no key
    /// behind it.
    pub fn mint() -> Option<Self> {
        use ::aws_lc_rs::encoding::AsDer;

        let generated = ::aws_lc_rs::rsa::PrivateDecryptingKey::generate(KEY_PAIR_MODULUS_BITS)
            .ok()?;
        // `openssl rsa -pubout -outform DER`: the SubjectPublicKeyInfo of the
        // public half, which is what the published fingerprint is the digest
        // of.
        let public_key_der = generated.public_key().as_der().ok()?.as_ref().to_vec();
        // The library hands the private half over as PKCS#8; the inner key of
        // that wrapper IS the PKCS#1 `RSAPrivateKey` an `RSA PRIVATE KEY` PEM
        // carries, and the crates implementing those two encodings are what
        // read and write them here.
        let pkcs8 = generated.as_der().ok()?;
        let pkcs1_der = ::pkcs8::PrivateKeyInfo::try_from(pkcs8.as_ref())
            .ok()?
            .private_key
            .to_vec();
        let parsed = <::pkcs1::RsaPrivateKey as ::der::Decode>::from_der(&pkcs1_der).ok()?;
        let public_key = ssh_rsa_public_key(&parsed)?;
        let private_key = ::der::Document::try_from(pkcs1_der.as_slice())
            .ok()?
            .to_pem(RSA_PRIVATE_KEY_PEM_LABEL, ::der::pem::LineEnding::LF)
            .ok()?;
        Some(Self {
            public_key,
            private_key,
            fingerprint: colon_hex(&::md5::Md5::digest(&public_key_der)),
        })
    }
}

/// "The RSA fingerprint of the key pair" (`KeyPair$fingerprint`) of the public
/// half a caller IMPORTS, read out of the value the request submitted — or
/// `None` when that value carries no public key of the `ssh-rsa` type this
/// service holds key pairs of.
///
/// The digest is the one [`MintedKeyPairMaterial::fingerprint`] documents: the
/// MD5 of the key's DER-encoded public half in colon-separated hex. It is
/// computed from the key ALONE, so a pair whose public half a caller brought
/// publishes the same fingerprint as a pair this service minted from the same
/// key — and it is all an imported pair needs beside what the service assigns
/// it, because the private half stays with the caller and the public half is
/// reported by no read of a key pair ([`StoredKeyPair`]).
///
/// `submitted` is a `publicKeyBase64` member — "a base64-encoded public key of
/// the ssh-rsa type" — so what is read is the key's own SSH encoding,
/// base64-encoded. BOTH renderings that encoding is published in are read: the
/// base64 body alone — which is what the two results that report a public half
/// carry ([`MintedKeyPairMaterial::public_key`]), so a pair this service minted
/// imports again exactly as it was reported — and the whole OpenSSH public key
/// line `<algorithm> <body>[ <comment>]` a caller reads out of a `.pub` file,
/// which is that same key with a text label before it. Whitespace around the
/// value is not part of either, so it is not read as key material.
///
/// The line form is read because the modelled `Base64` shape is a plain string
/// carrying no pattern (`smithy_query(query="shape",shape="Base64")`), so the
/// model refuses none of the text a caller pastes out of that file — and the two
/// forms carry the SAME key, which is what this answers about. The algorithm name
/// a line opens with is not extra key material either: an SSH public key's own
/// encoding names its algorithm inside itself, so the label only has to agree
/// with the body.
///
/// The key is decoded by the crate that implements the SSH key formats, so what
/// is accepted is a real key of the documented type: a value that is not base64,
/// that does not decode to an SSH public key, that decodes to a key of another
/// algorithm, or whose OpenSSH label disagrees with the key its body carries, is
/// refused rather than held as a key pair with no key behind it.
pub fn imported_public_key_fingerprint(submitted: &str) -> Option<String> {
    use ::md5::Digest;

    let text = submitted.trim();
    let mut fields = text.split_whitespace();
    let first = fields.next()?;
    let key = match fields.next() {
        // The base64 body alone. An SSH public key's own encoding names its
        // algorithm inside itself (RFC 4253 section 6.6), and the key crate
        // refuses a line whose label disagrees with the blob — so reading the
        // body under the `ssh-rsa` label is what fixes the type.
        None => ::ssh_key::PublicKey::from_openssh(&format!("{SSH_RSA_ALGORITHM} {first}")).ok()?,
        // A whole OpenSSH public key line, read as the line it is: its algorithm
        // label has to agree with the key its body carries, and the comment it
        // may carry is not key material.
        Some(_) => ::ssh_key::PublicKey::from_openssh(text).ok()?,
    };
    let rsa = key.key_data().rsa()?;
    Some(colon_hex(&::md5::Md5::digest(rsa_public_key_der(rsa)?)))
}

/// The algorithm name of the key type a Lightsail key pair is of: "a
/// base64-encoded public key of the ssh-rsa type"
/// (`ImportKeyPairRequest$publicKeyBase64`, and the same wording on the two
/// results that report a public half).
const SSH_RSA_ALGORITHM: &str = "ssh-rsa";

/// The DER-encoded public half of the RSA public key `public` — the
/// `SubjectPublicKeyInfo` that `openssl rsa -pubout -outform DER` writes, which
/// an AWS RSA key pair fingerprint is the MD5 digest of
/// ([`MintedKeyPairMaterial::fingerprint`]).
///
/// Built from the key's modulus and public exponent by the crates that implement
/// those encodings, so a key pair whose public half a caller brought publishes
/// the SAME fingerprint a pair this service minted does: the digest is taken
/// over the key, never over the text it arrived in.
fn rsa_public_key_der(public: &::ssh_key::public::RsaPublicKey) -> Option<Vec<u8>> {
    use ::der::Encode;

    let pkcs1 = ::pkcs1::RsaPublicKey {
        modulus: ::der::asn1::UintRef::new(public.n.as_positive_bytes()?).ok()?,
        public_exponent: ::der::asn1::UintRef::new(public.e.as_positive_bytes()?).ok()?,
    }
    .to_der()
    .ok()?;
    ::spki::SubjectPublicKeyInfoRef {
        algorithm: ::pkcs1::ALGORITHM_ID,
        subject_public_key: ::der::asn1::BitStringRef::new(0, &pkcs1).ok()?,
    }
    .to_der()
    .ok()
}

/// The key material this service HOLDS for the account's Lightsail default key
/// pair: the pair the service minted itself.
///
/// It exists because the default pair is the ONE pair whose halves the service
/// hands back on every call rather than once: `DownloadDefaultKeyPair`
/// "downloads the regional Amazon Lightsail default key pair", so the private
/// half of a pair the service generated for the account has to still be there
/// on the second download. A pair the CALLER brought or asked for is not held
/// this way — `CreateKeyPair` reports its private half once and
/// [`StoredKeyPair`] keeps the public half alone.
///
/// Not `Clone`: one copy of the private half is what the store holds, and a
/// caller is answered a copy built where it is reported.
pub struct HeldDefaultKeyPairMaterial {
    /// The public half, in the form [`MintedKeyPairMaterial::public_key`]
    /// documents — the same member, documented by the model with the same
    /// sentence, so the two calls that report a public half report it
    /// identically.
    pub public_key: String,
    /// The private half, in the PKCS#1 PEM form
    /// [`MintedKeyPairMaterial::private_key`] documents.
    pub private_key: String,
    /// The fingerprint of the key pair this material IS — the same value the
    /// stored record carries.
    ///
    /// It ties the material to the record: material is reported only for a
    /// stored default pair whose own `fingerprint` it matches, so a default
    /// pair that some other call put in the store is never answered with
    /// another key's halves.
    pub fingerprint: String,
}

/// Redacts the private half, for the reason [`MintedKeyPairMaterial`]'s own
/// `Debug` redacts it: the store derives `Debug`, so a derived one here would
/// carry the held private key into any formatter.
impl std::fmt::Debug for HeldDefaultKeyPairMaterial {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("HeldDefaultKeyPairMaterial")
            .field("public_key", &self.public_key)
            .field("fingerprint", &self.fingerprint)
            .finish_non_exhaustive()
    }
}

impl ComAmazonawsLightsailLightsail20161128State {
    /// The account's Lightsail default key pair and the material this service
    /// holds for it, for the call that downloads it.
    ///
    /// `None` when the account holds no pair under [`DEFAULT_SSH_KEY_NAME`], and
    /// also when it holds one this service has no material for — a pair whose
    /// private half was reported to the call that created it and never stored —
    /// because the halves answered have to be THAT pair's. The record's own
    /// `fingerprint` is what decides, so material left from a pair that has
    /// since been replaced is never reported for its successor.
    pub fn default_key_pair_material(
        &self,
    ) -> Option<(&StoredKeyPair, &HeldDefaultKeyPairMaterial)> {
        let record = self.key_pair(DEFAULT_SSH_KEY_NAME)?;
        let material = self.default_key_pair_material.as_ref()?;
        (material.fingerprint == record.fingerprint).then_some((record, material))
    }

    /// Hold `material` as the key material of the account's default key pair,
    /// which the call that just minted that pair stored the record of.
    pub fn hold_default_key_pair_material(&mut self, material: HeldDefaultKeyPairMaterial) {
        self.default_key_pair_material = Some(material);
    }
}

/// The PEM label a PKCS#1 RSA private key is published under, from the textual
/// encodings RFC 7468 defines ("RSA PRIVATE KEY"): the header and footer an SSH
/// client recognises the private half by.
const RSA_PRIVATE_KEY_PEM_LABEL: &str = "RSA PRIVATE KEY";

/// The size of the RSA key pair a create mints.
///
/// 2048 bits is the size an SSH key pair is generated at by default and the
/// smallest an OpenSSH client accepts without complaint; the modelled output
/// documents the TYPE of the halves ("the ssh-rsa type", "an RSA private key")
/// and not their size, so this is the size this service generates rather than a
/// published one.
const KEY_PAIR_MODULUS_BITS: ::aws_lc_rs::rsa::KeySize = ::aws_lc_rs::rsa::KeySize::Rsa2048;

/// "A base64-encoded public key of the ssh-rsa type"
/// (`CreateKeyPairResult$publicKeyBase64`, and the same wording on
/// `DownloadDefaultKeyPairResult$publicKeyBase64`) for the RSA key `private`'s
/// public half: the base64 of the key's own `ssh-rsa` encoding, built from the
/// key's modulus and public exponent by the crate that implements the SSH key
/// formats.
///
/// The value is base64 text ALONE, as the member it fills is documented to be:
/// decoding it gives the RFC 4253 `ssh-rsa` key blob, which names its algorithm
/// inside itself. The algorithm label, the space after it and the comment field
/// an OpenSSH line may carry are the LINE's, not the key's, so none of them is
/// published here and no whitespace surrounds the value — a caller composing an
/// `authorized_keys` entry writes the algorithm name before this body.
///
/// It is also one of the two renderings `ImportKeyPair` reads a key back out of
/// ([`imported_public_key_fingerprint`]), so a pair this service minted can be
/// imported again exactly as it was reported.
fn ssh_rsa_public_key(private: &::pkcs1::RsaPrivateKey<'_>) -> Option<String> {
    let key = ::ssh_key::public::KeyData::Rsa(::ssh_key::public::RsaPublicKey {
        e: ::ssh_key::Mpint::from_positive_bytes(private.public_exponent.as_bytes()).ok()?,
        n: ::ssh_key::Mpint::from_positive_bytes(private.modulus.as_bytes()).ok()?,
    });
    let openssh = ::ssh_key::PublicKey::new(key, "").to_openssh().ok()?;
    Some(openssh_key_body(&openssh)?.to_string())
}
