impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for ExecuteQuery<Eng>
{
    type Input = ExecuteQueryInput;
    type Output = ExecuteQueryOutput;
    type Error = ExecuteQueryError;

    const NAME: &'static str = "ExecuteQuery";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::EXECUTE_QUERY_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::EXECUTE_QUERY_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(ExecuteQueryErrorModeled::InternalServerException(
                InternalServerException {
                    message: "the neptune-graph store is not mounted on this engine".to_string(),
                },
            )
            .into());
        };

        // A graph lives in exactly one Region, so the Region this request was signed for
        // names the graph the query is authorized against and is part of the lookup.
        let region = crate::state::request_region(ctx);
        let graph_arn = crate::state::graph_resource(&region, &input.graph_identifier);

        // Whether the caller may run a query AT ALL is a decision about the caller and
        // the graph it named, so it is taken FIRST, from the request alone and with no
        // store of this service held: an unauthorized caller learns nothing about what
        // the account holds, and the data plane never reads the graph for it. The
        // decision and its sentence live in `crate::state::query_denial`.
        if let Some(denied) = crate::state::query_denial(&*self.engine, ctx, &graph_arn) {
            return Err(ExecuteQueryErrorModeled::AccessDeniedException(denied).into());
        }

        // `explainMode` asks for "a query explain instead of the actual query results" —
        // the planning decisions, the time spent in each operator and the solutions
        // flowing through it (`smithy_query(query="operation",operation="ExecuteQuery")`
        // -> input.explainMode). Those are facts about an execution plan this data plane
        // does not build, and a plan nothing produced is not a plan, so the request is
        // refused as the one thing this endpoint cannot do for it rather than answered
        // with results it did not ask for. The modelled reason for an operation the
        // service does not perform is `UNSUPPORTED_OPERATION`
        // (`crate::ops::types::VALIDATION_EXCEPTION_REASON_VALUES`).
        if let Some(mode) = input.explain_mode.as_deref() {
            return Err(ExecuteQueryErrorModeled::ValidationException(
                ValidationException {
                    message: format!(
                        "explainMode [{mode}] is not supported by this endpoint: it serves \
                         query results only"
                    ),
                    reason: Some(UNSUPPORTED_OPERATION_REASON.to_string()),
                },
            )
            .into());
        }

        // The query runs on the graph's OWN data endpoint — this operation is bound to
        // the host prefix `{graphIdentifier}.`
        // (`smithy_query(query="operation",operation="ExecuteQuery")` -> endpoint). Two
        // DIFFERENT facts can stop a query there, and each is reported as what it is:
        //
        // * this Region holds no graph under that identifier, so there is no graph to
        //   address at all — the missing resource the 404 reports;
        // * the graph EXISTS and its data plane is not serving (it is still coming up, is
        //   reconfiguring, is stopping or is stopped). The graph is still there — a read of
        //   it answers, and starting it brings the data plane back — so the query is
        //   refused as the server-side "not serving right now" it is
        //   (`crate::scaffolded::GRAPH_UNAVAILABLE_CODE`), which a client retries, rather
        //   than as a resource that is gone, which it cleans up after. Nothing about the
        //   graph is touched, so a start followed by the same query runs it.
        //
        // The sole write the lookup makes is materialising the status transition the clock
        // had already made due, which was owed whether or not anybody queried.
        //
        // The query is then evaluated over a SNAPSHOT of the graph's data, taken here and
        // read with the store's guard already GIVEN UP — the guard is released at the end
        // of this block: an evaluation walks every node and edge the pattern reaches, and
        // no other caller of this service waits on it. A query that WRITES takes the guard
        // again for its own evaluation (`crate::state::evaluate_query`).
        let (graph_id, data) = {
            let (mut store, now) = crate::state::locked_store_now(&state);
            let Some(graph) = store.settled_graph(&input.graph_identifier, &region, now) else {
                return Err(ExecuteQueryErrorModeled::ResourceNotFoundException(
                    crate::state::graph_not_found(&input.graph_identifier),
                )
                .into());
            };
            if !graph.status.is_serving() {
                return Err(crate::scaffolded::Scaffolded::graph_unavailable());
            }
            (graph.id.clone(), graph.data.clone())
        };

        // A text longer than one record of this store may carry is refused before the
        // query is admitted at all: a query the service will not read never becomes a
        // query in flight on the graph. Worded by the one builder every refusal of a run
        // is worded by, so the bound reads the same wherever the text was measured.
        let characters = input.query_string.chars().count();
        if characters > crate::state::MAX_QUERY_STRING_CHARS {
            return Err(query_refusal(crate::state::QueryFailure::TooLong {
                characters,
                ceiling: crate::state::MAX_QUERY_STRING_CHARS,
            })
            .into());
        }

        // "The data parameters the query can use in JSON format"
        // (`smithy_query(query="operation",operation="ExecuteQuery")` -> input.parameters)
        // are read HERE, into the data the query's `$name` references bind to — read as
        // values and handed to the evaluation as values, never spliced into the query
        // text, so a value carrying the delimiter a string literal is written with is
        // still that value. What one request may bind is bounded by the reading
        // (`crate::state::request_parameters`), which is the member's own ceiling and not
        // a statement about the query, hence the modelled reason for an argument the
        // service cannot take.
        let parameters = match crate::state::request_parameters(input.parameters.as_ref()) {
            Ok(parameters) => parameters,
            Err(refused) => {
                return Err(query_refusal(crate::state::QueryFailure::Rejected(refused)).into())
            }
        };

        // The evaluation is CPU-bound work whose cost the caller's own query chooses, so
        // four things hold it: a PERMIT, so the queries this service evaluates at once
        // are bounded and a request past that bound is shed as the throttle it is; a
        // THREAD of its own, with a stack sized for the depth the engine's parser may
        // descend, so the work neither blocks the runtime nor overflows the stack it was
        // given; a DEADLINE the evaluation itself stops at — the span the request asked
        // for, clamped to the one a graph's queries run under
        // (`crate::state::query_run_timeout`) — so a query whose cost diverges stops
        // ASKING rather than running on; and the same span again on the WAIT, so the
        // caller is answered at its deadline whatever the evaluation is doing. Nothing
        // here reads the query text: it is parsed and evaluated by the engine that covers
        // it (`crate::state::evaluate_query`), under the bounds those modules state on
        // what one request may read, nest, be handed and answer with.
        let Ok(permit) = crate::state::QUERY_SLOTS.try_acquire() else {
            return Err(ExecuteQueryErrorModeled::ThrottlingException(ThrottlingException {
                message: format!(
                    "this emulator evaluates at most {} queries at once",
                    crate::state::MAX_CONCURRENT_QUERIES
                ),
            })
            .into());
        };
        let timeout = crate::state::query_run_timeout(input.query_timeout_milliseconds);
        let started = ::std::time::Instant::now();
        let deadline = started.checked_add(timeout).unwrap_or(started);

        // The query is ADMITTED: the store files a record of it under the graph it runs
        // on, so the operations that report a graph's queries — `ListQueries`, `GetQuery`
        // and `CancelQuery` — can see this query, stop it, and then refuse the id it has
        // stopped under. The record carries the text the caller sent and the span this
        // run was given, and it reports `RUNNING`, because the permit above is held: this
        // query is executing rather than queued behind another. The only thing that can
        // turn the record away now is the store having no room for another in-flight query
        // — the one other reason it refuses a record, a text past the length it carries,
        // was refused above — and that is reported as the throttle it is, since the
        // condition clears as the queries in flight end rather than being a fault of this
        // request.
        let (query_id, cancellation) = {
            let (mut store, now) = crate::state::locked_store_now(&state);
            let query_id = store.next_query_id();
            let record =
                crate::state::Query::running(&query_id, &graph_id, &input.query_string, now)
                    .with_timeout(timeout);
            let cancellation = record.cancellation.clone();
            if let Err(full) = store.insert_query(record) {
                return Err(ExecuteQueryErrorModeled::ThrottlingException(
                    ThrottlingException { message: full },
                )
                .into());
            }
            (query_id, cancellation)
        };

        let text = input.query_string.clone();
        let (answered, evaluating) = ::tokio::sync::oneshot::channel();
        let evaluation_state = state.clone();
        let evaluated_graph = graph_id.clone();
        let evaluated_query = query_id.clone();
        let worker = ::std::thread::Builder::new()
            .stack_size(crate::state::QUERY_STACK_BYTES)
            .spawn(move || {
                let run = crate::state::evaluate_query(
                    &evaluation_state,
                    &evaluated_graph,
                    &data,
                    &text,
                    parameters,
                    deadline,
                    &cancellation,
                );
                // The run this record reports is over, so the end of the record falls
                // due. Reported by the THREAD that did the work rather than by the
                // request that was waiting for it, so a query whose caller has gone away
                // still stops being an in-flight query of its graph.
                {
                    let (mut store, now) = crate::state::locked_store_now(&evaluation_state);
                    if let Some(query) =
                        store.live_query_mut(&evaluated_graph, &evaluated_query, now)
                    {
                        query.end_run(now);
                    }
                }
                // The permit is held for the whole run and released with this thread, so
                // the bound counts the evaluations that are actually running.
                drop(permit);
                // Nobody is listening when the caller's connection has gone; the result
                // is then simply dropped with this thread.
                let _ = answered.send(run);
            });
        if worker.is_err() {
            // Nothing ran, so the record this request admitted reports no run: its end
            // falls due here, since the thread that would have reported it never started.
            let (mut store, now) = crate::state::locked_store_now(&state);
            if let Some(query) = store.live_query_mut(&graph_id, &query_id, now) {
                query.end_run(now);
            }
            return Err(ExecuteQueryErrorModeled::InternalServerException(
                InternalServerException {
                    message: "the query could not be evaluated".to_string(),
                },
            )
            .into());
        }
        let payload = match ::tokio::time::timeout(timeout, evaluating).await {
            Ok(Ok(Ok(payload))) => payload,
            Ok(Ok(Err(refused))) => {
                return Err(query_refusal(refused).into());
            }
            // The evaluation answered nothing at all: a panic inside it is a failure of
            // this service rather than of the request.
            Ok(Err(_lost)) => {
                return Err(ExecuteQueryErrorModeled::InternalServerException(
                    InternalServerException {
                        message: "the query could not be evaluated".to_string(),
                    },
                )
                .into());
            }
            // The wait reached the deadline before the evaluation reported stopping at
            // it: the caller is answered the timeout it was promised either way.
            Err(_elapsed) => {
                return Err(ExecuteQueryErrorModeled::UnprocessableException(
                    UnprocessableException {
                        message: "the query did not complete within the time it was given"
                            .to_string(),
                        reason: QUERY_TIMEOUT_REASON.to_string(),
                    },
                )
                .into());
            }
        };

        // The payload is the result set as this service spells one, computed from the data
        // the graph holds — so a query's answer and a later summary of the same graph
        // cannot disagree.
        Ok(ExecuteQueryOutput { payload })
    }
}

