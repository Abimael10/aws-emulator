#[tokio::test]
async fn the_accounts_list_scopes_a_member_recommendations_lifecycle() {
    let (router, engine, rows) = emulator_with_lifecycles();

    // The member account's own recommendation is where this list reads a
    // member's lifecycle from, so the rule answers to THAT recommendation's
    // `type`: the summary of a member whose recommendation is not prioritized
    // reports none of the three lifecycle members, while its `accountId` and
    // `lastUpdatedAt` — neither of which the model sources from Priority — are
    // reported either way.
    let row = full_lifecycle(&rows);
    let check_id = PRIORITIZED_CHECK_IDS[0];
    let member_arn = recommendation_arn(check_id);
    record_lifecycle(&engine, &member_arn, row);

    let path = format!(
        "/v1/organization-recommendations/{}/accounts",
        label(&organization_recommendation_arn(check_id))
    );

    for kind in RECOMMENDATION_TYPE_VALUES
        .iter()
        .copied()
        .chain(std::iter::once(RECOMMENDATION_TYPE_PRIORITY))
    {
        set_type(&engine, &member_arn, kind);
        let case = format!("member recommendation {member_arn} as {kind}");
        let (status, body) = call(&router, "GET", &path, None).await;
        assert_eq!(
            status, 200,
            "case {case}: expected 200 from ListOrganizationRecommendationAccounts, got {status} \
             with {body}"
        );
        let summary = body["accountRecommendationLifecycleSummaries"]
            .as_array()
            .unwrap_or_else(|| panic!("case {case}: response has no summaries: {body}"))
            .iter()
            .find(|summary| {
                summary["accountRecommendationArn"].as_str() == Some(member_arn.as_str())
            })
            .cloned()
            .unwrap_or_else(|| panic!("case {case}: the list reports no {member_arn}: {body}"));

        if kind == RECOMMENDATION_TYPE_PRIORITY {
            assert_eq!(
                (
                    summary["lifecycleStage"].as_str(),
                    summary["updateReason"].as_str(),
                    summary["updateReasonCode"].as_str(),
                ),
                (
                    row.lifecycle_stage.as_deref(),
                    row.update_reason.as_deref(),
                    row.update_reason_code.as_deref(),
                ),
                "case {case}: expected the stored lifecycle members, got {summary}"
            );
        } else {
            assert_withheld(
                &case,
                &summary,
                &["lifecycleStage", "updateReason", "updateReasonCode"],
            );
        }
        assert_eq!(
            summary["accountId"].as_str(),
            Some(engine::EMULATOR_ACCOUNT_ID),
            "case {case}: expected the member's own accountId, got {summary}"
        );
        assert!(
            !summary["lastUpdatedAt"].is_null(),
            "case {case}: expected a lastUpdatedAt on every summary, got {summary}"
        );
    }
}
