/// Assert `reported` carries none of `members` — what a recommendation the
/// service produced automatically reports of them, whatever the store holds.
fn assert_withheld(case: &str, reported: &Value, members: &[&str]) {
    for member in members {
        assert_eq!(
            reported[*member],
            Value::Null,
            "case {case}: expected no {member} on a recommendation that is not prioritized, got \
             {:?}",
            reported[*member]
        );
    }
}

/// What this suite asserts about the lifecycle members of one reported
/// recommendation: for a prioritized one, every member as the store holds it;
/// for one of any other type, none of them. `lastUpdatedAt` is reported either
/// way.
fn assert_lifecycle_scoped(case: &str, reported: &Value, kind: &str, row: &Lifecycle) {
    if kind == RECOMMENDATION_TYPE_PRIORITY {
        assert_eq!(
            reported["lifecycleStage"].as_str(),
            row.lifecycle_stage.as_deref(),
            "case {case}: expected lifecycleStage {:?} on a {kind} recommendation, got {reported}",
            row.lifecycle_stage
        );
        assert_eq!(
            reported["updateReason"].as_str(),
            row.update_reason.as_deref(),
            "case {case}: expected updateReason {:?} on a {kind} recommendation, got {reported}",
            row.update_reason
        );
        assert_eq!(
            reported["updateReasonCode"].as_str(),
            row.update_reason_code.as_deref(),
            "case {case}: expected updateReasonCode {:?} on a {kind} recommendation, got \
             {reported}",
            row.update_reason_code
        );
        match row.resolved_at_millis {
            Some(millis) => {
                let expected = millis as f64 / 1_000.0;
                let got = timestamp_secs(&reported["resolvedAt"]);
                assert!(
                    (got - expected).abs() < 0.001,
                    "case {case}: expected resolvedAt {expected} seconds on a {kind} \
                     recommendation, got {got}"
                );
            }
            None => assert_eq!(
                reported["resolvedAt"],
                Value::Null,
                "case {case}: expected no resolvedAt on a {kind} recommendation the store holds \
                 none for, got {:?}",
                reported["resolvedAt"]
            ),
        }
    } else {
        assert_withheld(
            case,
            reported,
            &[
                "lifecycleStage",
                "updateReason",
                "updateReasonCode",
                "resolvedAt",
            ],
        );
    }
    assert!(
        !reported["lastUpdatedAt"].is_null(),
        "case {case}: expected a lastUpdatedAt on a {kind} recommendation, got {reported}"
    );
}

