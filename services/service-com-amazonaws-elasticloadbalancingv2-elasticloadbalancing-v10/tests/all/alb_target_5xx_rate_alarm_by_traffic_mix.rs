//! What ONE pair of alarm configurations — a count of the server errors a load balancer's target
//! returned, and the SHARE those errors are of the requests that target answered — reports over
//! traffics of different error mixes.
//!
//! The rule under test: **an alarm over the per-minute series a load balancer publishes while
//! answering requests is decided by the value its own configuration computes over the window that
//! traffic fell in, so one count-and-rate pair left exactly as a client configures it reports
//! whatever the traffic's own error mix makes of it: traffic the target answered without a server
//! error pages neither alarm, traffic carrying a MINORITY of target server errors pages the count
//! and not the rate, and traffic the target answered with a server error every time pages BOTH —
//! and each alarm's own history records every state it transitioned into, so a rate alarm that
//! never breached is a rate alarm with no breach in its record.**
//!
//! `HTTPCode_Target_5XX_Count` ("The number of HTTP response codes generated by the targets") and
//! `RequestCount` are Elastic Load Balancing's published CloudWatch metrics for the Application
//! Load Balancer family, keyed by the `LoadBalancer` and `TargetGroup` dimensions. What a reader
//! then does with them is CloudWatch's own: "Use the `Metrics` parameter to create an alarm based
//! on a metric math expression"
//! (`smithy_query(query="doc",shape="PutMetricAlarmInput",member="Metrics")`) is what grades the
//! rate, "The number of data points that must be breaching to trigger the alarm"
//! (`smithy_query(query="doc",shape="PutMetricAlarmInput",member="DatapointsToAlarm")`) is the
//! 1-of-1 grading every alarm here uses, "Sets how this alarm is to handle missing data points"
//! (`smithy_query(query="doc",shape="PutMetricAlarmInput",member="TreatMissingData")`) is what
//! decides a window no datapoint reached, and "the alarm history"
//! (`smithy_query(query="doc",shape="DescribeAlarmHistoryInput")`) read for `StateUpdate` items is
//! where a client sees which of the two ever paged.
//!
//! The rows differ along what the rule generalises over: the ERROR MIX of the traffic a group was
//! given (no server error at all, a minority of them, nothing but them) and therefore where the
//! value each reader computes falls relative to the ONE threshold that reader keeps across every
//! row — which is the differential production alarming is built on, a count that pages on any
//! target server error beside a rate that tolerates a low background error rate and pages only
//! when the errors are the traffic.
//!
//! What this suite drives that its sibling [`crate::alb_target_5xx_count_versus_rate_alarms`] does
//! not: that one fixes ONE traffic and varies the alarm — two thresholds bracketing that traffic's
//! rate — so the rate alarm it grades never breaches; here the alarm configurations are fixed and
//! the TRAFFIC varies, which is the other half of the same differential: the very rate alarm that
//! tolerates a minority of errors has to page once the errors are all of the traffic. The readers,
//! the rate's arithmetic and the two history reads both suites share live in that sibling and in
//! [`crate::alb_target_metric_rate_alarms`], so no two of them can shape one of these reads
//! differently.
//!
//! Every request is made over a real TCP connection to the address the load balancer PUBLISHES,
//! every datapoint is read back through CloudWatch's own API on the shared engine, and that the
//! function really ran is asserted where nothing of this service can fake it: the handler reports
//! every invocation to an Amazon SQS queue through its own SDK before it decides what to return.
//! Each mix is answered by a `lambda` target group of its own behind one load balancer, so the
//! three mixes are three series of one traffic rather than three runs of the clock; the traffic has
//! to land in ONE period for the rate of that period to be the rate of the traffic, so the function
//! is warmed up through Lambda's own API before any window is claimed, most of a period is waited
//! for, and that every datapoint really did fall in that window is then read off the series rather
//! than assumed — a run the clock ran out on is driven again at a load balancer of its own, so no
//! attempt the period cut short can reach the series the alarms grade.

