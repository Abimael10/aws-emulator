//! The DIFFERENTIAL two alarms draw over ONE Application Load Balancer's traffic: a count of the
//! server errors its target returned, and the SHARE those errors are of the requests it answered.
//!
//! The rule under test: **the per-minute series a load balancer publishes while answering requests
//! are the only input an alarm over them is graded on, so an alarm is decided by the value its own
//! configuration computes over the window the traffic fell in — the statistic of ONE series for an
//! alarm that names a metric, and the value of the RETURNING query for an alarm configured with a
//! metric-math array — compared against that alarm's own threshold; one traffic therefore drives a
//! count alarm over the target-error series and a rate alarm over the share that series is of the
//! request series to OPPOSITE verdicts, each alarm breaching exactly when its own value crosses
//! its own threshold, while a window a series published no datapoint into is decided by the
//! alarm's missing-data treatment rather than by a value.**
//!
//! `HTTPCode_Target_5XX_Count` ("The number of HTTP response codes generated by the targets") and
//! `RequestCount` are Elastic Load Balancing's published CloudWatch metrics for the Application
//! Load Balancer family, keyed by the `LoadBalancer` and `TargetGroup` dimensions. What a reader
//! then does with them is CloudWatch's own: "Use the `Metrics` parameter to create an alarm based
//! on a metric math expression"
//! (`smithy_query(query="doc",shape="PutMetricAlarmInput",member="Metrics")`) is what grades the
//! rate, "A math expression can use the Id of the other metrics or queries to refer to those
//! metrics" (`smithy_query(query="doc",shape="MetricDataQuery",member="Expression")`) is how that
//! expression names the two series it reads, "The number of data points that must be breaching to
//! trigger the alarm" (`smithy_query(query="doc",shape="PutMetricAlarmInput",member="DatapointsToAlarm")`)
//! is the 1-of-1 grading every row uses, and "Sets how this alarm is to handle missing data
//! points" (`smithy_query(query="doc",shape="PutMetricAlarmInput",member="TreatMissingData")`) is
//! what decides a window no datapoint reached.
//!
//! The rows differ along what the rule generalises over: the READER an alarm is configured with (a
//! single metric and a statistic, or a `Metrics` array whose returning query is an expression over
//! two series), where the alarm's THRESHOLD sits relative to the value that reader computes (below
//! it, above it), and whether the series it reads published a datapoint into the graded window at
//! all.
//!
//! What this suite drives that its sibling [`crate::alb_target_metric_rate_alarms`] does not: that
//! one reads every series the traffic fed and grades three alarms left at the default missing-data
//! treatment; here ONE traffic is graded by four alarms that differ only in the reader, the
//! threshold and the series, every one of them treating a missing datapoint as not breaching, the
//! rate is derived through a `FILL` of the error series so a window with requests and no errors is
//! a rate of zero rather than a hole, and each verdict is read back against the value the alarm's
//! own state record says the evaluation that set it HAD and against the transitions its history
//! reports — which is where a client sees whether a rate alarm ever paged. The readers both suites
//! share live in that sibling, so the two cannot shape one of these reads two different ways.
//!
//! Every request is made over a real TCP connection to the address the load balancer PUBLISHES,
//! every datapoint is read back through CloudWatch's own API on the shared engine, and that the
//! function really ran is asserted where nothing of this service can fake it: the handler reports
//! every invocation to an Amazon SQS queue through its own SDK before it decides what to return.
//! The traffic has to land in ONE period for the rate of that period to be the rate of the traffic:
//! the function is warmed up through Lambda's own API before any window is claimed, most of a period
//! is waited for, and that the datapoints really did all fall in that window is then read off the
//! series rather than assumed; a run the clock ran out on is driven again at a load balancer of its
//! own, so no attempt the period cut short can reach the series the alarms grade.

