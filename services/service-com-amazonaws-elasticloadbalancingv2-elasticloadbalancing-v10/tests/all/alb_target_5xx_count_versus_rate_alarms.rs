/// The two series the rate is the quotient of, and the target-class series no request of this
/// traffic ended in — Elastic Load Balancing's own names for them.
const ERROR_SERIES: &str = "HTTPCode_Target_5XX_Count";
const REQUEST_SERIES: &str = "RequestCount";
const UNFED_SERIES: &str = "HTTPCode_Target_4XX_Count";

/// How much of the current period has to be LEFT before the traffic is sent, so every datapoint of
/// it falls in ONE window: a metric is aggregated into periods anchored at multiples of the period,
/// so a run that began just before a boundary would split its counts across two of them and the
/// rate of each half would not be the rate of the traffic. Polled for rather than slept through.
/// That the traffic really did land in one window is then asserted on the DATAPOINTS it left rather
/// than on the clock, and a run the period ran out on is driven again ([`ATTEMPTS`]).
const ROOM_IN_PERIOD: f64 = 30.0;

/// How many times the traffic may be driven, at a FRESH load balancer and target group each time,
/// because the period ran out while it was being sent: a machine under heavy load can take longer
/// over the exchanges than the room left in a period, and the rate of half a traffic is not the rate
/// of the traffic. Each run publishes into the series of its own load balancer and group, so a run
/// the clock cut short leaves the series the alarms below grade untouched.
const ATTEMPTS: usize = 4;

/// The `StateValue` values the four alarms must reach.
const ALARM: &str = "ALARM";
const OK: &str = "OK";

/// The comparison every alarm here grades with, and the treatment every one of them gives a window
/// no datapoint reached.
const GREATER_THAN: &str = "GreaterThanThreshold";
const NOT_BREACHING: &str = "notBreaching";

/// The function every request is forwarded to, the role it runs as, and the queue it reports each
/// invocation to.
const FUNCTION: &str = "alb-5xx-differential-target";
const ROLE_NAME: &str = "alb-5xx-differential-exec";
const SIDE_CHANNEL: &str = "alb-5xx-differential-side-channel";

/// The load balancer and the `lambda` target group every request reaches — one pair per run of the
/// traffic, so a run the clock cut short publishes into series of its own.
const LOAD_BALANCER: &str = "alb-5xx-rate-lb";
const TARGET_GROUP: &str = "alb-5xx-rate-tg";

/// The two paths the traffic asks for, and the bodies the shared handler answers them with — a
/// success, and a server error of the TARGET's own making, which is what makes the error one the
/// target returned rather than one the load balancer generated ([`package`]).
const SUCCESS_PATH: &str = "/differential/ok";
const FAILURE_PATH: &str = "/differential/fail";
const SUCCESS_BODY: &str = "TARGET-OK";
const FAILURE_BODY: &str = "TARGET-FAILED";
const SUCCESS_STATUS: u16 = 200;
const FAILURE_STATUS: u16 = 500;

/// The traffic: the requests the target answers as a success, and the ONE it answers with a server
/// error of its own. A low error RATE and a COUNT of one, which is the mix a client's rate-vs-count
/// alarming is configured for.
const SUCCESSES: usize = 5;
const TARGET_ERRORS: f64 = 1.0;
const REQUESTS: f64 = SUCCESSES as f64 + TARGET_ERRORS;

/// The share of that traffic the target's own server errors are, as a percentage — the value the
/// rate alarms grade.
const ERROR_RATE: f64 = TARGET_ERRORS * 100.0 / REQUESTS;

/// The thresholds the rows grade against: one ABOVE the traffic's rate of [`ERROR_RATE`] percent,
/// one BELOW it, and the count threshold any single error exceeds. The two rate thresholds bracket
/// that rate, which is what makes one rate alarm stay `OK` and the other breach over the very
/// traffic the count alarm breaches on.
const ABOVE_RATE: f64 = 50.0;
const BELOW_RATE: f64 = 5.0;
const COUNT_THRESHOLD: f64 = 0.0;

/// How long the suite waits for work the clock owes — the invocation reports the handler writes,
/// and the period the datapoints fell in to CLOSE so an alarm evaluation grades it — and how long
/// between two looks. Generous on purpose: the longest wait is for one period to close, and the
/// deadline is only here so a failure is a failure rather than a hang.
const BUDGET: Duration = Duration::from_secs(60);
const SETTLE_BUDGET: Duration = Duration::from_secs(180);
const LOOK_AGAIN: Duration = Duration::from_millis(100);

/// What one alarm GRADES.
#[derive(Clone, Copy, Debug)]
enum Watched {
    /// One series of the load balancer's own, folded by `Sum` over the alarm's period — what an
    /// alarm naming a metric grades.
    Count(&'static str),
    /// The share of the group's requests that ended in a server error the target returned, as the
    /// expression derives it — what an alarm configured with a `Metrics` array grades.
    Rate,
}

/// What one row's own state record has to say about the datapoint its state was decided over.
#[derive(Clone, Copy, Debug)]
enum Record {
    /// The state this traffic owes the alarm can only have been reached by grading this value, so
    /// the record of the evaluation that set it must name it.
    Over(f64),
    /// The series the alarm reads published nothing at all, so no evaluation of it ever had a value
    /// and its record names none.
    Nothing,
    /// The alarm may have reached this state before the window the traffic fell in had closed — the
    /// missing-data treatment reaches `OK` over no datapoint — and an alarm whose state does not
    /// change again keeps the record of the evaluation that set it, so its record says nothing about
    /// this traffic and is not pinned here. What such a row's value is asserted on instead is the
    /// expression read over the window and the alarm over that same expression that MUST breach.
    Unpinned,
}

/// One row of the alarm table: the reader, the threshold, the state the one traffic must leave that
/// alarm in, and what its own record must say it graded to get there.
#[derive(Debug)]
struct AlarmRow {
    case: &'static str,
    name: &'static str,
    watched: Watched,
    threshold: f64,
    expected: &'static str,
    record: Record,
}

/// The alarm table: four alarms over ONE traffic, differing only in the reader, the threshold and
/// the series read.
const ALARMS: &[AlarmRow] = &[
    AlarmRow {
        case: "a count of the errors the target returned breaches on the one error there was",
        name: "alb-5xx-rate-count",
        watched: Watched::Count(ERROR_SERIES),
        threshold: COUNT_THRESHOLD,
        expected: ALARM,
        record: Record::Over(TARGET_ERRORS),
    },
    AlarmRow {
        case: "the share those errors are of the traffic stays under a rate the count has breached",
        name: "alb-5xx-rate-under",
        watched: Watched::Rate,
        threshold: ABOVE_RATE,
        expected: OK,
        record: Record::Unpinned,
    },
    AlarmRow {
        case: "the same share breaches a threshold below it: the expression's own value is graded",
        name: "alb-5xx-rate-over",
        watched: Watched::Rate,
        threshold: BELOW_RATE,
        expected: ALARM,
        record: Record::Over(ERROR_RATE),
    },
    AlarmRow {
        case: "a series the traffic published nothing into is decided by the missing treatment",
        name: "alb-5xx-rate-unfed",
        watched: Watched::Count(UNFED_SERIES),
        threshold: COUNT_THRESHOLD,
        expected: OK,
        record: Record::Nothing,
    },
];

/// Whether one row has SETTLED: the alarm reports the state this traffic owes it, and its own state
/// record says what that row requires of it ([`Record`]).
fn settled(row: &AlarmRow, state: &str, graded: &[f64]) -> bool {
    state == row.expected
        && match row.record {
            Record::Over(value) => graded.iter().any(|point| (point - value).abs() < TOLERANCE),
            Record::Nothing => graded.is_empty(),
            Record::Unpinned => true,
        }
}

/// One request of the traffic: the path the client asks for, the status the load balancer must
/// answer with, the body that answer must carry, and the mode the handler reports for it.
#[derive(Debug)]
struct Request {
    case: String,
    target: &'static str,
    status: u16,
    body: &'static str,
    mode: &'static str,
}

/// The traffic, in the order it is sent: every success first and the one target error last, so the
/// error is counted into a window the successes are already in.
fn traffic() -> Vec<Request> {
    let mut requests: Vec<Request> = (1..=SUCCESSES)
        .map(|index| Request {
            case: format!("success {index} of {SUCCESSES}, answered by the target"),
            target: SUCCESS_PATH,
            status: SUCCESS_STATUS,
            body: SUCCESS_BODY,
            mode: "ok",
        })
        .collect();
    requests.push(Request {
        case: "the one server error, returned by the target itself".to_string(),
        target: FAILURE_PATH,
        status: FAILURE_STATUS,
        body: FAILURE_BODY,
        mode: "fail",
    });
    requests
}

/// The expression the rate is derived by: the share of the requests the group answered that ended
/// in a server error the TARGET returned, as a percentage, with the error series `FILL`ed so a
/// window that carried requests and no error is a rate of zero rather than a hole. It names the two
/// reads by their query ids, which is how a math expression refers to the queries it reads.
fn rate_expression() -> String {
    format!("100 * FILL({ERRORS_ID}, 0) / {REQUESTS_ID}")
}

/// The `PutMetricAlarm` request one row is written with: the same 1-of-1 grading and the same
/// missing-data treatment for every row, over the reader that row names.
fn alarm_request(row: &AlarmRow, dimensions: &Value) -> Value {
    let mut body = json!({
        "AlarmName": row.name,
        "EvaluationPeriods": 1,
        "DatapointsToAlarm": 1,
        "Threshold": row.threshold,
        "ComparisonOperator": GREATER_THAN,
        "TreatMissingData": NOT_BREACHING,
        "ActionsEnabled": false,
    });
    match row.watched {
        Watched::Count(metric) => {
            body["Namespace"] = json!(APPLICATION_NAMESPACE);
            body["MetricName"] = json!(metric);
            body["Dimensions"] = dimensions.clone();
            body["Statistic"] = json!("Sum");
            body["Period"] = json!(PERIOD_SECS);
        }
        Watched::Rate => body["Metrics"] = rate_queries(dimensions, &rate_expression()),
    }
    body
}

/// ONE look at an alarm: the `StateValue` it reports, and the values its `StateReasonData` says the
/// evaluation that set that state really had — the `recentDatapoints` of "The reason that this alarm
/// is set to this specific state, in JSON format." (`MetricAlarm$StateReasonData`), which is what
/// tells a state decided over a datapoint from one a missing-data treatment decided.
///
/// Both come out of the SAME read, so a look cannot pair one evaluation's state with another's
/// record.
async fn looked_at(router: &MultiServiceRouter, name: &str) -> (String, Vec<f64>) {
    let body = cloudwatch_ok(
        router,
        "DescribeAlarms",
        &json!({ "AlarmNames": [name], "AlarmTypes": ["MetricAlarm"] }),
    )
    .await;
    let alarm = &body["MetricAlarms"][0];
    let state = alarm["StateValue"].as_str().unwrap_or_default().to_string();
    let data = match alarm["StateReasonData"].as_str() {
        Some(text) => serde_json::from_str::<Value>(text).unwrap_or(Value::Null),
        None => alarm["StateReasonData"].clone(),
    };
    let graded = data["recentDatapoints"]
        .as_array()
        .cloned()
        .unwrap_or_default()
        .iter()
        .filter_map(Value::as_f64)
        .collect();
    (state, graded)
}

/// Every state one alarm has TRANSITIONED into, oldest first, as its own history records them: the
/// `newState.stateValue` of each `StateUpdate` item `DescribeAlarmHistory` reports for it.
async fn transitions(router: &MultiServiceRouter, name: &str) -> Vec<String> {
    let body = cloudwatch_ok(
        router,
        "DescribeAlarmHistory",
        &json!({
            "AlarmName": name,
            "AlarmTypes": ["MetricAlarm"],
            "HistoryItemType": "StateUpdate",
            "ScanBy": "TimestampAscending",
        }),
    )
    .await;
    body["AlarmHistoryItems"]
        .as_array()
        .cloned()
        .unwrap_or_default()
        .iter()
        .filter_map(|item| {
            let data = match item["HistoryData"].as_str() {
                Some(text) => serde_json::from_str::<Value>(text).unwrap_or(Value::Null),
                None => item["HistoryData"].clone(),
            };
            data["newState"]["stateValue"]
                .as_str()
                .map(str::to_string)
        })
        .collect()
}

/// What one run of the traffic left behind: the dimensions the series it fed are keyed by, and the
/// period every one of its datapoints fell in.
#[derive(Debug)]
struct Metered {
    dimensions: Value,
    window_start: f64,
}

/// Drive the whole traffic once, at a load balancer and `lambda` target group of this run's own, and
/// answer what it left behind — or `None` when the period ran out while it was being sent, which is
/// a run the caller drives again rather than a verdict ([`ATTEMPTS`]).
///
/// Whether it landed in one window is read off the DATAPOINTS, not off the clock: the window it
/// claimed holds one datapoint of the request series, counting every request it made.
async fn drive_traffic(
    router: &MultiServiceRouter,
    engine: &Arc<engine::InMemoryEngine>,
    queue_url: &str,
    function_arn: &str,
    run: usize,
) -> Option<Metered> {
    let (lb_arn, published) =
        create_load_balancer(router, &format!("{LOAD_BALANCER}-{run}")).await;
    let tg_arn = lambda_target_group(
        router,
        &format!("{TARGET_GROUP}-{run}"),
        FUNCTION,
        function_arn,
    )
    .await;

    let mut form = action("CreateListener");
    form.push(p("LoadBalancerArn", &lb_arn));
    form.push(p("Protocol", "HTTP"));
    form.push(p("Port", "80"));
    form.push(p("DefaultActions.member.1.Type", "forward"));
    form.push(p("DefaultActions.member.1.TargetGroupArn", &tg_arn));
    let reply = call(router, &form).await;
    assert_eq!(
        reply.status, 200,
        "setup CreateListener: expected 200, got {} body {}",
        reply.status, reply.body
    );

    // The move to `active` the clock owes the load balancer, placed rather than slept for.
    settle(engine, &lb_arn, SystemTime::now() - Duration::from_secs(1));

    let dimensions = json!([
        { "Name": TARGET_GROUP_DIMENSION, "Value": target_group_dimension(&tg_arn) },
        { "Name": LOAD_BALANCER_DIMENSION, "Value": load_balancer_dimension(&lb_arn) },
    ]);

    // A warm-up invocation through LAMBDA's own API, before any window is claimed: the first run of
    // a function pays for everything that run sets up, and that cost belongs outside the window the
    // rate is derived from. An invocation the load balancer did not make publishes nothing into the
    // series below, so it cannot be mistaken for traffic.
    let (status, warmed) = lambda(
        router,
        "POST",
        &format!("/2015-03-31/functions/{FUNCTION}/invocations"),
        json!({ "path": SUCCESS_PATH }),
    )
    .await;
    assert_eq!(
        status, 200,
        "setup Invoke: expected the warm-up invocation to answer 200, got {status} {warmed}"
    );
    let reported = reports(router, "the warm-up invocation", queue_url, BUDGET, 1).await;
    assert_eq!(
        reported.len(),
        1,
        "setup Invoke: expected the warm-up to have run the handler once, got {reported:?}"
    );

    wait_for_period_room(ROOM_IN_PERIOD).await;
    let window_start = current_window();

    let traffic = traffic();
    for request in &traffic {
        let answered = exchange(&request.case, &published, request.target).await;
        assert_eq!(
            answered.status, request.status,
            "case {:?}: expected HTTP {}, got {} in {:?}",
            request.case, request.status, answered.status, answered.raw
        );
        // The body is the FUNCTION's own, which is what makes the error one the target returned
        // rather than one the load balancer generated for it.
        assert!(
            answered.raw.contains(request.body),
            "case {:?}: expected the answer to carry {:?}, got {:?}",
            request.case,
            request.body,
            answered.raw
        );
    }

    // The function RAN, once per request: the handler reports before it decides what to return.
    let seen = reports(router, "the whole traffic", queue_url, BUDGET, traffic.len()).await;
    let mut modes: Vec<&str> = seen.iter().map(String::as_str).collect();
    modes.sort_unstable();
    let mut expected_modes: Vec<&str> = traffic.iter().map(|request| request.mode).collect();
    expected_modes.sort_unstable();
    assert_eq!(
        modes, expected_modes,
        "the traffic must have invoked the function once per request, got {seen:?}"
    );

    // What the window the traffic claimed holds: every one of its requests and nothing else. A run
    // the period ran out on left some of them in the NEXT window, which this read is what finds.
    let (total, points) = statistic(
        router,
        REQUEST_SERIES,
        &dimensions,
        window_start,
        window_start + PERIOD,
    )
    .await;
    if points != 1 || (total - REQUESTS).abs() >= TOLERANCE {
        return None;
    }
    Some(Metered {
        dimensions,
        window_start,
    })
}

/// RULE: each alarm over a load balancer's own series is decided by the value its own configuration
/// computes over the window the traffic fell in against its own threshold — so one traffic drives a
/// count of the target's server errors and the rate those errors are of the requests to opposite
/// verdicts, and a series the traffic published nothing into is decided by the missing-data
/// treatment instead.
#[tokio::test]
async fn one_traffic_grades_the_target_error_count_and_its_rate_apart() {
    let (router, engine) = emulator();

    // The side channel the handler reports every invocation to, and the role whose one grant admits
    // that report.
    let (status, queue) = sqs(&router, "CreateQueue", &json!({ "QueueName": SIDE_CHANNEL })).await;
    assert_eq!(
        status, 200,
        "setup CreateQueue: expected 200, got {status} {queue}"
    );
    let queue_url = queue["QueueUrl"]
        .as_str()
        .unwrap_or_else(|| panic!("setup CreateQueue: no QueueUrl in {queue}"))
        .to_string();
    let (status, attributes) = sqs(
        &router,
        "GetQueueAttributes",
        &json!({ "QueueUrl": queue_url, "AttributeNames": ["QueueArn"] }),
    )
    .await;
    assert_eq!(
        status, 200,
        "setup GetQueueAttributes: expected 200, got {status} {attributes}"
    );
    let queue_arn = attributes["Attributes"]["QueueArn"]
        .as_str()
        .unwrap_or_else(|| panic!("setup GetQueueAttributes: no QueueArn in {attributes}"))
        .to_string();
    let role = execution_role(&router, ROLE_NAME, &queue_arn).await;

    // The function every request is forwarded to, created through Lambda's own API.
    let (status, created) = lambda(
        &router,
        "POST",
        "/2015-03-31/functions",
        json!({
            "FunctionName": FUNCTION,
            "Role": role,
            "Runtime": RUNTIME,
            "Handler": HANDLER,
            "Timeout": 30,
            "Environment": { "Variables": { "QUEUE_URL": queue_url } },
            "Code": { "ZipFile": aws_smithy_types::base64::encode(package()) },
        }),
    )
    .await;
    assert_eq!(
        status, 201,
        "setup CreateFunction: expected 201, got {status} {created}"
    );
    let function_arn = created["FunctionArn"]
        .as_str()
        .unwrap_or_else(|| panic!("setup CreateFunction: no FunctionArn in {created}"))
        .to_string();
    // The activation span Lambda owes the function, placed rather than slept for.
    activate_functions(&engine);

    // The load balancer, the address it publishes, the `lambda` target group and the listener whose
    // default action forwards every request to it — then the traffic, driven at a pair of its own
    // until one run of it fell in a single period.
    let mut metered = None;
    for run in 0..ATTEMPTS {
        metered = drive_traffic(&router, &engine, &queue_url, &function_arn, run).await;
        if metered.is_some() {
            break;
        }
    }
    let Metered {
        dimensions,
        window_start,
    } = metered.unwrap_or_else(|| {
        panic!(
            "expected one of {ATTEMPTS} runs of the traffic to fall in a single period, so the \
             rate of that period is the rate of the traffic"
        )
    });

    // What the window the traffic fell in holds of the two series the rate is a quotient of, and
    // what the rate itself is over it: the share of the group's requests that ended in a server
    // error of the target's own. The window is read on its own boundaries, so the warm-up request
    // of an earlier period is no part of what is asserted here.
    let start = window_start;
    let end = window_start + PERIOD;
    for (case, metric, expected, expected_points) in [
        (
            "every request the group answered is one request processed, in the one window they \
             were all answered in",
            REQUEST_SERIES,
            REQUESTS,
            1,
        ),
        (
            "the server error the target returned, narrowed to the group that answered it",
            ERROR_SERIES,
            TARGET_ERRORS,
            1,
        ),
        (
            "a class no request of this traffic ended in holds no datapoint",
            UNFED_SERIES,
            0.0,
            0,
        ),
    ] {
        let (total, points) = statistic(&router, metric, &dimensions, start, end).await;
        assert!(
            (total - expected).abs() < TOLERANCE,
            "case {case:?}: expected {metric} of {APPLICATION_NAMESPACE} to sum to {expected}, \
             got {total} over {points} datapoint(s)"
        );
        assert_eq!(
            points, expected_points,
            "case {case:?}: expected {metric} to hold {expected_points} datapoint(s) over this \
             window, got {points}"
        );
    }

    let values = rate_values(&router, &dimensions, &rate_expression(), start, end).await;
    assert_eq!(
        values.len(),
        1,
        "case {:?}: expected the traffic to derive one window's rate, got {values:?}",
        rate_expression()
    );
    assert!(
        (values[0] - ERROR_RATE).abs() < TOLERANCE,
        "case {:?}: expected a rate of {ERROR_RATE}, got {}",
        rate_expression(),
        values[0]
    );

    // The four alarms over that one traffic.
    for row in ALARMS {
        cloudwatch_ok(&router, "PutMetricAlarm", &alarm_request(row, &dimensions)).await;
    }

    // Their verdicts are owed once the period the datapoints fell in has CLOSED — an alarm grades
    // the periods that are complete — so each alarm is looked at again until it reports the state
    // this traffic owes it AND its own record says that state was decided over the value the
    // traffic left in the series it reads, which is what tells a verdict computed over the traffic
    // from one the missing-data treatment stood in for.
    let deadline = Instant::now() + SETTLE_BUDGET;
    loop {
        let mut graded: Vec<(&str, String, Vec<f64>)> = Vec::new();
        for row in ALARMS {
            let (state, points) = looked_at(&router, row.name).await;
            graded.push((row.case, state, points));
        }
        if graded
            .iter()
            .zip(ALARMS)
            .all(|((_, state, points), row)| settled(row, state, points))
        {
            break;
        }
        assert!(
            Instant::now() < deadline,
            "expected the alarms to grade the window the traffic fell in as {:?}, got {graded:?}",
            ALARMS
                .iter()
                .map(|row| (row.case, row.expected, row.record))
                .collect::<Vec<(&str, &str, Record)>>()
        );
        tokio::time::sleep(LOOK_AGAIN).await;
    }

    // And what each alarm's own history reports of how it got there: the count alarm having
    // TRANSITIONED into `ALARM` over this traffic, while the rate alarm that stayed `OK` completed
    // its evaluations without ever having been in `ALARM` — which is the record a client reads to
    // tell a rate alarm that never paged from one that did.
    for row in ALARMS {
        let seen = transitions(&router, row.name).await;
        assert!(
            !seen.is_empty(),
            "case {:?}: expected {} to have recorded the state it reached, got {seen:?}",
            row.case,
            row.name
        );
        assert_eq!(
            seen.contains(&ALARM.to_string()),
            row.expected == ALARM,
            "case {:?}: expected a transition into {ALARM} to have been recorded={}, got {seen:?}",
            row.case,
            row.expected == ALARM
        );
        assert_eq!(
            seen.last().map(String::as_str),
            Some(row.expected),
            "case {:?}: expected the last state recorded to be {}, got {seen:?}",
            row.case,
            row.expected
        );
    }
}
