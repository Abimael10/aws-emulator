/// The stamp every token this operation issues carries: this service, the token format
/// version, and the list it is a boundary for.
const PAGE_STAMP: &str = "scn:1:data-integration-flow:";

/// The page token naming the flow called `name`, for the query it was cut from: the instance
/// addressed.
///
/// `DataIntegrationFlowNextToken` is modelled as a string of length 1..65535 and nothing
/// else, so the token is the stamped payload hex-encoded: one value for a client to hand
/// back, under 700 characters at the modelled maxima — well inside the modelled bound — and
/// read only through [`decode_page_token`]. The encoding is reversible and is no part of the
/// check: carrying the query identity is what lets a value this operation did not issue, or
/// one issued for another instance, be refused instead of honoured as a boundary for THIS
/// query. The two fields it holds are values the caller addressed the listing with or already
/// read in a page of it.
///
/// `:` separates the two fields because neither of them can contain one: an `instanceId` is a
/// hyphenated hex UUID and `DataIntegrationFlowName` is `^[A-Za-z0-9-]+$`.
fn encode_page_token(instance_id: &str, name: &str) -> String {
    ::hex::encode(format!("{PAGE_STAMP}{instance_id}:{name}").as_bytes())
}

/// The resume key a token names, or `None` when `token` is not one this operation issued for
/// this instance — which the caller is told as a `ValidationException`, never as a silently
/// truncated or restarted page.
fn decode_page_token(token: &str, instance_id: &str) -> Option<String> {
    let decoded = String::from_utf8(::hex::decode(token).ok()?).ok()?;
    let mut fields = decoded.strip_prefix(PAGE_STAMP)?.split(':');
    let token_instance = fields.next()?;
    let token_key = fields.next()?;
    // Every key this operation pages on is the name of a flow of the instance the page was
    // cut from, so anything else is a boundary this service could not have issued for this
    // query.
    (fields.next().is_none() && token_instance == instance_id && is_modelled_flow_name(token_key))
        .then(|| token_key.to_string())
}

/// Whether `value` is a name of the model's `DataIntegrationFlowName` shape: length 1..256
/// and `^[A-Za-z0-9-]+$`. Only such a value can be a flow this listing pages on, so a resume
/// key that is not one names no boundary this service issued.
fn is_modelled_flow_name(value: &str) -> bool {
    (MIN_FLOW_NAME_LEN..=MAX_FLOW_NAME_LEN).contains(&value.chars().count())
        && value.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'-')
}
