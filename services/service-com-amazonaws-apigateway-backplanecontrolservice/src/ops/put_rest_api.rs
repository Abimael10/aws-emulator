/// Both readers below build this: `serde_json` for the JSON spelling (its `MapAccess`
/// visits a mapping in document order) and the bounded event reader for the YAML one.
#[derive(Debug, Clone, Default)]
pub enum Node {
    /// A null, and the one a document writes as an empty value.
    #[default]
    Null,
    /// A scalar, as its text: a definition is read for strings, and for the SHAPE of
    /// everything else, so a number or a boolean is kept as it was written.
    ///
    /// `plain` is whether it was written WITHOUT quotes — a JSON number, boolean or `null`,
    /// and a YAML plain scalar — which is what says the text stands for a value of another
    /// type rather than for itself. Every reader below takes the text either way
    /// ([`Node::text`]); the one place the distinction matters is a document a JSON document
    /// is rebuilt from, where a quoted `3` is the string and a plain one is the number
    /// ([`Node::json`]).
    Scalar { text: String, plain: bool },
    /// A sequence, in order.
    Sequence(Vec<Node>),
    /// A mapping, entries in document order. A document that repeats a key keeps both
    /// entries and the readers below take the FIRST, so what the import reads does not
    /// depend on how far the reader got.
    Mapping(Vec<(String, Node)>),
}

impl Node {
    /// A scalar written WITH quotes, which stands for the text itself.
    fn quoted(text: String) -> Self {
        Node::Scalar { text, plain: false }
    }

    /// A scalar written WITHOUT quotes: a JSON number or boolean, or a YAML plain scalar.
    fn unquoted(text: String) -> Self {
        Node::Scalar { text, plain: true }
    }

    /// This node as the JSON document it was read from — the document a `Model`'s schema is
    /// stored as, so a schema a definition declares is stored as the JSON it was written in.
    ///
    /// A mapping keeps the document's own order (`serde_json`'s object preserves insertion
    /// order under its `preserve_order` feature, and the entries are inserted in document
    /// order either way), and an UNQUOTED scalar is the value its text spells where that text
    /// spells a JSON number or boolean — which is how a JSON number read into a scalar, and a
    /// YAML plain scalar, become numbers again. A quoted scalar is the string it was written
    /// as, whatever it looks like, so `"3"` in a schema's `enum` stays the string `3`.
    fn json(&self) -> ::serde_json::Value {
        self.json_at(1)
    }

    /// [`Node::json`] at nesting level `depth`, which bounds the recursion explicitly: a node
    /// past [`MAX_DEFINITION_DEPTH`] is rebuilt as the null value rather than descended into.
    ///
    /// Unreachable for a parsed definition — a document nesting that deeply is refused before
    /// anything reads it ([`bound_definition_nodes`], [`DefinitionBuilder::open_frame`]) — and
    /// written as a bound anyway, because the stack is the one resource a tree walk consumes
    /// that no later check can give back.
    fn json_at(&self, depth: usize) -> ::serde_json::Value {
        if depth > MAX_DEFINITION_DEPTH {
            return ::serde_json::Value::Null;
        }
        match self {
            Node::Null => ::serde_json::Value::Null,
            Node::Scalar { text, plain } => {
                let literal = plain
                    .then(|| ::serde_json::from_str::<::serde_json::Value>(text).ok())
                    .flatten()
                    .filter(|value| value.is_number() || value.is_boolean());
                literal.unwrap_or_else(|| ::serde_json::Value::String(text.clone()))
            }
            Node::Sequence(items) => ::serde_json::Value::Array(
                items.iter().map(|item| item.json_at(depth + 1)).collect(),
            ),
            Node::Mapping(entries) => ::serde_json::Value::Object(
                entries
                    .iter()
                    .map(|(name, value)| (name.clone(), value.json_at(depth + 1)))
                    .collect(),
            ),
        }
    }

    /// A member of this mapping by name; `None` for any other node.
    fn member(&self, key: &str) -> Option<&Node> {
        match self {
            Node::Mapping(entries) => entries
                .iter()
                .find(|(name, _)| name == key)
                .map(|(_, value)| value),
            _ => None,
        }
    }

    /// This node's text, when it is a scalar.
    fn text(&self) -> Option<&str> {
        match self {
            Node::Scalar { text, .. } => Some(text),
            _ => None,
        }
    }

    /// A string member of this mapping; `None` when it is absent or not a scalar.
    fn string_member(&self, key: &str) -> Option<String> {
        self.member(key).and_then(Node::text).map(str::to_owned)
    }

    /// This node's mapping entries, when it is a mapping.
    fn entries(&self) -> Option<&[(String, Node)]> {
        match self {
            Node::Mapping(entries) => Some(entries),
            _ => None,
        }
    }

    /// This node's items, when it is a sequence.
    fn items(&self) -> Option<&[Node]> {
        match self {
            Node::Sequence(items) => Some(items),
            _ => None,
        }
    }
}

impl<'de> Deserialize<'de> for Node {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        deserializer.deserialize_any(NodeVisitor)
    }
}

/// Builds a [`Node`] from `serde_json`'s visits. The JSON spelling of a definition is
/// read this way rather than through the YAML reader because `serde_json` enforces its
/// own recursion limit, so a nested JSON body cannot drive the parse deeper than that.
struct NodeVisitor;

impl<'de> Visitor<'de> for NodeVisitor {
    type Value = Node;

    fn expecting(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str("a JSON value")
    }

    fn visit_unit<E: ::serde::de::Error>(self) -> Result<Node, E> {
        Ok(Node::Null)
    }

    fn visit_bool<E: ::serde::de::Error>(self, value: bool) -> Result<Node, E> {
        Ok(Node::unquoted(value.to_string()))
    }

    fn visit_i64<E: ::serde::de::Error>(self, value: i64) -> Result<Node, E> {
        Ok(Node::unquoted(value.to_string()))
    }

    fn visit_u64<E: ::serde::de::Error>(self, value: u64) -> Result<Node, E> {
        Ok(Node::unquoted(value.to_string()))
    }

    fn visit_f64<E: ::serde::de::Error>(self, value: f64) -> Result<Node, E> {
        Ok(Node::unquoted(value.to_string()))
    }

    fn visit_str<E: ::serde::de::Error>(self, value: &str) -> Result<Node, E> {
        Ok(Node::quoted(value.to_owned()))
    }

    fn visit_seq<A: SeqAccess<'de>>(self, mut sequence: A) -> Result<Node, A::Error> {
        let mut items = Vec::new();
        while let Some(item) = sequence.next_element()? {
            items.push(item);
        }
        Ok(Node::Sequence(items))
    }

    fn visit_map<A: MapAccess<'de>>(self, mut mapping: A) -> Result<Node, A::Error> {
        let mut entries = Vec::new();
        while let Some((key, value)) = mapping.next_entry::<String, Node>()? {
            entries.push((key, value));
        }
        Ok(Node::Mapping(entries))
    }
}

/// One collection the YAML reader has open: what its entries are collected into until its
/// end event arrives.
#[derive(Debug)]
enum Frame {
    Sequence(Vec<Node>),
    Mapping {
        entries: Vec<(String, Node)>,
        /// The key of the entry being read; `None` while the NEXT node is a key.
        pending_key: Option<String>,
    },
}

/// Reads a YAML definition off the parser's EVENT stream, bounding what it builds.
///
/// The event stream rather than `YamlLoader` is what lets this refuse an ALIAS: an alias
/// copies the node its anchor named, which is how a few hundred bytes of YAML expand into
/// gigabytes, and nothing in an API definition needs one. The node count and the nesting
/// depth are bounded here too, so the tree is bounded by constants rather than by what the
/// document asks for.
///
/// The loader's own recursion is NOT abortable from an `EventReceiver` (`on_event` returns
/// `()`) and exhausting the stack aborts the process rather than unwinding, so nesting is
/// ALSO refused before `load` is called — see [`guard_yaml_nesting`].
#[derive(Debug, Default)]
struct DefinitionBuilder {
    /// The first document's root node.
    root: Option<Node>,
    /// The collections open at this point of the stream.
    open: Vec<Frame>,
    /// How many nodes have been placed.
    nodes: usize,
    /// Why this document is not read, once a bound or an alias refused it.
    refused: Option<&'static str>,
}

impl DefinitionBuilder {
    /// Place a finished node where the stream says it belongs: an item of the open
    /// sequence, a key or a value of the open mapping, or the document's root.
    fn place(&mut self, node: Node) {
        if self.refused.is_some() {
            return;
        }
        self.nodes = self.nodes.saturating_add(1);
        if self.nodes > MAX_DEFINITION_NODES {
            self.refused = Some("the definition carries more nodes than this emulator reads");
            return;
        }
        match self.open.last_mut() {
            // Only the FIRST document of a multi-document body is read, which is the
            // document an API definition is.
            None => {
                if self.root.is_none() {
                    self.root = Some(node);
                }
            }
            Some(Frame::Sequence(items)) => items.push(node),
            Some(Frame::Mapping {
                entries,
                pending_key,
            }) => match pending_key.take() {
                None => match node {
                    Node::Scalar { text, .. } => *pending_key = Some(text),
                    _ => {
                        self.refused = Some("every key of the definition must be a string");
                    }
                },
                Some(key) => entries.push((key, node)),
            },
        }
    }

    /// Open a collection, refusing a document that nests deeper than
    /// [`MAX_DEFINITION_DEPTH`].
    fn open_frame(&mut self, frame: Frame) {
        if self.refused.is_some() {
            return;
        }
        if self.open.len() >= MAX_DEFINITION_DEPTH {
            self.refused = Some(TOO_DEEPLY_NESTED);
            return;
        }
        self.open.push(frame);
    }

    /// Close the open collection and place it in its parent.
    fn close_frame(&mut self) {
        if self.refused.is_some() {
            return;
        }
        let Some(frame) = self.open.pop() else {
            return;
        };
        let node = match frame {
            Frame::Sequence(items) => Node::Sequence(items),
            Frame::Mapping { entries, .. } => Node::Mapping(entries),
        };
        self.place(node);
    }
}

impl ::yaml_rust2::parser::EventReceiver for DefinitionBuilder {
    fn on_event(&mut self, event: ::yaml_rust2::parser::Event) {
        use ::yaml_rust2::parser::Event;
        if self.refused.is_some() {
            return;
        }
        match event {
            Event::Scalar(value, style, _anchor, _tag) => {
                // A plain scalar resolves by YAML's core schema, where an empty value,
                // `~` and `null` are the null value; a quoted scalar is always text.
                let plain = matches!(style, ::yaml_rust2::scanner::TScalarStyle::Plain);
                let node = if plain && matches!(value.as_str(), "" | "~" | "null" | "Null" | "NULL")
                {
                    Node::Null
                } else {
                    Node::Scalar { text: value, plain }
                };
                self.place(node);
            }
            Event::SequenceStart(..) => self.open_frame(Frame::Sequence(Vec::new())),
            Event::MappingStart(..) => self.open_frame(Frame::Mapping {
                entries: Vec::new(),
                pending_key: None,
            }),
            Event::SequenceEnd | Event::MappingEnd => self.close_frame(),
            // An alias copies an anchored node, which is the unbounded amplification a
            // YAML body can carry. No API definition needs one, so a body with one is
            // not read.
            Event::Alias(_) => {
                self.refused =
                    Some("an alias expands the document it appears in and is not read here");
            }
            _ => {}
        }
    }
}

/// Pre-flight bounds on an untrusted YAML definition, applied BEFORE the loader builds
/// anything from it. Only the YAML spelling needs this: the JSON spelling is read by
/// `serde_json`, which enforces its own nesting limit.
///
/// What has to be bounded is how deep the loader can RECURSE, because an `EventReceiver`
/// cannot abort `load` and because exhausting the stack aborts the process rather than
/// unwinding. Three measures do that, and each bounds NESTING rather than how big the
/// document is, so a large flat definition is not affected by any of them:
///
/// * [`MAX_DEFINITION_FLOW_DEPTH`] — the flow collections (`[`, `{`) open at once, with
///   closers subtracted: the nesting a well-formed body reaches.
/// * [`MAX_DEFINITION_FLOW_OPENERS`] — the total flow openers, the backstop for the one
///   way the measure above can be fooled: this is a byte scan, so a `]` inside a scalar
///   lowers the running depth while the loader's own depth keeps climbing. However many
///   closers a body hides, its real flow nesting cannot exceed its opener COUNT.
/// * [`MAX_DEFINITION_INDENT`] columns of leading indentation and
///   [`MAX_DEFINITION_COMPACT_PER_LINE`] compact `- `/`? ` indicators on one line — the
///   two ways block nesting descends.
///
/// The measures and their reasoning are the sibling CloudFormation reader's
/// (`services/service-com-amazonaws-cloudformation-cloudformation/src/state/template.rs`,
/// `guard_yaml_body`), which guards the same loader version against the same kind of
/// caller-supplied body.
fn guard_yaml_nesting(body: &str) -> Result<(), String> {
    let refusal =
        || "Unable to parse API definition: it nests more deeply than this emulator reads";
    let mut flow_depth = 0usize;
    let mut flow_openers = 0usize;
    let mut compact_on_line = 0usize;
    let mut indent = 0usize;
    let mut counting_indent = true;
    let mut previous = b'\n';

    for byte in body.bytes() {
        match byte {
            b'\n' | b'\r' => {
                indent = 0;
                compact_on_line = 0;
                counting_indent = true;
            }
            b' ' | b'\t' if counting_indent => {
                indent += 1;
                if indent > MAX_DEFINITION_INDENT {
                    return Err(refusal().to_string());
                }
            }
            b'[' | b'{' => {
                counting_indent = false;
                flow_depth += 1;
                flow_openers += 1;
                if flow_depth > MAX_DEFINITION_FLOW_DEPTH
                    || flow_openers > MAX_DEFINITION_FLOW_OPENERS
                {
                    return Err(refusal().to_string());
                }
            }
            b']' | b'}' => {
                counting_indent = false;
                flow_depth = flow_depth.saturating_sub(1);
            }
            _ => counting_indent = false,
        }
        // A `-` or `?` is a block indicator only where a token may start — at the start of
        // a line or after a space — and only when a space follows it, which is what
        // separates `- item` from the hyphen in `/pet-store` or `2026-01-01`.
        if matches!(previous, b'-' | b'?') && matches!(byte, b' ' | b'\t' | b'\n' | b'\r') {
            compact_on_line += 1;
            if compact_on_line > MAX_DEFINITION_COMPACT_PER_LINE {
                return Err(refusal().to_string());
            }
        }
        previous = byte;
    }
    Ok(())
}

/// The root members an OpenAPI/Swagger document declares the format it is written in in:
/// `openapi` from 3.0 on, `swagger` before it.
///
/// Which one of them a document carries is the first thing read, and whether EITHER was
/// read is what picks the sentence a document that is not a readable definition is refused
/// with — see [`UNDETERMINED_VERSION`] and [`INVALID_DEFINITION`].
const VERSION_MEMBERS: [&str; 2] = ["openapi", "swagger"];

/// Whether `node` declares the format it is written in, which is one of
/// [`VERSION_MEMBERS`] at its root. A node that is no mapping carries no member at all, so
/// it declares no version either ([`Node::member`]).
fn declares_version(node: &Node) -> bool {
    VERSION_MEMBERS
        .iter()
        .any(|member| node.member(member).is_some())
}

/// Whether `text` writes one of [`VERSION_MEMBERS`] as a member, read off the document as
/// it was RECEIVED.
///
/// This is what settles the format of a body the readers below could not finish, and it is
/// read from the text because a tree is not available for one: those readers build the
/// document as they go, and a document that stops being readable can stop before the reader
/// has delivered anything at all of what it did read (the YAML scanner resolves a flow
/// mapping's key before it hands over the mapping it belongs to), so how much of a
/// half-built tree exists says nothing about what the document declares.
///
/// What a member looks like is the same in both spellings, and is all this decides: the
/// name, quoted or not, where a member may START — at the beginning of the document, after
/// the opener or the separator of a flow collection, or at the start of a line — and
/// followed by `:`. So a name that merely CONTAINS one (`swaggerVersion`, `x-openapi`) is
/// not one, and neither is one inside a string value, where the escaped quote before it is
/// no member separator. WHICH collection the member belongs to is not decided — an
/// unreadable document has no structure to place it in — so a nested member of that name
/// settles the format too. Bounded by the length of the body, which [`parse_definition`]
/// bounds before anything else.
fn text_declares_version(text: &str) -> bool {
    VERSION_MEMBERS.iter().any(|member| {
        text.match_indices(member).any(|(at, _)| {
            let (before, after) = (&text[..at], &text[at + member.len()..]);
            // A quoted name owns the quotes on both sides of it, so they are not what
            // precedes or follows the member.
            let (before, after) = match (before.chars().next_back(), after.chars().next()) {
                (Some(opening @ ('"' | '\'')), Some(closing)) if closing == opening => {
                    (&before[..before.len() - opening.len_utf8()], &after[1..])
                }
                _ => (before, after),
            };
            starts_a_member(before) && after.trim_start().starts_with(':')
        })
    })
}

/// Whether a member may START where `before` ends: at the beginning of the document, at the
/// start of a line, or after the opener or the separator of the flow collection it belongs
/// to — whitespace aside.
fn starts_a_member(before: &str) -> bool {
    let kept = before.trim_end();
    kept.is_empty() || before[kept.len()..].contains('\n') || kept.ends_with(['{', ','])
}

/// The refusal for a document the reader could not finish, decided by whether the document
/// says which format it is written in.
///
/// Which format a definition is written in is settled from the document's own version member
/// BEFORE it is read as one, so a document that declares a version and then cannot be read
/// as a definition of that format is refused as that ([`INVALID_DEFINITION`]), while a body
/// that declares no version at all is refused as the version that could not be determined
/// ([`UNDETERMINED_VERSION`]) — the same sentence a document that read WHOLE and declares
/// neither member earns.
fn unread_document_refusal(text: &str) -> String {
    if text_declares_version(text) {
        INVALID_DEFINITION.to_string()
    } else {
        UNDETERMINED_VERSION.to_string()
    }
}

/// The YAML spelling of a definition, read through the bounded event reader.
fn parse_yaml(text: &str) -> Result<Node, String> {
    guard_yaml_nesting(text)?;
    let mut builder = DefinitionBuilder::default();
    let read = ::yaml_rust2::parser::Parser::new_from_str(text).load(&mut builder, true);
    if let Some(refusal) = builder.refused {
        return Err(format!("Unable to parse API definition: {refusal}"));
    }
    // A body the parser stopped on, and a document whose collections never close, are the
    // same case: the reader did not finish the document. Refused by whether the document
    // says which format it is written in, and not with the parser's own position — see
    // [`unread_document_refusal`].
    if read.is_err() || !builder.open.is_empty() {
        return Err(unread_document_refusal(text));
    }
    Ok(builder.root.unwrap_or_default())
}

/// The full path of a resource for `path` as the definition writes it: the segments
/// joined again, so a trailing or doubled separator names the same resource as the path
/// without it, and a path of only separators is the API's root.
pub fn normalized_path(path: &str) -> String {
    let mut normalized = ROOT_RESOURCE_PATH.to_string();
    for segment in path.split('/').filter(|segment| !segment.is_empty()) {
        normalized = child_path(&normalized, segment);
    }
    normalized
}

/// Read an OpenAPI/Swagger definition out of a `body` payload.
///
/// The body is an OpenAPI definition "JSON/YAML file" per the member's documentation, so
/// both spellings are read: JSON by `serde_json` under its own recursion limit, and
/// anything else by the bounded YAML reader above. Either way the parse is bounded by
/// [`MAX_DEFINITION_BYTES`], [`MAX_DEFINITION_NODES`] and [`MAX_DEFINITION_DEPTH`] and
/// cannot amplify what the body carries.
///
/// `Err` carries the message for a body that is not such a document: the caller has to
/// fix the definition from this text alone. A request that carries no definition at all is
/// the first thing read ([`EMPTY_DEFINITION`]), because nothing a reader could say about a
/// document applies to zero bytes.
pub fn parse_definition(body: &[u8], scope: &ImportScope) -> Result<ImportedDefinition, String> {
    if body.is_empty() {
        return Err(EMPTY_DEFINITION.to_string());
    }
    if body.len() > MAX_DEFINITION_BYTES {
        return Err(format!(
            "body may be at most {MAX_DEFINITION_BYTES} bytes, got {}",
            body.len()
        ));
    }
    // Bytes that are not text are a body no reader could read a version member out of, so
    // they are refused as the version that could not be determined.
    let text = std::str::from_utf8(body).map_err(|_| UNDETERMINED_VERSION.to_string())?;
    let document = match ::serde_json::from_str::<Node>(text) {
        Ok(document) => {
            // The YAML reader counts nodes AS it builds them
            // ([`DefinitionBuilder::place`]); `serde_json` has its own recursion limit but
            // no node ceiling, so the same bound is applied to the tree it built. Both
            // spellings of a definition are therefore read under one node bound, which is
            // what bounds every walk over the parsed document below.
            bound_definition_nodes(&document)?;
            document
        }
        // Not JSON — or JSON past `serde_json`'s recursion limit, which the YAML reader's
        // own depth bound refuses in turn.
        Err(_) => parse_yaml(text)?,
    };
    read_definition(&document, scope)
}

/// Refuse a parsed definition carrying more nodes than [`MAX_DEFINITION_NODES`], or nesting
/// deeper than [`MAX_DEFINITION_DEPTH`].
///
/// Both bounds are budgets, so a document past either is refused at the node that breaks it
/// rather than after however much it carries. The walk is ITERATIVE, over a worklist on the
/// heap: the one check that bounds the nesting of a tree cannot itself recurse to the bottom
/// of the tree it is checking, and the worklist is bounded by the node budget.
///
/// The DEPTH bound is what every later walk over the parsed document rests on
/// ([`Node::json`], [`ReferenceWalk::visit`]): a document this refuses never reaches one.
/// `serde_json` enforces a recursion limit of its own while it BUILDS the tree, which is
/// what keeps this check reachable at all; the bound applied here is this emulator's, and is
/// the same one the YAML reader applies as it builds ([`DefinitionBuilder::open_frame`]), so
/// both spellings of a definition are read under one nesting bound.
fn bound_definition_nodes(document: &Node) -> Result<(), String> {
    let mut pending: Vec<(&Node, usize)> = vec![(document, 1)];
    let mut budget = MAX_DEFINITION_NODES;
    while let Some((node, depth)) = pending.pop() {
        if budget == 0 {
            return Err("the definition carries more nodes than this emulator reads".to_string());
        }
        budget -= 1;
        if depth > MAX_DEFINITION_DEPTH {
            return Err(TOO_DEEPLY_NESTED.to_string());
        }
        match node {
            Node::Mapping(entries) => {
                pending.extend(entries.iter().map(|(_, value)| (value, depth + 1)));
            }
            Node::Sequence(items) => {
                pending.extend(items.iter().map(|item| (item, depth + 1)));
            }
            _ => {}
        }
    }
    Ok(())
}

/// The base path a definition declares its paths under, as [`ImportedDefinition`]'s
/// `base_path`.
///
/// Swagger 2.0 declares it as the document's own `basePath`; OpenAPI 3 replaced that
/// member with `servers`, whose first entry's URL carries the same path (and may be a
/// relative URL, which is only that path). The URL's scheme and authority are not a
/// path, so they are dropped, and a path that is only separators is no base path at all.
fn declared_base_path(document: &Node) -> Option<String> {
    let declared = document.string_member("basePath").or_else(|| {
        let url = document
            .member("servers")
            .and_then(Node::items)
            .and_then(<[Node]>::first)
            .and_then(|server| server.string_member("url"))?;
        // A server URL is absolute (`https://host/v1`) or relative (`/v1`); only the
        // path part of either is a base path.
        Some(match url.split_once("://") {
            Some((_, authority_and_path)) => authority_and_path
                .find('/')
                .map(|start| authority_and_path[start..].to_string())
                .unwrap_or_default(),
            None => url,
        })
    })?;
    let normalized = normalized_path(&declared);
    (normalized != ROOT_RESOURCE_PATH).then_some(normalized)
}

/// What an import takes out of a parsed definition document.
fn read_definition(document: &Node, scope: &ImportScope) -> Result<ImportedDefinition, String> {
    // Every OpenAPI/Swagger document declares its version — `openapi` from 3.0 on,
    // `swagger` before it — and that is the FIRST thing read: which of the two formats the
    // document is written in decides how the rest of it is read, so a document carrying
    // neither says nothing a reader could go on. That holds whatever the document parsed
    // to: a sequence and a scalar carry no member at all, so neither declares a version
    // either ([`Node::member`]), and each is refused as the one thing that is wrong with
    // it rather than as a body no reader could parse.
    if !declares_version(document) {
        return Err(UNDETERMINED_VERSION.to_string());
    }

    let info = document.member("info");
    let mut definition = ImportedDefinition {
        title: info.and_then(|info| info.string_member("title")),
        description: info.and_then(|info| info.string_member("description")),
        version: info.and_then(|info| info.string_member("version")),
        base_path: declared_base_path(document),
        binary_media_types: document
            .member(BINARY_MEDIA_TYPES_EXTENSION)
            .and_then(Node::items)
            .map(|values| {
                values
                    .iter()
                    .filter_map(|value| value.text().map(str::to_owned))
                    .collect()
            }),
        paths: Vec::new(),
        gateway_responses: BTreeMap::new(),
        request_validators: Vec::new(),
        models: Vec::new(),
        warnings: Vec::new(),
    };

    // The gateway responses the document customizes, which describe the API ITSELF
    // rather than one of its paths.
    definition.gateway_responses =
        imported_gateway_responses(document, scope, &mut definition.warnings);

    // The references the document does not resolve. A `$ref` names the model a part of
    // the document stands for, and one whose target the document does not declare — or
    // whose target is outside the document altogether — names no model an import could
    // carry over, so it is reported rather than silently dropped.
    for warning in model_reference_warnings(document) {
        warn(&mut definition.warnings, warning);
    }
    // And what THIS import loses with it: a method's body is read under the model the
    // schema reference names, so a reference that resolves to nothing leaves the method
    // with no format for that media type. Reported here rather than beside the reference
    // above, because it is about the METHODS this import creates — which a documentation
    // import, reading the same document through the same reader, creates none of.
    for (media_type, verb) in unreadable_body_formats(document) {
        warn(
            &mut definition.warnings,
            format!("Invalid format for model {media_type} for method {verb}"),
        );
    }

    // The security schemes the document declares. API Gateway carries one over as an
    // `Authorizer` only for the scheme types its authorizers cover, and reports a type it
    // cannot. `securityDefinitions` is Swagger 2.0's spelling of the set, replaced by
    // `components.securitySchemes` from OpenAPI 3 on.
    let mut sigv4_schemes: BTreeSet<String> = BTreeSet::new();
    for (name, scheme) in declared_security_schemes(document) {
        let kind = scheme.string_member("type").unwrap_or_default();
        if !IMPORTABLE_SECURITY_SCHEME_TYPES.contains(&kind.as_str()) {
            warn(
                &mut definition.warnings,
                format!("Unsupported security definition type '{kind}' for '{name}'. Ignoring."),
            );
        }
        // ...and which of them stand for the CALLER's own SigV4 credential, which is the
        // authorization an import carries over without creating anything for it: the scheme's
        // own authentication type is what says so. Held as a SET, so a requirement naming a
        // scheme is answered by one lookup rather than by a scan of every declared scheme.
        if scheme.string_member(AUTHTYPE_EXTENSION).as_deref() == Some(AUTHTYPE_SIGV4) {
            sigv4_schemes.insert(name);
        }
    }

    // What the DOCUMENT says about security, answered ONCE: every operation that declares no
    // requirement of its own is imported under it, so the document's own list is read here
    // rather than per operation ([`DocumentSecurity`]).
    let document_security = DocumentSecurity::of(document, &sigv4_schemes);

    // The REQUEST VALIDATORS the document's own extension declares, and the SCHEMAS it
    // names: each is a record of the api rather than of one of its paths, so both are read
    // once here, and what the operations below reference is named out of them
    // ([`DocumentReferences`]).
    definition.request_validators = imported_request_validators(document);
    definition.models = imported_models(document);
    let references =
        DocumentReferences::of(document, &definition.request_validators, &definition.models);

    // `paths` is optional from OpenAPI 3.1 on, and a document without it describes an
    // API with no resources rather than a malformed definition.
    let Some(paths) = document.member("paths") else {
        return Ok(definition);
    };
    if matches!(paths, Node::Null) {
        return Ok(definition);
    }
    let paths = paths
        .entries()
        .ok_or_else(|| INVALID_DEFINITION.to_string())?;
    for (path, item) in paths {
        if !path.starts_with('/') {
            return Err(format!(
                "Invalid path '{path}': a path of the API definition must start with '/'"
            ));
        }
        let mut methods = Vec::new();
        for (operation, declared) in item.entries().unwrap_or_default() {
            let operation = operation.to_ascii_lowercase();
            if let Some((_, verb)) = OPERATION_KEYS
                .iter()
                .find(|(candidate, _)| *candidate == operation.as_str())
            {
                methods.push(imported_method(
                    verb,
                    declared,
                    path,
                    &document_security,
                    &references,
                    scope,
                    &mut definition.warnings,
                ));
            } else if UNSUPPORTED_OPERATION_KEYS.contains(&operation.as_str()) {
                warn(
                    &mut definition.warnings,
                    format!(
                        "Unsupported method '{operation}' for path '{path}': the method was not imported"
                    ),
                );
            }
            // Any other key of a path item (`summary`, `parameters`, a vendor extension)
            // describes the path rather than a method, so it imports nothing and warns
            // about nothing.
        }
        definition.paths.push(ImportedPath {
            path: path.clone(),
            methods,
        });
    }
    Ok(definition)
}

/// The gateway responses [`GATEWAY_RESPONSES_EXTENSION`] declares, as the records
/// `PutGatewayResponse` stores: keyed by `responseType`, each carrying the status code
/// the customization answers with and the two caller-supplied maps, with every pseudo
/// parameter resolved against `scope`.
///
/// A stored record is a CUSTOMIZATION, so `defaultResponse` is false, and a `statusCode`
/// the entry leaves out keeps the one the type's generated response carries
/// (`crate::state::default_gateway_status_code`) — the same resolution
/// `PutGatewayResponse` makes at write time, so a read of an imported record agrees with
/// a read of a put one.
///
/// An entry keyed by a value outside the modelled `GatewayResponseType` enum names no
/// gateway response of an API, so it customizes nothing and is reported rather than
/// stored.
fn imported_gateway_responses(
    document: &Node,
    scope: &ImportScope,
    warnings: &mut Vec<String>,
) -> BTreeMap<String, GetGatewayResponseOutput> {
    let mut responses = BTreeMap::new();
    for (response_type, declared) in document
        .member(GATEWAY_RESPONSES_EXTENSION)
        .and_then(Node::entries)
        .unwrap_or_default()
    {
        if !GATEWAY_RESPONSE_TYPE_VALUES.contains(&response_type.as_str()) {
            warn(
                warnings,
                format!("Unsupported gateway response type '{response_type}'. Ignoring."),
            );
            continue;
        }
        responses.insert(
            response_type.clone(),
            GetGatewayResponseOutput {
                response_type: Some(response_type.clone()),
                status_code: declared
                    .string_member(GATEWAY_RESPONSE_STATUS_CODE)
                    .or_else(|| {
                        crate::state::default_gateway_status_code(response_type)
                            .map(str::to_string)
                    }),
                response_parameters: crate::state::non_empty_map(Some(string_map(
                    declared,
                    GATEWAY_RESPONSE_PARAMETERS,
                    scope,
                ))),
                response_templates: crate::state::non_empty_map(Some(string_map(
                    declared,
                    GATEWAY_RESPONSE_TEMPLATES,
                    scope,
                ))),
                default_response: false,
            },
        );
    }
    responses
}

/// The request validators [`REQUEST_VALIDATORS_EXTENSION`] declares, in document order: one
/// per entry of that mapping, named by the entry's key and carrying the two flags the entry
/// declares.
///
/// Both flags are `RequestValidator`'s own, each `@default false`
/// (`smithy_query(query="shape", shape="RequestValidator")`), so an entry that declares
/// neither is a validator that checks nothing — which is a validator API Gateway creates and
/// a method may name, and not something an import invents a value for. An entry whose value
/// is not a mapping declares no flags and is read the same way.
fn imported_request_validators(document: &Node) -> Vec<ImportedRequestValidator> {
    document
        .member(REQUEST_VALIDATORS_EXTENSION)
        .and_then(Node::entries)
        .unwrap_or_default()
        .iter()
        .map(|(name, declared)| ImportedRequestValidator {
            name: name.clone(),
            validate_request_body: declares_flag(declared, VALIDATE_REQUEST_BODY),
            validate_request_parameters: declares_flag(declared, VALIDATE_REQUEST_PARAMETERS),
        })
        .collect()
}

/// Whether `node` declares the boolean member `key` as true.
///
/// A definition's scalars are read as the text they were written in ([`Node`]), so a flag is
/// read off that text — case-insensitively, because the two spellings a definition may be
/// written in differ in it: JSON writes a boolean `true`, and YAML's core schema resolves
/// `True` and `TRUE` to the same value.
fn declares_flag(node: &Node, key: &str) -> bool {
    node.string_member(key)
        .is_some_and(|declared| declared.eq_ignore_ascii_case(DECLARED_TRUE))
}

/// The `Model` records the schemas a definition NAMES become, in document order.
///
/// A model is "the data structure of a transferred payload" (`Model`) and it is addressed BY
/// NAME, so what becomes one is a schema the document itself names: an entry of Swagger 2.0's
/// `definitions` or of OpenAPI 3's `components.schemas`. A schema written INLINE in an
/// operation's body names nothing, so there is no name for a model of it to be stored under —
/// the method keeps the body it declares and names no model for that media type.
///
/// The schema is carried over as the JSON document it was declared as ([`Node::json`]), which
/// is what `Model$schema` holds — "the schema for the model. For application/json models,
/// this should be JSON schema draft 4 model" — and the media type it describes a payload of is
/// the JSON one those schemas type.
fn imported_models(document: &Node) -> Vec<ImportedModel> {
    declared_schemas(document)
        .into_iter()
        .map(|(name, schema)| ImportedModel {
            name,
            content_type: DEFAULT_BODY_MEDIA_TYPE.to_string(),
            schema: schema.json().to_string(),
        })
        .collect()
}

/// The schemas a definition NAMES, in document order: Swagger 2.0's `definitions`, or OpenAPI
/// 3's `components.schemas`.
fn declared_schemas(document: &Node) -> Vec<(String, &Node)> {
    document
        .member(DEFINITIONS_KEY)
        .or_else(|| {
            document
                .member("components")
                .and_then(|components| components.member(COMPONENT_SCHEMAS_KEY))
        })
        .and_then(Node::entries)
        .unwrap_or_default()
        .iter()
        .map(|(name, schema)| (name.clone(), schema))
        .collect()
}

/// What the DOCUMENT says about the records its operations REFERENCE, read ONCE for the whole
/// document: which request validator an operation is imported under, which names a body's
/// schema reference may resolve to, and the media types a schema written without one is
/// declared for.
///
/// Read here rather than per operation for the reason [`DocumentSecurity`] gives: each of
/// these is one value of the document, and resolving it per operation would walk a
/// caller-sized part of the document once per operation. The names are SETS, so a reference
/// is answered by one lookup.
///
/// `pub` because [`imported_method`] takes one, as the operation's own reader of what the
/// document says; every member of it stays private to this module.
#[derive(Debug, Default)]
pub struct DocumentReferences {
    /// The name [`REQUEST_VALIDATOR_EXTENSION`] selects at the document root: the validator
    /// every operation that overrides it with none is imported under.
    request_validator: Option<String>,
    /// The names of the validators the document declares, which is what a selector may name.
    validators: BTreeSet<String>,
    /// The names of the schemas the document declares, which is what a body's reference may
    /// name.
    models: BTreeSet<String>,
    /// The first media type the document `consumes`, which a bare Swagger 2.0 request
    /// `schema` is declared for.
    consumed: Option<String>,
    /// The first media type the document `produces`; see [`Self::consumed`].
    produced: Option<String>,
}

impl DocumentReferences {
    /// What `document` references, against the validators and models this import creates for
    /// it.
    fn of(
        document: &Node,
        validators: &[ImportedRequestValidator],
        models: &[ImportedModel],
    ) -> Self {
        Self {
            request_validator: document.string_member(REQUEST_VALIDATOR_EXTENSION),
            validators: validators
                .iter()
                .map(|declared| declared.name.clone())
                .collect(),
            models: models.iter().map(|model| model.name.clone()).collect(),
            consumed: first_media_type(document, "consumes"),
            produced: first_media_type(document, "produces"),
        }
    }

    /// The NAME of the request validator in force for `operation`: the one the operation
    /// selects for itself, else the document's own — and `None` when neither selects one the
    /// document DECLARES.
    ///
    /// An operation's own selector overrides the document's rather than falling back to it,
    /// which is what overriding one means. A selector naming no declared entry names no
    /// validator of the api, so the method is imported naming none: that is the same thing a
    /// method whose `requestValidatorId` resolves to nothing is validated by
    /// (`crate::service::invoke::declared_validator`), and refusing the import for it would
    /// refuse a definition AWS imports.
    fn request_validator_of(&self, operation: &Node) -> Option<String> {
        let selected = match operation.string_member(REQUEST_VALIDATOR_EXTENSION) {
            Some(declared) => declared,
            None => self.request_validator.clone()?,
        };
        self.validators.contains(&selected).then_some(selected)
    }

    /// The MODEL a declared schema names, or `None` for a schema that names none: an inline
    /// schema, or a reference to something the document does not declare — which
    /// [`model_reference_warnings`] already reports.
    ///
    /// A `$ref` is a JSON Pointer into the document and the schemas it may name are keyed by
    /// their own name ([`declared_schemas`]), so the model it names is the pointer's last
    /// token.
    fn referenced_model(&self, schema: &Node) -> Option<String> {
        let reference = schema.member(REFERENCE_KEY).and_then(Node::text)?;
        let name = reference.rsplit('/').next()?;
        self.models.contains(name).then(|| name.to_string())
    }
}

/// The refusal a definition import answers when the caller asked it to roll back on a
/// warning: the diagnostics the served response would have carried, one per line under
/// API Gateway's fixed lead, so the caller is told WHAT was reported rather than only that
/// something was.
///
/// `pub` because `ImportRestApi` reads a definition through the same reader and refuses it
/// on the same condition, so the two cannot word that refusal differently.
pub fn warnings_refusal(warnings: &[String]) -> String {
    let mut message = String::from("Warnings found during import:");
    for warning in warnings {
        message.push_str("\n\t");
        message.push_str(warning);
    }
    message
}

/// The warnings a document earns for the MODEL REFERENCES it does not itself resolve, in
/// document order and one per PLACE the import resolves each of them.
///
/// A `$ref` names the model a part of the document stands for, so one whose target the
/// document does not declare — or whose target is outside the document altogether — names
/// no model at all: API Gateway reports it by the MODEL's own name
/// ([`crate::state::reference_model_name`], the one reading of the name a reference stands
/// for) rather than by the pointer that failed, and carries on with the rest of the
/// document, which is what "Ignoring." says. It reports it ONCE PER RESOLUTION rather than
/// once per
/// reference: once where the document CARRIES the reference, and once more for every media
/// type that declares its model by it ([`media_type_bindings`]), which is why a document
/// declaring one unresolvable schema under a media type earns the sentence twice.
///
/// `pub` because `ImportDocumentationParts` reads the same OpenAPI document — its `body`
/// is "a JSON object" of the same shape, carrying the documentation set in an extension of
/// it — and reports the same condition, so neither importer can word it differently. What
/// is NOT here is what an import loses BESIDE the model ([`unreadable_body_formats`]):
/// that is about the methods a definition import creates, which a documentation import
/// creates none of.
pub fn model_reference_warnings(document: &Node) -> Vec<String> {
    // Counted ONCE for the whole document rather than per reference, so reporting costs
    // the document once however many references it carries.
    let bindings = media_type_bindings(document);
    let mut warnings: Vec<String> = Vec::new();
    for reference in unresolved_references(document) {
        let warning = format!(
            "Reference to model '{}' not found. Ignoring.",
            crate::state::reference_model_name(&reference)
        );
        let resolutions = 1 + bindings.get(&reference).copied().unwrap_or_default();
        for _ in 0..resolutions {
            // Bounded exactly as every other diagnostic this import reports is: a
            // document cannot earn more warnings than a response carries.
            if warnings.len() >= crate::state::MAX_COLLECTION_ENTRIES {
                return warnings;
            }
            warnings.push(warning.clone());
        }
    }
    warnings
}

/// How many media types of a method's payload or of one of its responses declare their
/// MODEL by each reference the document carries, which is how many times an import
/// resolves that reference BESIDE the place the document carries it
/// ([`model_reference_warnings`]).
///
/// A `content` map keys the schema BY media type, so the model that media type names and
/// the binding of that model to the method are two resolutions of the one reference.
/// Swagger 2.0's bare `schema` declares no media type of its own — the media type is what
/// the operation or the document `produces`/`consumes` — and so adds no second resolution.
/// The counts are what the recorded warning sets for the two spellings carry.
///
/// A reference the DOCUMENT repeats is resolved once wherever it is carried
/// ([`ReferenceWalk::resolved`] is what bounds that walk), so what a repeat adds is its own
/// media-type binding. ONE walk over the document, which is itself bounded
/// ([`MAX_DEFINITION_NODES`]), so this costs the document once.
fn media_type_bindings(document: &Node) -> BTreeMap<String, usize> {
    let mut bindings: BTreeMap<String, usize> = BTreeMap::new();
    for (_, item) in document
        .member("paths")
        .and_then(Node::entries)
        .unwrap_or_default()
    {
        for (operation, declared) in item.entries().unwrap_or_default() {
            let operation = operation.to_ascii_lowercase();
            if !OPERATION_KEYS
                .iter()
                .any(|(candidate, _)| *candidate == operation.as_str())
            {
                continue;
            }
            for schema in media_type_schemas(declared) {
                if let Some(reference) = schema.member(REFERENCE_KEY).and_then(Node::text) {
                    *bindings.entry(reference.to_string()).or_default() += 1;
                }
            }
        }
    }
    bindings
}

/// The schemas `operation` declares UNDER A MEDIA TYPE: the entries of the `content` map
/// of its payload (`requestBody`) and of each of its responses, which is OpenAPI 3's
/// spelling of a declared body. Reading one operation costs what that operation declares,
/// so the walk over a document stays linear in it.
fn media_type_schemas(operation: &Node) -> Vec<&Node> {
    let mut containers: Vec<&Node> = operation.member("requestBody").into_iter().collect();
    for (_, response) in operation
        .member("responses")
        .and_then(Node::entries)
        .unwrap_or_default()
    {
        containers.push(response);
    }
    let mut schemas = Vec::new();
    for container in containers {
        for (_, keyed) in container
            .member("content")
            .and_then(Node::entries)
            .unwrap_or_default()
        {
            if let Some(schema) = keyed.member("schema") {
                schemas.push(schema);
            }
        }
    }
    schemas
}

/// The media type a body or a response is read as when the document names none for it:
/// the type API Gateway assumes for a payload, and the one it reports such a model's
/// format by.
const DEFAULT_BODY_MEDIA_TYPE: &str = "application/json";

/// The media types whose model an operation declares by a reference the document does not
/// resolve, as `(media type, HTTP method)` in document order and each reported once.
///
/// A model is what a method reads one media type of its payload — or of one of its
/// responses — under, so a schema reference that names no model leaves that method with no
/// format for that media type. Both spellings of a declaration are read: OpenAPI 3's
/// `content` map, which keys the schema by media type, and Swagger 2.0's bare `schema`,
/// whose media type is the `consumes`/`produces` the operation or the document declares.
///
/// Bounded exactly as the sibling reference walk is, and for the same reason: resolving a
/// reference looks through the document it points into, so the PRODUCT of how many
/// references a body carries and how much document each resolution looks through is what
/// has to be bounded, not either factor. Each distinct reference is resolved ONCE
/// ([`ReferenceWalk::resolved`] does the same for the other walk), at most
/// [`MAX_DEFINITION_REFERENCES`] resolutions happen, and the walk stops as soon as it holds
/// as many entries as a response can report — finding more than a response can carry is
/// work no caller sees.
fn unreadable_body_formats(document: &Node) -> Vec<(String, String)> {
    let mut reported: Vec<(String, String)> = Vec::new();
    let mut seen: BTreeSet<(String, String)> = BTreeSet::new();
    let mut resolved: BTreeMap<String, bool> = BTreeMap::new();
    let mut budget = MAX_DEFINITION_REFERENCES;
    // The DOCUMENT's own fallback media types, read once here rather than per schema: they
    // are the same for every body of every operation, so deriving them inside the walk
    // would cost the product of how many bodies the document declares and how long its own
    // list is.
    let consumed = first_media_type(document, "consumes");
    let produced = first_media_type(document, "produces");
    for (_, item) in document
        .member("paths")
        .and_then(Node::entries)
        .unwrap_or_default()
    {
        for (operation, declared) in item.entries().unwrap_or_default() {
            let operation = operation.to_ascii_lowercase();
            let Some((_, verb)) = OPERATION_KEYS
                .iter()
                .find(|(candidate, _)| *candidate == operation.as_str())
            else {
                continue;
            };
            // Checked BEFORE the operation's bodies are read, so the bound covers reading
            // them as well as resolving what they reference.
            if budget == 0 || reported.len() >= crate::state::MAX_COLLECTION_ENTRIES {
                return reported;
            }
            for (media_type, schema) in
                declared_body_schemas(declared, consumed.as_deref(), produced.as_deref())
            {
                if budget == 0 || reported.len() >= crate::state::MAX_COLLECTION_ENTRIES {
                    return reported;
                }
                let Some(reference) = schema.member(REFERENCE_KEY).and_then(Node::text) else {
                    continue;
                };
                // Resolved at most once per distinct reference, so a document that repeats
                // one costs a single resolution however many bodies declare it.
                let unresolved = match resolved.get(reference) {
                    Some(known) => !known,
                    None => {
                        budget -= 1;
                        let known = resolves(document, reference);
                        resolved.insert(reference.to_string(), known);
                        !known
                    }
                };
                let entry = (media_type, (*verb).to_string());
                if unresolved && seen.insert(entry.clone()) {
                    reported.push(entry);
                }
            }
        }
    }
    reported
}

/// The FIRST media type `node` lists under `key` (`consumes`, `produces`), read without
/// materialising the list: only its first entry decides the media type a bare `schema` is
/// declared for, so the rest of a caller-sized list is never copied.
fn first_media_type(node: &Node, key: &str) -> Option<String> {
    node.member(key)
        .and_then(Node::items)
        .and_then(<[Node]>::first)
        .and_then(Node::text)
        .map(str::to_string)
}

/// The schemas `operation` declares for a payload of its own or of one of its responses,
/// each beside the media type it is declared for.
///
/// OpenAPI 3 keys them by media type under `content` (`requestBody` and each response);
/// Swagger 2.0 writes one bare `schema` (a `body` parameter and each response) whose media
/// type is what the operation `consumes`/`produces`, failing that what the DOCUMENT does
/// (`consumed`/`produced`, resolved once by the caller), and failing that
/// [`DEFAULT_BODY_MEDIA_TYPE`]. Reading one operation costs what that operation declares,
/// so the walk over a document stays linear in it.
fn declared_body_schemas<'d>(
    operation: &'d Node,
    consumed: Option<&str>,
    produced: Option<&str>,
) -> Vec<(String, &'d Node)> {
    let mut declared = request_body_schemas(operation, consumed);
    // The media type a RESPONSE's bare schema is declared for is what the OPERATION
    // produces, failing that what the document does: resolved once here, so reading an
    // operation costs what that operation declares.
    let produced = body_media_type(operation, "produces", produced);
    for (_, response) in operation
        .member("responses")
        .and_then(Node::entries)
        .unwrap_or_default()
    {
        declared.extend(response_body_schemas(response, Some(produced.as_str())));
    }
    declared
}

/// The media type a body of `operation` written with no media type of its own is declared
/// for: what the operation itself declares under `key` (`consumes`, `produces`), failing that
/// what the DOCUMENT declares (resolved once by the caller), failing that
/// [`DEFAULT_BODY_MEDIA_TYPE`].
fn body_media_type(operation: &Node, key: &str, document: Option<&str>) -> String {
    first_media_type(operation, key)
        .or_else(|| document.map(str::to_string))
        .unwrap_or_else(|| DEFAULT_BODY_MEDIA_TYPE.to_string())
}

/// The schemas `operation` declares for its own REQUEST payload, each beside the media type
/// it is declared for: OpenAPI 3's `requestBody.content`, keyed by media type, and Swagger
/// 2.0's `body` parameter, whose media type is what the operation or the document `consumes`.
fn request_body_schemas<'d>(
    operation: &'d Node,
    consumed: Option<&str>,
) -> Vec<(String, &'d Node)> {
    let mut declared = Vec::new();
    if let Some(content) = operation
        .member("requestBody")
        .and_then(|body| body.member("content"))
        .and_then(Node::entries)
    {
        for (keyed, schema) in content {
            if let Some(schema) = schema.member("schema") {
                declared.push((keyed.clone(), schema));
            }
        }
    }
    for parameter in operation
        .member("parameters")
        .and_then(Node::items)
        .unwrap_or_default()
    {
        if parameter.string_member("in").as_deref() == Some("body") {
            if let Some(schema) = parameter.member("schema") {
                declared.push((
                    body_media_type(operation, "consumes", consumed),
                    schema,
                ));
            }
        }
    }
    declared
}

/// The schemas one RESPONSE of an operation declares, each beside the media type it is
/// declared for — the two spellings [`request_body_schemas`] reads, on the response side.
///
/// The operation-level `produces` is not read here: a response's own bare `schema` is
/// declared for what the OPERATION produces, which the caller resolved once and passes as
/// `produced`.
fn response_body_schemas<'d>(
    response: &'d Node,
    produced: Option<&str>,
) -> Vec<(String, &'d Node)> {
    let mut declared = Vec::new();
    if let Some(content) = response.member("content").and_then(Node::entries) {
        for (keyed, schema) in content {
            if let Some(schema) = schema.member("schema") {
                declared.push((keyed.clone(), schema));
            }
        }
    }
    if let Some(schema) = response.member("schema") {
        declared.push((
            produced
                .map(str::to_string)
                .unwrap_or_else(|| DEFAULT_BODY_MEDIA_TYPE.to_string()),
            schema,
        ));
    }
    declared
}

/// Report what an import could not carry over, up to the entries this emulator reports
/// for a caller-sized list: what the response carries stays bounded however much the
/// document declares.
fn warn(warnings: &mut Vec<String>, message: String) {
    if warnings.len() < crate::state::MAX_COLLECTION_ENTRIES {
        warnings.push(message);
    }
}

/// The security scheme types API Gateway's own authorizers cover, so a scheme of one of
/// these types is a scheme an import can carry over: the `apiKey` scheme an API key or a
/// custom authorizer is declared as, and the `oauth2` scheme a user-pool authorizer is.
/// Any other type (HTTP basic or bearer authentication, say) has no `Authorizer` to
/// become.
const IMPORTABLE_SECURITY_SCHEME_TYPES: &[&str] = &["apiKey", "oauth2"];

/// The document key API Gateway's OpenAPI extensions use for an operation's integration.
const INTEGRATION_EXTENSION: &str = "x-amazon-apigateway-integration";

/// The extension key that names an operation's integration, which API Gateway reads an
/// authorizer's configuration out of; a method that specifies security and carries
/// neither an imported authorizer nor this extension keeps no authorization.
const AUTHORIZER_EXTENSION: &str = "x-amazon-apigateway-auth";

/// The key [`INTEGRATION_EXTENSION`]'s `responses` map uses for the integration response
/// that matches everything the other entries' selection patterns do not.
const INTEGRATION_RESPONSE_DEFAULT_KEY: &str = "default";

/// Where a declared parameter of an operation lands in a method's request parameters: the
/// OpenAPI parameter locations API Gateway maps onto a `method.request.<section>.<name>`
/// mapping expression. A `body` parameter is the request payload rather than a mapping,
/// so it is not one of these.
const REQUEST_PARAMETER_SECTIONS: &[(&str, &str)] = &[
    ("path", "path"),
    ("query", "querystring"),
    ("header", "header"),
];

/// The `Method` an imported operation becomes.
///
/// Everything of an OpenAPI operation object that a `Method` has a member for is carried
/// over: its `operationId`, the `parameters` it declares as request parameters, the
/// `responses` it declares as method responses, the MODELS its declared bodies name, the
/// request validator in force for it, and API Gateway's own integration extension as the
/// method's integration. What the import cannot carry over is reported in `warnings`.
///
/// `security` is what the DOCUMENT says about the authorization of its operations, read once
/// for the whole document ([`DocumentSecurity`]), which an operation that states no
/// requirement of its own is imported under; `references` is what it says about the records
/// its operations reference ([`DocumentReferences`]) — the validator and the models an
/// operation that names none of its own is imported with.
///
/// `requestValidatorId` carries the validator's NAME rather than its id: the record is named
/// by the id this import mints for the entry of that name, which only the materialisation
/// holds ([`ImportedPath::methods`]).
pub fn imported_method(
    verb: &str,
    operation: &Node,
    path: &str,
    security: &DocumentSecurity,
    references: &DocumentReferences,
    scope: &ImportScope,
    warnings: &mut Vec<String>,
) -> MethodEntry {
    let mut method = MethodEntry {
        http_method: verb.to_string(),
        authorization_type: IMPORTED_AUTHORIZATION_TYPE.to_string(),
        authorizer_id: None,
        api_key_required: false,
        operation_name: operation.string_member("operationId"),
        request_parameters: imported_request_parameters(operation),
        // "A key-value map specifying data schemas, specified as the request body for the
        // method. A key is a content type and the value is a `Model` name"
        // (`Method$requestModels`): the model a declared body names, for each media type the
        // operation declares one for.
        request_models: imported_request_models(operation, references),
        request_validator_id: references.request_validator_of(operation),
        authorization_scopes: Vec::new(),
        method_responses: imported_method_responses(operation, references),
        integration: None,
    };

    // An operation that specifies security needs the authorizer its security scheme named
    // to have been created for the method to keep that authorization. This import creates
    // no authorizer, so the method is imported OPEN, and the diagnostic reports that
    // OUTCOME — the method is left unsecured — rather than only that the declaration was
    // dropped.
    //
    // A security requirement is the DOCUMENT's unless the operation declares one of its
    // own: an OpenAPI document's `security` applies across the API, and an operation
    // overrides it — with an EMPTY list where it means no security at all.
    //
    // The one authorization that needs NO authorizer is the caller's own SigV4 credential:
    // the scheme IS the authorization, so a requirement naming such a scheme is carried over
    // to the method, which is then imported under it rather than open. Each operation's OWN
    // requirement is read once here and the document's was read once for the document, so
    // this costs one pass over the definition however the two are sized.
    let (states_a_requirement, requires_sigv4) = match required_schemes(operation) {
        Some(requirement) => (
            !requirement.is_empty(),
            security.names_a_sigv4_scheme(requirement),
        ),
        None => (security.states_a_requirement, security.requires_sigv4),
    };
    if requires_sigv4 {
        method.authorization_type = IMPORTED_SIGV4_AUTHORIZATION_TYPE.to_string();
    } else if states_a_requirement && operation.member(AUTHORIZER_EXTENSION).is_none() {
        warn(
            warnings,
            format!(
                "Method '{verb}' on resource '{path}' specified security, but no custom \
                 authorizers were created and the extension {AUTHORIZER_EXTENSION} was not \
                 properly set. This method will be not be secured."
            ),
        );
    }

    method.integration = imported_integration(&method, operation, path, scope, warnings);
    method
}

/// The request parameters an operation's declared `parameters` become: API Gateway names
/// a method request parameter by the mapping expression
/// `method.request.<section>.<name>`, whose section is the parameter's own location (see
/// [`REQUEST_PARAMETER_SECTIONS`]). A path parameter is required by construction; any
/// other is required only where the document says so.
fn imported_request_parameters(operation: &Node) -> BTreeMap<String, bool> {
    let mut parameters = BTreeMap::new();
    for parameter in operation
        .member("parameters")
        .and_then(Node::items)
        .unwrap_or_default()
    {
        let Some(name) = parameter.string_member("name") else {
            continue;
        };
        let Some(location) = parameter.string_member("in") else {
            continue;
        };
        let Some((_, section)) = REQUEST_PARAMETER_SECTIONS
            .iter()
            .find(|(declared, _)| *declared == location.as_str())
        else {
            continue;
        };
        let required = location == "path"
            || parameter
                .member("required")
                .and_then(Node::text)
                .is_some_and(|required| required == "true");
        parameters.insert(format!("method.request.{section}.{name}"), required);
    }
    parameters
}

/// The MODELS an operation's declared REQUEST body names, keyed by the media type each is
/// declared for — `Method$requestModels`, "a key-value map specifying data schemas …  a key
/// is a content type and the value is a `Model` name".
///
/// A model is named by a REFERENCE to a schema the document declares
/// ([`DocumentReferences::referenced_model`]): a body whose schema is written inline names
/// none, so the method maps no model for that media type and the method's own request
/// validator has nothing to validate that body against.
fn imported_request_models(
    operation: &Node,
    references: &DocumentReferences,
) -> BTreeMap<String, String> {
    let mut models = BTreeMap::new();
    for (media_type, schema) in request_body_schemas(operation, references.consumed.as_deref()) {
        if let Some(name) = references.referenced_model(schema) {
            models.insert(media_type, name);
        }
    }
    models
}

/// The method responses an operation's `responses` become, keyed by status code.
///
/// A response's declared headers become the response parameters the method may map onto,
/// named by the `method.response.header.<name>` mapping expression, and the model a declared
/// response body names becomes the `responseModels` entry for its media type — the response
/// side of [`imported_request_models`]. A key that is not a
/// status code (`default`, a vendor extension) describes no method response: a
/// `MethodResponse` is addressed BY its status code, so there is nothing for such an
/// entry to be stored under.
fn imported_method_responses(
    operation: &Node,
    references: &DocumentReferences,
) -> BTreeMap<String, GetMethodResponseOutput> {
    // The media type a bare response schema is declared for is what the OPERATION produces,
    // failing that what the document does: read once for the operation.
    let produced = body_media_type(operation, "produces", references.produced.as_deref());
    let mut responses = BTreeMap::new();
    for (code, response) in operation
        .member("responses")
        .and_then(Node::entries)
        .unwrap_or_default()
    {
        if !crate::state::is_status_code(code) {
            continue;
        }
        let headers: ::std::collections::HashMap<String, bool> = response
            .member("headers")
            .and_then(Node::entries)
            .unwrap_or_default()
            .iter()
            .map(|(name, _)| (format!("method.response.header.{name}"), false))
            .collect();
        let models: ::std::collections::HashMap<String, String> =
            response_body_schemas(response, Some(produced.as_str()))
                .into_iter()
                .filter_map(|(media_type, schema)| {
                    references
                        .referenced_model(schema)
                        .map(|name| (media_type, name))
                })
                .collect();
        responses.insert(
            code.clone(),
            GetMethodResponseOutput {
                status_code: Some(code.clone()),
                response_parameters: crate::state::non_empty_map(Some(headers)),
                // "Specifies the `Model` resources used for the response's content-type"
                // (`MethodResponse$responseModels`): the model this response's own declared
                // body names, for each media type it declares one for.
                response_models: crate::state::non_empty_map(Some(models)),
            },
        );
    }
    responses
}

/// The `Integration` an operation's [`INTEGRATION_EXTENSION`] becomes, with every pseudo
/// parameter of its ARNs resolved against `scope`.
///
/// The record is checked by the SAME rules `PutIntegration` applies
/// ([`super::put_integration::validate_integration`]), so an integration this emulator
/// refuses on that path cannot reach the store through an import either: one the
/// definition declares wrongly is reported and the method is imported without it, which
/// is what the rest of the definition being imported means for it.
fn imported_integration(
    method: &MethodEntry,
    operation: &Node,
    path: &str,
    scope: &ImportScope,
    warnings: &mut Vec<String>,
) -> Option<GetIntegrationOutput> {
    use super::put_integration::{
        complete_integration, validate_integration, DEFAULT_PASSTHROUGH_BEHAVIOR,
        DEFAULT_TIMEOUT_IN_MILLIS,
    };

    let declared = operation.member(INTEGRATION_EXTENSION)?;
    let mut integration = GetIntegrationOutput {
        // The extension writes the enumerated values in either case (`aws_proxy`,
        // `AWS_PROXY`), and the stored record carries the modelled spelling.
        r#type: declared
            .string_member("type")
            .map(|kind| kind.to_ascii_uppercase()),
        http_method: declared
            .string_member("httpMethod")
            .map(|verb| verb.to_ascii_uppercase()),
        uri: declared
            .string_member("uri")
            .map(|uri| scope.resolved(uri.trim())),
        // `connectionType` names "the type of the network connection to the integration
        // endpoint", and an imported integration has the one its own definition declares:
        // the member's documented default (INTERNET) belongs to the request member of the
        // call that sets an integration up, so an extension that declares no connection
        // type imports an integration that reports none.
        connection_type: declared
            .string_member("connectionType")
            .map(|kind| kind.to_ascii_uppercase()),
        connection_id: declared.string_member("connectionId"),
        credentials: declared
            .string_member("credentials")
            .map(|credentials| scope.resolved(credentials.trim())),
        request_parameters: crate::state::non_empty_map(Some(string_map(
            declared,
            "requestParameters",
            scope,
        ))),
        request_templates: crate::state::non_empty_map(Some(string_map(
            declared,
            "requestTemplates",
            scope,
        ))),
        passthrough_behavior: Some(
            declared
                .string_member("passthroughBehavior")
                .map(|behavior| behavior.to_ascii_uppercase())
                .unwrap_or_else(|| DEFAULT_PASSTHROUGH_BEHAVIOR.to_string()),
        ),
        content_handling: declared.string_member("contentHandling"),
        timeout_in_millis: declared
            .member("timeoutInMillis")
            .and_then(Node::text)
            .and_then(|millis| millis.parse().ok())
            .unwrap_or(DEFAULT_TIMEOUT_IN_MILLIS),
        // Left to the materialisation, which is where the resource this method hangs off
        // is known: "By default, API Gateway uses the resource ID as the cacheNamespace".
        cache_namespace: None,
        cache_key_parameters: Some(string_list(declared, "cacheKeyParameters")),
        integration_responses: imported_integration_responses(declared, scope),
        tls_config: declared.member("tlsConfig").map(|tls| TlsConfig {
            insecure_skip_verification: tls
                .member("insecureSkipVerification")
                .and_then(Node::text)
                .is_some_and(|value| value == "true"),
        }),
        response_transfer_mode: declared.string_member("responseTransferMode"),
        integration_target: declared.string_member("integrationTarget"),
    };
    complete_integration(&mut integration);
    if let Err(reason) = validate_integration(&integration, method) {
        warn(
            warnings,
            format!(
                "Unable to import the integration of method '{}' on resource '{path}': \
                 {reason}. Ignoring.",
                method.http_method
            ),
        );
        return None;
    }
    Some(integration)
}

/// The integration responses an integration extension's `responses` become, keyed by
/// status code.
///
/// The extension keys each entry by the SELECTION PATTERN the integration response
/// matches, with [`INTEGRATION_RESPONSE_DEFAULT_KEY`] naming the one that matches
/// everything the others do not — which is the `selectionPattern` member of the record,
/// while the record itself is addressed by the `statusCode` it declares. An entry that
/// declares no status code names no integration response.
fn imported_integration_responses(
    declared: &Node,
    scope: &ImportScope,
) -> Option<::std::collections::HashMap<String, GetIntegrationResponseOutput>> {
    let mut responses: ::std::collections::HashMap<String, GetIntegrationResponseOutput> =
        ::std::collections::HashMap::new();
    for (pattern, response) in declared
        .member("responses")
        .and_then(Node::entries)
        .unwrap_or_default()
    {
        let Some(status_code) = response.string_member("statusCode") else {
            continue;
        };
        responses.insert(
            status_code.clone(),
            GetIntegrationResponseOutput {
                status_code: Some(status_code),
                selection_pattern: (pattern != INTEGRATION_RESPONSE_DEFAULT_KEY)
                    .then(|| pattern.clone()),
                response_parameters: crate::state::non_empty_map(Some(string_map(
                    response,
                    "responseParameters",
                    scope,
                ))),
                response_templates: crate::state::non_empty_map(Some(string_map(
                    response,
                    "responseTemplates",
                    scope,
                ))),
                content_handling: response.string_member("contentHandling"),
            },
        );
    }
    (!responses.is_empty()).then_some(responses)
}

/// A mapping member of `node` as a map of strings, skipping an entry whose value is not a
/// scalar: the modelled member it lands in carries strings. Every value is resolved
/// against `scope`, because a definition writes a pseudo parameter wherever it needs this
/// account's own values — a mapping template that forwards the Region as much as an
/// integration ARN.
fn string_map(
    node: &Node,
    key: &str,
    scope: &ImportScope,
) -> ::std::collections::HashMap<String, String> {
    node.member(key)
        .and_then(Node::entries)
        .unwrap_or_default()
        .iter()
        .filter_map(|(name, value)| {
            value
                .text()
                .map(|text| (name.clone(), scope.resolved(text)))
        })
        .collect()
}

/// A sequence member of `node` as a list of strings; see [`string_map`].
fn string_list(node: &Node, key: &str) -> Vec<String> {
    node.member(key)
        .and_then(Node::items)
        .unwrap_or_default()
        .iter()
        .filter_map(|value| value.text().map(str::to_string))
        .collect()
}

/// The security schemes a definition declares, in document order: Swagger 2.0's
/// `securityDefinitions`, or OpenAPI 3's `components.securitySchemes`.
fn declared_security_schemes(document: &Node) -> Vec<(String, &Node)> {
    document
        .member("securityDefinitions")
        .or_else(|| {
            document
                .member("components")
                .and_then(|components| components.member("securitySchemes"))
        })
        .and_then(Node::entries)
        .unwrap_or_default()
        .iter()
        .map(|(name, scheme)| (name.clone(), scheme))
        .collect()
}

/// What the DOCUMENT says about the authorization of its operations, read ONCE for the whole
/// document.
///
/// An OpenAPI document's own `security` applies across the api, so every operation that
/// states no requirement of its own is imported under it. Answering that per operation would
/// walk the document's list once for each of them — a product of two caller-sized parts of one
/// body — so the two questions an operation asks of it are decided here, when the document is
/// read, and the set of schemes a requirement is resolved against is a SET, so a name is
/// answered by one lookup.
pub struct DocumentSecurity {
    /// Whether the document states a requirement that names anything at all.
    states_a_requirement: bool,
    /// Whether that requirement names a scheme standing for the caller's own SigV4
    /// credential.
    requires_sigv4: bool,
    /// The schemes that stand for that credential ([`AUTHTYPE_SIGV4`]).
    sigv4_schemes: BTreeSet<String>,
}

impl DocumentSecurity {
    /// What `document` says about its operations' authorization, against the `sigv4_schemes`
    /// its own scheme set declared.
    fn of(document: &Node, sigv4_schemes: &BTreeSet<String>) -> Self {
        let required = required_schemes(document);
        Self {
            states_a_requirement: required.is_some_and(|requirement| !requirement.is_empty()),
            requires_sigv4: required
                .is_some_and(|requirement| names_a_scheme_of(requirement, sigv4_schemes)),
            sigv4_schemes: sigv4_schemes.clone(),
        }
    }

    /// Whether `requirement` — one operation's own — names a scheme standing for the caller's
    /// own SigV4 credential.
    fn names_a_sigv4_scheme(&self, requirement: &[Node]) -> bool {
        names_a_scheme_of(requirement, &self.sigv4_schemes)
    }
}

/// The `security` requirement `node` states, as the list the document wrote, or `None` where
/// the node states no requirement at all.
///
/// An OpenAPI security requirement is a LIST of objects whose keys name the schemes the
/// document declares. A requirement list that is EMPTY names none, which is how an operation
/// says it needs no security where the document requires some — so an empty list and an absent
/// member are deliberately different answers.
fn required_schemes(node: &Node) -> Option<&[Node]> {
    node.member("security")?.items()
}

/// Whether one security `requirement` names any of `schemes`: the keys of its entries are the
/// scheme names, each answered by a lookup in the set.
fn names_a_scheme_of(requirement: &[Node], schemes: &BTreeSet<String>) -> bool {
    requirement.iter().any(|entry| {
        entry
            .entries()
            .unwrap_or_default()
            .iter()
            .any(|(name, _)| schemes.contains(name))
    })
}

/// The most references one definition's walk RESOLVES against the document.
///
/// Resolving a reference looks through the document the reference points into, so this is
/// what bounds the PRODUCT of the two caller-chosen factors — how many references a body
/// carries and how much document each resolution looks through — rather than each factor
/// on its own. A reference the document repeats is resolved once
/// ([`ReferenceWalk::resolved`]), and the walk stops as soon as it has as many unresolved
/// references as a response can report, so what remains is a constant number of
/// resolutions per request. Chosen: far past the distinct references a definition of
/// [`crate::state::MAX_RESOURCES_PER_API`] paths carries, and small enough that the walk
/// costs a constant multiple of one document's size.
const MAX_DEFINITION_REFERENCES: usize = 256;

/// The document member a `$ref` names a reference with.
const REFERENCE_KEY: &str = "$ref";

/// The prefix of a reference INTO the document carrying it; every other form names
/// something outside the document.
const LOCAL_REFERENCE_PREFIX: &str = "#/";

/// The references `document` does not resolve, in document order and each reported once.
///
/// A reference stands for the part of the document it points at, so a reference whose
/// target the document does not declare stands for nothing — and one that points OUTSIDE
/// the document (another file, a URL) names something an import has no access to at all.
/// Either way the part of the document that carries it cannot be imported, which is what
/// an import reports as a warning.
///
/// Bounded by [`MAX_DEFINITION_REFERENCES`] and by the number of warnings a response can
/// carry; see [`ReferenceWalk`].
fn unresolved_references(document: &Node) -> Vec<String> {
    let mut walk = ReferenceWalk {
        document,
        resolved: BTreeMap::new(),
        unresolved: Vec::new(),
        budget: MAX_DEFINITION_REFERENCES,
    };
    walk.visit(document, 1);
    walk.unresolved
}

/// [`unresolved_references`]' walk over a parsed definition.
///
/// Every step is bounded: a reference is resolved at most once (`resolved` answers a
/// repeat), at most [`MAX_DEFINITION_REFERENCES`] resolutions happen per document, the walk
/// descends at most [`MAX_DEFINITION_DEPTH`] levels, and it ends as soon as it holds as many
/// unresolved references as an import can report — finding more than a response can carry is
/// work no caller sees.
struct ReferenceWalk<'a> {
    /// The whole document, which every reference is resolved against.
    document: &'a Node,
    /// Whether each reference already resolved does resolve, so a document that repeats
    /// one costs a single resolution and the lookup is not a scan of what came before.
    resolved: BTreeMap<String, bool>,
    /// The references that did not resolve, in document order.
    unresolved: Vec<String>,
    /// How many more references may be resolved.
    budget: usize,
}

impl ReferenceWalk<'_> {
    /// Whether the walk has done all the work a response can report.
    fn exhausted(&self) -> bool {
        self.budget == 0 || self.unresolved.len() >= crate::state::MAX_COLLECTION_ENTRIES
    }

    /// Resolve every reference `node` carries, and then those of the nodes under it.
    ///
    /// `depth` is this node's nesting level, which bounds the recursion explicitly: the walk
    /// does not descend past [`MAX_DEFINITION_DEPTH`]. A parsed definition never nests that
    /// deeply — one that does is refused before anything reads it
    /// ([`bound_definition_nodes`], [`DefinitionBuilder::open_frame`]) — and the bound is
    /// written here anyway, because the stack is the one resource a tree walk consumes that
    /// no later check can give back.
    fn visit(&mut self, node: &Node, depth: usize) {
        if self.exhausted() || depth > MAX_DEFINITION_DEPTH {
            return;
        }
        match node {
            Node::Mapping(entries) => {
                for (key, value) in entries {
                    if key == REFERENCE_KEY {
                        if let Some(reference) = value.text() {
                            self.inspect(reference);
                        }
                    }
                    self.visit(value, depth + 1);
                    if self.exhausted() {
                        return;
                    }
                }
            }
            Node::Sequence(items) => {
                for item in items {
                    self.visit(item, depth + 1);
                    if self.exhausted() {
                        return;
                    }
                }
            }
            _ => {}
        }
    }

    /// Resolve one reference, unless this walk has already resolved it.
    fn inspect(&mut self, reference: &str) {
        if self.resolved.contains_key(reference) {
            return;
        }
        self.budget = self.budget.saturating_sub(1);
        let resolved = resolves(self.document, reference);
        self.resolved.insert(reference.to_string(), resolved);
        if !resolved {
            self.unresolved.push(reference.to_string());
        }
    }
}

/// Whether `reference` names a part of `document`: a local reference
/// ([`LOCAL_REFERENCE_PREFIX`]) whose every path segment is a member of what the segment
/// before it names. The segments are JSON Pointer tokens, so `~1` spells a separator
/// inside one and `~0` spells the escape itself.
fn resolves(document: &Node, reference: &str) -> bool {
    let Some(path) = reference.strip_prefix(LOCAL_REFERENCE_PREFIX) else {
        // The whole document (`#`) resolves to itself; anything else names a target
        // outside this document.
        return reference == "#";
    };
    let mut target = document;
    for token in path.split('/') {
        let member = token.replace("~1", "/").replace("~0", "~");
        match target.member(&member) {
            Some(next) => target = next,
            None => return false,
        }
    }
    true
}

/// One resource an import has to create: the full path it materialises, its own last
/// segment, and the full path of the resource it hangs off.
#[derive(Debug, Clone)]
pub struct PlannedResource {
    pub path: String,
    pub path_part: String,
    pub parent_path: String,
}

/// The ids and creation ranks a materialisation was handed did not line up with the plan
/// it was handed, or a planned resource's parent was not in the API.
///
/// Neither can happen for a plan built by [`plan_resources`] against the same API, so
/// each caller answers this as the server-side failure it would be rather than leaving a
/// partly imported API reported as a success.
#[derive(Debug)]
pub struct Inconsistent;

/// The resources `definition`'s paths ask for beyond the full paths `known` already
/// names, in document order, each ancestor before the path that needs it:
/// `/pets/{petId}` plans `/pets` first, exactly as `CreateResource` would have to. Every
/// planned path is added to `known`, so a path two entries share is planned once.
///
/// The per-API resource quota is enforced AS the plan grows, not after it: a definition
/// asking for more resources than an API may hold is refused at the entry that breaks
/// the quota, so neither the plan nor the set it is built from can grow past the quota
/// however long the document's paths are. `Err` carries that refusal's message, which is
/// a `LimitExceededException` on either operation that imports a definition.
pub fn plan_resources(
    known: &mut BTreeSet<String>,
    definition: &ImportedDefinition,
) -> Result<Vec<PlannedResource>, String> {
    let mut planned: Vec<PlannedResource> = Vec::new();
    for imported in &definition.paths {
        let mut parent = ROOT_RESOURCE_PATH.to_string();
        for segment in imported.path.split('/').filter(|part| !part.is_empty()) {
            let path = child_path(&parent, segment);
            if known.insert(path.clone()) {
                if known.len() > crate::state::MAX_RESOURCES_PER_API {
                    return Err(crate::state::quota_reached("Resources", "API"));
                }
                planned.push(PlannedResource {
                    path: path.clone(),
                    path_part: segment.to_string(),
                    parent_path: parent.clone(),
                });
            }
            parent = path;
        }
    }
    Ok(planned)
}

/// The ids and creation ranks an import reserved from the store for the records it creates.
///
/// Reserved in ONE pass over the store, before the api is borrowed for writing, exactly as
/// each creating operation draws its own: the resources at the width a record held INSIDE an
/// api carries ([`crate::state::ComAmazonawsApigatewayBackplanecontrolserviceState::reserve_sub_resource_ids`]),
/// and the validators and models from the store's own minter, the way
/// `CreateRequestValidator` and `CreateModel` mint one. One creation rank per record, so the
/// imported records are listed in the order the definition declares them.
///
/// Shared by the two operations that import a definition, so neither can reserve what the
/// materialisation does not then use.
#[derive(Debug, Default)]
pub struct ReservedIds {
    /// One id per planned resource, in the plan's order.
    pub resources: Vec<String>,
    /// One creation rank per planned resource, in the plan's order.
    pub resource_sequences: Vec<u64>,
    /// One `(id, creation rank)` per declared request validator, in document order.
    pub request_validators: Vec<(String, u64)>,
    /// One `(id, creation rank)` per declared model, in document order.
    pub models: Vec<(String, u64)>,
}

impl ReservedIds {
    /// Reserve what `definition` needs to be materialised into an api that is to hold
    /// `planned` new resources.
    pub fn of(
        definition: &ImportedDefinition,
        planned: usize,
        store: &mut crate::state::ComAmazonawsApigatewayBackplanecontrolserviceState,
    ) -> Self {
        Self {
            resources: store.reserve_sub_resource_ids(planned),
            resource_sequences: (0..planned).map(|_| store.next_sequence()).collect(),
            request_validators: definition
                .request_validators
                .iter()
                .map(|_| (store.mint_id(), store.next_sequence()))
                .collect(),
            models: definition
                .models
                .iter()
                .map(|_| (store.mint_id(), store.next_sequence()))
                .collect(),
        }
    }
}

/// Materialise `definition` into `api`: the `RequestValidator` and `Model` records it
/// declares, every resource `planned` names under the id and creation rank reserved for it,
/// and then every operation the definition declares on a path as a `Method` on that path's
/// resource.
///
/// The imported definition wins over what a path already carried, which is what an
/// import means for a path the definition declares. `reserved` holds the ids and creation
/// ranks drawn from the store before it was mutated ([`ReservedIds`]), so the imported
/// records are listed in the order the definition declares them.
///
/// A validator or a model the api ALREADY holds under the declared name keeps its own id and
/// creation rank: both are addressed by a name the document chose, so re-importing a
/// definition restates what that name means rather than leaving a second record behind under
/// a new id.
///
/// Shared by the two operations that import a definition, so the tree `ImportRestApi`
/// builds for a document and the tree `PutRestApi` builds for the same document are the
/// same tree.
pub fn materialise_definition(
    api: &mut RestApiEntry,
    definition: &ImportedDefinition,
    planned: &[PlannedResource],
    reserved: &ReservedIds,
) -> Result<(), Inconsistent> {
    // The api's own id, read before the records below are borrowed for writing: a model's
    // schema names a sibling model by the URL that api's schema resource carries.
    let api_id = api.id.clone();
    // The `RequestValidator` records [`REQUEST_VALIDATORS_EXTENSION`] declares: one per
    // entry, carrying the entry's own name and flags, and keyed — as every stored validator
    // is — by its minted id, which is what a method's `requestValidatorId` names.
    let mut validator_ids: BTreeMap<String, String> = BTreeMap::new();
    for (index, declared) in definition.request_validators.iter().enumerate() {
        let (minted, next_rank) = reserved
            .request_validators
            .get(index)
            .ok_or(Inconsistent)?
            .clone();
        let held = api
            .request_validators
            .values()
            .find(|held| held.name.as_deref() == Some(declared.name.as_str()))
            .map(|held| (held.id.clone(), held.sequence));
        let (id, sequence) = held.unwrap_or((minted, next_rank));
        validator_ids.insert(declared.name.clone(), id.clone());
        api.request_validators.insert(
            id.clone(),
            crate::state::RequestValidatorEntry {
                id,
                name: Some(declared.name.clone()),
                validate_request_body: declared.validate_request_body,
                validate_request_parameters: declared.validate_request_parameters,
                sequence,
            },
        );
    }
    // The `Model` records the schemas the definition NAMES become, keyed by that name as
    // every stored model is.
    for (index, declared) in definition.models.iter().enumerate() {
        let (minted, next_rank) = reserved.models.get(index).ok_or(Inconsistent)?.clone();
        let held = api
            .models
            .get(&declared.name)
            .map(|held| (held.id.clone(), held.sequence));
        let (id, sequence) = held.unwrap_or((minted, next_rank));
        api.models.insert(
            declared.name.clone(),
            crate::state::ModelEntry {
                id,
                name: declared.name.clone(),
                // `CreateModel$description` is optional and a schema the document names
                // carries no description of its own, so the stored model reports none
                // rather than one invented for it.
                description: None,
                content_type: declared.content_type.clone(),
                schema: Some(model_schema_references_resolved(&declared.schema, &api_id)),
                sequence,
            },
        );
    }
    let mut by_path: BTreeMap<String, String> = api
        .resources
        .values()
        .map(|resource| (resource.path.clone(), resource.id.clone()))
        .collect();
    for (index, resource) in planned.iter().enumerate() {
        let id = reserved.resources.get(index).ok_or(Inconsistent)?.clone();
        let sequence = *reserved
            .resource_sequences
            .get(index)
            .ok_or(Inconsistent)?;
        // A path is planned only after every one of its ancestors, so the parent is in
        // the API or in what this loop has already inserted.
        let parent_id = by_path
            .get(&resource.parent_path)
            .cloned()
            .ok_or(Inconsistent)?;
        api.resources.insert(
            id.clone(),
            ResourceEntry {
                id: id.clone(),
                parent_id: Some(parent_id),
                path_part: Some(resource.path_part.clone()),
                path: resource.path.clone(),
                methods: BTreeMap::new(),
                sequence,
            },
        );
        by_path.insert(resource.path.clone(), id);
    }
    for imported in &definition.paths {
        // The path's own resource: planned above when it did not exist, and in `by_path`
        // either way (see the loop above).
        let resource_id = by_path
            .get(&normalized_path(&imported.path))
            .cloned()
            .ok_or(Inconsistent)?;
        let resource = api
            .resources
            .get_mut(&resource_id)
            .ok_or(Inconsistent)?;
        for method in &imported.methods {
            let mut method = method.clone();
            // The validator the document NAMED for this method, as the id the record it
            // became is held under ([`ImportedPath::methods`]).
            method.request_validator_id = method
                .request_validator_id
                .as_deref()
                .and_then(|name| validator_ids.get(name).cloned());
            if let Some(integration) = &mut method.integration {
                // The one member of an imported integration that depends on where the
                // method landed: "By default, API Gateway uses the resource ID as the
                // cacheNamespace", which is the default `PutIntegration` applies too.
                if integration.cache_namespace.is_none() {
                    integration.cache_namespace = Some(resource_id.clone());
                }
            }
            resource.methods.insert(method.http_method.clone(), method);
        }
    }
    // The gateway responses the definition customizes, which describe the API itself.
    // The imported definition wins over what the API already carried for that response
    // type, the same way an imported path wins over what the path carried — which is
    // also what RE-RESOLVES a template's pseudo parameters on a later import, since the
    // record is written from the document as read in THIS request's scope.
    for (response_type, response) in &definition.gateway_responses {
        api.gateway_responses
            .insert(response_type.clone(), response.clone());
    }
    Ok(())
}

/// `schema` with every reference to a SIBLING schema of the document rewritten onto the model
/// of the api that schema became.
///
/// A stored `Model`'s schema is a JSON Schema resource identified by the api's own model-schema
/// URL (`crate::service::invoke::model_schema_url`), which is the identifier a reference from
/// another model of that api resolves against — so a reference the DOCUMENT wrote as a pointer
/// into itself (`#/definitions/{name}`, `#/components/schemas/{name}`) names the model of that
/// name once the document's schemas are stored one per model.
///
/// Rewritten on the stored text, which is the JSON the schema was declared as, and ANCHORED to
/// the start of a JSON string: a reference is the whole value of the member that carries it, so
/// the pointer is matched with its opening quote and text that merely CONTAINS the pointer's
/// spelling (a description, an enumerated value) is left as the document wrote it.
fn model_schema_references_resolved(schema: &str, api_id: &str) -> String {
    // The URL prefix every model of this api is identified under: the schema resource of the
    // model named by what follows the pointer's last `/`.
    let models = format!("\"{}", crate::service::invoke::model_schema_url(api_id, ""));
    let mut resolved = schema.to_string();
    for pointer in [
        format!("\"#/{DEFINITIONS_KEY}/"),
        format!("\"#/components/{COMPONENT_SCHEMAS_KEY}/"),
    ] {
        if resolved.contains(&pointer) {
            resolved = resolved.replace(&pointer, &models);
        }
    }
    resolved
}

/// Refuse a definition whose paths, or the operations on them, would grow the store past a
/// bound.
///
/// Called BEFORE the store lock is taken, so an over-sized definition never reaches the
/// records. Each bound is this emulator's resource guard from `crate::state`, and every
/// caller-sized member a definition writes has one: the API's own members here, and each
/// operation's in [`bound_imported_method`].
pub fn bound_definition(definition: &ImportedDefinition) -> Result<(), String> {
    use crate::state::{
        bound_chars, bound_entries, MAX_COLLECTION_ENTRIES, MAX_PATH_CHARS, MAX_PATH_PART_CHARS,
        MAX_STRING_CHARS,
    };

    // The members this import writes onto the `RestApiEntry` are bounded exactly as
    // `CreateRestApi` bounds the same members of its request: nothing caller-sized
    // reaches the store unchecked, whichever operation writes it.
    for (member, value) in [
        ("info.title", &definition.title),
        ("info.description", &definition.description),
        ("info.version", &definition.version),
    ] {
        if let Some(value) = value {
            bound_chars(member, value, MAX_STRING_CHARS)?;
        }
    }
    if let Some(types) = &definition.binary_media_types {
        bound_entries(BINARY_MEDIA_TYPES_EXTENSION, types.len(), MAX_COLLECTION_ENTRIES)?;
        for value in types {
            bound_chars(BINARY_MEDIA_TYPES_EXTENSION, value, MAX_STRING_CHARS)?;
        }
    }
    bound_entries(
        "the paths of the API definition",
        definition.paths.len(),
        crate::state::MAX_RESOURCES_PER_API,
    )?;
    // The records the definition's own extensions declare, bounded exactly as the operations
    // that create one bound it: a validator's name as `CreateRequestValidator` bounds it, a
    // model's name and schema as `CreateModel` does, and each set by the per-API quota.
    bound_entries(
        REQUEST_VALIDATORS_EXTENSION,
        definition.request_validators.len(),
        crate::state::MAX_REQUEST_VALIDATORS_PER_API,
    )?;
    for validator in &definition.request_validators {
        bound_chars("name", &validator.name, MAX_STRING_CHARS)?;
    }
    bound_entries(
        "the schemas of the API definition",
        definition.models.len(),
        crate::state::MAX_MODELS_PER_API,
    )?;
    for model in &definition.models {
        bound_chars("name", &model.name, MAX_STRING_CHARS)?;
        bound_chars("contentType", &model.content_type, MAX_STRING_CHARS)?;
        bound_chars(
            "schema",
            &model.schema,
            super::create_model::MAX_MODEL_SCHEMA_CHARS,
        )?;
    }
    // A gateway response is keyed by a `responseType` the model declares as an enum, so
    // their COUNT needs no cap of its own; what a caller sizes is each one's two maps.
    for response in definition.gateway_responses.values() {
        for (member, map) in [
            (GATEWAY_RESPONSE_PARAMETERS, &response.response_parameters),
            (GATEWAY_RESPONSE_TEMPLATES, &response.response_templates),
        ] {
            let Some(entries) = map else { continue };
            bound_entries(member, entries.len(), MAX_COLLECTION_ENTRIES)?;
            for (key, value) in entries {
                bound_chars(&format!("a {member} key"), key, MAX_STRING_CHARS)?;
                bound_chars(&format!("a {member} value"), value, MAX_STRING_CHARS)?;
            }
        }
    }
    for imported in &definition.paths {
        bound_chars("a path of the API definition", &imported.path, MAX_PATH_CHARS)?;
        for segment in imported.path.split('/').filter(|part| !part.is_empty()) {
            bound_chars(
                "a path segment of the API definition",
                segment,
                MAX_PATH_PART_CHARS,
            )?;
        }
        // A path's operations become `Method` records on the resource it becomes, so what
        // they carry is bounded here too: the paths above are only the resources.
        bound_entries(
            "the operations of a path of the API definition",
            imported.methods.len(),
            MAX_COLLECTION_ENTRIES,
        )?;
        for method in &imported.methods {
            bound_imported_method(method)?;
        }
    }
    Ok(())
}

/// Refuse an imported operation whose records would grow the store past a bound.
///
/// An imported operation becomes the same records `PutMethod`, `PutMethodResponse`,
/// `PutIntegration` and `PutIntegrationResponse` write, so it is bounded by exactly those
/// operations' limits, member for member and under their member names: whichever call
/// writes a method, what is stored for it is the same size. Called from
/// [`bound_definition`], before the store lock is taken, so an over-sized definition never
/// reaches the records.
fn bound_imported_method(method: &MethodEntry) -> Result<(), String> {
    use super::put_integration::MAX_TEMPLATE_CHARS;
    use crate::state::{bound_chars, bound_entries, MAX_COLLECTION_ENTRIES, MAX_STRING_CHARS};

    // What `PutMethod` bounds on the method itself.
    bound_chars(
        "authorizationType",
        &method.authorization_type,
        MAX_STRING_CHARS,
    )?;
    for (member, value) in [
        ("operationName", &method.operation_name),
        ("authorizerId", &method.authorizer_id),
        ("requestValidatorId", &method.request_validator_id),
    ] {
        if let Some(value) = value {
            bound_chars(member, value, MAX_STRING_CHARS)?;
        }
    }
    bound_entries(
        "requestParameters",
        method.request_parameters.len(),
        MAX_COLLECTION_ENTRIES,
    )?;
    for key in method.request_parameters.keys() {
        bound_chars("a requestParameters key", key, MAX_STRING_CHARS)?;
    }
    bound_entries(
        "requestModels",
        method.request_models.len(),
        MAX_COLLECTION_ENTRIES,
    )?;
    for (key, value) in &method.request_models {
        bound_chars("a requestModels key", key, MAX_STRING_CHARS)?;
        bound_chars("a requestModels value", value, MAX_STRING_CHARS)?;
    }
    bound_entries(
        "authorizationScopes",
        method.authorization_scopes.len(),
        MAX_COLLECTION_ENTRIES,
    )?;
    for scope in &method.authorization_scopes {
        bound_chars("authorizationScopes", scope, MAX_STRING_CHARS)?;
    }

    // What `PutMethodResponse` bounds on each response of the method.
    bound_entries(
        "the responses of an operation of the API definition",
        method.method_responses.len(),
        MAX_COLLECTION_ENTRIES,
    )?;
    for (key, response) in &method.method_responses {
        // The key is what the response is STORED under, so it is bounded like the key of
        // every other caller-sized map here, and before its members.
        bound_chars("a methodResponses key", key, MAX_STRING_CHARS)?;
        if let Some(status_code) = &response.status_code {
            bound_chars("statusCode", status_code, MAX_STRING_CHARS)?;
        }
        if let Some(parameters) = &response.response_parameters {
            bound_entries(
                "responseParameters",
                parameters.len(),
                MAX_COLLECTION_ENTRIES,
            )?;
            for key in parameters.keys() {
                bound_chars("a responseParameters key", key, MAX_STRING_CHARS)?;
            }
        }
        if let Some(models) = &response.response_models {
            bound_entries("responseModels", models.len(), MAX_COLLECTION_ENTRIES)?;
            for (key, value) in models {
                bound_chars("a responseModels key", key, MAX_STRING_CHARS)?;
                bound_chars("a responseModels value", value, MAX_STRING_CHARS)?;
            }
        }
    }

    // What `PutIntegration` bounds on the method's integration, and
    // `PutIntegrationResponse` on each response of that integration.
    let Some(integration) = &method.integration else {
        return Ok(());
    };
    for (member, value) in [
        ("type", &integration.r#type),
        ("integrationHttpMethod", &integration.http_method),
        ("uri", &integration.uri),
        ("connectionType", &integration.connection_type),
        ("connectionId", &integration.connection_id),
        ("credentials", &integration.credentials),
        ("passthroughBehavior", &integration.passthrough_behavior),
        ("contentHandling", &integration.content_handling),
        ("cacheNamespace", &integration.cache_namespace),
        ("responseTransferMode", &integration.response_transfer_mode),
        ("integrationTarget", &integration.integration_target),
    ] {
        if let Some(value) = value {
            bound_chars(member, value, MAX_STRING_CHARS)?;
        }
    }
    if let Some(parameters) = &integration.request_parameters {
        bound_entries(
            "requestParameters",
            parameters.len(),
            MAX_COLLECTION_ENTRIES,
        )?;
        for (key, value) in parameters {
            bound_chars("a requestParameters key", key, MAX_STRING_CHARS)?;
            bound_chars("a requestParameters value", value, MAX_STRING_CHARS)?;
        }
    }
    if let Some(templates) = &integration.request_templates {
        bound_entries("requestTemplates", templates.len(), MAX_COLLECTION_ENTRIES)?;
        for (key, value) in templates {
            bound_chars("a requestTemplates key", key, MAX_STRING_CHARS)?;
            bound_chars("a requestTemplates value", value, MAX_TEMPLATE_CHARS)?;
        }
    }
    if let Some(parameters) = &integration.cache_key_parameters {
        bound_entries(
            "cacheKeyParameters",
            parameters.len(),
            MAX_COLLECTION_ENTRIES,
        )?;
        for value in parameters {
            bound_chars("cacheKeyParameters", value, MAX_STRING_CHARS)?;
        }
    }
    let Some(responses) = &integration.integration_responses else {
        return Ok(());
    };
    bound_entries(
        "the responses of the integration of an operation of the API definition",
        responses.len(),
        MAX_COLLECTION_ENTRIES,
    )?;
    for (key, response) in responses {
        bound_chars("an integrationResponses key", key, MAX_STRING_CHARS)?;
        for (member, value) in [
            ("statusCode", &response.status_code),
            ("selectionPattern", &response.selection_pattern),
            ("contentHandling", &response.content_handling),
        ] {
            if let Some(value) = value {
                bound_chars(member, value, MAX_STRING_CHARS)?;
            }
        }
        if let Some(parameters) = &response.response_parameters {
            bound_entries(
                "responseParameters",
                parameters.len(),
                MAX_COLLECTION_ENTRIES,
            )?;
            for (key, value) in parameters {
                bound_chars("a responseParameters key", key, MAX_STRING_CHARS)?;
                bound_chars("a responseParameters value", value, MAX_STRING_CHARS)?;
            }
        }
        if let Some(templates) = &response.response_templates {
            bound_entries("responseTemplates", templates.len(), MAX_COLLECTION_ENTRIES)?;
            for (key, value) in templates {
                bound_chars("a responseTemplates key", key, MAX_STRING_CHARS)?;
                bound_chars("a responseTemplates value", value, MAX_TEMPLATE_CHARS)?;
            }
        }
    }
    Ok(())
}

