/// The `PutRestApi` operation.
///
/// Owns the shared engine (the constructor seam) and implements
/// [`smithy_server_runtime::Operation`]. Generic over the engine type `Eng`, so this
/// crate names no concrete engine type: a migrated service that needs state picks a
/// concrete engine where it mounts the service, not here.
pub struct PutRestApi<Eng> {
    engine: ::std::sync::Arc<Eng>,
}

impl<Eng> PutRestApi<Eng> {
    /// Construct the operation from the shared engine. INFALLIBLE — the engine is a
    /// construction-time dependency, so engine access is guaranteed by the time any
    /// request runs. Called by the generated `EmulatedService::new(engine)` constructor.
    pub fn new(engine: ::std::sync::Arc<Eng>) -> Self {
        Self { engine }
    }
}

impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for PutRestApi<Eng>
{
    type Input = PutRestApiInput;
    type Output = PutRestApiOutput;
    type Error = PutRestApiError;

    const NAME: &'static str = "PutRestApi";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::PUT_REST_API_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::PUT_REST_API_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let state = crate::state::service_state(&*self.engine)
            .ok_or_else(crate::state::state_unavailable)?;

        // Every refusal below is the modelled 400: the request's definition, mode or
        // size is wrong, and the message names what to fix.
        fn bad_request(message: String) -> PutRestApiError {
            PutRestApiErrorModeled::BadRequestException(BadRequestException {
                message: Some(message),
            })
            .into()
        }

        // The definition is parsed and bounded BEFORE the store lock is taken, so a
        // malformed or over-sized body never reaches the records at all.
        let mode = put_mode(input.mode.as_deref()).map_err(bad_request)?;
        let definition =
            parse_definition(&input.body, &ImportScope::of(ctx.parts())).map_err(bad_request)?;
        bound_definition(&definition).map_err(bad_request)?;

        // `parameters` is `@httpQueryParams`, so it carries this request's query string
        // rather than a member of its own. Its documented key, `ignore=documentation`,
        // excludes the definition's DocumentationParts from the import — and THIS
        // operation imports no documentation part either way: a definition's
        // `x-amazon-apigateway-documentation` set is read by
        // `ImportDocumentationParts`, which is the operation that writes those records,
        // so there is nothing here for that key to change and nothing it could silently
        // drop.
        let _ = &input.parameters;

        // `failOnWarnings` is "a query parameter to indicate whether to rollback the API
        // update (true) or not (false) when a warning is encountered": the definition is
        // read before anything is written, so the rollback is that no record changes at
        // all.
        if input.fail_on_warnings && !definition.warnings.is_empty() {
            return Err(bad_request(warnings_refusal(&definition.warnings)));
        }

        let mut store = state.lock();

        // What the API already holds, so the plan below knows which paths exist. In
        // `overwrite` mode the imported definition REPLACES the API's own, so only the
        // root resource survives and every other path counts as new.
        let (root_resource_id, kept_paths) = {
            let api = store.rest_apis.get(&input.rest_api_id).ok_or_else(|| {
                PutRestApiErrorModeled::NotFoundException(NotFoundException {
                    message: Some(crate::state::no_such_rest_api(&input.rest_api_id)),
                })
            })?;
            let kept: BTreeSet<String> = match mode {
                PutModeKind::Merge => api
                    .resources
                    .values()
                    .map(|resource| resource.path.clone())
                    .collect(),
                PutModeKind::Overwrite => {
                    BTreeSet::from([ROOT_RESOURCE_PATH.to_string()])
                }
            };
            (api.root_resource_id.clone(), kept)
        };

        // The resources the definition asks for that this API does not hold yet, planned
        // under the per-API resource quota before any record is touched.
        let mut known = kept_paths;
        let planned = plan_resources(&mut known, &definition).map_err(|message| {
            PutRestApiErrorModeled::LimitExceededException(LimitExceededException {
                retry_after_seconds: None,
                message: Some(message),
            })
        })?;

        // One id and one creation rank per record the import creates, so the imported
        // records are listed in the order the definition declares them.
        let reserved = ReservedIds::of(&definition, planned.len(), &mut store);

        let api = store.rest_apis.get_mut(&input.rest_api_id).ok_or_else(|| {
            PutRestApiErrorModeled::NotFoundException(NotFoundException {
                message: Some(crate::state::no_such_rest_api(&input.rest_api_id)),
            })
        })?;

        if mode == PutModeKind::Overwrite {
            // The API's root resource is an attribute of the API itself — `GetRestApi`
            // reports it as `rootResourceId` — so it survives the replacement under its
            // own id; what the previous definition hung off it does not.
            api.resources
                .retain(|id, _| *id == root_resource_id);
            if let Some(root) = api.resources.get_mut(&root_resource_id) {
                root.methods.clear();
            }
            // Nor do the gateway responses the previous definition customized: in
            // `overwrite` mode the imported definition REPLACES the API's own, so a
            // response type this document says nothing about goes back to the response
            // API Gateway generates for it.
            api.gateway_responses.clear();
            // Nor the request validators it declared: a validator is a record the
            // definition's own extension creates, so one this document does not declare is
            // not part of the definition the api now holds. The MODELS are not cleared with
            // them: an api is never empty of models — every one holds the two API Gateway
            // seeds it with — and a model is addressed by name, so a name this document
            // declares restates that name and one it does not say nothing about.
            api.request_validators.clear();
        }

        // The planned resources, the records the definition's extensions declare, and then
        // every operation the definition puts on a path as a method on that path's
        // resource. One id and one rank was reserved per record, so the materialisation
        // cannot be short of either.
        materialise_definition(api, &definition, &planned, &reserved)
            .map_err(|_| crate::state::state_unavailable())?;

        // The definition also describes the API itself: the `info` object is where an
        // OpenAPI document carries the API's name, description and version, and an
        // import takes each of them from the document — in BOTH modes, since `info`
        // describes the definition being imported rather than the paths under it. A
        // member the document leaves out leaves the stored one alone, so a definition
        // that says nothing about the API renames nothing. `binaryMediaTypes` comes from
        // API Gateway's own extension the same way.
        if let Some(title) = &definition.title {
            api.name = title.clone();
        }
        if definition.description.is_some() {
            api.description = crate::state::stored_description(definition.description.clone());
        }
        if definition.version.is_some() {
            api.version = definition.version.clone();
        }
        if let Some(types) = &definition.binary_media_types {
            api.binary_media_types = types.clone();
        }

        let stored = store
            .rest_apis
            .get(&input.rest_api_id)
            .ok_or_else(crate::state::state_unavailable)?;
        let mut output = PutRestApiOutput::from(stored);
        // The only member of the body that is not a stored one: what THIS import could
        // not carry over. Assigned unconditionally, because an import that warned about
        // nothing reports no warnings — never a value some other call left behind.
        output.warnings =
            (!definition.warnings.is_empty()).then(|| definition.warnings.clone());
        // Everything below is owned, so the store lock is released before the record is
        // formatted: the critical section covers the state change only.
        drop(store);
        // The access record for a state-changing operation: who, what, and the outcome.
        // Metadata only — never the definition itself.
        ::tracing::info!(
            target: crate::state::AUDIT_TARGET,
            operation = Self::NAME,
            caller = ?crate::state::request_caller(ctx.parts()),
            rest_api = ?input.rest_api_id,
            mode = ?mode,
            paths = definition.paths.len(),
            outcome = "imported",
            "api definition imported",
        );
        Ok(output)
    }
}

#[cfg(test)]
mod version_detection {
    use super::*;

    /// What a document has to write for its format to be settled: the member's name, in
    /// either spelling and at a position a member starts, followed by `:`. A name that
    /// merely contains one, and one inside a string value, are not that — the distinction
    /// the refusal for an unreadable body is drawn on.
    #[test]
    fn the_version_member_is_found_in_either_spelling() {
        for (case, text, declared) in [
            (
                "a JSON object cut off after its version member",
                "{\"openapi\": \"3.0.1\", \"info\": {\"title\": \"x\" NOT A DOCUMENT",
                true,
            ),
            (
                "the same object with no version member",
                "{\"info\": {\"title\": \"x\" NOT A DOCUMENT",
                false,
            ),
            (
                "the version member after another, on the separator",
                "{\"info\": {\"title\": \"x\"},\"swagger\":\"2.0\"",
                true,
            ),
            ("the block spelling", "swagger: '2.0'\npaths: {", true),
            ("the block spelling, quoted", "\"swagger\": '2.0'\n", true),
            (
                "the block spelling on a later line",
                "info:\n  title: x\nopenapi: 3.0.1\n",
                true,
            ),
            (
                "the flow spelling, unquoted",
                "{openapi: 3.0.1, paths: {",
                true,
            ),
            ("a document writing neither member", "paths: {", false),
            ("text that is no document", "}not a document{", false),
            (
                "a member whose name merely resembles the version field",
                "{\"swaggerVersion\": \"1.2\"",
                false,
            ),
            (
                "a vendor extension whose name ends in one",
                "{\"x-openapi\": \"3.0.1\"",
                false,
            ),
            (
                "a version-looking name inside a string value",
                "{\"info\": {\"description\": \"see \\\"openapi\\\": 3\"}, \"paths\": {",
                false,
            ),
            (
                "an indented member of another mapping, which settles the format too",
                "info:\n  openapi: 3.0.1\n",
                true,
            ),
        ] {
            assert_eq!(
                text_declares_version(text),
                declared,
                "case {case}: expected text_declares_version {declared}, got {}",
                text_declares_version(text)
            );
        }
    }
}
