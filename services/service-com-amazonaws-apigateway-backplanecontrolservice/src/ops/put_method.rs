/// The HTTP verbs API Gateway accepts for a `Method`, plus the `ANY` catch-all that
/// matches every verb.
///
/// Hand-written because the model types `httpMethod` as a bare `String` and declares no
/// enum for it; the set is the one the API Gateway developer guide lists for a method's
/// HTTP verb (`ANY`, `DELETE`, `GET`, `HEAD`, `OPTIONS`, `PATCH`, `POST`, `PUT`).
pub const HTTP_METHODS: &[&str] = &[
    "ANY", "DELETE", "GET", "HEAD", "OPTIONS", "PATCH", "POST", "PUT",
];

/// The same catalog in the order API Gateway LISTS it in when it refuses a verb outside
/// it, which is the order the developer guide publishes the verbs in rather than the
/// alphabetical order [`HTTP_METHODS`] is written in.
///
/// Two spellings of ONE catalog: [`valid_http_methods_are_listed`] holds them to the same
/// members, so a verb added to one is a verb of the other.
const HTTP_METHODS_AS_LISTED: &[&str] = &[
    "GET", "PUT", "POST", "DELETE", "PATCH", "OPTIONS", "HEAD", "ANY",
];

/// The `BadRequestException` message for a verb outside the catalog ([`HTTP_METHODS`]).
///
/// API Gateway's own sentence for it: ENTIRELY FIXED text — it states the member in the
/// record's spelling (`HttpMethod`, as the sentence for an EMPTY one does, see
/// [`super::put_integration::EMPTY_INTEGRATION_HTTP_METHOD`]) and then lists the catalog,
/// comma-separated with no spaces, in [`HTTP_METHODS_AS_LISTED`]'s order. The submitted
/// verb is NOT part of it: the caller has to pick one of the options, which the sentence
/// names in full, and the request already carries the verb it sent.
///
/// `pub` because every call that reads a verb onto this catalog states the same refusal —
/// the method a `PutMethod` creates and the integration whose own `httpMethod` is one of
/// the same verbs — so the two cannot disagree about the sentence.
pub fn invalid_http_method() -> String {
    format!(
        "Invalid HttpMethod specified. Valid options are {}",
        HTTP_METHODS_AS_LISTED.join(",")
    )
}

/// The envelope API Gateway states a MAPPING EXPRESSION it could not read in.
///
/// A mapping expression names what a request or a response carries over — a method request
/// parameter, a method or gateway response header, an integration response's source — and
/// one that is not of the documented form is refused with this one structured sentence,
/// which carries the service's own validation finding about the expression: the fixed
/// `Validation Result` frame with no warnings and the one error, inside which the offending
/// expression appears again. BUILT FROM THE REQUEST: the only variable part is the
/// expression the caller has to change, which the sentence states twice as AWS words it.
///
/// `pub` because every member of this service that carries a mapping expression is refused
/// by it, whichever operation wrote it, so there is one wording for the class rather than
/// one per member.
pub fn invalid_mapping_expression(expression: &str) -> String {
    format!(
        "Invalid mapping expression specified: Validation Result: warnings : [], errors : \
         [Invalid mapping expression specified: {expression}]"
    )
}

/// The key a method is stored under, and the one an operation addressing a method by its
/// `httpMethod` resolves it with: the verb EXACTLY as the request spelled it.
///
/// A method's verb is an IDENTIFIER, not a value read loosely: it is one of the
/// enumeration in [`HTTP_METHODS`], and a request naming anything else — a verb outside
/// the catalog, or one of them in another case — names no method on the resource. So the
/// key is the request's own spelling, which is what makes `PutMethod` refuse a verb that
/// is not in the catalog and every reader of a method answer `NotFoundException` for a
/// verb the resource holds no method under.
pub fn method_key(http_method: &str) -> String {
    http_method.to_string()
}

/// The stored verb a REQUEST ARRIVING ON THE WIRE names — an invoke of a deployed stage,
/// whose own HTTP method is the verb, and the method settings in force for it.
///
/// Upper case, because that is how the HTTP methods are spelled, and a stored method
/// carries one of [`HTTP_METHODS`]: this reads a wire verb onto the catalog rather than
/// addressing a record by an identifier the caller typed, which is [`method_key`].
pub fn wire_verb(verb: &str) -> String {
    verb.to_ascii_uppercase()
}

/// The `authorizationType`s whose method is authorized BY AN `Authorizer` of its own api:
/// "`CUSTOM` for using a custom authorizer, or `COGNITO_USER_POOLS` for using a Cognito
/// user pool" (`Method$authorizationType`).
///
/// Such a method NAMES that authorizer — "specifies the identifier of an `Authorizer` to
/// use on this `Method`, if the type is `CUSTOM` or `COGNITO_USER_POOLS`"
/// (`Method$authorizerId`) — so one that names none is authorized by nothing and is
/// refused rather than stored ([`validate_method`]).
///
/// `pub` because the operation that PATCHES a method states the same rule over the same
/// record (`UpdateMethod`), so the set is resolved in one place.
pub const AUTHORIZATION_BY_AUTHORIZER: &[&str] = &["CUSTOM", "COGNITO_USER_POOLS"];

/// The prefix of a method request parameter mapping expression: "a key defines a method
/// request parameter name matching the pattern of `method.request.{location}.{name}`"
/// (`Method$requestParameters`).
///
/// Hand-written because the model types the map key as a bare `String` and declares no
/// pattern for it; the form is the one that member's own documentation publishes.
pub const METHOD_REQUEST_PARAMETER_PREFIX: &str = "method.request.";

/// The `{location}`s that pattern admits: "where location is querystring, path, or header"
/// (`Method$requestParameters`).
pub const METHOD_REQUEST_PARAMETER_LOCATIONS: &[&str] = &["querystring", "path", "header"];

/// Whether `key` is a `method.request.{location}.{name}` mapping expression naming a
/// parameter: the documented prefix, one of the documented locations, and a non-empty
/// parameter name.
///
/// The name's character set is the HTTP field-name token of RFC 9110 §5.1 (`tchar`), the
/// same one a method RESPONSE parameter's header name is read with
/// ([`super::put_method_response::is_field_name_char`]): it is what "a valid … parameter
/// name" admits for a header, and a query-string or path parameter travels in a URI, where
/// the same token is safe unencoded.
pub fn is_method_request_parameter(key: &str) -> bool {
    let Some(rest) = key.strip_prefix(METHOD_REQUEST_PARAMETER_PREFIX) else {
        return false;
    };
    let Some((location, name)) = rest.split_once('.') else {
        return false;
    };
    METHOD_REQUEST_PARAMETER_LOCATIONS.contains(&location)
        && !name.is_empty()
        && name
            .chars()
            .all(super::put_method_response::is_field_name_char)
}

/// The `BadRequestException` message for a `requestParameters` key that is not a
/// `method.request.{location}.{name}` mapping expression; see
/// [`is_method_request_parameter`].
///
/// One mapping expression the service could not read, stated in the envelope it states
/// every such finding in ([`invalid_mapping_expression`]).
///
/// `pub` because `UpdateMethod` writes the same member under the same rule, so the two
/// operations cannot disagree on how a key outside the documented form is stated.
pub fn invalid_request_parameter(key: &str) -> String {
    invalid_mapping_expression(key)
}

/// The `BadRequestException` message for a method whose `authorizationType` is authorized
/// by an `Authorizer` ([`AUTHORIZATION_BY_AUTHORIZER`]) and which names none: API Gateway's
/// own sentence for it, which states the rule as well as the refusal.
pub const MISSING_METHOD_AUTHORIZER: &str = "Invalid authorizer ID specified. Setting the \
     authorization type to CUSTOM or COGNITO_USER_POOLS requires a valid authorizer.";

/// The `Authorizer` `method` USES, or `None` when it uses none.
///
/// `Method$authorizerId` is "the identifier of an Authorizer to use on this method. The
/// `authorizationType` must be `CUSTOM`", so the identifier names an authorizer the method
/// uses only while its own `authorizationType` is one an `Authorizer` authorizes
/// ([`AUTHORIZATION_BY_AUTHORIZER`]): a method authorized by `NONE` or `AWS_IAM` is decided
/// without asking any authorizer — which is how the data plane decides it
/// ([`crate::service::invoke`]) and how an export renders it
/// ([`super::get_export`]) — so the identifier such a method still carries names no
/// authorizer in use. A member set to the empty string names no authorizer either, the same
/// unnamed authorizer an absent member is ([`validate_method`]).
///
/// `pub` because it is the one reading of that pairing: whether an authorizer is USED by a
/// method is what decides a request to a deployed stage, and it is also what decides whether
/// a stored authorizer is still depended on
/// ([`crate::state::RestApiEntry::method_referencing_authorizer`]).
pub fn authorizer_in_use(method: &MethodEntry) -> Option<&str> {
    if !AUTHORIZATION_BY_AUTHORIZER.contains(&method.authorization_type.as_str()) {
        return None;
    }
    method.authorizer_id.as_deref().filter(|id| !id.is_empty())
}

/// Refuse a `Method` record that breaks one of the rules its own members publish: a
/// `requestParameters` key that is no method request parameter mapping expression, and an
/// `authorizerId` that names no `Authorizer` of the api the method belongs to.
///
/// Every rule is stated over the RECORD, so the same check serves the operation that
/// creates a method and the one that patches it (`UpdateMethod`) — the way
/// [`super::put_integration::validate_integration`] serves both of an integration's.
/// `api_authorizer_ids` are the ids of the authorizers the method's own api holds, which is
/// what an `authorizerId` has to name: an `Authorizer` lives inside one REST API
/// ([`crate::state::RestApiEntry::authorizers`] is keyed by that id), and the set is passed
/// in rather than the api because a patch is applied to a COPY of the record with the api's
/// borrow already given up (as [`crate::state::unknown_model_name`] takes the model names).
pub fn validate_method(
    method: &MethodEntry,
    api_authorizer_ids: &::std::collections::BTreeSet<String>,
) -> Result<(), String> {
    // Read in key order, so a record carrying several malformed keys is refused with the
    // same one every time.
    for key in method.request_parameters.keys() {
        if !is_method_request_parameter(key) {
            return Err(invalid_request_parameter(key));
        }
    }
    // A member set to the empty string names no authorizer, so it is the same unnamed
    // authorizer an absent member is.
    match method.authorizer_id.as_deref().filter(|id| !id.is_empty()) {
        // A reference that resolves to nothing authorizes nothing: the method would claim
        // an authorization no record of the api can take, so it is refused with the
        // sentence this service states for an authorizer identifier that names no record.
        Some(id) if !api_authorizer_ids.contains(id) => {
            Err(crate::state::NO_SUCH_AUTHORIZER.to_string())
        }
        None if AUTHORIZATION_BY_AUTHORIZER.contains(&method.authorization_type.as_str()) => {
            Err(MISSING_METHOD_AUTHORIZER.to_string())
        }
        _ => Ok(()),
    }
}

/// Refuse a request whose caller-sized members would grow the store past a bound.
///
/// Called BEFORE the store lock is taken, so an over-sized request never reaches the
/// records at all. The method COUNT per resource needs no cap of its own: a method is
/// keyed by a verb from [`HTTP_METHODS`], so a resource holds at most that many.
fn bound_input(input: &PutMethodInput) -> Result<(), String> {
    use crate::state::{bound_chars, bound_entries, MAX_COLLECTION_ENTRIES, MAX_STRING_CHARS};

    bound_chars("authorizationType", &input.authorization_type, MAX_STRING_CHARS)?;
    for (member, value) in [
        ("authorizerId", &input.authorizer_id),
        ("operationName", &input.operation_name),
        ("requestValidatorId", &input.request_validator_id),
    ] {
        if let Some(value) = value {
            bound_chars(member, value, MAX_STRING_CHARS)?;
        }
    }
    if let Some(parameters) = &input.request_parameters {
        bound_entries(
            "requestParameters",
            parameters.len(),
            MAX_COLLECTION_ENTRIES,
        )?;
        for key in parameters.keys() {
            bound_chars("a requestParameters key", key, MAX_STRING_CHARS)?;
        }
    }
    if let Some(models) = &input.request_models {
        bound_entries("requestModels", models.len(), MAX_COLLECTION_ENTRIES)?;
        for (key, value) in models {
            bound_chars("a requestModels key", key, MAX_STRING_CHARS)?;
            bound_chars("a requestModels value", value, MAX_STRING_CHARS)?;
        }
    }
    if let Some(scopes) = &input.authorization_scopes {
        bound_entries("authorizationScopes", scopes.len(), MAX_COLLECTION_ENTRIES)?;
        for value in scopes {
            bound_chars("authorizationScopes", value, MAX_STRING_CHARS)?;
        }
    }
    Ok(())
}

