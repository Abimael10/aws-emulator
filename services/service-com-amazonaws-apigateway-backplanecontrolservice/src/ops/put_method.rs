impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for PutMethod<Eng>
{
    type Input = PutMethodInput;
    type Output = PutMethodOutput;
    type Error = PutMethodError;

    const NAME: &'static str = "PutMethod";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::PUT_METHOD_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::PUT_METHOD_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 201u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        let state = crate::state::service_state(&*self.engine)
            .ok_or_else(crate::state::state_unavailable)?;

        bound_input(&input).map_err(|message| {
            PutMethodErrorModeled::BadRequestException(BadRequestException {
                message: Some(message),
            })
        })?;

        let mut store = state.lock();

        let verb = method_key(&input.http_method);
        if !HTTP_METHODS.contains(&verb.as_str()) {
            return Err(PutMethodErrorModeled::BadRequestException(BadRequestException {
                message: Some(invalid_http_method()),
            })
            .into());
        }

        // A `requestModels` value "specifies the Model resources used for the request's
        // content type" (`Method$requestModels`), so it has to name a `Model` of THIS
        // api: a value no model of the api answers to configures nothing and is refused
        // before the method is stored. Resolved against the api BEFORE the resource is
        // borrowed out of it, so one lookup answers for the whole map.
        if let Some(message) = store
            .rest_apis
            .get(&input.rest_api_id)
            .and_then(|api| {
                crate::state::unresolved_model_reference(api, input.request_models.as_ref())
            })
        {
            return Err(PutMethodErrorModeled::BadRequestException(BadRequestException {
                message: Some(message),
            })
            .into());
        }
        // The authorizers the method's own api holds, read off the same api and in the
        // same place, which is what the record's `authorizerId` has to name.
        let api_authorizer_ids: ::std::collections::BTreeSet<String> = store
            .rest_apis
            .get(&input.rest_api_id)
            .map(|api| api.authorizers.keys().cloned().collect())
            .unwrap_or_default();
        // A method is put ON a resource, so the `(restApiId, resourceId)` pair is resolved
        // as ONE lookup for that resource: an identifier no stored API answers to leaves
        // the addressed resource unresolvable too, and the refusal names the resource the
        // method would hang off rather than the API above it.
        let resource = store
            .resource_mut(&input.rest_api_id, &input.resource_id)
            .map_err(|message| {
                PutMethodErrorModeled::NotFoundException(NotFoundException {
                    message: Some(message),
                })
            })?;
        // A verb names at most one method on a resource: re-putting one is a conflict,
        // not an overwrite. The message is API Gateway's own wording for it, as a
        // recorded refusal reports: it names the conflict, not the verb, which the
        // request already carries in its URI.
        if resource.methods.contains_key(&verb) {
            return Err(PutMethodErrorModeled::ConflictException(ConflictException {
                message: Some("Method already exists for this resource".to_string()),
            })
            .into());
        }

        let entry = MethodEntry {
            http_method: verb.clone(),
            authorization_type: input.authorization_type,
            authorizer_id: input.authorizer_id,
            api_key_required: input.api_key_required,
            operation_name: input.operation_name,
            request_parameters: input
                .request_parameters
                .unwrap_or_default()
                .into_iter()
                .collect::<BTreeMap<String, bool>>(),
            request_models: input
                .request_models
                .unwrap_or_default()
                .into_iter()
                .collect::<BTreeMap<String, String>>(),
            request_validator_id: input.request_validator_id,
            authorization_scopes: input.authorization_scopes.unwrap_or_default(),
            // `PutMethodResponse` is the call that adds a method response and
            // `PutIntegration` the one that attaches an integration, so a method is
            // created with neither.
            method_responses: BTreeMap::new(),
            integration: None,
        };
        // The record is held to the rules its own members publish — the forms a
        // `requestParameters` key takes, and the authorizer an authorization type needs —
        // BEFORE it is stored, so a refused request leaves the resource's methods as they
        // were. The same check holds a patched method ([`validate_method`]).
        validate_method(&entry, &api_authorizer_ids).map_err(|message| {
            PutMethodErrorModeled::BadRequestException(BadRequestException {
                message: Some(message),
            })
        })?;

        resource.methods.insert(verb.clone(), entry);

        let stored = resource.methods.get(&verb).ok_or_else(|| {
            PutMethodErrorModeled::NotFoundException(NotFoundException {
                message: Some(crate::state::NO_SUCH_METHOD.to_string()),
            })
        })?;
        let body = GetMethodOutput::from(stored);
        Ok(PutMethodOutput {
            http_method: body.http_method,
            authorization_type: body.authorization_type,
            authorizer_id: body.authorizer_id,
            api_key_required: body.api_key_required,
            request_validator_id: body.request_validator_id,
            operation_name: body.operation_name,
            request_parameters: body.request_parameters,
            request_models: body.request_models,
            method_responses: body.method_responses,
            method_integration: body.method_integration,
            authorization_scopes: body.authorization_scopes,
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The two spellings of the verb catalog hold the same verbs: the set a request is
    /// checked against ([`HTTP_METHODS`]) and the list the refusal names
    /// ([`HTTP_METHODS_AS_LISTED`]) are one catalog, so neither can gain a verb the other
    /// does not have.
    #[test]
    fn valid_http_methods_are_listed() {
        let mut checked: Vec<&str> = HTTP_METHODS.to_vec();
        checked.sort_unstable();
        let mut listed: Vec<&str> = HTTP_METHODS_AS_LISTED.to_vec();
        listed.sort_unstable();
        assert_eq!(
            checked, listed,
            "case the verb catalog: expected the listed verbs {listed:?} to be the checked \
             ones {checked:?}"
        );
    }
}
