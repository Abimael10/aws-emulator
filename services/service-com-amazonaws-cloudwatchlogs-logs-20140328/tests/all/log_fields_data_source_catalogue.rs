//! End-to-end tests for the SCHEMA `GetLogFields` reports for one data source: which fields
//! are available for it and what each one's reported type is.
//!
//! Every case drives the service the way a client does — `POST /` with
//! `X-Amz-Target: Logs_20140328.GetLogFields` — so a response that is not computed from the
//! shared store cannot pass. What the fields of an INGESTING data source are discovered from
//! is the subject of `tests/all/log_fields.rs`; this suite is about the catalogue every
//! answer carries.
//!
//! The rules:
//!
//! * the two instants CloudWatch Logs keeps for every log event (`@timestamp`,
//!   `@ingestionTime`) are reported by what they MEAN — as timestamps — and the three names
//!   it keeps as text, whatever a data source holds;
//! * a data source AWS publishes no schema of its own for carries the dimensions its records
//!   are addressed by as well: the account and Region they were ingested in, the log they came
//!   from, the format they arrived in, the data source's own name and type, and the ids of the
//!   log group and log stream holding them.
//!
//! The table spans what the second rule generalises over: whether the data source's NAME is
//! one of AWS's own, which AWS prefix it carries, and which type it is asked about under —
//! including entries neither the issue nor `tests/all/log_fields.rs` cites.

use std::collections::BTreeMap;

use serde_json::{json, Value};

use crate::harness::Logs;

/// The operation every case calls.
const OP: &str = "GetLogFields";

/// The fields CloudWatch Logs generates on every stored log event, with the type each is
/// reported by. Source: the generated-field sentence `GetLogGroupFields` documents — "fields
/// that start with @ are fields generated by CloudWatch Logs. For example, @timestamp is the
/// timestamp of each log event" — and the two instants and three names a stored event carries.
const GENERATED_FIELDS: [(&str, &str); 5] = [
    ("@ingestionTime", "timestamp"),
    ("@log", "string"),
    ("@logStream", "string"),
    ("@message", "string"),
    ("@timestamp", "timestamp"),
];

/// The dimension fields a record of a data source AWS publishes no schema for is addressed
/// by, each naming something rather than measuring it, so each is text.
const GENERIC_DATA_SOURCE_FIELDS: [(&str, &str); 8] = [
    ("@aws.account", "string"),
    ("@aws.region", "string"),
    ("@data_format", "string"),
    ("@data_source_name", "string"),
    ("@data_source_type", "string"),
    ("@logGroupId", "string"),
    ("@logStreamId", "string"),
    ("@source.log", "string"),
];

/// The fields one call reports, keyed by name, with each field's reported type name.
async fn reported(logs: &Logs, case: &str, name: &str, source_type: &str) -> BTreeMap<String, String> {
    let response = logs
        .ok(OP, &json!({"dataSourceName": name, "dataSourceType": source_type}))
        .await;
    response
        .get("logFields")
        .and_then(Value::as_array)
        .unwrap_or_else(|| panic!("case {case:?}: {OP} must return logFields, got {response}"))
        .iter()
        .map(|field| {
            let name = field
                .get("logFieldName")
                .and_then(Value::as_str)
                .unwrap_or_else(|| {
                    panic!("case {case:?}: every reported field carries a name, got {field}")
                })
                .to_string();
            let type_name = field
                .get("logFieldType")
                .and_then(|field_type| field_type.get("type"))
                .and_then(Value::as_str)
                .unwrap_or_default()
                .to_string();
            (name, type_name)
        })
        .collect()
}

/// Which fields a data source is reported to carry, and with which type: the generated five
/// for every data source, plus the dimension fields for one AWS publishes no schema for.
#[tokio::test]
async fn the_reported_catalogue_is_the_data_sources_own() {
    let logs = Logs::new();

    // (case, dataSourceName, dataSourceType, whether the name is one of AWS's own)
    //
    // The AWS-published names come from the ones this service itself states: the
    // `GroupingIdentifier` documentation's examples of a data source's name, type and format
    // (`amazon_vpc`, `flow`, `OCSF`) and the `S3TablesIntegration` datasource names of the
    // vended-log catalogue (`aws_alb` with `access` and `connection`).
    let cases: [(&str, &str, &str, bool); 7] = [
        ("a published VPC flow data source", "amazon_vpc", "flow", true),
        ("a published load-balancer access data source", "aws_alb", "access", true),
        (
            "a published load-balancer connection data source",
            "aws_alb",
            "connection",
            true,
        ),
        (
            "a published name asked about under another type",
            "aws_alb",
            "no_such_type",
            true,
        ),
        ("a caller's own data source", "orders-service", "application", false),
        ("a generic data source under an unknown type", "payments", "unknown", false),
        (
            "a name that only CONTAINS an AWS prefix",
            "my_aws_alb",
            "access",
            false,
        ),
    ];

    for (case, name, source_type, published) in cases {
        let fields = reported(&logs, case, name, source_type).await;
        let mut expected: BTreeMap<String, String> = GENERATED_FIELDS
            .iter()
            .map(|(field, type_name)| ((*field).to_string(), (*type_name).to_string()))
            .collect();
        if !published {
            expected.extend(
                GENERIC_DATA_SOURCE_FIELDS
                    .iter()
                    .map(|(field, type_name)| ((*field).to_string(), (*type_name).to_string())),
            );
        }
        assert_eq!(
            fields, expected,
            "case {case:?}: expected the catalogue of that data source, got {fields:?}"
        );
    }
}

/// Reporting the fields is a READ: two identical calls answer identically, and asking about
/// one data source does not change what another is answered.
#[tokio::test]
async fn reporting_one_data_sources_fields_changes_no_other_answer() {
    let logs = Logs::new();

    let generic_first = reported(&logs, "a generic source, first call", "orders", "application").await;
    let published = reported(&logs, "a published source", "amazon_vpc", "flow").await;
    let generic_again = reported(&logs, "a generic source, second call", "orders", "application").await;

    assert_eq!(
        generic_again, generic_first,
        "case \"a generic source, second call\": a report is repeatable, got {generic_again:?} \
         after {generic_first:?}"
    );
    assert!(
        !published.contains_key("@data_source_name"),
        "case \"a published source\": a published data source carries its own schema, got \
         {published:?}"
    );
}
