//! End-to-end tests for the TRANSFORMATION an ingested log event is STORED with, which is what
//! a query of the log group then reads.
//!
//! RULE: every log event `PutLogEvents` stores into a log group a transformer is in force for
//! — one created on the group by `PutTransformer` or one an account-level `TRANSFORMER_POLICY`
//! selects it with — is stored with the FIELDS that transformer's processor pipeline produced
//! from it ("CloudWatch Logs performs the transformations at the time of log ingestion"), and
//! those fields are what the query-side reads report: a query's records, the whole record one
//! `@ptr` addresses, and the fields a log group is reported to carry. The ingested message
//! itself stands unchanged beside them — `GetLogEvents` and `FilterLogEvents` "return only the
//! original versions of log events, before they were transformed", and a record's `@message` is
//! the message as it arrived. The transformation belongs to the INGESTION, so a transformer put,
//! reconfigured or deleted decides what LATER events are stored as and rewrites nothing already
//! stored.
//!
//! The table spans what the rule generalises over: the processor kind that structures the event
//! (`parseJSON` at the root and into a destination, `parseKeyValue`, `csv`), the mutate
//! processors that follow it (`renameKeys`, `addKeys`, `deleteKeys`), the FORM of the ingested
//! message (a JSON object, delimited text, comma-separated text, bare text), and both
//! directions of the difference — a field only the transformed event carries and a field only
//! the ingested one does.
//!
//! Every case drives the service the way a client does — `POST /` with
//! `X-Amz-Target: Logs_20140328.<Operation>` through the router that mounts it — so a response
//! that is not computed from the shared store cannot pass.

use std::collections::{BTreeMap, BTreeSet};
use std::time::Duration;

use serde_json::{json, Value};

use crate::account_policies::put_body;
use crate::harness::{batch, group_with_stream, messages, now_ms, Logs};

/// The operations under test.
const PUT_EVENTS: &str = "PutLogEvents";
const PUT_TRANSFORMER: &str = "PutTransformer";
const DELETE_TRANSFORMER: &str = "DeleteTransformer";
const GROUP_FIELDS: &str = "GetLogGroupFields";
const START: &str = "StartQuery";
const RESULTS: &str = "GetQueryResults";
const RECORD: &str = "GetLogRecord";

/// The fields CloudWatch Logs generates for every stored event, which every read reports
/// whatever the event carried. Source: `GetLogGroupFields` — "fields that start with @ are
/// fields generated by CloudWatch Logs" — and the crate's `insights::GENERATED_FIELDS`.
const GENERATED_FIELDS: [&str; 5] = [
    "@ingestionTime",
    "@log",
    "@logStream",
    "@message",
    "@timestamp",
];

/// How long a case waits for a started query to reach a finished status before giving up:
/// generous room for a loaded host, since what is waited for is the status the query reports
/// and never this bound.
const COMPLETION_DEADLINE: Duration = Duration::from_secs(60);

/// How often that status is looked at again.
const POLL_INTERVAL: Duration = Duration::from_millis(25);

/// One row of the table.
struct Row {
    /// What this row varies, named in every assertion.
    case: &'static str,
    /// The `transformerConfig` the log group is given.
    transformer: Value,
    /// The message ingested, as one log event.
    message: &'static str,
    /// The fields the stored event must then be reported to carry, beside the generated ones.
    discovered: &'static [&'static str],
    /// A field the INGESTED message names that the stored event must NOT be reported to
    /// carry, for a row whose pipeline renames or deletes one.
    gone: &'static [&'static str],
}

/// The table: one row per form of the rule.
fn rows() -> Vec<Row> {
    vec![
        Row {
            case: "parseJSON at the root, then a renamed key",
            transformer: json!([
                {"parseJSON": {}},
                {"renameKeys": {"entries": [{"key": "orig", "renameTo": "renamed_field"}]}},
            ]),
            message: r#"{"orig":"value","keep":1}"#,
            discovered: &["renamed_field", "keep"],
            gone: &["orig"],
        },
        Row {
            case: "parseJSON into a destination, reached by its nested path",
            transformer: json!([{"parseJSON": {"source": "@message", "destination": "parsed"}}]),
            message: r#"{"status":"fail","bytes":7}"#,
            discovered: &["parsed.status", "parsed.bytes"],
            gone: &[],
        },
        Row {
            case: "parseKeyValue structures delimited text that is no JSON document",
            transformer: json!([{"parseKeyValue": {
                "fieldDelimiter": "&",
                "keyValueDelimiter": "=",
            }}]),
            message: "action=login&user=amy",
            discovered: &["action", "user"],
            gone: &[],
        },
        Row {
            case: "csv names the columns of comma-separated text",
            transformer: json!([{"csv": {"columns": ["ip", "code", "size"]}}]),
            message: "10.0.0.1,500,256",
            discovered: &["ip", "code", "size"],
            gone: &[],
        },
        Row {
            case: "addKeys adds a key the ingested message never carried",
            transformer: json!([
                {"parseJSON": {}},
                {"addKeys": {"entries": [{"key": "env", "value": "prod"}]}},
            ]),
            message: r#"{"count":5}"#,
            discovered: &["env", "count"],
            gone: &[],
        },
        Row {
            case: "deleteKeys removes a key the ingested message carried",
            transformer: json!([
                {"parseJSON": {}},
                {"deleteKeys": {"withKeys": ["secret"]}},
            ]),
            message: r#"{"secret":"x","n":3}"#,
            discovered: &["n"],
            gone: &["secret"],
        },
        Row {
            case: "a message the pipeline structures nothing out of keeps only the generated fields",
            transformer: json!([{"parseJSON": {}}]),
            message: "plain text WARN 42",
            discovered: &[],
            gone: &[],
        },
    ]
}

/// The field NAMES `GetLogGroupFields` reports for one log group.
async fn reported_fields(logs: &Logs, case: &str, group: &str) -> BTreeSet<String> {
    let answer = logs
        .ok(GROUP_FIELDS, &json!({"logGroupName": group}))
        .await;
    answer["logGroupFields"]
        .as_array()
        .unwrap_or_else(|| panic!("case {case:?}: a response lists logGroupFields, got {answer}"))
        .iter()
        .map(|field| {
            field["name"]
                .as_str()
                .unwrap_or_else(|| panic!("case {case:?}: a field carries a name, got {field}"))
                .to_string()
        })
        .collect()
}

/// A log group with one stream, holding `message` as one event stamped a minute ago — inside
/// both `PutLogEvents`' ingestion window and the window `GetLogGroupFields` searches by
/// default.
async fn ingest_one(logs: &Logs, group: &str, message: &str) -> i64 {
    let at = now_ms() - 60 * 1_000;
    logs.ok(
        PUT_EVENTS,
        &json!({
            "logGroupName": group,
            "logStreamName": STREAM,
            "logEvents": batch(&[(at, message)]),
        }),
    )
    .await;
    at
}

/// The stream every case ingests into.
const STREAM: &str = "events";

/// An event ingested while a transformer is in force is stored with the fields that
/// transformer produced — reported by the group's own field discovery — while the stream still
/// serves the message exactly as it arrived.
#[tokio::test]
async fn an_ingested_event_is_stored_with_the_fields_its_transformer_produced() {
    for (index, row) in rows().iter().enumerate() {
        // One account per row, so what the reader reports is this row's event.
        let logs = Logs::new();
        let case = row.case;
        let group = format!("/transformer-ingest/row-{index}");
        group_with_stream(&logs, &group, STREAM, None).await;
        logs.ok(
            PUT_TRANSFORMER,
            &json!({"logGroupIdentifier": &group, "transformerConfig": row.transformer}),
        )
        .await;
        ingest_one(&logs, &group, row.message).await;

        let reported = reported_fields(&logs, case, &group).await;
        for generated in GENERATED_FIELDS {
            assert!(
                reported.contains(generated),
                "case {case:?}: every stored event carries {generated}, got {reported:?}"
            );
        }
        for field in row.discovered {
            assert!(
                reported.contains(*field),
                "case {case:?}: the transformed event carries {field}, got {reported:?}"
            );
        }
        for field in row.gone {
            assert!(
                !reported.contains(*field),
                "case {case:?}: the pipeline left no {field} on the stored event, got {reported:?}"
            );
        }

        // The transformation structures the stored event; it does not rewrite what the stream
        // serves.
        let read = logs
            .ok(
                "GetLogEvents",
                &json!({"logGroupName": &group, "logStreamName": STREAM}),
            )
            .await;
        assert_eq!(
            messages(&read),
            vec![row.message.to_string()],
            "case {case:?}: the ingested message is what the stream serves"
        );
    }
}

/// The rows one finished query produced, each as the field/value pairs it carries.
///
/// The wait is on the CONDITION the query reaches, looked at again until it holds or
/// [`COMPLETION_DEADLINE`] passes, so nothing here depends on how fast the host runs.
async fn query_rows(
    logs: &Logs,
    case: &str,
    group: &str,
    query_string: &str,
) -> Vec<BTreeMap<String, String>> {
    let now_secs = now_ms() / 1_000;
    let started = logs
        .ok(
            START,
            &json!({
                "logGroupName": group,
                "startTime": now_secs - 3_600,
                "endTime": now_secs + 60,
                "queryString": query_string,
            }),
        )
        .await;
    let id = started["queryId"]
        .as_str()
        .unwrap_or_else(|| panic!("case {case:?}: a start answers a queryId, got {started}"))
        .to_string();
    let deadline = std::time::Instant::now() + COMPLETION_DEADLINE;
    loop {
        let answer = logs.ok(RESULTS, &json!({"queryId": &id})).await;
        if answer["status"].as_str() == Some("Complete") {
            return answer["results"]
                .as_array()
                .unwrap_or_else(|| panic!("case {case:?}: results are a list, got {answer}"))
                .iter()
                .map(|row| {
                    row.as_array()
                        .unwrap_or_else(|| panic!("case {case:?}: a row is a list, got {row}"))
                        .iter()
                        .map(|field| {
                            (
                                field["field"].as_str().unwrap_or_default().to_string(),
                                field["value"].as_str().unwrap_or_default().to_string(),
                            )
                        })
                        .collect()
                })
                .collect();
        }
        assert!(
            std::time::Instant::now() < deadline,
            "case {case:?}: the query never completed, last answer {answer}"
        );
        tokio::time::sleep(POLL_INTERVAL).await;
    }
}

/// The value of one field, or the empty string when the record does not carry it.
fn value(fields: &BTreeMap<String, String>, field: &str) -> String {
    fields.get(field).cloned().unwrap_or_default()
}

/// The whole record `GetLogRecord` reports for one `@ptr`.
async fn pointed_record(logs: &Logs, case: &str, pointer: &str) -> BTreeMap<String, String> {
    let answer = logs
        .ok(RECORD, &json!({"logRecordPointer": pointer}))
        .await;
    answer["logRecord"]
        .as_object()
        .unwrap_or_else(|| panic!("case {case:?}: a record is a map, got {answer}"))
        .iter()
        .map(|(field, held)| (field.clone(), held.as_str().unwrap_or_default().to_string()))
        .collect()
}

/// A query of the group reads the transformed fields of each event, and the whole record its
/// `@ptr` addresses carries them too — with `@message` still the message as ingested.
#[tokio::test]
async fn a_query_reads_the_transformed_fields_and_the_raw_message() {
    let logs = Logs::new();
    let case = "parseKeyValue then renameKeys, read back through a query";
    const GROUP: &str = "/transformer-ingest/query";
    let message = "action=login&user=amy";
    group_with_stream(&logs, GROUP, STREAM, None).await;
    logs.ok(
        PUT_TRANSFORMER,
        &json!({
            "logGroupIdentifier": GROUP,
            "transformerConfig": [
                {"parseKeyValue": {"fieldDelimiter": "&", "keyValueDelimiter": "="}},
                {"renameKeys": {"entries": [{"key": "user", "renameTo": "renamed_field"}]}},
            ],
        }),
    )
    .await;
    ingest_one(&logs, GROUP, message).await;

    let rows = query_rows(
        &logs,
        case,
        GROUP,
        "fields @message, action, renamed_field, user",
    )
    .await;
    assert_eq!(
        rows.len(),
        1,
        "case {case:?}: the one stored event is one row, got {rows:?}"
    );
    let row = &rows[0];
    for (field, expected) in [
        ("@message", message),
        ("action", "login"),
        ("renamed_field", "amy"),
        // The rename took the key away, so the transformed event names it no more.
        ("user", ""),
    ] {
        let found = value(row, field);
        assert_eq!(
            found, expected,
            "case {case:?}: {field} must read {expected:?}, got {found:?}"
        );
    }

    // "All fields are retrieved, even if the original query that produced the
    // logRecordPointer retrieved only a subset of fields" (`GetLogRecord`).
    let record = pointed_record(&logs, case, &value(row, "@ptr")).await;
    for (field, expected) in [
        ("@message", message),
        ("action", "login"),
        ("renamed_field", "amy"),
    ] {
        let found = value(&record, field);
        assert_eq!(
            found, expected,
            "case {case:?}: the whole record's {field} must read {expected:?}, got {found:?}"
        );
    }
}

/// The transformation belongs to the ingestion: an event ingested before the transformer is put
/// carries no transformed field, one ingested while it is in force carries them and KEEPS them,
/// and one ingested after `DeleteTransformer` carries none again — "as soon as you do this, the
/// transformation of incoming log events according to that transformer stops".
#[tokio::test]
async fn the_transformer_in_force_at_ingestion_is_the_one_an_event_is_stored_with() {
    let logs = Logs::new();
    let case = "before the transformer, while it is in force, and after it is deleted";
    const GROUP: &str = "/transformer-ingest/lifecycle";
    group_with_stream(&logs, GROUP, STREAM, None).await;

    let before = "action=before&user=amy";
    ingest_one(&logs, GROUP, before).await;
    logs.ok(
        PUT_TRANSFORMER,
        &json!({
            "logGroupIdentifier": GROUP,
            "transformerConfig": [
                {"parseKeyValue": {"fieldDelimiter": "&", "keyValueDelimiter": "="}},
            ],
        }),
    )
    .await;
    let during = "action=login&user=amy";
    ingest_one(&logs, GROUP, during).await;
    logs.ok(DELETE_TRANSFORMER, &json!({"logGroupIdentifier": GROUP}))
        .await;
    let after = "action=after&user=amy";
    ingest_one(&logs, GROUP, after).await;

    // One query over all three events: the `action` field is on the record of the event that
    // was transformed and on neither of the others, which is the whole rule in one read.
    let rows = query_rows(&logs, case, GROUP, "fields @message, action").await;
    let by_message: BTreeMap<String, String> = rows
        .iter()
        .map(|row| (value(row, "@message"), value(row, "action")))
        .collect();
    for (message, expected) in [(before, ""), (during, "login"), (after, "")] {
        let found = by_message
            .get(message)
            .unwrap_or_else(|| panic!("case {case:?}: every event has a row, got {by_message:?}"));
        assert_eq!(
            found, expected,
            "case {case:?}: the event {message:?} must read action {expected:?}, got {found:?}"
        );
    }
}

/// An account-level `TRANSFORMER_POLICY` transforms what the log groups it SELECTS ingest, the
/// groups it does not select ingest untransformed, and a group that carries its own transformer
/// is transformed by that one: "if a log group has both an account-level transformer and a
/// log-group level transformer, the log-group level transformer is used".
#[tokio::test]
async fn an_account_level_transformer_policy_transforms_the_groups_it_selects() {
    let logs = Logs::new();
    // The policy's processors structure the message under one prefix; the group-level
    // transformer of one of those groups renames what they produced, so which transformer ran
    // is readable off the fields of the stored event.
    let document = json!([
        {"parseKeyValue": {"fieldDelimiter": "&", "keyValueDelimiter": "="}},
    ])
    .to_string();
    logs.ok(
        "PutAccountPolicy",
        &put_body(
            "ingest-transformer",
            "TRANSFORMER_POLICY",
            &document,
            Some(r#"LogGroupNamePrefix IN ["/transformer-policy/"]"#),
        ),
    )
    .await;

    const SELECTED: &str = "/transformer-policy/selected";
    const OWN: &str = "/transformer-policy/own-transformer";
    const OUTSIDE: &str = "/outside/not-selected";
    for group in [SELECTED, OWN, OUTSIDE] {
        group_with_stream(&logs, group, STREAM, None).await;
    }
    logs.ok(
        PUT_TRANSFORMER,
        &json!({
            "logGroupIdentifier": OWN,
            "transformerConfig": [
                {"parseKeyValue": {"fieldDelimiter": "&", "keyValueDelimiter": "=", "keyPrefix": "kv_"}},
            ],
        }),
    )
    .await;

    let message = "action=login&user=amy";
    // (case, the group, the fields its stored event must carry, the fields it must not)
    let rows: [(&str, &str, &[&str], &[&str]); 3] = [
        (
            "a group the policy selects",
            SELECTED,
            &["action", "user"],
            &["kv_action"],
        ),
        (
            "a group carrying its own transformer",
            OWN,
            &["kv_action", "kv_user"],
            &["action"],
        ),
        (
            "a group the policy does not select",
            OUTSIDE,
            &[],
            &["action", "kv_action"],
        ),
    ];
    for (case, group, carried, absent) in rows {
        ingest_one(&logs, group, message).await;
        let reported = reported_fields(&logs, case, group).await;
        for field in carried {
            assert!(
                reported.contains(*field),
                "case {case:?}: the stored event carries {field}, got {reported:?}"
            );
        }
        for field in absent {
            assert!(
                !reported.contains(*field),
                "case {case:?}: the stored event carries no {field}, got {reported:?}"
            );
        }
    }
}
