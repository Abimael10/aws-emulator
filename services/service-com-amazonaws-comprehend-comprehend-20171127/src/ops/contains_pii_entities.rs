//! @op ContainsPiiEntities
//!
//! Analyses the submitted document for personally identifiable information and
//! answers the LABELS — the PII entity types — it carries.
//!
//! ## How the document is analysed
//!
//! The recognizer in this module places PII entities in a document by matching the
//! published FORM of each entity type and, where the defining standard gives the
//! value a check digit, verifying it. Every label this operation returns therefore
//! comes from something the recognizer found in the text, at a known offset: a
//! document with no recognisable PII answers an empty `Labels` list rather than a
//! verdict nothing computed.
//!
//! [`detect_pii_spans`] is that recognizer, and it is the ONE place the entity rules
//! live. The kinds with no closed form of their own — a personal name, the place name
//! an address is written with — come from the service's own recogniser of what a
//! document names (`crate::ops::detect_entities::pii_bearing_spans`), so this family
//! and `DetectEntities` cannot disagree. Each span carries the confidence ITS OWN
//! evidence leaves, never a constant of the rule class that found it, and this
//! operation combines the spans of one type into the confidence that the document
//! CONTAINS that type ([`labels_of`]), which is the detection its `Labels` are about —
//! a coarser question than any one span's, which a whole value of the type answers and
//! a component of one does not put in the label set at all.
//! `DetectPiiEntities` projects the same spans into `PiiEntity` values, so the two
//! operations agree by construction.
//!
//! ## Shape of an operation
//!
//! Each operation is a struct that owns the shared engine and implements
//! [`smithy_server_runtime::Operation`]. The framework constructs one per service via
//! `ContainsPiiEntities::new(engine)` and drives it through the centralized request walk:
//! deserialize → validate → `handle` → serialize. You write ONLY the `handle` body.
//!
//! This operation holds NO state: its answer is a function of `Text` and
//! `LanguageCode` alone, so repeating a call returns the same labels and nothing a
//! later caller reads is changed by one. The recognizer is synchronous, CPU-bound
//! work with no await of its own, so [`recognize_pii`] runs it OFF the async worker
//! under a wall-clock budget: the request has a real await point, so it stays
//! cancellable and timeout-able, and a burst of concurrent documents cannot starve
//! the operations sharing the runtime.
//!
//! @generated by the emulator core scaffold op-stub generator.
//! Shared types live in `super::types`; the error channel in `crate::scaffolded`.
//!
//! ---
//!
//! # Modeled contract for `ContainsPiiEntities`
//!
//! What AWS documents for this operation, from this service's Smithy model. HTML is
//! stripped and long entries are clipped at ` …`. For the FULL text of any one item,
//! ask the model rather than reading the raw JSON:
//!
//! ```text
//! smithy_query(query="doc",shape="<Shape>",member="<Member>",model_path="services/service-com-amazonaws-comprehend-comprehend-20171127/smithy-model/com-amazonaws-comprehend-comprehend-20171127.json")
//! ```
//!
//! Analyzes input text for the presence of personally identifiable information (PII) and
//! returns the labels of identified PII entity types such as name, address, bank account
//! number, or phone number.
//!
//! ## Input
//!
//! * `LanguageCode` (LanguageCode, one of: ar | de | en | es | fr | hi | it | ja | ko | pt |
//!   zh | zh-TW) **required** — The language of the input documents.
//! * `Text` (String, len 1..) **required** — A UTF-8 text string. The maximum string size is
//!   100 KB.
//!
//! ## Output
//!
//! * `Labels` (ListOfEntityLabels) — The labels used in the document being analyzed.
//!   Individual labels represent personally identifiable information (PII) entity types.
//!
//! ## Errors
//!
//! * `InternalServerException` (HTTP 500) — An internal server error occurred. Retry your
//!   request.
//! * `InvalidRequestException` (HTTP 400) — The request is invalid.
//! * `TextSizeLimitExceededException` (HTTP 400) — The size of the input text exceeds the
