/// The most matches the recognizer collects from one document FOR ONE RULE.
///
/// The EMULATOR's bound, not an AWS one: it exists so no document can grow the
/// recognizer's working set — or the work the overlap sweep does — without limit.
/// It is PER RULE, so saturating it can never hide an entity type: every rule gets
/// its own budget and runs whatever the rules before it found. It is also far above
/// the per-type entity count of any realistic document, and matches past it are
/// dropped rather than refused, because what the operation answers is a SET of types
/// and the type is already in it by the first match.
pub const MAX_MATCHES_PER_RULE: usize = 1_000;

/// A match while its offsets are still the byte offsets the matcher reported.
///
/// Byte offsets are translated to the character offsets [`PiiSpan`] carries in ONE
/// pass over the document, once the surviving spans are known — rather than by
/// re-walking the document prefix per match, which would make the cost of a request
/// quadratic in the size of its document.
struct ByteSpan {
    entity_type: &'static str,
    evidence: Evidence,
    begin: usize,
    end: usize,
    /// Characters of the document's own label for the value that the rule's match
    /// spanned beside it: zero for a rule whose pattern IS the value.
    label_chars: usize,
    /// The confidence the service's own entity recogniser already computed for this
    /// span, for a mention IT placed rather than a rule here. One recognition, one
    /// confidence: a name is reported with the confidence it was recognised with.
    recognised: Option<f32>,
    /// Whether the span is a COMPLETE value of its type rather than a component of
    /// one. See [`PiiSpan::complete`].
    complete: bool,
}

/// Place every PII entity this service's recognizer can find in `text`.
///
/// Spans are returned in document order and never overlap: where two rules claim
/// overlapping text the one with the stronger evidence wins, then the longer span,
/// then the earlier one — so an e-mail address is never also reported as the URL its
/// host alone would have made it. The one reading that outranks evidence strength is
/// the document's own: a value the surrounding text LABELS keeps the type the label
/// names, against a rule that claimed exactly the same characters on their form or
/// issuance range alone.
///
/// The cost is linear in the document plus `k log k` in the number of matches, and
/// each rule collects at most [`MAX_MATCHES_PER_RULE`] of them, so the work one
/// document can ask for is bounded for every caller — not only for the operation,
/// which also refuses a document over its documented byte ceiling before calling
/// this. A caller that needs every span (rather than the set of types) must treat
/// the returned list as TRUNCATED at that budget for any one rule.
///
/// This is the ONE recognizer for Comprehend's PII family: `ContainsPiiEntities`
/// projects these spans into the distinct set of types, and `DetectPiiEntities`
/// projects the same spans into `PiiEntity` values, so the two operations
/// cannot disagree. Every REQUEST-time caller runs it through [`recognize_pii`],
/// which keeps the scan off the async worker; this function itself stays available
/// to a pass that already yields of its own accord.
pub fn detect_pii_spans(text: &str) -> Vec<PiiSpan> {
    let mut matched: Vec<ByteSpan> = Vec::new();
    for rule in rules() {
        let mut collected = 0usize;
        for captures in rule.pattern.captures_iter(text) {
            if collected >= MAX_MATCHES_PER_RULE {
                // This rule's budget is spent; the rules after it keep theirs.
                break;
            }
            let Some(found) = captures.get(rule.group) else {
                continue;
            };
            if found.start() >= found.end() {
                continue;
            }
            if rule.validate.is_some_and(|check| !check(found.as_str())) {
                continue;
            }
            collected += 1;
            matched.push(ByteSpan {
                entity_type: rule.entity_type,
                evidence: rule.evidence,
                begin: found.start(),
                end: found.end(),
                // What the rule matched AROUND the value: for a contextual rule
                // that is the document's own label for it, which is evidence about
                // this value. A rule whose pattern is the value itself spans
                // nothing else, so it carries none.
                label_chars: captures
                    .get(0)
                    .map_or(0, |whole| whole.as_str().chars().count())
                    .saturating_sub(found.as_str().chars().count()),
                recognised: None,
                // A rule's pattern IS a value of its type, written out: a mail
                // address, a checksummed number, the whole address line.
                complete: true,
            });
        }
    }

    // A mention of a kind that has no closed form to match: a personal NAME the
    // document does not introduce with a courtesy title or a name field ("Contact
    // John Smith at …"), and a place name, which the modelled `ADDRESS` type covers
    // as a component of a physical address ("can include a street, building,
    // location, city, state, country, county, zip, precinct, neighborhood"). What
    // places either is the service's ONE recogniser of the things a document names
    // (`crate::ops::detect_entities::pii_bearing_spans`) — the same evidence
    // `DetectEntities` types a PERSON or a LOCATION on — rather than a narrower rule
    // here, so the two operations cannot disagree about what a document names, and
    // each is reported with the confidence THAT recognition carries. The evidence
    // class is `Context` for the reason the rules above carry it: what admits the
    // value is the text around it, not a form or a check digit of its own, and the
    // recogniser also says which of the two is a WHOLE value of its type. Where a
    // rule above claimed a wider span over the same characters — the street-address
    // rule over the whole address line — the overlap sweep below keeps the wider one.
    for (span, entity_type, confidence, extent) in
        crate::ops::detect_entities::pii_bearing_spans(text)
    {
        matched.push(ByteSpan {
            entity_type,
            evidence: Evidence::Context,
            begin: span.start,
            end: span.end,
            label_chars: 0,
            recognised: Some(confidence),
            complete: extent == crate::ops::detect_entities::PiiExtent::WholeValue,
        });
    }

    // A value the document itself NAMES is of the type the document names: where a
    // contextual rule (one admitted by the label beside the value) and a rule that
    // read the value's form or issuance range alone claim exactly the same
    // characters and disagree about the type, the labelled reading is the one kept.
    // The surrounding label is evidence about THIS value; a form or a range is
    // evidence about values of a kind, and cannot overrule a document that says what
    // its own value is. Rules that AGREE with the label are left alone, so a value
    // that is both labelled and structurally confirmed keeps the stronger evidence's
    // score.
    let mut labelled: BTreeMap<(usize, usize), BTreeSet<&'static str>> = BTreeMap::new();
    for span in matched.iter().filter(|span| span.evidence == Evidence::Context) {
        labelled
            .entry((span.begin, span.end))
            .or_default()
            .insert(span.entity_type);
    }
    matched.retain(|span| {
        span.evidence == Evidence::Context
            || labelled
                .get(&(span.begin, span.end))
                .is_none_or(|types| types.contains(span.entity_type))
    });

    // Strongest evidence first, then the longest span, then document order: the
    // order the overlap sweep below resolves a conflict in.
    matched.sort_by(|left, right| {
        evidence_rank(right.evidence)
            .cmp(&evidence_rank(left.evidence))
            .then((right.end - right.begin).cmp(&(left.end - left.begin)))
            .then(left.begin.cmp(&right.begin))
            .then(left.entity_type.cmp(right.entity_type))
    });

    // The spans kept so far, indexed by their begin offset. They are pairwise
    // non-overlapping, so a candidate overlaps one of them exactly when the nearest
    // span starting at or before it reaches past its begin, or the nearest span
    // starting after it begins before its end — two ordered-map lookups rather than
    // a scan of everything kept.
    let mut kept_by_begin: BTreeMap<usize, usize> = BTreeMap::new();
    let mut kept: Vec<ByteSpan> = Vec::new();
    for span in matched {
        let overlaps_before = kept_by_begin
            .range(..=span.begin)
            .next_back()
            .is_some_and(|(_, end)| *end > span.begin);
        let overlaps_after = kept_by_begin
            .range(span.begin..)
            .next()
            .is_some_and(|(begin, _)| *begin < span.end);
        if overlaps_before || overlaps_after {
            continue;
        }
        kept_by_begin.insert(span.begin, span.end);
        kept.push(span);
    }
    kept.sort_by(|left, right| {
        left.begin
            .cmp(&right.begin)
            .then(left.entity_type.cmp(right.entity_type))
    });

    // One walk of the document translates every surviving offset at once.
    let mut byte_offsets: Vec<usize> = kept
        .iter()
        .flat_map(|span| [span.begin, span.end])
        .collect();
    byte_offsets.sort_unstable();
    byte_offsets.dedup();
    let character_offsets = char_offsets(text, &byte_offsets);
    let translate = |byte_offset: usize| {
        byte_offsets
            .binary_search(&byte_offset)
            .map_or(byte_offset, |index| character_offsets[index])
    };

    // What the REST of the document says about each detection: a value the document
    // writes again, read the same way, corroborates the reading. Counted in one pass
    // over the surviving spans, so the weighing stays linear in the number of
    // detections however many a document carries, and the count is a property of the
    // document — every writing of the value carries the same one.
    let mut writings: BTreeMap<(&str, &str), usize> = BTreeMap::new();
    for span in &kept {
        *writings
            .entry((&text[span.begin..span.end], span.entity_type))
            .or_default() += 1;
    }

    kept.into_iter()
        .map(|span| {
            let value = &text[span.begin..span.end];
            let repeats = writings
                .get(&(value, span.entity_type))
                .copied()
                .unwrap_or(1)
                .saturating_sub(1);
            let score = span.recognised.unwrap_or_else(|| {
                let mut reading = reading_of(span.evidence, value, span.label_chars);
                reading.support += EVIDENCE_PER_CORROBORATING_OCCURRENCE * repeats as f64;
                reading.confidence()
            });
            PiiSpan {
                entity_type: span.entity_type,
                evidence: span.evidence,
                complete: span.complete,
                score,
                begin: translate(span.begin),
                end: translate(span.end),
            }
        })
        .collect()
}

/// [`detect_pii_spans`] run OFF the async worker: the recognizer is synchronous,
/// CPU-bound work with no await of its own, so it goes to the blocking pool and the
/// worker serving this request is released while it runs. The
/// `spawn_blocking(..).await` is a real await point, so a request waiting on a scan
/// can be cancelled or timed out, and a burst of concurrent documents cannot starve
/// the operations sharing the runtime.
///
/// `Err` carries the sentence the caller puts in its OWN modelled server error: the
/// scan either did not answer inside [`RECOGNITION_TIME_BUDGET`] — the budget bounds
/// the caller's wait, not the blocking task, which runs to its natural end — or did
/// not run at all, and in both cases nothing was analysed, so no labels may be
/// fabricated for it.
pub(crate) async fn recognize_pii(text: String) -> Result<Vec<PiiSpan>, String> {
    match ::tokio::time::timeout(
        RECOGNITION_TIME_BUDGET,
        ::tokio::task::spawn_blocking(move || detect_pii_spans(&text)),
    )
    .await
    {
        Ok(Ok(spans)) => Ok(spans),
        Ok(Err(error)) => Err(format!("the PII analysis did not complete: {error}")),
        Err(_) => Err(format!(
            "the PII analysis did not complete within {} seconds",
            RECOGNITION_TIME_BUDGET.as_secs()
        )),
    }
}

/// How strong an evidence class is, for the overlap sweep.
fn evidence_rank(evidence: Evidence) -> u8 {
    match evidence {
        Evidence::Validated => 2,
        Evidence::Format => 1,
        Evidence::Context => 0,
    }
}

/// The zero-based CHARACTER offsets — the scale the modelled PII offsets use — of
/// the ASCENDING byte offsets `wanted`, answered position for position.
///
/// One pass over the document for the whole batch, so translating the offsets of a
/// document costs the document once however many entities it carries.
fn char_offsets(text: &str, wanted: &[usize]) -> Vec<usize> {
    let mut answers: Vec<usize> = Vec::with_capacity(wanted.len());
    let mut characters_seen = 0usize;
    for (byte_index, _) in text.char_indices() {
        while answers.len() < wanted.len() && wanted[answers.len()] <= byte_index {
            answers.push(characters_seen);
        }
        characters_seen += 1;
    }
    // Anything left asks for the end of the document (a span's exclusive end), which
    // is one past its last character.
    while answers.len() < wanted.len() {
        answers.push(characters_seen);
    }
    answers
}

/// The decimal digits of `value`, with any separator dropped.
fn digits_of(value: &str) -> Vec<u32> {
    value.chars().filter_map(|c| c.to_digit(10)).collect()
}

/// Whether `value` parses as an IPv4 or IPv6 address.
fn is_ip_address(value: &str) -> bool {
    value.parse::<IpAddr>().is_ok()
}

/// The Luhn check of ISO/IEC 7812-1: doubling every second digit from the right and
/// casting out nines leaves a multiple of ten.
fn is_luhn_valid(value: &str) -> bool {
    let digits = digits_of(value);
    if digits.len() < 2 {
        return false;
    }
    let sum: u32 = digits
        .iter()
        .rev()
        .enumerate()
        .map(|(index, digit)| {
            if index % 2 == 1 {
                let doubled = digit * 2;
                if doubled > 9 {
                    doubled - 9
                } else {
                    doubled
                }
            } else {
                *digit
            }
        })
        .sum();
    sum.is_multiple_of(10)
}

/// A payment card number: a 13-19 digit primary account number (ISO/IEC 7812-1)
/// whose last digit is its Luhn check digit.
fn is_payment_card_number(value: &str) -> bool {
    let digits = digits_of(value);
    (13..=19).contains(&digits.len()) && is_luhn_valid(value)
}

/// A US Social Security number, by the SSA's published issuance rules: the area is
/// never 000, 666 or 900-999, the group is never 00 and the serial is never 0000.
fn is_social_security_number(value: &str) -> bool {
    let digits = digits_of(value);
    if digits.len() != 9 {
        return false;
    }
    let number = |slice: &[u32]| slice.iter().fold(0u32, |acc, digit| acc * 10 + digit);
    let area = number(&digits[0..3]);
    let group = number(&digits[3..5]);
    let serial = number(&digits[5..9]);
    area != 0 && area != 666 && area < 900 && group != 0 && serial != 0
}

/// A US Individual Taxpayer Identification Number, by the IRS's published form: nine
/// digits beginning with 9 whose middle pair falls in 50-65, 70-88, 90-92 or 94-99.
fn is_individual_tax_identification_number(value: &str) -> bool {
    let digits = digits_of(value);
    if digits.len() != 9 || digits[0] != 9 {
        return false;
    }
    let group = digits[3] * 10 + digits[4];
    (50..=65).contains(&group)
        || (70..=88).contains(&group)
        || (90..=92).contains(&group)
        || (94..=99).contains(&group)
}

/// An ABA routing transit number: nine digits whose 3-7-1 weighted sum is a multiple
/// of ten.
fn is_aba_routing_number(value: &str) -> bool {
    let digits = digits_of(value);
    if digits.len() != 9 {
        return false;
    }
    const WEIGHTS: [u32; 9] = [3, 7, 1, 3, 7, 1, 3, 7, 1];
    let sum: u32 = digits
        .iter()
        .zip(WEIGHTS)
        .map(|(digit, weight)| digit * weight)
        .sum();
    sum.is_multiple_of(10)
}

/// An NHS number: ten digits whose first nine, weighted 10 down to 2, leave a
/// mod-11 check digit equal to the tenth. A remainder of ten makes the number
/// invalid, which is why NHS numbers never carry that check digit.
fn is_nhs_number(value: &str) -> bool {
    let digits = digits_of(value);
    if digits.len() != 10 {
        return false;
    }
    let sum: u32 = digits[..9]
        .iter()
        .enumerate()
        .map(|(index, digit)| digit * (10 - index as u32))
        .sum();
    let remainder = 11 - (sum % 11);
    let check = match remainder {
        11 => 0,
        10 => return false,
        other => other,
    };
    check == digits[9]
}

/// An IBAN, by ISO 13616: move the country code and check digits to the end, map
/// each letter to its position value plus nine, and the whole number is 1 mod 97.
fn is_iban(value: &str) -> bool {
    let compact: String = value.chars().filter(|c| c.is_ascii_alphanumeric()).collect();
    if !(15..=34).contains(&compact.len()) {
        return false;
    }
    let rearranged: String = compact[4..].chars().chain(compact[..4].chars()).collect();
    let mut remainder: u32 = 0;
    for character in rearranged.chars() {
        let value = if let Some(digit) = character.to_digit(10) {
            digit
        } else if character.is_ascii_uppercase() {
            character as u32 - 'A' as u32 + 10
        } else {
            return false;
        };
        // Fold digit by digit so the number never has to be held whole.
        remainder = if value > 9 {
            (remainder * 100 + value) % 97
        } else {
            (remainder * 10 + value) % 97
        };
    }
    remainder == 1
}

/// A vehicle identification number, by ISO 3779 / 49 CFR 565: the transliterated
/// characters weighted 8,7,6,5,4,3,2,10,0,9,8,7,6,5,4,3,2 leave a mod-11 check that
/// position nine carries, as a digit or as `X` for ten.
fn is_vehicle_identification_number(value: &str) -> bool {
    const WEIGHTS: [u32; 17] = [8, 7, 6, 5, 4, 3, 2, 10, 0, 9, 8, 7, 6, 5, 4, 3, 2];
    let characters: Vec<char> = value.chars().collect();
    if characters.len() != 17 {
        return false;
    }
    let mut sum = 0;
    for (index, character) in characters.iter().enumerate() {
        let transliterated = match character {
            '0'..='9' => character.to_digit(10).unwrap_or_default(),
            'A' | 'J' => 1,
            'B' | 'K' | 'S' => 2,
            'C' | 'L' | 'T' => 3,
            'D' | 'M' | 'U' => 4,
            'E' | 'N' | 'V' => 5,
            'F' | 'W' => 6,
            'G' | 'P' | 'X' => 7,
            'H' | 'Y' => 8,
            'R' | 'Z' => 9,
            _ => return false,
        };
        sum += transliterated * WEIGHTS[index];
    }
    let check = sum % 11;
    match characters[8] {
        'X' => check == 10,
        digit => digit.to_digit(10).is_some_and(|value| value == check),
    }
}

