//! What a custom domain name PRESENTS on the address it publishes, end to end in one
//! process: the TLS handshake on that address, the certificate the handshake presents, and
//! what a rotation of that certificate changes.
//!
//! The rule these cases assert, one level above the recorded case (one domain name, one
//! imported certificate, one rotation):
//!
//! > The address a custom domain name publishes
//! > (`DomainNameConfiguration$ApiGatewayDomainName`) is one a client DIALS, and the front
//! > door on it terminates TLS under the Certificate Manager certificate the record's
//! > `DomainNameConfigurations` name — "an AWS-managed certificate that will be used by the
//! > endpoint for this domain name. AWS Certificate Manager is the only supported source"
//! > (`DomainNameConfiguration$CertificateArn`) — choosing among the certificates the record
//! > names by the server name the `ClientHello` asked for (RFC 6066 §3) and falling back to
//! > the first one, under a TLS version at or above the record's `SecurityPolicy`. The
//! > certificate is read PER HANDSHAKE, so an `UpdateDomainName` that swaps the
//! > `CertificateArn` swaps the leaf presented on the next handshake while the published
//! > address stays the same.
//!
//! Nothing here is staged in a store: every certificate is minted by `rcgen` (something
//! other than the code under test), brought in through Certificate Manager's OWN
//! `ImportCertificate` over the in-process callback, and the client is a real `rustls`
//! client that dials the published address in this process — so the leaf asserted on is the
//! one that travelled over the wire, byte for byte.
//!
//! The rows span what the selection generalises over: the name asked for (the domain name
//! itself, a name a LATER entry of the list covers, one label under a WILDCARD entry, a name
//! no entry covers, and no name at all), whether the imported material carries a chain, and
//! the certificate a rotation moves the record to.
//!
//! The control-plane surface of a domain name is not restated here: `domain_name_lifecycle`
//! owns it, `domain_name_tls_preconditions` owns the policy and mutual-TLS preconditions (and
//! the harness this suite drives), and `custom_domain_mapping_invoke` owns which stage a
//! request made on the address is served by.

use std::sync::Arc;
use std::time::Duration;

use serde_json::{json, Value};
use tokio::io::{AsyncReadExt as _, AsyncWriteExt as _};

use crate::api_lifecycle::call_in_region;
use crate::domain_name_tls_preconditions::{emulator_with_certificates, Emulator, REGION};

/// How long one case gives one dial, one handshake and one exchange — all of it inside this
/// process. Generous for a loaded machine, and bounded so a case that will never be answered
/// fails instead of hanging the suite.
const EXCHANGE_TIMEOUT: Duration = Duration::from_secs(30);

/// How long a case waits for the status a rotation moves the record through to settle, and
/// how often it looks again. The CONDITION is what is waited for; the deadline only bounds
/// the wait.
const SETTLED_DEADLINE: Duration = Duration::from_secs(60);
const LOOK_AGAIN: Duration = Duration::from_millis(50);

/// The status and sentence the domain name's front door turns a request away with when no api
/// mapping of it answers the path — every case here maps none, so every request is answered
/// this way once its handshake completed.
const NO_MAPPING: &str = "HTTP/1.1 403";
const NO_MAPPING_MESSAGE: &str = "Forbidden";

/// The `DomainNameStatus` a settled record reports.
const AVAILABLE: &str = "AVAILABLE";

// ---------------------------------------------------------------------------
// Real certificates, brought in through the service that owns them
// ---------------------------------------------------------------------------

/// A certificate authority a case signs a leaf with, so the material a case imports can
/// carry a CHAIN as well as a leaf.
struct Authority {
    certificate: rcgen::Certificate,
    key: rcgen::KeyPair,
}

/// A real CA certificate, generated by `rcgen`.
fn authority(name: &str) -> Authority {
    let key = rcgen::KeyPair::generate().expect("a key pair");
    let mut params =
        rcgen::CertificateParams::new(vec![name.to_string()]).expect("certificate parameters");
    params.is_ca = rcgen::IsCa::Ca(rcgen::BasicConstraints::Unconstrained);
    params.key_usages = vec![
        rcgen::KeyUsagePurpose::KeyCertSign,
        rcgen::KeyUsagePurpose::CrlSign,
        rcgen::KeyUsagePurpose::DigitalSignature,
    ];
    let certificate = params.self_signed(&key).expect("a self-signed CA");
    Authority { certificate, key }
}

/// One certificate a case brings in: the material a client imports, and the DER of the leaf,
/// which is what the presented certificate is compared against.
struct Minted {
    certificate_pem: String,
    private_key_pem: String,
    chain_pem: Option<String>,
    der: Vec<u8>,
}

/// A real leaf covering `names`, signed by `signer` when there is one and self-signed
/// otherwise — the two shapes of material a caller imports (with a chain, and without one).
fn mint(names: &[&str], signer: Option<&Authority>) -> Minted {
    let key = rcgen::KeyPair::generate().expect("a key pair");
    let owned: Vec<String> = names.iter().map(|name| (*name).to_string()).collect();
    let mut params = rcgen::CertificateParams::new(owned).expect("certificate parameters");
    let mut subject = rcgen::DistinguishedName::new();
    subject.push(
        rcgen::DnType::CommonName,
        *names.first().expect("a certificate covers a name"),
    );
    params.distinguished_name = subject;
    let (certificate, chain_pem) = match signer {
        None => (
            params.self_signed(&key).expect("a self-signed leaf"),
            None,
        ),
        Some(signer) => (
            params
                .signed_by(&key, &signer.certificate, &signer.key)
                .expect("a leaf signed by the authority"),
            Some(signer.certificate.pem()),
        ),
    };
    Minted {
        certificate_pem: certificate.pem(),
        private_key_pem: key.serialize_pem(),
        chain_pem,
        der: certificate.der().to_vec(),
    }
}

/// Import `minted` through Certificate Manager's OWN `ImportCertificate`, answering the ARN
/// it was stored under — the ARN a custom domain name's configuration then names.
async fn import(emulator: &Emulator, case: &str, minted: &Minted) -> String {
    let mut request = emulator
        .certificates
        .import_certificate()
        .certificate(::aws_smithy_types::Blob::new(
            minted.certificate_pem.clone().into_bytes(),
        ))
        .private_key(::aws_smithy_types::Blob::new(
            minted.private_key_pem.clone().into_bytes(),
        ));
    if let Some(chain) = minted.chain_pem.as_ref() {
        request = request.certificate_chain(::aws_smithy_types::Blob::new(
            chain.clone().into_bytes(),
        ));
    }
    let answer = request
        .send()
        .await
        .unwrap_or_else(|error| panic!("case {case:?}: ImportCertificate must succeed: {error:?}"));
    answer
        .certificate_arn()
        .unwrap_or_else(|| panic!("case {case:?}: ImportCertificate must answer the ARN it stored"))
        .to_string()
}

// ---------------------------------------------------------------------------
// The custom domain name, and the address it publishes
// ---------------------------------------------------------------------------

/// `CreateDomainName` for `domain` naming `certificate_arns` as its configuration entries,
/// answering the address the record published.
///
/// The published member exists for a client to DIAL, so what it answers has to be an address
/// this machine can open a connection to.
async fn created_domain(
    emulator: &Emulator,
    case: &str,
    domain: &str,
    certificate_arns: &[&str],
) -> String {
    let configurations: Vec<Value> = certificate_arns
        .iter()
        .map(|arn| json!({ "certificateArn": arn }))
        .collect();
    let (status, created) = call_in_region(
        &emulator.router,
        REGION,
        "POST",
        "/v2/domainnames",
        Some(json!({
            "domainName": domain,
            "domainNameConfigurations": configurations
        })),
    )
    .await;
    assert_eq!(
        status, 201,
        "case {case:?}: CreateDomainName must answer 201, got {status} {created}"
    );
    let published = published_address(&created);
    assert!(
        published.parse::<std::net::SocketAddr>().is_ok(),
        "case {case:?}: expected an address a client can dial, got {published:?}"
    );
    published
}

/// The `ApiGatewayDomainName` a `DomainName` answer publishes, which every configuration
/// entry of one record carries.
fn published_address(record: &Value) -> String {
    record
        .pointer("/domainNameConfigurations/0/apiGatewayDomainName")
        .and_then(Value::as_str)
        .unwrap_or_default()
        .to_string()
}

/// `GetDomainName` for `domain`, looked at again until every configuration entry reports
/// [`AVAILABLE`] — the status under which "the domain can be updated" — or the deadline
/// passes. Answers the record read back.
async fn settled(emulator: &Emulator, case: &str, domain: &str) -> Value {
    let deadline = std::time::Instant::now() + SETTLED_DEADLINE;
    loop {
        let (status, record) = call_in_region(
            &emulator.router,
            REGION,
            "GET",
            &format!("/v2/domainnames/{domain}"),
            None,
        )
        .await;
        assert_eq!(
            status, 200,
            "case {case:?}: GetDomainName must answer 200, got {status} {record}"
        );
        let statuses: Vec<String> = record
            .pointer("/domainNameConfigurations")
            .and_then(Value::as_array)
            .map(|entries| {
                entries
                    .iter()
                    .map(|entry| {
                        entry
                            .get("domainNameStatus")
                            .and_then(Value::as_str)
                            .unwrap_or_default()
                            .to_string()
                    })
                    .collect()
            })
            .unwrap_or_default();
        if !statuses.is_empty() && statuses.iter().all(|reported| reported == AVAILABLE) {
            return record;
        }
        assert!(
            std::time::Instant::now() < deadline,
            "case {case:?}: expected every endpoint to reach {AVAILABLE}, got {statuses:?}"
        );
        tokio::time::sleep(LOOK_AGAIN).await;
    }
}

// ---------------------------------------------------------------------------
// The client that dials the published address
// ---------------------------------------------------------------------------

/// What one exchange on a published address observed.
struct Presented {
    /// The leaf the front door presented, as it travelled on the wire.
    leaf: Vec<u8>,
    /// The TLS version the handshake negotiated.
    version: Option<rustls::ProtocolVersion>,
    /// Everything the front door then answered the request with.
    answer: String,
}

/// Dial `published`, complete a TLS handshake asking for `server_name` (or asking for no name
/// at all, which is what a client dialling an address itself does), send one request carrying
/// `host`, and read the answer.
async fn tls_exchange(
    case: &str,
    published: &str,
    server_name: Option<&str>,
    host: &str,
) -> Presented {
    let port = published
        .parse::<std::net::SocketAddr>()
        .unwrap_or_else(|error| {
            panic!("case {case:?}: the published address {published:?} is no address: {error}")
        })
        .port();
    let conn = tokio::time::timeout(
        EXCHANGE_TIMEOUT,
        tokio::net::TcpStream::connect((std::net::Ipv4Addr::LOCALHOST, port)),
    )
    .await
    .unwrap_or_else(|_| panic!("case {case:?}: {published} did not accept a connection"))
    .unwrap_or_else(|error| panic!("case {case:?}: {published} refused a connection: {error}"));
    let asked_for = match server_name {
        Some(name) => rustls::pki_types::ServerName::try_from(name.to_string())
            .unwrap_or_else(|error| panic!("case {case:?}: {name} is no server name: {error}")),
        None => rustls::pki_types::ServerName::from(std::net::Ipv4Addr::LOCALHOST),
    };
    let connector = tokio_rustls::TlsConnector::from(client_config());
    let mut stream = tokio::time::timeout(EXCHANGE_TIMEOUT, connector.connect(asked_for, conn))
        .await
        .unwrap_or_else(|_| panic!("case {case:?}: the handshake did not complete in time"))
        .unwrap_or_else(|error| panic!("case {case:?}: the handshake must complete: {error}"));
    let leaf = stream
        .get_ref()
        .1
        .peer_certificates()
        .and_then(|chain| chain.first().map(|leaf| leaf.as_ref().to_vec()))
        .unwrap_or_else(|| panic!("case {case:?}: the front door presented no certificate"));
    let version = stream.get_ref().1.protocol_version();
    let request = format!("GET / HTTP/1.1\r\nHost: {host}\r\nConnection: close\r\n\r\n");
    stream
        .write_all(request.as_bytes())
        .await
        .unwrap_or_else(|error| panic!("case {case:?}: the request was not sent: {error}"));
    let mut answered = Vec::new();
    tokio::time::timeout(EXCHANGE_TIMEOUT, stream.read_to_end(&mut answered))
        .await
        .unwrap_or_else(|_| panic!("case {case:?}: the address did not answer in time"))
        .unwrap_or_else(|error| panic!("case {case:?}: the answer was not read: {error}"));
    Presented {
        leaf,
        version,
        answer: String::from_utf8_lossy(&answered).to_string(),
    }
}

/// The client-side TLS configuration every case dials with.
///
/// The server-certificate verifier ACCEPTS whatever is presented and the certificate itself
/// is asserted on afterwards, byte for byte: what is under test is WHICH certificate the
/// front door presents, and a client that refused an unexpected one would report a handshake
/// failure instead of naming the certificate it got.
fn client_config() -> Arc<rustls::ClientConfig> {
    let provider = Arc::new(rustls::crypto::aws_lc_rs::default_provider());
    Arc::new(
        rustls::ClientConfig::builder_with_provider(Arc::clone(&provider))
            .with_safe_default_protocol_versions()
            .expect("the provider supports the default protocol versions")
            .dangerous()
            .with_custom_certificate_verifier(Arc::new(AssertedAfterwards(provider)))
            .with_no_client_auth(),
    )
}

/// See [`client_config`].
#[derive(Debug)]
struct AssertedAfterwards(Arc<rustls::crypto::CryptoProvider>);

impl rustls::client::danger::ServerCertVerifier for AssertedAfterwards {
    fn verify_server_cert(
        &self,
        _end_entity: &rustls::pki_types::CertificateDer<'_>,
        _intermediates: &[rustls::pki_types::CertificateDer<'_>],
        _server_name: &rustls::pki_types::ServerName<'_>,
        _ocsp_response: &[u8],
        _now: rustls::pki_types::UnixTime,
    ) -> Result<rustls::client::danger::ServerCertVerified, rustls::Error> {
        Ok(rustls::client::danger::ServerCertVerified::assertion())
    }

    fn verify_tls12_signature(
        &self,
        message: &[u8],
        cert: &rustls::pki_types::CertificateDer<'_>,
        dss: &rustls::DigitallySignedStruct,
    ) -> Result<rustls::client::danger::HandshakeSignatureValid, rustls::Error> {
        rustls::crypto::verify_tls12_signature(
            message,
            cert,
            dss,
            &self.0.signature_verification_algorithms,
        )
    }

    fn verify_tls13_signature(
        &self,
        message: &[u8],
        cert: &rustls::pki_types::CertificateDer<'_>,
        dss: &rustls::DigitallySignedStruct,
    ) -> Result<rustls::client::danger::HandshakeSignatureValid, rustls::Error> {
        rustls::crypto::verify_tls13_signature(
            message,
            cert,
            dss,
            &self.0.signature_verification_algorithms,
        )
    }

    fn supported_verify_schemes(&self) -> Vec<rustls::SignatureScheme> {
        self.0.signature_verification_algorithms.supported_schemes()
    }
}

/// The versions a record on this service's enforced security policy may negotiate: that
/// policy is a FLOOR, and these are the versions at or above it this emulator's TLS
/// implementation completes a handshake under.
fn at_or_above_the_floor() -> [Option<rustls::ProtocolVersion>; 2] {
    [
        Some(rustls::ProtocolVersion::TLSv1_2),
        Some(rustls::ProtocolVersion::TLSv1_3),
    ]
}

/// Assert the answer that reached the client past the handshake: no api mapping exists, so the
/// front door turns the request away with its own refusal — which is also what proves the
/// tunnel carried HTTP at all.
fn assert_answered_without_a_mapping(case: &str, presented: &Presented) {
    assert!(
        presented.answer.starts_with(NO_MAPPING)
            && presented.answer.contains(NO_MAPPING_MESSAGE),
        "case {case:?}: expected {NO_MAPPING} {NO_MAPPING_MESSAGE:?} past the handshake, got \
         {:?}",
        presented.answer
    );
    assert!(
        at_or_above_the_floor().contains(&presented.version),
        "case {case:?}: expected a version at or above the enforced policy, got {:?}",
        presented.version
    );
}

