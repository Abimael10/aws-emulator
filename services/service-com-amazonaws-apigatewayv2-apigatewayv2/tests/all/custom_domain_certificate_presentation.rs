#[tokio::test(flavor = "multi_thread")]
async fn the_published_address_presents_the_certificate_the_client_asked_for() {
    let emulator = emulator_with_certificates();
    let case = "a domain name whose endpoints name three certificates";
    let signer = authority("ca.presented.example.com");

    let domain = "api.presented.example.com";
    // The three certificates the record names, in the order its configuration list names
    // them: the one covering the domain name itself (imported WITH a chain), one covering
    // another name entirely (imported WITHOUT one), and a WILDCARD one.
    let apex = mint(&[domain], Some(&signer));
    let other = mint(&["alt.presented.example.net"], None);
    let wildcard = mint(&["*.shop.presented.example.org"], Some(&signer));
    let apex_arn = import(&emulator, case, &apex).await;
    let other_arn = import(&emulator, case, &other).await;
    let wildcard_arn = import(&emulator, case, &wildcard).await;

    let published = created_domain(
        &emulator,
        case,
        domain,
        &[&apex_arn, &other_arn, &wildcard_arn],
    )
    .await;
    let record = settled(&emulator, case, domain).await;
    assert_eq!(
        published_address(&record),
        published,
        "case {case:?}: GetDomainName must report the address the create published, got {record}"
    );

    // The rows: which name the client asks for, and which imported leaf the front door must
    // then present.
    let rows: &[(&str, Option<&str>, &Minted)] = &[
        ("the domain name itself", Some(domain), &apex),
        (
            "a name a later entry of the list covers",
            Some("alt.presented.example.net"),
            &other,
        ),
        (
            "one label under a wildcard entry",
            Some("api.shop.presented.example.org"),
            &wildcard,
        ),
        (
            "a name no entry of the list covers",
            Some("nothing.presented.example.com"),
            &apex,
        ),
        ("no name at all", None, &apex),
    ];
    for (row, server_name, expected) in rows {
        // The `Host` is the domain name a caller pointed at this address, which is what a
        // client of the custom domain sends whichever name it asked for in the handshake.
        let presented = tls_exchange(row, &published, *server_name, domain).await;
        assert_eq!(
            presented.leaf,
            expected.der,
            "case {row:?}: expected the imported leaf of {} bytes, got {} bytes",
            expected.der.len(),
            presented.leaf.len()
        );
        assert_answered_without_a_mapping(row, &presented);
    }
}

#[tokio::test(flavor = "multi_thread")]
async fn an_update_that_swaps_the_certificate_swaps_the_leaf_presented() {
    let emulator = emulator_with_certificates();
    let case = "a certificate rotated by UpdateDomainName";
    let signer = authority("ca.rotated.example.com");

    let domain = "api.rotated.example.com";
    let old = mint(&[domain], Some(&signer));
    let new = mint(&[domain], Some(&signer));
    let old_arn = import(&emulator, case, &old).await;
    let new_arn = import(&emulator, case, &new).await;
    assert_ne!(
        old.der, new.der,
        "case {case:?}: the two imported leaves must differ, or the rotation proves nothing"
    );

    let published = created_domain(&emulator, case, domain, &[&old_arn]).await;
    settled(&emulator, case, domain).await;
    let before = tls_exchange("before the rotation", &published, Some(domain), domain).await;
    assert_eq!(
        before.leaf, old.der,
        "case {case:?}: expected the certificate the create named, got {} bytes",
        before.leaf.len()
    );
    assert_answered_without_a_mapping("before the rotation", &before);

    let (status, updated) = call_in_region(
        &emulator.router,
        REGION,
        "PATCH",
        &format!("/v2/domainnames/{domain}"),
        Some(json!({
            "domainNameConfigurations": [{ "certificateArn": new_arn }]
        })),
    )
    .await;
    assert_eq!(
        status, 200,
        "case {case:?}: UpdateDomainName must answer 200, got {status} {updated}"
    );
    let record = settled(&emulator, case, domain).await;
    // The address a caller already pointed their DNS record at is the resource's, so a
    // rotation cannot move it.
    assert_eq!(
        published_address(&record),
        published,
        "case {case:?}: expected the published address to survive the rotation, got {record}"
    );
    assert_eq!(
        record
            .pointer("/domainNameConfigurations/0/certificateArn")
            .and_then(Value::as_str)
            .unwrap_or_default(),
        new_arn,
        "case {case:?}: expected the rotated certificate to be reported, got {record}"
    );

    // Three handshakes after the rotation: the new leaf is presented, and stays presented.
    for attempt in 1..=3 {
        let row = format!("handshake {attempt} after the rotation");
        let after = tls_exchange(&row, &published, Some(domain), domain).await;
        assert_eq!(
            after.leaf, new.der,
            "case {row:?}: expected the rotated leaf of {} bytes, got {} bytes",
            new.der.len(),
            after.leaf.len()
        );
        assert_answered_without_a_mapping(&row, &after);
    }
}
