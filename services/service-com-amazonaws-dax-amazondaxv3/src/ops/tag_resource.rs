//! @op TagResource
//!
//! Stores the request's tags on the cluster its `ResourceName` ARN addresses and answers
//! the tag set as it now stands, so a following `ListTags` reports exactly those tags. A
//! key the cluster already carries keeps its place and takes the new value (`Tag$Key`:
//! "Every DAX cluster can only have one tag with the same key. If you try to add an
