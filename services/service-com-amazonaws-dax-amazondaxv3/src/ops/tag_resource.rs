//! one is refused with `InvalidARNFault`, and one addressing a cluster this account does
//! not hold with `ClusterNotFoundFault`, both before anything is stored. Past
//! [`crate::state::MAX_TAGS_PER_RESOURCE`] tags on one cluster the request is refused with
//! `TagQuotaPerResourceExceeded` ("You can add up to 50 tags to a single DAX cluster").
//!
