impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for TagResource<Eng>
{
    type Input = TagResourceInput;
    type Output = TagResourceOutput;
    type Error = TagResourceError;

    const NAME: &'static str = "TagResource";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TAG_RESOURCE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TAG_RESOURCE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        let state = crate::state::store(&*self.engine, Self::NAME)?;
        let now = ::std::time::SystemTime::now();

        let mut store = state.lock();
        // The clock's due transitions first: a cluster whose deletion was already owed
        // holds no tags any more.
        store.settle_due(now);

        let cluster_name = match store.tagged_cluster_name(&input.resource_name) {
            Ok(name) => name,
            Err(crate::state::ResourceNameRefusal::InvalidArn(fault)) => {
                return Err(TagResourceErrorModeled::InvalidARNFault(fault).into())
            }
            Err(crate::state::ResourceNameRefusal::ClusterNotFound(fault)) => {
                return Err(TagResourceErrorModeled::ClusterNotFoundFault(fault).into())
            }
        };

        // Every tag must carry the key it is stored under, and neither half may be longer
        // than this emulator stores per tag.
        let mut requested: Vec<(String, String)> = Vec::with_capacity(input.tags.len());
        for tag in input.tags {
            let key = tag.key.unwrap_or_default();
            let value = tag.value.unwrap_or_default();
            if let Some(reason) = crate::state::tag_violation(&key, &value) {
                return Err(TagResourceErrorModeled::InvalidParameterValueException(
                    InvalidParameterValueException {
                        message: Some(reason),
                    },
                )
                .into());
            }
            requested.push((key, value));
        }

        let Some(cluster) = store.clusters.get_mut(&cluster_name) else {
            return Err(TagResourceErrorModeled::ClusterNotFoundFault(
                crate::state::cluster_not_found(),
            )
            .into());
        };
        // The quota is on what the cluster would CARRY: a key it already holds takes a new
        // value rather than adding to the count.
        let after: usize = cluster.tags.len()
            + requested
                .iter()
                .filter(|(key, _)| !cluster.tags.iter().any(|(stored, _)| stored == key))
                .count();
        if after > crate::state::MAX_TAGS_PER_RESOURCE {
            return Err(TagResourceErrorModeled::TagQuotaPerResourceExceeded(
                TagQuotaPerResourceExceeded {
                    message: Some(format!(
                        "The cluster would carry {after} tags, more than the {} allowed per \
                         cluster",
                        crate::state::MAX_TAGS_PER_RESOURCE
                    )),
                },
            )
            .into());
        }

        for (key, value) in requested {
            cluster.set_tag(key, value);
        }

        Ok(TagResourceOutput {
            tags: Some(cluster.tag_views()),
        })
    }
}
