impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for UntagResource<Eng>
{
    type Input = UntagResourceInput;
    type Output = UntagResourceOutput;
    type Error = UntagResourceError;

    const NAME: &'static str = "UntagResource";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UNTAG_RESOURCE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::UNTAG_RESOURCE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let _ = ctx;
        let state = crate::state::store(&*self.engine, Self::NAME)?;
        let now = ::std::time::SystemTime::now();

        let mut store = state.lock();
        store.settle_due(now);

        let cluster_name = match store.tagged_cluster_name(&input.resource_name) {
            Ok(name) => name,
            Err(crate::state::ResourceNameRefusal::InvalidArn(fault)) => {
                return Err(UntagResourceErrorModeled::InvalidARNFault(fault).into())
            }
            Err(crate::state::ResourceNameRefusal::ClusterNotFound(fault)) => {
                return Err(UntagResourceErrorModeled::ClusterNotFoundFault(fault).into())
            }
        };
        let Some(cluster) = store.clusters.get_mut(&cluster_name) else {
            return Err(UntagResourceErrorModeled::ClusterNotFoundFault(
                crate::state::cluster_not_found(),
            )
            .into());
        };

        // Resolved first, so a key the cluster does not carry leaves every tag in place,
        // and the refusal lists EVERY key that is not present rather than the first.
        let mut removed: Vec<Tag> = Vec::with_capacity(input.tag_keys.len());
        let mut missing: Vec<String> = Vec::new();
        for key in &input.tag_keys {
            match cluster
                .tags
                .iter()
                .find(|(stored, _)| stored == key)
                .cloned()
            {
                Some((stored_key, value)) => removed.push(Tag {
                    key: Some(stored_key),
                    value: Some(value),
                }),
                None => missing.push(key.clone()),
            }
        }
        if !missing.is_empty() {
            return Err(UntagResourceErrorModeled::TagNotFoundFault(
                crate::state::tag_not_found(&missing),
            )
            .into());
        }
        for key in &input.tag_keys {
            cluster.remove_tag(key);
        }

        Ok(UntagResourceOutput {
            tags: Some(removed),
        })
    }
}
