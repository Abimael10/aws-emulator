    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::ADD_DATASET_EXAMPLES_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::ADD_DATASET_EXAMPLES_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 202u16;

