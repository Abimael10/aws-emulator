impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for TagResource<Eng>
{
    type Input = TagResourceInput;
    type Output = TagResourceOutput;
    type Error = TagResourceError;

    const NAME: &'static str = "TagResource";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TAG_RESOURCE_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::TAG_RESOURCE_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 204u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let region = crate::state::request_region(ctx.parts());
        let state = crate::state::service_state(&*self.engine).ok_or_else(|| {
            TagResourceErrorModeled::InternalServerException(InternalServerException {
                message: Some("the resource store is unavailable".to_string()),
            })
        })?;
        let now = ::std::time::SystemTime::now();
        let mut store = state.lock();
        // A resource whose removal the clock has already made due is gone before this
        // write looks for it, with the tags it carried: both removals were owed at this
        // instant whether or not anybody called.
        store.expire_deleted_taggable_resources(now);

        // Tags are addressed through the resource that carries them, and which answer
        // the ARN earns is the one classification every tag operation shares: a taggable
        // resource this service holds is tagged, a taggable type naming no such resource
        // is the 404 this plane is served with, another resource type of this service
        // takes no tag through this plane, and an ARN naming no resource type of this
        // service addresses nothing of this account.
        let target = match store.tag_target(&region, &input.resource_arn) {
            crate::state::TagTarget::Resolved(target) => target,
            crate::state::TagTarget::Absent => return Err(crate::state::tag_target_not_found()),
            crate::state::TagTarget::OutOfScope => {
                return Err(TagResourceErrorModeled::ValidationException(
                    crate::state::tagging_unsupported_type(),
                )
                .into())
            }
            crate::state::TagTarget::Unrecognized => {
                // Decided with no store guard held: the denial is read off the signing
                // identity, which lives in another store.
                drop(store);
                return Err(TagResourceErrorModeled::AccessDeniedException(
                    crate::service::authorization::access_denied(&*self.engine, ctx, Self::NAME),
                )
                .into());
            }
        };

        let submitted = crate::state::sorted_map(Some(input.tags));
        let Some(held) = store.resource_tags_mut(&target) else {
            return Err(crate::state::tag_target_not_found());
        };
        // The set a resource carries is bounded, so a caller looping on tag writes meets
        // the modelled quota instead of a tag set no read can report. Counted on the
        // MERGED set: a key the resource already carries is replaced, not added.
        let merged = held
            .keys()
            .chain(submitted.keys())
            .collect::<::std::collections::BTreeSet<_>>()
            .len();
        if merged > crate::state::MAX_TAGS_PER_RESOURCE {
            return Err(TagResourceErrorModeled::ServiceQuotaExceededException(
                crate::state::tag_quota_exceeded(merged),
            )
            .into());
        }
        held.extend(submitted);

        Ok(TagResourceOutput {})
    }
}
