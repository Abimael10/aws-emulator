/// Whether `alarm` is an alarm whose state is contributed to by SEVERAL time series — the kind
/// of alarm this operation reports on.
///
/// A contributor "Represents an individual contributor to a multi-timeseries alarm, containing
/// information about a specific time series and its contribution to the alarm's state"
/// (`AlarmContributor`), so the alarms that have contributors are exactly the ones whose
/// evaluation grades a vector of series rather than one
/// ([`crate::state::alarm_evaluation::grades_a_vector_of_series`], which is where that one rule
/// lives): a query of vector type, or a Metrics Insights query that groups its result into one
/// series per group. An alarm graded on ONE series — the single metric its own members name, the
/// one query of its `Metrics` array the evaluation watches, a composite alarm's rule over other
/// alarms, a log alarm's scheduled query — has none to report at all.
fn multi_time_series(alarm: &MetricAlarm) -> bool {
    crate::state::alarm_evaluation::grades_a_vector_of_series(alarm)
}

/// How CloudWatch states that the alarm a request named is not of that kind: one sentence
/// carrying the name the request asked for.
fn not_a_multi_time_series_alarm(alarm_name: &str) -> String {
    format!("Alarm {alarm_name} is not a multi time series alarm")
}

/// How CloudWatch states that no alarm of this account and Region answers to the name a request
/// named: one sentence carrying that name.
fn no_alarm_for_name(alarm_name: &str) -> String {
    format!("No alarm for name {alarm_name} was found")
}

/// The contributors of one multi-time-series alarm: "the current alarm contributors that are in
/// `ALARM` state" (`DescribeAlarmContributors`).
///
/// Such an alarm's contributors are the entries of its query's result vector
/// ([`multi_time_series`]), and a contributor is reported exactly while it is in `ALARM` — an
/// entry in `OK` or `INSUFFICIENT_DATA` is not a contributor to the alarm's state, which is what
/// this read reports from. Nothing is recorded per contributor by a caller: every member below is
/// what the evaluation that graded that entry left
/// ([`crate::state::StoredAlarmContributor`]), reported in the order the query RANKED its
/// entries — the ranking the query asked the service to make.
///
/// An alarm whose query returns a vector this engine resolves no entries of — the query language
/// of its `EvaluationCriteria` is resolved by no engine of this emulator — still has the one
/// contributor its own `ALARM` state accounts for, described by the identity this store can name
/// for it, which is the alarm's own.
fn contributors_of(stored: &crate::state::StoredAlarm) -> Vec<AlarmContributor> {
    let alarm = &stored.alarm;
    if alarm.state_value.as_deref() != Some(crate::state::ALARM_STATE_ALARM) {
        return Vec::new();
    }
    if !stored.contributors.is_empty() {
        return stored
            .contributors
            .iter()
            .filter(|contributor| {
                contributor.state_value == crate::state::ALARM_STATE_ALARM
            })
            .map(|contributor| AlarmContributor {
                contributor_id: contributor.contributor_id.clone(),
                contributor_attributes: contributor
                    .attributes
                    .iter()
                    .map(|(name, value)| (name.clone(), value.clone()))
                    .collect(),
                state_reason: contributor.state_reason.clone(),
                state_transitioned_timestamp: Some(crate::state::to_timestamp(
                    contributor.state_transitioned_secs,
                )),
            })
            .collect();
    }
    // WHICH series the alarm evaluates is read from the same resolution the evaluation itself
    // reads it by, so a contributor describes the series the configuration identified, whichever
    // form identified it.
    let series = crate::state::alarm_evaluation::graded_series_key(alarm);
    vec![AlarmContributor {
        contributor_id: crate::state::alarm_evaluation::contributor_id(
            alarm.alarm_name.as_deref().unwrap_or_default(),
            series.as_ref(),
        ),
        // "A map of attributes that describe the contributor, such as metric dimensions and other
        // identifying characteristics." (`AlarmContributor$ContributorAttributes`) — the
        // dimensions of that series, as the write that configured the alarm named them, and
        // nothing this service made up: a series with no dimensions is described by no attribute,
        // and so is an alarm graded on a computed series that has no identity of its own.
        contributor_attributes: series
            .as_ref()
            .map(|series| {
                series
                    .dimensions
                    .iter()
                    .map(|(name, value)| (name.clone(), value.clone()))
                    .collect()
            })
            .unwrap_or_default(),
        // Why that series is in `ALARM`, and when it got there: the alarm's own evaluated reason
        // and transition instant, since the series IS what the alarm evaluates.
        state_reason: alarm.state_reason.clone().unwrap_or_default(),
        state_transitioned_timestamp: alarm.state_transitioned_timestamp,
    }]
}

