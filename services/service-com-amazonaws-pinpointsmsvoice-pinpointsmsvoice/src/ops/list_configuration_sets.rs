/// Read `PageSize` as the page bound, clamped to [`MAX_PAGE_SIZE`] — `None` for anything
/// that is not a positive count, which the caller records as a finding against the request.
///
/// A page of zero items would make a paginating client loop forever, so it is refused
/// alongside a negative, fractional or non-numeric value. A count above the maximum is
/// clamped rather than refused: the caller asked for at most that many, and it gets a
/// `NextToken` for the remainder.
///
/// "Above the maximum" is decided by the DIGITS the caller wrote, never by what this
/// build's `usize` can hold: a count is read digit by digit, and one too large for the
/// machine is by construction larger than [`MAX_PAGE_SIZE`], so it is clamped like any
/// other count above that bound. Handing the decision to `str::parse` alone would refuse
/// such a count, and would put the line between a clamped and a refused value at the
/// host's pointer width, so one request would be answered differently on a 32-bit and a
/// 64-bit build.
///
/// The refusal carries NO detail text of its own — it is this service's one
/// `refusal_wording::Unusable::Unworded` class. `BadRequestException$Message` is optional in
/// the model (`smithy_query(query="shape",shape="BadRequestException",model_path="services/service-com-amazonaws-pinpointsmsvoice-pinpointsmsvoice/smithy-model/com-amazonaws-pinpointsmsvoice-pinpointsmsvoice.json")`)
/// and the service sends none for this parameter, so none is written: writing one would
/// put a sentence on the wire the real response does not carry, and a client that reads a
/// present detail as "the service explained the problem" would branch on it. The code and
/// the status are the whole answer where this is the ONLY parameter the request failed on;
/// the member itself still travels, as JSON `null` — the one value an SDK reports as unset,
/// the rule and the reason being `crate::service::WIRE_DETAIL_MEMBER`'s. Carrying no
/// sentence is not silencing one, so a request that ALSO carried an unusable `NextToken` —
/// which this service mints and therefore names — is answered with that sentence (see the
/// caller).
fn parse_page_size(raw: &str) -> Option<usize> {
    // What makes a value a count is how it is written: one optional `+` and then nothing
    // but ASCII decimal digits. Everything else — empty, negative, fractional, exponent
    // notation, a digit of another script, plain text — is not a count and is refused,
    // whatever magnitude it was meant to denote.
    let digits = raw.strip_prefix('+').unwrap_or(raw);
    if digits.is_empty() || !digits.bytes().all(|byte| byte.is_ascii_digit()) {
        return None;
    }

    // A count this build can hold is clamped by `min`; one it cannot hold is already past
    // every bound the clamp could apply, so it clamps to the maximum rather than being
    // refused. Zero is the one count refused: a page of nothing would make a paginating
    // client loop forever.
    match digits.parse::<usize>() {
        Ok(0) => None,
        Ok(size) => Some(size.min(MAX_PAGE_SIZE)),
        Err(_) => Some(MAX_PAGE_SIZE),
    }
}

/// Mint the opaque `NextToken` for a page whose last entry was `after`.
///
/// The cursor travels inside the token — [`TOKEN_SCOPE`] and then the exclusive-start
/// name, which is enough to resume because the stored order is total — behind the
/// authenticator this store's `key` puts over it. That authenticator is what makes the
/// token THIS store's: the key is drawn from the system's randomness, stays in memory
/// and is never reported, so no caller can produce the authenticator for a cursor of its
/// own ([`decode_token`]).
///
/// Rendered hex rather than base64 because the token travels back in a query string
/// (`?NextToken=...`), where hex needs no escaping while base64's `+` would arrive as a
/// space.
fn encode_token(key: &crate::state::PageTokenKey, after: &str) -> String {
    hex::encode(key.mint(&format!("{TOKEN_SCOPE}{after}")))
}

/// The inverse of [`encode_token`]; `None` for anything THIS store did not mint.
///
/// The authenticator is verified, not just the shape: a value that is not hex, one whose
/// bytes this store's key does not authenticate (a cursor a caller assembled from the
/// prefix above, one another store minted, one altered on the way back) and one carrying
/// a cursor of another layout all name no position in this listing. Checking the shape
/// alone would honour any value of that shape, and a caller that assembled one would
/// silently get a listing resumed after a position this service never handed out.
fn decode_token(key: &crate::state::PageTokenKey, token: &str) -> Option<String> {
    let cursor = key.cursor_of(&hex::decode(token).ok()?)?;
    cursor.strip_prefix(TOKEN_SCOPE).map(str::to_string)
}
