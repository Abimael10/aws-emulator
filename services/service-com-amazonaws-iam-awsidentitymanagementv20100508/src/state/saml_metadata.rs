//! What IAM READS out of a SAML provider's metadata document, and the quotas that reading
//! is bounded by.
//!
//! `CreateSAMLProvider` and `UpdateSAMLProvider` do not store a metadata document blindly:
//! "that document includes the issuer's name, expiration information, and keys"
//! (`CreateSAMLProvider`), and those are what a held provider reports about itself. One
//! reading, stated here, so the create, the update and both reads cannot describe one
//! document differently — and one place where the quotas on what a document may describe
//! are taken, so a document past them is refused rather than silently read in part.

use super::*;

/// How many signing keys one SAML provider's metadata document may publish.
///
/// AWS's "IAM and STS quotas" page gives the quota "Keys per SAML provider: 10", and
/// `CreateSAMLProvider`/`UpdateSAMLProvider` model `LimitExceededException` ("it attempted
/// to create resources beyond the current … account limits. The error message describes the
/// limit exceeded"), so a document publishing more is refused and no provider holds it. It
/// is also what bounds the work reading one document costs: `SAMLMetadataDocumentType`
/// admits ten million characters, which is room for a great many key elements, so the walk
/// stops one key past the quota — enough to know the document is over it, and never more.
pub const MAX_SIGNING_KEYS_PER_SAML_METADATA: usize = 10;

/// How many identity providers one SAML provider's metadata document may describe.
///
/// A metadata document "generated by an identity provider (IdP) that supports SAML 2.0"
/// (`CreateSAMLProvider$SAMLMetadataDocument`) may describe several entities — the OASIS
/// vocabulary nests an entity descriptor per IdP inside a group of them ("Metadata for SAML
/// V2.0" §2.3) — and AWS's "IAM and STS quotas" page gives the quota "Identity providers
/// per SAML provider: 10". A document describing more is refused with the same
/// `LimitExceededException` an over-quota key count is, and the count is taken one entity
/// past the quota for the same reason the key walk is bounded.
pub const MAX_IDENTITY_PROVIDERS_PER_SAML_METADATA: usize = 10;

/// The quota name IAM's refusal of a document publishing more than
/// [`MAX_SIGNING_KEYS_PER_SAML_METADATA`] keys states: the keys of one SAML IdP, which is
/// what a provider's metadata describes.
///
/// The quota NAME is what identifies WHICH of an operation's several `LimitExceeded` causes
/// refused the call, so it is part of the message rather than decoration, and it is IAM's
/// own spelling of the quota rather than a restatement of a member's name.
const KEYS_PER_SAML_PROVIDER_QUOTA: &str = "KeysPerSamlIdp";

/// The quota name IAM's refusal of a document describing more than
/// [`MAX_IDENTITY_PROVIDERS_PER_SAML_METADATA`] identity providers states: the SAML IdPs
/// of one provider resource, in IAM's own spelling of the quota.
const IDENTITY_PROVIDERS_PER_SAML_PROVIDER_QUOTA: &str = "SamlIdpsPerSamlProvider";

/// What IAM reads out of a SAML provider's metadata document.
///
/// `CreateSAMLProvider` has to READ the document rather than store it blindly, because
/// what a provider reports about itself comes from it: "that document includes the
/// issuer's name, expiration information, and keys" (`CreateSAMLProvider`), and the
/// expiration is what `GetSAMLProvider$ValidUntil` answers.
#[derive(Debug, Clone)]
pub struct SamlMetadata {
    /// The root descriptor's `validUntil`, when the document carries one: the instant
    /// the metadata — and so the provider — stops being valid.
    pub valid_until: Option<::aws_smithy_types::DateTime>,
    /// "The issuer's name": the entity descriptor's `entityID`
    /// (`CreateSAMLProvider$SAMLMetadataDocument`, OASIS "Metadata for SAML V2.0" §2.3),
    /// which is the name the provider's own messages carry as their `Issuer`.
    pub entity_id: String,
    /// How many identity providers the document describes: one entity descriptor each.
    /// Counted at most one past [`MAX_IDENTITY_PROVIDERS_PER_SAML_METADATA`], which is all
    /// the quota reader needs ([`saml_metadata_over_quota`]).
    pub identity_providers: usize,
    /// The "keys" the document publishes for SIGNING: the base64 of each DER X.509
    /// certificate an `X509Certificate` element inside a signing `KeyDescriptor` carries,
    /// in document order, once per distinct certificate and at most one past
    /// [`MAX_SIGNING_KEYS_PER_SAML_METADATA`] of them — the extra entry is what tells the
    /// quota reader the document is over the quota, and a document that is over it is
    /// refused, so no held provider carries more than the quota. These are the certificates
    /// a reader of this metadata checks a message from the provider against, so a document
    /// publishing none can verify nothing.
    pub signing_certificates: Vec<String>,
}

/// The quota `metadata` exceeds, worded as IAM's `LimitExceededException` message —
/// `Cannot exceed quota for `, the quota's name, `: ` and its value — or `None` when the
/// document is within every quota on what one may describe.
///
/// Asked by every operation that takes a `SAMLMetadataDocument`, before anything is
/// written: a document past a quota leaves the account exactly as it was.
pub fn saml_metadata_over_quota(metadata: &SamlMetadata) -> Option<String> {
    if metadata.identity_providers > MAX_IDENTITY_PROVIDERS_PER_SAML_METADATA {
        return Some(quota_exceeded(
            IDENTITY_PROVIDERS_PER_SAML_PROVIDER_QUOTA,
            MAX_IDENTITY_PROVIDERS_PER_SAML_METADATA,
        ));
    }
    (metadata.signing_certificates.len() > MAX_SIGNING_KEYS_PER_SAML_METADATA).then(|| {
        quota_exceeded(
            KEYS_PER_SAML_PROVIDER_QUOTA,
            MAX_SIGNING_KEYS_PER_SAML_METADATA,
        )
    })
}

/// IAM's sentence for a call that would take the account past a quota: the fixed text
/// `Cannot exceed quota for ` and `: ` around the quota's name and its value, and nothing
/// of the request.
fn quota_exceeded(quota: &str, value: usize) -> String {
    format!("Cannot exceed quota for {quota}: {value}")
}

/// Read `document` as a SAML 2.0 metadata document, or `None` when it is not one.
///
/// A metadata document is "an XML document generated by an identity provider (IdP) that
/// supports SAML 2.0" whose root is an entity (or entities) descriptor in the SAML
/// metadata namespace ([`SAML_METADATA_NAMESPACE`]) and which "includes the issuer's
/// name" — the entity descriptor's `entityID`
/// (`CreateSAMLProvider$SAMLMetadataDocument`, OASIS "Metadata for SAML V2.0" §2.3).
/// So a document that is not well-formed XML, is rooted at something else, or names no
/// issuer describes no identity provider, and the operation taking it is refused as
/// having been "supplied an invalid … value … for an input parameter"
/// (`InvalidInputException`).
///
/// Validation deliberately stops there: the keys and endpoints BELOW the descriptor are
/// not checked, so a 200 from an operation taking a metadata document is the claim
/// "this is SAML 2.0 metadata for an issuer", not "every binding in it is usable". What
/// the document describes TOO MUCH of is a separate question, asked of the reading rather
/// than of the text ([`saml_metadata_over_quota`]).
/// This is the ONE definition of the rule, shared by every operation that accepts a
/// metadata document.
///
/// WHICH of those it was is deliberately not reported: the refusal is
/// [`INVALID_SAML_METADATA_DOCUMENT`], one fixed sentence for every way a document can
/// fail to be SAML 2.0 metadata, so no reader of the document can put its own diagnostics
/// on the wire.
pub fn parse_saml_metadata(document: &str) -> Option<SamlMetadata> {
    let parsed = ::roxmltree::Document::parse(document).ok()?;
    let root = parsed.root_element();
    let in_metadata_namespace = |node: &::roxmltree::Node<'_, '_>, local: &str| {
        node.tag_name().namespace() == Some(SAML_METADATA_NAMESPACE)
            && node.tag_name().name() == local
    };
    // The descriptor that names the issuer: the root itself for a document describing
    // one entity, or the first entity descriptor nested in a group of them.
    let entity = if in_metadata_namespace(&root, SAML_ENTITY_DESCRIPTOR) {
        root
    } else if in_metadata_namespace(&root, SAML_ENTITIES_DESCRIPTOR) {
        root.descendants()
            .find(|node| in_metadata_namespace(node, SAML_ENTITY_DESCRIPTOR))?
    } else {
        return None;
    };
    if entity
        .attribute(SAML_ENTITY_ID_ATTRIBUTE)
        .is_none_or(str::is_empty)
    {
        return None;
    }
    let entity_id = entity
        .attribute(SAML_ENTITY_ID_ATTRIBUTE)
        .unwrap_or_default()
        .to_string();
    // HOW MANY identity providers the document describes: one entity descriptor each, the
    // root itself when it describes a single entity. Counted one past the quota and no
    // further, so a document cannot choose how much counting it costs.
    let identity_providers = if in_metadata_namespace(&root, SAML_ENTITY_DESCRIPTOR) {
        1
    } else {
        root.descendants()
            .filter(|node| in_metadata_namespace(node, SAML_ENTITY_DESCRIPTOR))
            .take(MAX_IDENTITY_PROVIDERS_PER_SAML_METADATA.saturating_add(1))
            .count()
    };
    // The keys the document publishes for SIGNING, each an `X509Certificate` of the XML
    // signature namespace (W3C "XML Signature Syntax and Processing" §4.4.4), with the
    // whitespace a PEM-wrapped body carries removed so the value is the base64 the element
    // means. A key published for ENCRYPTION only is not one of them: a reader of this
    // metadata verifies a message from the provider against its SIGNING keys, and a
    // `KeyDescriptor` says which a key is (OASIS "Metadata for SAML V2.0" §2.4.1.1) —
    // where saying nothing means both. One key is one entry however many descriptors
    // publish it, because what the entry identifies is the KEY.
    //
    // Reading one document is work a REQUEST sizes, so every step of it is bounded by the
    // document rather than by the square of it: membership is asked of a set rather than of
    // the keys collected so far, the set holds at most one key past
    // [`MAX_SIGNING_KEYS_PER_SAML_METADATA`] because the walk stops once that many
    // distinct keys are read, and the descriptor above a key is looked for a fixed number
    // of steps up ([`publishes_signing_key`]) rather than along however deep the document
    // nests.
    let mut read_keys: BTreeSet<String> = BTreeSet::new();
    let signing_certificates: Vec<String> = entity
        .descendants()
        .filter(|node| {
            node.tag_name().namespace() == Some(XML_SIGNATURE_NAMESPACE)
                && node.tag_name().name() == XML_SIGNATURE_CERTIFICATE
                && publishes_signing_key(node)
        })
        .filter_map(|node| node.text())
        .map(|text| text.split_whitespace().collect::<String>())
        .filter(|text| !text.is_empty())
        // `contains` before `insert` so a key the document repeats is not COPIED again to
        // be rejected: `insert` would answer the same, after cloning the whole body.
        .filter(|text| !read_keys.contains(text.as_str()) && read_keys.insert(text.clone()))
        .take(MAX_SIGNING_KEYS_PER_SAML_METADATA.saturating_add(1))
        .collect();
    // "Expiration information": `validUntil` on the root descriptor, or on the entity
    // descriptor itself when the root is a group that carries none. It is an
    // `xs:dateTime`, so it may state a UTC offset rather than `Z` (XML Schema Part 2,
    // §3.2.7) — read through the ONE reader every service with a text timestamp shares.
    let valid_until = match root
        .attribute(SAML_VALID_UNTIL_ATTRIBUTE)
        .or_else(|| entity.attribute(SAML_VALID_UNTIL_ATTRIBUTE))
    {
        None => None,
        Some(text) => Some(parse_xs_date_time(text)?),
    };
    Some(SamlMetadata {
        valid_until,
        entity_id,
        identity_providers,
        signing_certificates,
    })
}

/// Whether the `X509Certificate` node `certificate` publishes one of the entity's SIGNING
/// keys.
///
/// A key sits inside a `KeyDescriptor`, whose optional `use` says what the key is for, and
/// "the absence of this attribute signifies that the contained key may be used for both
/// encryption and signing" (OASIS "Metadata for SAML V2.0" §2.4.1.1) — so a descriptor
/// saying nothing, or saying `signing`, publishes a signing key, and one saying anything
/// else does not. A key published outside any descriptor is not one of the entity's
/// published keys at all.
///
/// The descriptor is looked for a FIXED number of steps up
/// ([`SAML_KEY_DESCRIPTOR_ANCESTRY`]), never along the whole ancestry: the vocabulary fixes
/// how far above a key its descriptor sits, so the cost of reading a document stays
/// proportional to the document rather than to the keys in it times the depth it nests
/// them at — a product a request would otherwise choose both factors of.
fn publishes_signing_key(certificate: &::roxmltree::Node<'_, '_>) -> bool {
    certificate
        .ancestors()
        .take(SAML_KEY_DESCRIPTOR_ANCESTRY)
        .find(|node| {
            node.tag_name().namespace() == Some(SAML_METADATA_NAMESPACE)
                && node.tag_name().name() == SAML_KEY_DESCRIPTOR
        })
        .is_some_and(|descriptor| {
            descriptor
                .attribute(SAML_KEY_USE_ATTRIBUTE)
                .is_none_or(|purpose| purpose == SAML_KEY_USE_SIGNING)
        })
}
