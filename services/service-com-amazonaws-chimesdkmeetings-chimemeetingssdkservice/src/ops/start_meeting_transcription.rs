/// How the service words the one rule `TranscriptionConfiguration` itself states: the
/// choice between the two engines' settings is EXCLUSIVE, so exactly one of them has to be
/// there. The sentence is fixed text for this refusal — the only names in it are the
/// modelled member names it cites, so neither half of the violation (neither block, or
/// both blocks) nor anything else the request carried changes a word of it.
const ENGINE_CHOICE_PROBLEM: &str = "Exactly one out of EngineTranscribeSettings and \
     EngineTranscribeMedicalSettings must be specified in the TranscriptionConfiguration";

/// The message for the one rule this API refuses a `TranscriptionConfiguration` on, or
/// `None` when the configuration is one it accepts.
///
/// That rule is the one `TranscriptionConfiguration` itself states
/// (`smithy_query(query="shape",shape="TranscriptionConfiguration")`: "Must contain
/// EngineTranscribeSettings or EngineTranscribeMedicalSettings."), and the message names
/// the MEMBERS it constrains rather than any value from the request. Per-member
/// constraints — the required members of the medical settings, the enums, the lengths and
/// the patterns — are refused by the boundary validator before this handler runs.
///
/// How the settings INSIDE the chosen engine's block combine is not judged here, because
/// the model does not report it through this API: `EngineTranscribeSettings` documents
/// that "If you specify an invalid combination of parameters, a `TranscriptFailed` event
/// will be sent with the contents of the `BadRequestException` generated by Amazon
/// Transcribe", which is the transcription session failing afterwards rather than this
/// call being refused. A parameter's CONTENT is part of that combination: the subset
/// `PreferredLanguage` has to come from, and the one-dialect-per-language limit on
/// `LanguageOptions`, are rules about the engine's parameters, so they too travel on the
/// session rather than being refused here.
fn configuration_problem(configuration: &TranscriptionConfiguration) -> Option<String> {
    match (
        configuration.engine_transcribe_settings.as_ref(),
        configuration.engine_transcribe_medical_settings.as_ref(),
    ) {
        // `TranscriptionConfiguration`: "Must contain EngineTranscribeSettings or
        // EngineTranscribeMedicalSettings." One engine transcribes the meeting's audio,
        // so naming both is as unserveable as naming neither, and the service words the
        // exclusive choice itself — one fixed sentence for both halves of the violation,
        // naming the two engine members and the structure they sit in and nothing from
        // the request.
        (None, None) | (Some(_), Some(_)) => Some(ENGINE_CHOICE_PROBLEM.to_string()),
        // Exactly one engine's settings: the choice is made, so this API has nothing left
        // to refuse. How that engine's own parameters combine is Amazon Transcribe's
        // judgement, reported on the transcription session rather than on this call.
        (Some(_), None) | (None, Some(_)) => None,
    }
}

