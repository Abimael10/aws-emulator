        // A key the resource already carries takes the new value rather than a second
        // entry, so only the keys it does NOT carry grow the set: that count is what the
        // documented maximum bounds, and it is checked before anything is written so a
        // refused call leaves the set exactly as it was.
        let added = input
            .tags
            .keys()
            .filter(|key| !tags.contains_key(*key))
            .count();
