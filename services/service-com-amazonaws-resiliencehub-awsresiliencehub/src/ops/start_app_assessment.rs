/// How long a recovery takes where the service owning the resources ABSORBS the
/// disruption with redundancy it holds itself: no time at all, because nothing has
/// to be restored for the application to carry on.
const ABSORBED_SECONDS: i32 = 0;

/// The recovery time an assessment reports for a recovery the application does not
/// reach, judged against an objective of `objective` seconds: one second past it.
///
/// A recovery nothing performs has no duration to measure, and the member it is
/// reported in is a plain `Seconds` (`smithy_query query="shape" shape="Seconds"`:
/// an integer bounded below by 0 and not above) with no value reserved for "never",
/// so the service states the one thing that IS known about it — that it is past the
/// objective — as the smallest value that says so.
fn unreached_seconds(objective: i32) -> i32 {
    objective.saturating_add(1)
}

/// What the assessment makes of a version against `policy`, one entry per
/// disruption type the POLICY states an objective for — an application is only
/// compliant with the objectives it was given, so a disruption type the policy
/// leaves out is not judged, and an application with no policy is not judged at
/// all.
///
/// The recovery times are MEASURED on the assessed version, never copied from the
/// objectives they are judged against: a disruption every resource of the version
/// recovers from is absorbed where those resources stand ([`ABSORBED_SECONDS`] —
/// nothing is restored, so no time passes), and one that some resource does not
/// recover from is not reached at all ([`unreached_seconds`]). What a resource
/// recovers is [`crate::state::recovers_disruption`]; an Application Component with
/// no resource mapped to it recovers nothing, whatever the disruption, and nothing
/// that could be recommended for it changes that until a resource is mapped, so
/// neither the current nor the ACHIEVABLE recovery reaches the objective there.
/// Everywhere else the achievable recovery is the absorbed one: every resource type
/// this service assesses can be given the recovery its class needs, and that
/// recovery is its own service's, which restores nothing.
fn disruption_compliance(
    policy: Option<&ResiliencyPolicy>,
    assessed: &crate::state::AppVersionContents,
    breaching_components: &[String],
) -> ::std::collections::HashMap<String, DisruptionCompliance> {
    let Some(objectives) = policy.and_then(|policy| policy.policy.as_ref()) else {
        return ::std::collections::HashMap::new();
    };

    objectives
        .iter()
        .map(|(disruption_type, objective)| {
            let measured = measured_recovery(assessed, breaching_components, disruption_type);
            let current_rto = measured
                .current
                .unwrap_or_else(|| unreached_seconds(objective.rto_in_secs));
            let current_rpo = measured
                .current
                .unwrap_or_else(|| unreached_seconds(objective.rpo_in_secs));
            let compliance = DisruptionCompliance {
                current_rto_in_secs: current_rto,
                achievable_rto_in_secs: measured
                    .achievable
                    .unwrap_or_else(|| unreached_seconds(objective.rto_in_secs)),
                current_rpo_in_secs: current_rpo,
                achievable_rpo_in_secs: measured
                    .achievable
                    .unwrap_or_else(|| unreached_seconds(objective.rpo_in_secs)),
                // The verdict is that comparison and nothing else: an objective is
                // met while the recovery measured on the application is within it.
                compliance_status: if current_rto > objective.rto_in_secs
                    || current_rpo > objective.rpo_in_secs
                {
                    COMPLIANCE_STATUS_BREACHED.to_string()
                } else {
                    COMPLIANCE_STATUS_MET.to_string()
                },
                message: measured.message,
                ..DisruptionCompliance::default()
            };
            (disruption_type.clone(), compliance)
        })
        .collect()
}

/// What an assessment measures about recovering one application from one
/// disruption: the recovery the version reaches AS IT STANDS and the one it could
/// reach, each in seconds, with `None` for a recovery it does not reach — which the
/// entry then reports against the objective it was judged by.
struct MeasuredRecovery {
    current: Option<i32>,
    achievable: Option<i32>,
    /// What stopped the recovery being reached, when something did — the
    /// `DisruptionCompliance$message` of the entry.
    message: Option<String>,
}

/// The recovery [`disruption_compliance`] reports for one disruption type, measured
/// on the assessed version: what recovers the resources it maps, and what it leaves
/// with nothing to recover it.
fn measured_recovery(
    assessed: &crate::state::AppVersionContents,
    breaching_components: &[String],
    disruption_type: &str,
) -> MeasuredRecovery {
    // An Application Component with nothing mapped to it has nothing that could
    // recover it, whichever disruption is asked about.
    if let Some(component) = breaching_components.first() {
        return MeasuredRecovery {
            current: None,
            achievable: None,
            message: Some(format!(
                "Application Component {component} has no resources, so nothing recovers it"
            )),
        };
    }
    let included = assessed.included_resources();
    // A version that maps nothing describes nothing to recover.
    if included.is_empty() {
        return MeasuredRecovery {
            current: None,
            achievable: None,
            message: Some(
                "The assessed app version maps no resource, so nothing recovers it".to_string(),
            ),
        };
    }

    // One resource that does not recover this disruption is enough: an application
    // recovers only as far as its least recoverable resource does.
    let unrecovered = included.iter().find(|resource| {
        !crate::state::recovers_disruption(&resource.resource_type, disruption_type)
    });
    match unrecovered {
        // Every resource of the version recovers this disruption where it stands.
        None => MeasuredRecovery {
            current: Some(ABSORBED_SECONDS),
            achievable: Some(ABSORBED_SECONDS),
            message: None,
        },
        // At least one does not, so the application does not — while the recovery
        // its resources could be given still would.
        Some(resource) => MeasuredRecovery {
            current: None,
            achievable: Some(ABSORBED_SECONDS),
            message: Some(format!(
                "Resource {} ({}) does not recover a {disruption_type} disruption",
                resource
                    .resource_name
                    .as_deref()
                    .unwrap_or(resource.logical_resource_id.identifier.as_str()),
                resource.resource_type
            )),
        },
    }
}

/// The `currency` every cost this service states is in — the `CurrencyCode` a
/// Resilience Hub assessment reports a cost in.
const COST_CURRENCY: &str = "USD";

/// The `frequency` every cost this service states carries: a cost per month, as the
/// model's `CostFrequency` enum spells it.
const COST_FREQUENCY: &str = "Monthly";

/// What one mapped resource adds to the application's cost: nothing this service
/// stores about a resource carries a price — a `PhysicalResource` records what a
/// resource IS and what it is grouped into — so there is no price to add up for any
/// of them.
const UNPRICED_RESOURCE_AMOUNT: f64 = 0.0;

/// What the assessed application costs, as the model's `Cost` — whose `amount`,
/// `currency` and `frequency` are all REQUIRED (`smithy_query query="shape"
/// shape="Cost"`), so an assessment reports a complete cost object or no cost at
/// all.
///
/// The amount is what the resources the assessed version maps cost, which is
/// [`UNPRICED_RESOURCE_AMOUNT`] for every one of them, so the application's cost of
/// resiliency is STATED, in a currency and at a frequency, rather than left
/// unanswered. Should this service ever record what a resource costs, the amount is
/// the sum of those prices over the version's included resources.
fn application_cost() -> Cost {
    Cost {
        amount: UNPRICED_RESOURCE_AMOUNT,
        currency: COST_CURRENCY.to_string(),
        frequency: COST_FREQUENCY.to_string(),
    }
}

/// The drift verdict a finishing assessment reaches: whether the compliance it
/// computed DEVIATES from the compliance of the application's previous assessment,
/// which is the application-compliance drift the model's `DriftType` names.
///
/// Running an assessment is what evaluates drift, so the verdict is one of the two
/// answers and never [`crate::state::DRIFT_STATUS_NOT_CHECKED`] — the first
/// assessment of an application establishes the baseline, and so deviates from
/// nothing.
fn drift_status(
    previous: Option<&::std::collections::HashMap<String, DisruptionCompliance>>,
    computed: &::std::collections::HashMap<String, DisruptionCompliance>,
) -> &'static str {
    let Some(previous) = previous else {
        return crate::state::DRIFT_STATUS_NOT_DETECTED;
    };
    if deviates(previous, computed) {
        return crate::state::DRIFT_STATUS_DETECTED;
    }
    crate::state::DRIFT_STATUS_NOT_DETECTED
}

/// Whether two assessments' compliance differ: in WHICH disruption types they
/// judged, or in what either of them found about one — its verdict or any of the
/// recovery times it measured. The reference ids, the descriptions and the message
/// are no part of it: they state the same finding in words.
fn deviates(
    previous: &::std::collections::HashMap<String, DisruptionCompliance>,
    computed: &::std::collections::HashMap<String, DisruptionCompliance>,
) -> bool {
    if previous.len() != computed.len() {
        return true;
    }
    computed.iter().any(|(disruption_type, entry)| {
        previous.get(disruption_type).is_none_or(|earlier| {
            (
                earlier.compliance_status.as_str(),
                earlier.current_rto_in_secs,
                earlier.current_rpo_in_secs,
                earlier.achievable_rto_in_secs,
                earlier.achievable_rpo_in_secs,
            ) != (
                entry.compliance_status.as_str(),
                entry.current_rto_in_secs,
                entry.current_rpo_in_secs,
                entry.achievable_rto_in_secs,
                entry.achievable_rpo_in_secs,
            )
        })
    })
}

/// The names of `assessed`'s Application Components that no resource of `assessed`
/// is mapped to, in the stored components' own stable order.
///
/// A resource carries the components it was created with, so the mapping is read
/// from the resource side — by the `name` the model gives `AppComponentNameList`'s
/// members or by the `id` the component is stored under, the two ways this service
/// lets a resource name one.
fn components_without_resources(assessed: &crate::state::AppVersionContents) -> Vec<String> {
    assessed
        .app_components
        .values()
        .filter(|component| {
            !assessed.resources.values().any(|resource| {
                resource
                    .app_components
                    .as_deref()
                    .unwrap_or_default()
                    .iter()
                    .any(|mapped| {
                        mapped.name == component.name
                            || (mapped.id.is_some() && mapped.id == component.id)
                    })
            })
        })
        .map(|component| component.name.clone())
        .collect()
}

/// The `ComplianceStatus` of an application whose every stated objective is
/// reached.
const COMPLIANCE_STATUS_MET: &str = "PolicyMet";

/// The `ComplianceStatus` of an application that misses at least one of them.
const COMPLIANCE_STATUS_BREACHED: &str = "PolicyBreached";

/// The `ComplianceStatus` of an application there is no policy to judge against.
const COMPLIANCE_STATUS_MISSING_POLICY: &str = "MissingPolicy";

/// The `ComplianceStatus` of an application whose policy states no objective to
/// judge against.
const COMPLIANCE_STATUS_NOT_APPLICABLE: &str = "NotApplicable";

/// The assessment's verdict on the application as a whole: an application is
/// compliant only while EVERY objective its policy states is reached, there is
/// nothing to judge an application against while it names no policy, and a policy
/// that states no objective judges nothing.
fn overall_compliance_status(
    policy: Option<&ResiliencyPolicy>,
    compliance: &::std::collections::HashMap<String, DisruptionCompliance>,
) -> String {
    if policy.is_none() {
        return COMPLIANCE_STATUS_MISSING_POLICY.to_string();
    }
    if compliance.is_empty() {
        return COMPLIANCE_STATUS_NOT_APPLICABLE.to_string();
    }
    if compliance
        .values()
        .any(|entry| entry.compliance_status != COMPLIANCE_STATUS_MET)
    {
        return COMPLIANCE_STATUS_BREACHED.to_string();
    }
    COMPLIANCE_STATUS_MET.to_string()
}

/// The whole of a resiliency score. A score is reported as the FRACTION of its
/// maximum that was earned, so what is earned for everything a score is made up of
/// — one disruption type's objective, one scoring component's share — adds up to
/// this, and an application that meets everything it is judged on scores exactly
/// it.
const WHOLE_SCORE: f64 = 1.0;

/// The assessment's resiliency score: each disruption type the policy states an
/// objective for earns the whole of [`WHOLE_SCORE`] when that objective is reached
/// and none of it when it is not, and the application's score is the mean of them —
/// so the score says exactly how much of the policy the application meets, and an
/// application with nothing to judge scores nothing.
///
/// `componentScore` breaks that same score down by scoring component — see
/// [`component_score`].
fn resiliency_score(
    compliance: &::std::collections::HashMap<String, DisruptionCompliance>,
    breaching_components: &[String],
) -> ResiliencyScore {
    let disruption_score: ::std::collections::HashMap<String, f64> = compliance
        .iter()
        .map(|(disruption_type, entry)| {
            let score = if entry.compliance_status == COMPLIANCE_STATUS_MET {
                WHOLE_SCORE
            } else {
                0.0
            };
            (disruption_type.clone(), score)
        })
        .collect();
    let score = if disruption_score.is_empty() {
        0.0
    } else {
        disruption_score.values().sum::<f64>() / disruption_score.len() as f64
    };
    ResiliencyScore {
        component_score: Some(component_score(score, compliance, breaching_components)),
        score,
        disruption_score,
    }
}

/// The scoring component that grades an application against the objectives its
/// resiliency policy states, as the model's `ResiliencyScoreType` enum names it;
/// every other member of that enum ([`RESILIENCY_SCORE_TYPE_VALUES`]) is a
/// component graded on implemented recommendations instead — resiliency tests,
/// Amazon CloudWatch alarms and standard operating procedures.
const SCORING_COMPONENT_COMPLIANCE: &str = "Compliance";

/// How the assessment's score breaks down over the scoring components: one entry
/// per member of the model's `ResiliencyScoreType` enum, so a member that enum
/// gains is a component the breakdown reports. Every point of the score is earned
/// by the one component this service grades — compliance with the policy's
/// objectives — so that component's `possibleScore` is the whole share of the score
/// and its `score` is the part of that share the application earned, while a
/// component graded on implemented recommendations can earn no share and scores
/// nothing: this service records no test, alarm or standard operating procedure
/// recommendation, so there is none to implement and none to score. The shares
/// therefore add up to the whole of a score, and what the components earn adds up
/// to the score itself.
///
/// `outstandingCount` is what must still be done to reach that component's
/// `possibleScore` — for compliance, the Application Components that breached the
/// policy; `excludedCount` counts the recommendations excluded from the assessment,
/// and this service excludes none. Should this service ever record recommendations
/// to score, the shares have to be re-derived together, so that they still add up
/// to the whole of a score and what they earn still adds up to the score.
fn component_score(
    score: f64,
    compliance: &::std::collections::HashMap<String, DisruptionCompliance>,
    breaching_components: &[String],
) -> ::std::collections::HashMap<String, ScoringComponentResiliencyScore> {
    RESILIENCY_SCORE_TYPE_VALUES
        .iter()
        .map(|component| {
            let graded = if *component == SCORING_COMPONENT_COMPLIANCE {
                ScoringComponentResiliencyScore {
                    score,
                    possible_score: WHOLE_SCORE,
                    // Nothing breached a policy that states no objective to breach.
                    outstanding_count: if compliance.is_empty() {
                        0
                    } else {
                        breaching_components.len() as i64
                    },
                    excluded_count: 0,
                }
            } else {
                ScoringComponentResiliencyScore::default()
            };
            ((*component).to_string(), graded)
        })
        .collect()
}

/// Whether `stored` is the assessment `request` asks for — the idempotency check: a
/// replayed token with the same parameters answers the first assessment, a replayed
/// token with different parameters is a conflict.
///
/// `appVersion` is no part of the comparison: the only version this operation
/// assesses is the release alias, so two calls that reach here named the same one,
/// while the assessments they record pin whichever snapshot that alias resolved to
/// at each call.
fn describes_same_assessment(stored: &AppAssessment, request: &StartAppAssessmentInput) -> bool {
    stored.app_arn.as_deref() == Some(request.app_arn.as_str())
        && stored.assessment_name.as_deref() == Some(request.assessment_name.as_str())
        && stored.tags == crate::state::reported_tags(request.tags.clone())
}

/// The 500 for a service mounted on an engine that holds no state for it.
fn internal_failure() -> StartAppAssessmentError {
    StartAppAssessmentErrorModeled::InternalServerException(InternalServerException {
        message: Some("resiliencehub state is unavailable on this engine".to_string()),
    })
    .into()
}

/// A 404 `ResourceNotFoundException` for an `appArn` that was never created, or was
/// deleted, worded as this service words that error class.
fn app_not_found(app_arn: &str) -> StartAppAssessmentError {
    StartAppAssessmentErrorModeled::ResourceNotFoundException(ResourceNotFoundException {
        message: Some(crate::state::app_not_found_message(app_arn)),
        resource_id: Some(app_arn.to_string()),
        resource_type: Some("App".to_string()),
    })
    .into()
}

/// A 404 for an `appVersion` label that addresses no version of the application an
/// assessment was asked for — neither its draft nor a frozen release. The refusal
/// names the label, the application (by its stored name and the ARN the request
/// carried) and the precondition the label has to satisfy; see
/// [`crate::state::invalid_app_version_message`].
fn invalid_app_version(
    app_version: &str,
    app_name: &str,
    app_arn: &str,
) -> StartAppAssessmentError {
    StartAppAssessmentErrorModeled::ResourceNotFoundException(ResourceNotFoundException {
        message: Some(crate::state::invalid_app_version_message(
            app_version,
            app_name,
            app_arn,
        )),
        resource_id: Some(app_version.to_string()),
        resource_type: Some("AppVersion".to_string()),
    })
    .into()
}

/// A 400 `ValidationException` for an assessment of a version that is not the
/// application's published release: the request names a version this operation does
/// not assess, which is what this operation's `ValidationException` is for.
fn version_not_assessable(app_version: &str) -> StartAppAssessmentError {
    StartAppAssessmentErrorModeled::ValidationException(ValidationException {
        message: Some(format!(
            "AppAssessment version {app_version} is invalid, must be {}",
            crate::state::RELEASE_APP_VERSION
        )),
    })
    .into()
}

/// A 409 `ConflictException` naming the assessment that already holds the replayed
/// `clientToken`.
fn token_conflict(client_token: &str, assessment_arn: &str) -> StartAppAssessmentError {
    StartAppAssessmentErrorModeled::ConflictException(ConflictException {
        message: Some(format!(
            "clientToken {client_token} was already used to start app assessment \
             {assessment_arn} with different parameters"
        )),
        resource_id: Some(assessment_arn.to_string()),
        resource_type: Some("AppAssessment".to_string()),
    })
    .into()
}

/// The 402 for a request that would take one application past
/// [`crate::state::MAX_ASSESSMENTS_PER_APP`].
fn too_many_assessments(app_arn: &str) -> StartAppAssessmentError {
    StartAppAssessmentErrorModeled::ServiceQuotaExceededException(ServiceQuotaExceededException {
        message: Some(format!(
            "this emulator stores at most {} assessments per application, and {app_arn} \
             has that many",
            crate::state::MAX_ASSESSMENTS_PER_APP
        )),
    })
    .into()
}
