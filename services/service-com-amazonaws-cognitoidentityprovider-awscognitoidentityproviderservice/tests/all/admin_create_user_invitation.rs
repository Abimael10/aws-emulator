/// The wire error code of an error body (`__type`), without its namespace.
fn error_code(body: &Value) -> String {
    body["__type"]
        .as_str()
        .unwrap_or_default()
        .rsplit('#')
        .next()
        .unwrap_or_default()
        .to_string()
}

/// Create a symmetric key and return the ARN the key service minted for it.
async fn create_key(router: &MultiServiceRouter) -> String {
    let created = kms(router, "CreateKey", &json!({ "Description": "custom sender" })).await;
    created["KeyMetadata"]["Arn"]
        .as_str()
        .unwrap_or_else(|| panic!("CreateKey must mint a key ARN, got {created}"))
        .to_string()
}

/// A .zip deployment package holding `source` as the module the handler names.
fn package(source: &str) -> Vec<u8> {
    let mut buffer = std::io::Cursor::new(Vec::new());
    {
        let mut writer = zip::ZipWriter::new(&mut buffer);
        let options: zip::write::FileOptions<'_, '_, ()> = zip::write::FileOptions::default();
        writer
            .start_file("lambda_function.py", options)
            .expect("the entry starts");
        writer
            .write_all(source.as_bytes())
            .expect("the entry's bytes");
        writer.finish().expect("a finished archive");
    }
    buffer.into_inner()
}

/// One Lambda read, as its parsed body.
async fn lambda_get(router: &MultiServiceRouter, uri: &str) -> Value {
    let request = http::Request::builder()
        .method("GET")
        .uri(uri)
        .header("host", format!("lambda.{REGION}.amazonaws.com"))
        .header("authorization", authorization("lambda"))
        .body(Bytes::new())
        .expect("the test request is well formed");
    let response = router.dispatch(request).await;
    serde_json::from_slice(&response.into_body()).unwrap_or(Value::Null)
}

/// Create a Lambda function running `source`, and return the ARN Lambda minted for it.
///
/// An invocation only reaches a function Lambda reports as `Active`, and that transition
/// is the clock's, so the wait is for that CONDITION with a generous deadline.
async fn create_function(router: &MultiServiceRouter, name: &str, source: &str) -> String {
    let request = http::Request::builder()
        .method("POST")
        .uri(FUNCTIONS_URI)
        .header("host", format!("lambda.{REGION}.amazonaws.com"))
        .header("content-type", "application/json")
        .header("authorization", authorization("lambda"))
        .body(Bytes::from(
            serde_json::to_vec(&json!({
                "FunctionName": name,
                "Role": ROLE,
                "Runtime": "python3.12",
                "Handler": HANDLER,
                "Timeout": 30,
                "Code": {
                    "ZipFile": base64::engine::general_purpose::STANDARD.encode(package(source)),
                },
            }))
            .expect("the create body serializes"),
        ))
        .expect("the test request is well formed");
    let response = router.dispatch(request).await;
    let status = response.status().as_u16();
    let created: Value = serde_json::from_slice(&response.into_body()).unwrap_or(Value::Null);
    assert_eq!(
        status, 201,
        "CreateFunction must answer 201, got {status} with {created}"
    );
    let deadline = Instant::now() + ACTIVE_BUDGET;
    loop {
        let read = lambda_get(router, &format!("{FUNCTIONS_URI}/{name}/configuration")).await;
        if read["State"].as_str() == Some("Active") {
            break;
        }
        assert!(
            Instant::now() < deadline,
            "the function {name:?} never became Active within {ACTIVE_BUDGET:?}, got {read}"
        );
        tokio::time::sleep(LOOK_AGAIN).await;
    }
    // Amazon Cognito invokes a trigger as its OWN service principal, so the function's
    // resource-based policy has to admit it — the grant AWS asks for on every function a
    // pool's `LambdaConfig` names, written through the one spelling of it this crate has
    // (`crate::trigger_invoke_permission`, the suite that owns that rule).
    crate::trigger_invoke_permission::grant_cognito_trigger_invoke(router, REGION, name).await;
    created["FunctionArn"]
        .as_str()
        .unwrap_or_else(|| panic!("CreateFunction must mint an ARN, got {created}"))
        .to_string()
}

/// The handler the trigger function runs: it forwards what it was handed to the queue, so
/// what reached the function is what this suite reads.
fn handler_source(queue_url: &str) -> String {
    format!(
        r#"
import json

import boto3

QUEUE_URL = "{queue_url}"


def lambda_handler(event, context):
    client = boto3.client("sqs")
    client.send_message(
        QueueUrl=QUEUE_URL,
        MessageBody=json.dumps(
            {{
                "triggerSource": event["triggerSource"],
                "userName": event["userName"],
                "userPoolId": event["userPoolId"],
                "code": event["request"]["code"],
                "type": event["request"]["type"],
            }}
        ),
    )
    return {{}}
"#
    )
}

/// Create a pool whose `LambdaConfig` routes its email to `function_arn`, encrypting under
/// `key_arn`, plus an app client of it that admits the administrative password sign-in
/// these suites present a delivered password to.
async fn pool_with_client(
    router: &MultiServiceRouter,
    name: &str,
    function_arn: &str,
    key_arn: &str,
) -> (String, String) {
    pool_with_policy(router, name, function_arn, key_arn, &Value::Null).await
}

/// The same pool, with `password_policy` as its `Policies.PasswordPolicy` — `Value::Null`
/// for a pool that configures none and so keeps the documented defaults.
///
/// The pool also carries an `SmsConfiguration`, which is its SMS delivery path: a create
/// that asks for the invitation over SMS needs one, since a pool with no SMS path at all
/// refuses that request ([`crate::message_delivery_and_live_codes`] owns that rule), and
/// these suites are about which messages the custom EMAIL sender is handed.
async fn pool_with_policy(
    router: &MultiServiceRouter,
    name: &str,
    function_arn: &str,
    key_arn: &str,
    password_policy: &Value,
) -> (String, String) {
    let mut body = json!({
        "PoolName": name,
        "LambdaConfig": {
            "CustomEmailSender": { "LambdaVersion": "V1_0", "LambdaArn": function_arn },
            "KMSKeyID": key_arn,
        },
        "SmsConfiguration": { "SnsCallerArn": SNS_CALLER_ROLE },
    });
    if !password_policy.is_null() {
        body["Policies"] = json!({ "PasswordPolicy": password_policy.clone() });
    }
    let created = ok(router, "CreateUserPool", &body).await;
    let user_pool_id = created["UserPool"]["Id"]
        .as_str()
        .unwrap_or_else(|| panic!("CreateUserPool must mint an id, got {created}"))
        .to_string();
    let client = ok(
        router,
        "CreateUserPoolClient",
        &json!({
            "UserPoolId": user_pool_id,
            "ClientName": format!("{name}-app"),
            "ExplicitAuthFlows": ["ALLOW_ADMIN_USER_PASSWORD_AUTH", "ALLOW_REFRESH_TOKEN_AUTH"],
        }),
    )
    .await;
    let client_id = client["UserPoolClient"]["ClientId"]
        .as_str()
        .unwrap_or_else(|| panic!("CreateUserPoolClient must mint an id, got {client}"))
        .to_string();
    (user_pool_id, client_id)
}

/// Every message the queue holds right now, as the bodies the function wrote.
///
/// Each one is DELETED as it is read, so a message one row already accounted for cannot be
/// read a second time by the next.
async fn received(router: &MultiServiceRouter, queue_url: &str) -> Vec<Value> {
    let received = sqs(
        router,
        "ReceiveMessage",
        &json!({
            "QueueUrl": queue_url,
            "MaxNumberOfMessages": 10,
            "WaitTimeSeconds": RECEIVE_WAIT_SECONDS,
        }),
    )
    .await;
    let messages: Vec<Value> = received["Messages"]
        .as_array()
        .cloned()
        .unwrap_or_default();
    let mut bodies = Vec::with_capacity(messages.len());
    for message in &messages {
        if let Some(handle) = message["ReceiptHandle"].as_str() {
            sqs(
                router,
                "DeleteMessage",
                &json!({ "QueueUrl": queue_url, "ReceiptHandle": handle }),
            )
            .await;
        }
        if let Some(body) = message["Body"].as_str() {
            bodies.push(serde_json::from_str(body).unwrap_or(Value::Null));
        }
    }
    bodies
}

/// The message the trigger function forwarded for `username`, waited for until
/// [`DELIVERY_WAIT`] is spent.
async fn next_delivery(
    router: &MultiServiceRouter,
    case: &str,
    queue_url: &str,
    username: &str,
) -> Value {
    let deadline = Instant::now() + DELIVERY_WAIT;
    loop {
        let delivered = received(router, queue_url).await;
        if let Some(delivery) = delivered
            .into_iter()
            .find(|delivery| delivery["userName"].as_str() == Some(username))
        {
            return delivery;
        }
        assert!(
            Instant::now() < deadline,
            "case {case:?}: no custom sender delivery for {username:?} reached the queue \
             within {DELIVERY_WAIT:?}"
        );
        tokio::time::sleep(LOOK_AGAIN).await;
    }
}

/// The password a delivery carried, decrypted under the pool's own key.
///
/// Every step is the one a decrypting client performs: the member is base64, the bytes are
/// an encryption-SDK message, the key it names is asked to unwrap the data key, and the
/// message opens under the data key that comes back.
async fn decrypted(
    router: &MultiServiceRouter,
    case: &str,
    delivery: &Value,
    key_arn: &str,
) -> String {
    let carried = delivery["code"]
        .as_str()
        .unwrap_or_else(|| panic!("case {case:?}: the delivery carries nothing: {delivery}"));
    let bytes = base64::engine::general_purpose::STANDARD
        .decode(carried)
        .unwrap_or_else(|error| {
            panic!("case {case:?}: the message is not base64 ({error}): {carried}")
        });
    let parsed = esdk::parse(&bytes)
        .unwrap_or_else(|fault| panic!("case {case:?}: the member is not a message: {fault}"));
    assert_eq!(
        parsed.key_provider_info, key_arn,
        "case {case:?}: expected the pool's own key, got {:?}",
        parsed.key_provider_info
    );
    let unwrapped = kms(
        router,
        "Decrypt",
        &json!({
            "CiphertextBlob": base64::engine::general_purpose::STANDARD
                .encode(&parsed.encrypted_data_key),
        }),
    )
    .await;
    let data_key = base64::engine::general_purpose::STANDARD
        .decode(
            unwrapped["Plaintext"]
                .as_str()
                .unwrap_or_else(|| panic!("case {case:?}: Decrypt answered no plaintext")),
        )
        .expect("the key service answers base64");
    let opened = parsed
        .open(&data_key)
        .unwrap_or_else(|fault| panic!("case {case:?}: the message does not open: {fault}"));
    String::from_utf8(opened)
        .unwrap_or_else(|error| panic!("case {case:?}: the password is not text: {error}"))
}

/// Create `username` with an email address, asking for the invitation `body_extra` describes
/// on top of that, and return what the create answered.
async fn admin_create_user(
    router: &MultiServiceRouter,
    user_pool_id: &str,
    username: &str,
    extra: &Value,
) -> Value {
    let mut body = json!({
        "UserPoolId": user_pool_id,
        "Username": username,
        "UserAttributes": [{ "Name": "email", "Value": format!("{username}@example.test") }],
    });
    if let Some(members) = extra.as_object() {
        for (name, value) in members {
            body[name.as_str()] = value.clone();
        }
    }
    ok(router, "AdminCreateUser", &body).await
}

/// What an administrative password sign-in of `username` with `password` answered.
async fn sign_in(
    router: &MultiServiceRouter,
    user_pool_id: &str,
    client_id: &str,
    username: &str,
    password: &str,
) -> (u16, Value) {
    cognito(
        router,
        "AdminInitiateAuth",
        &json!({
            "UserPoolId": user_pool_id,
            "ClientId": client_id,
            "AuthFlow": "ADMIN_USER_PASSWORD_AUTH",
            "AuthParameters": { "USERNAME": username, "PASSWORD": password },
        }),
    )
    .await
}

/// Where the temporary password one row's invitation carries comes from.
#[derive(Debug, Clone, Copy)]
enum Credential {
    /// The request submitted it: "the user's temporary password"
    /// (`AdminCreateUser.TemporaryPassword`).
    Submitted,
    /// The request submitted none, so the pool generated one: "if you don't specify a
    /// value, Amazon Cognito generates one for you" (`AdminCreateUser.TemporaryPassword`).
    Generated,
}

#[tokio::test]
async fn the_invitation_hands_the_custom_sender_the_password_the_user_signs_in_with() {
    let router = router();
    let key_arn = create_key(&router).await;
    let queue = sqs(
        &router,
        "CreateQueue",
        &json!({ "QueueName": "invitation-sink" }),
    )
    .await;
    let queue_url = queue["QueueUrl"]
        .as_str()
        .expect("CreateQueue must mint a queue URL")
        .to_string();
    let function_arn =
        create_function(&router, "invitation-sender", &handler_source(&queue_url)).await;
    let (user_pool_id, client_id) =
        pool_with_client(&router, "invitation-pool", &function_arn, &key_arn).await;

    // One row per place the invitation's credential comes from: the rule is the trigger's
    // and not one request's, so a password the pool generated travels exactly as a
    // submitted one does.
    for credential in [Credential::Submitted, Credential::Generated] {
        let case = format!("{credential:?}");
        let username = format!("invited-{}", case.to_lowercase());
        let extra = match credential {
            Credential::Submitted => json!({
                "DesiredDeliveryMediums": ["EMAIL"],
                "TemporaryPassword": SUBMITTED_PASSWORD,
            }),
            Credential::Generated => json!({ "DesiredDeliveryMediums": ["EMAIL"] }),
        };
        let created = admin_create_user(&router, &user_pool_id, &username, &extra).await;
        assert_eq!(
            created["User"]["UserStatus"].as_str(),
            Some("FORCE_CHANGE_PASSWORD"),
            "case {case:?}: an invited user owes its invitation a password change, got {created}"
        );

        let delivery = next_delivery(&router, &case, &queue_url, &username).await;
        assert_eq!(
            (
                delivery["triggerSource"].as_str(),
                delivery["userName"].as_str(),
                delivery["userPoolId"].as_str(),
                delivery["type"].as_str(),
            ),
            (
                Some(ADMIN_CREATE_USER_SOURCE),
                Some(username.as_str()),
                Some(user_pool_id.as_str()),
                Some("customEmailSenderRequestV1"),
            ),
            "case {case:?}: expected the create's own invitation event, got {delivery}"
        );

        let delivered = decrypted(&router, &case, &delivery, &key_arn).await;
        match credential {
            Credential::Submitted => assert_eq!(
                delivered, SUBMITTED_PASSWORD,
                "case {case:?}: expected the submitted password, got {delivered:?}"
            ),
            Credential::Generated => assert!(
                !delivered.is_empty() && !delivered.chars().any(char::is_whitespace),
                "case {case:?}: expected a generated password with no whitespace, \
                 got {delivered:?}"
            ),
        }

        // The delivered password is the account's real credential: it is what the sign-in
        // accepts, and what it accepts is the challenge to replace it.
        let (status, answered) =
            sign_in(&router, &user_pool_id, &client_id, &username, &delivered).await;
        assert_eq!(
            (status, answered["ChallengeName"].as_str()),
            (200, Some("NEW_PASSWORD_REQUIRED")),
            "case {case:?}: the delivered password must sign the user in, got {status} \
             with {answered}"
        );

        // A password that was not delivered is not the account's credential.
        let (status, refused) = sign_in(
            &router,
            &user_pool_id,
            &client_id,
            &username,
            NOT_THE_DELIVERED_PASSWORD,
        )
        .await;
        assert_eq!(
            (status, error_code(&refused).as_str()),
            (400, "NotAuthorizedException"),
            "case {case:?}: a password the invitation never carried must be refused, \
             got {status} with {refused}"
        );
    }

    // A resend "resend[s] the invitation message to a user that already exists, and ...
    // reset[s] the temporary-password duration with a new temporary password"
    // (`AdminCreateUser.MessageAction`): the function is handed a FRESH password, and that
    // one is the credential from then on.
    let case = "RESEND";
    let username = "invited-submitted";
    admin_create_user(
        &router,
        &user_pool_id,
        username,
        &json!({ "DesiredDeliveryMediums": ["EMAIL"], "MessageAction": "RESEND" }),
    )
    .await;
    let resent = next_delivery(&router, case, &queue_url, username).await;
    assert_eq!(
        (
            resent["triggerSource"].as_str(),
            resent["userName"].as_str()
        ),
        (Some(ADMIN_CREATE_USER_SOURCE), Some(username)),
        "case {case:?}: expected the invitation's own event again, got {resent}"
    );
    let resent_password = decrypted(&router, case, &resent, &key_arn).await;
    assert_ne!(
        resent_password, SUBMITTED_PASSWORD,
        "case {case:?}: expected a fresh password, got the one the create delivered"
    );
    let (status, answered) = sign_in(
        &router,
        &user_pool_id,
        &client_id,
        username,
        &resent_password,
    )
    .await;
    assert_eq!(
        (status, answered["ChallengeName"].as_str()),
        (200, Some("NEW_PASSWORD_REQUIRED")),
        "case {case:?}: the resent password must sign the user in, got {status} with {answered}"
    );
    let (status, refused) = sign_in(
        &router,
        &user_pool_id,
        &client_id,
        username,
        SUBMITTED_PASSWORD,
    )
    .await;
    assert_eq!(
        (status, error_code(&refused).as_str()),
        (400, "NotAuthorizedException"),
        "case {case:?}: the superseded password must be refused, got {status} with {refused}"
    );
}

/// Why one row's create sends no email invitation at all.
#[derive(Debug, Clone, Copy)]
enum Unsent {
    /// "Set to SUPPRESS to suppress sending the message"
    /// (`AdminCreateUser.MessageAction`).
    Suppressed,
    /// The message was asked for over the other medium: "specify SMS if the phone number
    /// will be used" (`AdminCreateUser.DesiredDeliveryMediums`), which a custom EMAIL
    /// sender is not the channel of.
    OtherMedium,
}

#[tokio::test]
async fn a_create_that_sends_no_email_invitation_hands_the_custom_sender_nothing() {
    let router = router();
    let key_arn = create_key(&router).await;
    let queue = sqs(
        &router,
        "CreateQueue",
        &json!({ "QueueName": "unsent-sink" }),
    )
    .await;
    let queue_url = queue["QueueUrl"]
        .as_str()
        .expect("CreateQueue must mint a queue URL")
        .to_string();
    let function_arn =
        create_function(&router, "unsent-sender", &handler_source(&queue_url)).await;
    let (user_pool_id, _client_id) =
        pool_with_client(&router, "unsent-pool", &function_arn, &key_arn).await;

    // Each row's create is answered before the next call is made, and the trigger is
    // invoked before the create answers, so anything these rows delivered is already in
    // the queue by the time the sentinel below is created.
    let mut quiet = Vec::new();
    for unsent in [Unsent::Suppressed, Unsent::OtherMedium] {
        let case = format!("{unsent:?}");
        let username = format!("uninvited-{}", case.to_lowercase());
        let extra = match unsent {
            Unsent::Suppressed => json!({
                "DesiredDeliveryMediums": ["EMAIL"],
                "MessageAction": "SUPPRESS",
            }),
            Unsent::OtherMedium => json!({
                "DesiredDeliveryMediums": ["SMS"],
                "UserAttributes": [
                    { "Name": "email", "Value": "uninvited-othermedium@example.test" },
                    { "Name": "phone_number", "Value": "+15555550123" },
                ],
            }),
        };
        let created = admin_create_user(&router, &user_pool_id, &username, &extra).await;
        assert_eq!(
            created["User"]["UserStatus"].as_str(),
            Some("FORCE_CHANGE_PASSWORD"),
            "case {case:?}: the account is created either way, got {created}"
        );
        // Read back through the pool's own reader: an account with no invitation is still
        // an account.
        let read = ok(
            &router,
            "AdminGetUser",
            &json!({ "UserPoolId": user_pool_id, "Username": username }),
        )
        .await;
        assert_eq!(
            read["Username"].as_str(),
            Some(username.as_str()),
            "case {case:?}: the created user must read back, got {read}"
        );
        quiet.push(username);
    }

    // The sentinel: one create that DOES send its invitation, so the absence above is read
    // off a queue that has been reached rather than off a wait.
    let sentinel = "invited-sentinel";
    admin_create_user(
        &router,
        &user_pool_id,
        sentinel,
        &json!({ "DesiredDeliveryMediums": ["EMAIL"] }),
    )
    .await;
    let mut seen: Vec<Value> = Vec::new();
    let deadline = Instant::now() + DELIVERY_WAIT;
    loop {
        seen.extend(received(&router, &queue_url).await);
        if seen
            .iter()
            .any(|delivery| delivery["userName"].as_str() == Some(sentinel))
        {
            break;
        }
        assert!(
            Instant::now() < deadline,
            "the sentinel's invitation never reached the queue within {DELIVERY_WAIT:?}, \
             saw {seen:?}"
        );
        tokio::time::sleep(LOOK_AGAIN).await;
    }
    for username in quiet {
        assert!(
            !seen
                .iter()
                .any(|delivery| delivery["userName"].as_str() == Some(username.as_str())),
            "case {username:?}: a create that sends no email invitation must hand the \
             custom sender nothing, saw {seen:?}"
        );
    }
}

/// One character class a password policy can require: what it is called in a failed
/// assertion, and whether a character belongs to it.
type PasswordClass = (&'static str, fn(char) -> bool);

/// One pool's password policy, and what a password of it has to carry.
///
/// The members are `PasswordPolicyType`'s own — `MinimumLength`, `RequireUppercase`,
/// `RequireLowercase`, `RequireNumbers` and `RequireSymbols` (this service's model) — and
/// the requirements a row states are the ones the pool it creates configures.
struct Policy {
    /// What the row is called in a failed assertion.
    case: &'static str,
    /// The `PasswordPolicy` the pool is created with, or `Value::Null` for the documented
    /// defaults.
    configured: fn() -> Value,
    /// The length a password of that policy must reach.
    minimum_length: usize,
    /// The character classes that policy requires, as the test can decide them.
    required: &'static [PasswordClass],
}

/// Whether `c` counts as a symbol: neither a letter nor a digit, which is the complement of
/// the classes `PasswordPolicyType` names beside `RequireSymbols`.
fn is_symbol(c: char) -> bool {
    !c.is_alphanumeric()
}

#[tokio::test]
async fn a_generated_invitation_password_satisfies_the_pools_own_policy() {
    // The classes a policy can require, decided here rather than read back from the
    // service: `RequireUppercase` / `RequireLowercase` / `RequireNumbers` /
    // `RequireSymbols` (`PasswordPolicyType`).
    const EVERY_CLASS: &[PasswordClass] = &[
        ("an uppercase character", |c: char| c.is_uppercase()),
        ("a lowercase character", |c: char| c.is_lowercase()),
        ("a digit", |c: char| c.is_ascii_digit()),
        ("a symbol", is_symbol),
    ];

    // Rows differ along the policy the pool configured: the defaults, the shortest
    // password the model's own bound admits with nothing required, and a long one with
    // every class required.
    let policies = [
        Policy {
            case: "the documented defaults",
            configured: || Value::Null,
            minimum_length: 8,
            required: EVERY_CLASS,
        },
        Policy {
            case: "the model's own minimum, nothing required",
            configured: || {
                json!({
                    "MinimumLength": 6,
                    "RequireUppercase": false,
                    "RequireLowercase": false,
                    "RequireNumbers": false,
                    "RequireSymbols": false,
                })
            },
            minimum_length: 6,
            required: &[],
        },
        Policy {
            case: "a long password with every class required",
            configured: || {
                json!({
                    "MinimumLength": 20,
                    "RequireUppercase": true,
                    "RequireLowercase": true,
                    "RequireNumbers": true,
                    "RequireSymbols": true,
                })
            },
            minimum_length: 20,
            required: EVERY_CLASS,
        },
    ];

    let router = router();
    let key_arn = create_key(&router).await;
    let queue = sqs(
        &router,
        "CreateQueue",
        &json!({ "QueueName": "policy-sink" }),
    )
    .await;
    let queue_url = queue["QueueUrl"]
        .as_str()
        .expect("CreateQueue must mint a queue URL")
        .to_string();
    let function_arn =
        create_function(&router, "policy-sender", &handler_source(&queue_url)).await;

    for (index, policy) in policies.iter().enumerate() {
        let case = policy.case;
        let (user_pool_id, client_id) = pool_with_policy(
            &router,
            &format!("policy-pool-{index}"),
            &function_arn,
            &key_arn,
            &(policy.configured)(),
        )
        .await;
        let username = format!("invited-policy-{index}");
        admin_create_user(
            &router,
            &user_pool_id,
            &username,
            &json!({ "DesiredDeliveryMediums": ["EMAIL"] }),
        )
        .await;
        let delivery = next_delivery(&router, case, &queue_url, &username).await;
        let delivered = decrypted(&router, case, &delivery, &key_arn).await;

        assert!(
            delivered.chars().count() >= policy.minimum_length,
            "case {case:?}: expected at least {} characters, got {delivered:?}",
            policy.minimum_length
        );
        assert!(
            !delivered.chars().any(char::is_whitespace),
            "case {case:?}: a password carries no whitespace, got {delivered:?}"
        );
        for (class, holds) in policy.required {
            assert!(
                delivered.chars().any(holds),
                "case {case:?}: expected {class}, got {delivered:?}"
            );
        }

        // The policy is satisfied in the only way that counts: the pool itself accepts the
        // password it generated as this account's credential.
        let (status, answered) =
            sign_in(&router, &user_pool_id, &client_id, &username, &delivered).await;
        assert_eq!(
            (status, answered["ChallengeName"].as_str()),
            (200, Some("NEW_PASSWORD_REQUIRED")),
            "case {case:?}: the generated password must sign the user in, got {status} \
             with {answered}"
        );
    }
}
