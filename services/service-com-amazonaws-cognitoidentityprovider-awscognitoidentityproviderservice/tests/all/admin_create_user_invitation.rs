//! The invitation an administrative create sends, on a pool that routes its email to a
//! custom sender Lambda trigger.
//!
//! The rule under test: on a pool whose `LambdaConfig` carries a `CustomEmailSender` —
//! "this trigger routes all email notifications from a user pool to a Lambda function"
//! (`LambdaConfigType$CustomEmailSender`) — every message the pool would have emailed is
//! handed to that function instead, encrypted under `LambdaConfig.KMSKeyID`: "Amazon
//! Cognito uses the key to encrypt codes and temporary passwords sent to
//! `CustomEmailSender` and `CustomSMSSender`" (`LambdaConfigType$KMSKeyID`). The
//! invitation `AdminCreateUser` sends is such a message — it carries the temporary
//! password "the user must enter ... in the sign-in page, along with a new password to be
//! used in all future sign-ins" (`AdminCreateUser.TemporaryPassword`), generated by the
//! pool when the request submits none — so the function receives it under the trigger
//! source of that stage, and the credential it decrypts is the one that signs the created
//! user in.
//!
//! Two suites:
//!
//! 1. the invitation reaches the function and the password it carries is the account's
//!    real credential — over a table whose rows differ along where the password came from
//!    (submitted by the request, or generated by the pool), plus the resend that replaces
//!    it ("set to RESEND to resend the invitation message to a user that already exists,
//!    and to reset the temporary-password duration with a new temporary password",
//!    `AdminCreateUser.MessageAction`);
//! 2. a create that sends no email invitation hands over nothing — over a table whose
//!    rows differ along why no message is sent (suppressed, or asked for over the other
//!    medium).
//!
//! Nothing here asserts a value baked into a service: the key ARN, the queue URL, the
//! function ARN, the pool id and every password all come back from the state these calls
//! created, and a generated password is only ever read out of what the function reported.

use std::io::Write as _;
use std::sync::Arc;
use std::time::{Duration, Instant};

use base64::Engine as _;
use bytes::Bytes;
use serde_json::{json, Value};
use smithy_server_runtime::MultiServiceRouter;

use service_com_amazonaws_cognitoidentityprovider_awscognitoidentityproviderservice as cognito_idp;

use cognito_idp::state::lambda_triggers::esdk;

/// The Region every request below is signed for.
const REGION: &str = "us-east-1";

/// The local name of Cognito's Smithy shape, which is the `X-Amz-Target` prefix.
const COGNITO_TARGET_PREFIX: &str = "AWSCognitoIdentityProviderService";

/// The `X-Amz-Target` prefix of the key service.
const KMS_TARGET_PREFIX: &str = "TrentService";

/// The `X-Amz-Target` prefix of Amazon SQS.
const SQS_TARGET_PREFIX: &str = "AmazonSQS";

/// Where Lambda's `CreateFunction` is bound.
const FUNCTIONS_URI: &str = "/2015-03-31/functions";

/// A well-formed execution role ARN, satisfying Lambda's `Role` pattern.
const ROLE: &str = "arn:aws:iam::000000000000:role/service-role/lambda-exec";

/// The Amazon SNS caller role a pool's `SmsConfiguration` names, which is the SMS delivery
/// path the pools below carry: "the ARN of the IAM role in your Amazon Web Services account
/// that Amazon Cognito will use to send SMS messages" (`SmsConfigurationType.SnsCallerArn`).
const SNS_CALLER_ROLE: &str = "arn:aws:iam::000000000000:role/service-role/cognito-sms";

/// The module and attribute the trigger function's package carries its handler as.
const HANDLER: &str = "lambda_function.lambda_handler";

/// The one `triggerSource` an administrative create's invitation carries: the trigger and
/// the stage that sent the message.
const ADMIN_CREATE_USER_SOURCE: &str = "CustomEmailSender_AdminCreateUser";

/// A temporary password satisfying a default pool's password policy, for the row whose
/// request submits one.
const SUBMITTED_PASSWORD: &str = "Temp0rary!2024";

/// A password satisfying that policy that no row's invitation carries, for the refusal a
/// password other than the delivered one earns.
const NOT_THE_DELIVERED_PASSWORD: &str = "Someth1ng!Else";

/// How long these suites wait for a message the trigger function forwarded. Generous: the
/// wait is for the message, and a loaded host takes far longer than an idle one.
const DELIVERY_WAIT: Duration = Duration::from_secs(60);

/// How long a poll of the queue waits for a message to appear.
const RECEIVE_WAIT_SECONDS: u64 = 1;

/// How long these suites wait for the trigger function to become `Active`. Generous for
/// the same reason.
const ACTIVE_BUDGET: Duration = Duration::from_secs(60);

/// How often a wait looks again.
const LOOK_AGAIN: Duration = Duration::from_millis(50);

/// Cognito, the key service, Lambda and Amazon SQS over ONE shared engine, as
/// `core/router/src/lib.rs` mounts them: the trigger wraps the message with a key the key
/// service holds and hands it to a function Lambda holds, which writes what it received to
/// a queue.
fn router() -> MultiServiceRouter {
    let engine: Arc<engine::InMemoryEngine> = Arc::new(engine::InMemoryEngine::new());
    let mut router = MultiServiceRouter::new();
    router.set_request_authentication(false);
    router.register_service(cognito_idp::EmulatedService::new(Arc::clone(&engine)));
    router.register_service(service_com_amazonaws_kms_trentservice::EmulatedService::new(
        Arc::clone(&engine),
    ));
    router.register_service(
        service_com_amazonaws_lambda_awsgirapiservice::EmulatedService::new(Arc::clone(&engine)),
    );
    router.register_service(service_com_amazonaws_sqs_amazonsqs::EmulatedService::new(
        Arc::clone(&engine),
    ));
    router
}

/// A SigV4 `Authorization` whose credential scope names `service`, which is what routes
/// the request. The signature is never checked here.
fn authorization(service: &str) -> String {
    format!(
        "AWS4-HMAC-SHA256 Credential=emulator-test-key/20260101/{REGION}/{service}/aws4_request, \
         SignedHeaders=host, Signature=not-verified"
    )
}

/// One `awsJson` call to the service whose signing name is `service`, addressed by
/// `X-Amz-Target`.
async fn json_call(
    router: &MultiServiceRouter,
    service: &str,
    content_type: &str,
    target: &str,
    body: &Value,
) -> (u16, Value) {
    let request = http::Request::builder()
        .method("POST")
        .uri("/")
        .header("host", format!("{service}.{REGION}.amazonaws.com"))
        .header("content-type", content_type)
        .header("x-amz-target", target)
        .header("authorization", authorization(service))
        .body(Bytes::from(
            serde_json::to_vec(body).expect("the request body serializes"),
        ))
        .expect("the test request is well formed");
    let response = router.dispatch(request).await;
    let status = response.status().as_u16();
    let bytes = response.into_body();
    let parsed = if bytes.is_empty() {
        Value::Null
    } else {
        serde_json::from_slice(&bytes).unwrap_or(Value::Null)
    };
    (status, parsed)
}

/// One Cognito call, as its status and parsed body.
async fn cognito(router: &MultiServiceRouter, operation: &str, body: &Value) -> (u16, Value) {
    json_call(
        router,
        "cognito-idp",
        "application/x-amz-json-1.1",
        &format!("{COGNITO_TARGET_PREFIX}.{operation}"),
        body,
    )
    .await
}

/// A Cognito call that must answer 200, with its response body.
async fn ok(router: &MultiServiceRouter, operation: &str, body: &Value) -> Value {
    let (status, payload) = cognito(router, operation, body).await;
    assert_eq!(
        status, 200,
        "{operation} must succeed, got {status} with {payload}"
    );
    payload
}

