/// Everything this call is refused for, and what the rotation it starts is driven with.
///
/// Taken under the store's guard and taken AGAIN once that guard has been re-acquired, so
/// every refusal is decided against what the store holds when the rotation is applied.
fn plan(
    store: &mut crate::state::ComAmazonawsSecretsmanagerSecretsmanagerState,
    region: &str,
    input: &RotateSecretInput,
    requesting_owner: Option<&crate::state::service_owned::OwningService>,
    under_managed_rotation: bool,
) -> Result<Planned, RotateSecretError> {
    // "A unique identifier for the new version of the secret. ... If you use
    // the Amazon Web Services CLI or one of the Amazon Web Services SDKs to
    // call this operation, then you can leave this parameter empty. The CLI
    // or SDK generates a random UUID for you": the id of the version this
    // rotation creates, minted here when the caller named none.
    let version_id = input
        .client_request_token
        .clone()
        .unwrap_or_else(crate::state::new_version_id);
    // "The default for RotateImmediately is true. If you don't specify this
    // value, Secrets Manager rotates the secret immediately."
    let rotate_immediately = input.rotate_immediately.unwrap_or(true);

    let Some(secret) = store.get(region, &input.secret_id) else {
        return Err(RotateSecretErrorModeled::ResourceNotFoundException(
            ResourceNotFoundException {
                message: Some(crate::state::SECRET_NOT_FOUND_MESSAGE.to_string()),
            },
        )
        .into());
    };

    // "In RotateSecret, you can set the rotation schedule in RotationRules
    // with AutomaticallyAfterDays or ScheduleExpression, but not both" —
    // rules that cannot hold together, or a schedule expression that is not
    // one of the documented forms, are refused before anything is stored.
    // Checked after the secret is resolved, so a call that names a secret
    // this service does not hold is answered with that, whatever else it
    // carries. `configure_rotation` reads the same schedule back out of the
    // stored rules when it computes the next due instant.
    if let Some(rules) = input.rotation_rules.as_ref() {
        crate::state::parse_rotation_rules(rules).map_err(invalid_parameter)?;
    }

    // The documented causes of `InvalidRequestException`, in the order the
    // model lists them: "The secret is scheduled for deletion. You tried to
    // enable rotation on a secret that doesn't already have a Lambda
    // function ARN configured and you didn't include such an ARN as a
    // parameter in this call. The secret is managed by another service, and
    // you must use that service to update it."
    if secret.scheduled_for_deletion() {
        return Err(invalid_request(crate::state::MARKED_FOR_DELETION_MESSAGE));
    }
    // A replica tracks its primary, so the rotation of the secret is
    // configured and started on the primary, and the versions it creates
    // reach the replica from there.
    if secret.is_replica() {
        return Err(invalid_parameter(
            crate::state::NOT_PERMITTED_ON_REPLICA_MESSAGE.to_string(),
        ));
    }
    if let Some(owner) = crate::state::service_owned::refusing_owner(
        secret.owning_service.as_deref(),
        requesting_owner,
    ) {
        // A secret under that service's MANAGED ROTATION is the one thing about it a caller
        // still asks Secrets Manager for: there is no rotation function of the caller's, the
        // managing service performs the rotation, and this call is how it is asked for. So a
        // call that asks for nothing BUT the rotation is served and handed over
        // ([`crate::state::managed_rotation`]), while one that would CONFIGURE rotation on
        // the secret — name a function, a schedule or an external rotation role — is asking
        // to change the secret, which is the owning service's to change.
        if !under_managed_rotation || configures_rotation(input) {
            return Err(invalid_request(
                crate::state::service_owned::managed_by_another_service_message(owner),
            ));
        }
    }
    // "For secrets that use a Lambda rotation function to rotate, the ARN of
    // the Lambda rotation function. For secrets that use managed rotation,
    // omit this field" — and a managed external secret names a rotation role
    // instead, so a rotation is configurable once the secret has either, from
    // this call or from a previous one. An empty `RotationLambdaARN` names no
    // function (`RotationLambdaARNType` is modelled with a minimum length of
    // 0).
    let configured_lambda_arn = input
        .rotation_lambda_arn
        .clone()
        .filter(|arn| !arn.is_empty());
    // A rotation is driven by INVOKING the function this member names, so the value has to
    // name one: a value that is not the ARN of a Lambda function states no function to
    // invoke (`crate::state::rotation::names_a_function`), which is a malformed parameter
    // rather than a secret that has no rotation function at all.
    if configured_lambda_arn
        .as_deref()
        .is_some_and(|arn| !crate::state::rotation::names_a_function(arn))
    {
        return Err(invalid_request(
            crate::state::rotation::not_a_function_message(region),
        ));
    }
    let role_arn = input
        .external_secret_rotation_role_arn
        .clone()
        .filter(|arn| !arn.is_empty());
    if configured_lambda_arn.is_none()
        && role_arn.is_none()
        && secret.rotation_lambda_arn.is_none()
        && secret.external_rotation_role_arn.is_none()
        // "For secrets that use managed rotation, omit this field": such a secret has no
        // rotation function BY DESIGN — the service that owns it performs the rotation — so
        // naming none for it is not "rotation enabled on a secret that has no function".
        && !under_managed_rotation
    {
        return Err(invalid_request(crate::state::NO_ROTATION_FUNCTION_MESSAGE));
    }

    // "If the AWSPENDING staging label is present but not attached to the
    // same version as AWSCURRENT, then any later invocation of RotateSecret
    // assumes that a previous rotation request is still in progress and
    // returns an error." The sentence is AWS's own for that condition, and it is
    // fixed: it names no version, because what it reports is that a rotation of
    // this secret has not finished and will be tried again.
    //
    // It is a LATER invocation — one asking for a rotation beside the outstanding one — that
    // the refusal stands for, so two calls do not earn it. The first is the one whose rotation
    // was CANCELLED (`resumable_rotation_version_id`): nothing will reattempt that rotation, so
    // this call RESUMES it instead — the rotation it starts is the cancelled one, staked on the
    // id that rotation already holds, which is why the call reports that id rather than minting
    // a version under the token it carried. The second is the one that NAMES the candidate of a
    // rotation that has ENDED unfinished ([`re_driven_candidate`]), which is that same rotation
    // being driven again rather than a further one. Every other outstanding candidate keeps the
    // refusal.
    let resumed = secret
        .resumable_rotation_version_id()
        .map(str::to_string)
        .or_else(|| re_driven_candidate(secret, input));
    if resumed.is_none() && secret.rotation_in_progress() {
        return Err(invalid_request(crate::state::ROTATION_IN_PROGRESS_MESSAGE));
    }
    // A `ClientRequestToken` this secret already has a version under is NOT refused:
    // "This value helps ensure idempotency. Secrets Manager uses this value to prevent
    // the accidental creation of duplicate versions if there are failures and retries
    // during a rotation" (`RotateSecretRequest$ClientRequestToken`, this service's
    // Smithy model) — so a rotation retried under the token a previous attempt staked
    // is THAT rotation again, staked on the version that attempt left behind, rather
    // than a request the service rejects for the token's sake. The model's causes of
    // `InvalidRequestException` for this operation are the state ones checked above,
    // and a token naming a stored version is not among them.

    Ok(Planned {
        arn: secret.arn.clone(),
        // A resumed rotation keeps working on the candidate it already staked, so the id is
        // that one rather than the token this call carried.
        version_id: resumed.unwrap_or(version_id),
        rotate_immediately,
        // The rotation is driven through the function in force for this secret once this
        // call's configuration is applied: the one it names, else the one already stored.
        lambda_arn: configured_lambda_arn
            .clone()
            .or_else(|| secret.rotation_lambda_arn.clone()),
        configured_lambda_arn,
        role_arn,
    })
}

/// The outstanding candidate this call RE-DRIVES the rotation of, rather than being refused
/// for it: the one its own `ClientRequestToken` names, once that rotation has ENDED.
/// `None` for every other call, which includes every call that carries no token of its own.
///
/// Two sentences of the model decide this together. The refusal is for a rotation STILL IN
/// PROGRESS — "any later invocation of RotateSecret assumes that a previous rotation request is
/// still in progress and returns an error" — and a rotation whose function ran a step and did
/// not complete it is not in progress any more: it reached a terminal outcome, recorded as such
/// (`crate::state::Secret::rotation_stopped`), and nothing is driving it. What a call may then
/// do with that rotation is what its token says: "a unique identifier for the new version of
/// the secret. You only need to specify this value if you implement your own retry logic and
/// you want to ensure that Secrets Manager doesn't attempt to create a secret version twice.
/// [...] This value helps ensure idempotency. Secrets Manager uses this value to prevent the
/// accidental creation of duplicate versions if there are failures and retries during a
/// rotation" (`RotateSecretRequest$ClientRequestToken`, `@idempotencyToken`) — so a call naming
/// the stopped rotation's own version IS that rotation being retried, which is the recovery a
/// client whose rotation function failed part-way makes once that function is repaired. It is
/// served on the version already staked, and mints no second one. A call naming any other
/// version asks for a rotation BESIDE the outstanding candidate, and keeps the refusal.
fn re_driven_candidate(
    secret: &crate::state::Secret,
    input: &RotateSecretInput,
) -> Option<String> {
    if !secret.rotation_stopped {
        return None;
    }
    let token = input.client_request_token.as_deref()?;
    secret
        .pending_version_id()
        .filter(|pending| *pending == token)
        .map(str::to_string)
}

/// Whether this call would CONFIGURE rotation for the secret, rather than only ask for a
/// rotation of it: "If you include the configuration parameters, the operation sets the
/// values for the secret and then immediately starts a rotation. If you don't include the
/// configuration parameters, the operation starts a rotation with the values already stored
/// in the secret" (`RotateSecret`, this service's Smithy model).
///
/// The configuration parameters are the rotation function, the schedule, and the external
/// rotation a partner-held secret is rotated through; an empty value for either ARN names
/// nothing (both are modelled with a minimum length of 0).
fn configures_rotation(input: &RotateSecretInput) -> bool {
    input
        .rotation_lambda_arn
        .as_deref()
        .is_some_and(|arn| !arn.is_empty())
        || input.rotation_rules.is_some()
        || input
            .external_secret_rotation_metadata
            .as_ref()
            .is_some_and(|items| !items.is_empty())
        || input
            .external_secret_rotation_role_arn
            .as_deref()
            .is_some_and(|arn| !arn.is_empty())
}

/// `InvalidParameterException` for a parameter value this operation refuses:
/// "The parameter name or value is invalid."
fn invalid_parameter(message: String) -> RotateSecretError {
    RotateSecretErrorModeled::InvalidParameterException(InvalidParameterException {
        message: Some(message),
    })
    .into()
}

/// `InvalidRequestException` for a request this secret's current state does not
/// allow: "A parameter value is not valid for the current state of the
/// resource."
fn invalid_request(message: impl Into<String>) -> RotateSecretError {
    RotateSecretErrorModeled::InvalidRequestException(InvalidRequestException {
        message: Some(message.into()),
    })
    .into()
}

/// The modelled server error for a rotation the MANAGING service did not perform: this
/// emulator could not hand the rotation to the service that owns the secret, or that service
/// refused it.
///
/// It is a server-side fault, never anything the request carried: the request asked for the
/// one thing such a secret is rotated by, and the credential is unchanged.
fn rotation_not_performed(message: String) -> RotateSecretError {
    RotateSecretErrorModeled::InternalServiceError(InternalServiceError {
        message: Some(message),
    })
    .into()
}

/// The modelled server error for a request that cannot reach this service's
/// store. `service_state` answers `None` only when the engine is not the shared
/// in-memory one, which is a server-side fault, never a bad request.
fn state_unavailable() -> RotateSecretError {
    RotateSecretErrorModeled::InternalServiceError(InternalServiceError {
        message: Some("the Secrets Manager emulator's state store is unavailable".to_string()),
    })
    .into()
}
