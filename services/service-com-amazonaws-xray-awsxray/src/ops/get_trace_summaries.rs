//! @op GetTraceSummaries
//!
//! Selects the stored traces whose earliest segment `start_time` falls in
//! [`StartTime`, `EndTime`) and, when the request carries a `FilterExpression`,
//! the ones that expression selects ([`crate::state::filter`]); each
//! `TraceSummary` is then built from the persisted segment documents, so a trace
//! just written by `PutTraceSegments` appears here. `TracesProcessedCount`
//! counts the traces the REQUESTED WINDOW holds — the ones this query took
//! through the filter, matching or not — so it stays consistent with the
//! summaries served for that window, is the same on every page of one query,
//! and reports none for a window holding nothing. A query may also scope itself
//! to a stored GROUP, which is resolved against the stored groups before the
//! expression is parsed ([`crate::state::group_scope`]) and narrows the query by
//! the expression that group carries, and it may ask for "only a subset of
//! available traces", which takes a deterministic sample of what the window, the
//! group and the expression selected, at the rate the request states.
//!
//! A summary's `ServiceIds` are the NODES of that trace's own service graph
//! ([`crate::state::service_graph`]) — the root service typed by the `origin` it
//! reported, the services it called typed by those calls, and the `client` node
//! for the callers of each root segment — so the services a summary reports and
//! the nodes a service map draws for the same stored segments cannot disagree.
//!
//! The answer is PAGED by the REQUESTED WINDOW itself: the pages of one query
//! are steps of `[StartTime, EndTime)` measured back from its own `EndTime`
//! ([`crate::state::trace_pages`]), never cut on a grid the request never named,
//! so a window no longer than one step is answered in ONE page carrying every
//! trace it holds — a trace just accepted is in the answer to the minutes-wide
//! window that covers it. `ApproximateTime` is the start of the step this page
//! served, which is the requested `StartTime` for the page that reaches it, and
//! a `NextToken` is due while the query has anything left to serve — the rest of
//! a step holding more summaries than one page carries
//! ([`TRACE_SUMMARIES_PAGE_SIZE`]), or the step before it while the window
//! reaches into one.
//!
//! A request outside what this read serves is REFUSED with
//! `InvalidRequestException` rather than answered over part of it: an inverted
//! time range, a window wider than the longest one this read serves
//! ([`crate::state::MAX_TRACE_SUMMARIES_WINDOW_HOURS`]) or ending further ahead
//! of the clock than it reaches
//! ([`crate::state::MAX_TRACE_SUMMARIES_FUTURE_MINUTES`]), a sampling strategy
//! named beside a time-range type that does not admit one, and a sampled query
//! stating no usable rate.
