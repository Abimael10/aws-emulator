    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_TRACE_SUMMARIES_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_TRACE_SUMMARIES_OUTPUT_SCHEMA;
