            crate::state::audit(
                Self::NAME,
                ctx,
                crate::state::AuditOutcome::StoreUnavailable,
                None,
            );
            ListReadSetsErrorModeled::InternalServerException(InternalServerException {
                message: "the omics sequence store registry is unavailable".to_string(),
            })
