impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for GetStatement<Eng>
{
    type Input = GetStatementInput;
    type Output = GetStatementOutput;
    type Error = GetStatementError;

    const NAME: &'static str = "GetStatement";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_STATEMENT_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_STATEMENT_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            // This operation models a server fault, so an unreachable store is reported
            // as that rather than as a client error the caller could act on.
            return Err(GetStatementErrorModeled::InternalServiceException(
                InternalServiceException {
                    message: Some("the Glue session store is unavailable".into()),
                },
            )
            .into());
        };

        // "The origin of the request" names who is asking, not which statement is asked
        // for, so it changes nothing about this read.
        let _ = &input.request_origin;
        // A session is served only through the endpoint that created it, so the Region,
        // the session id and the statement id together are the whole address this read
        // resolves.
        let region = crate::state::request_region(ctx.parts());
        // The EXECUTION a statement of this session is still owed was owed the instant that
        // statement was submitted, whoever submitted it, so this read hands off what was
        // already owed before it reports — exactly as a read of a job's runs performs the
        // script a run was owed ([`crate::state::perform_owed_session_statements`]). The code
        // is run only inside the contained, bounded interpreter that module states the
        // containment and the bounds of; this read applies no host capability to it. Awaited
        // with no store guard held; nothing of the code itself is waited for.
        crate::state::perform_owed_session_statements(
            &*self.engine,
            ctx,
            &region,
            &input.session_id,
        )
        .await;
        let now = ::std::time::SystemTime::now();
        let mut store = state.lock();
        let Some(session) = store.session_mut(&region, &input.session_id) else {
            return Err(GetStatementErrorModeled::EntityNotFoundException(
                EntityNotFoundException {
                    message: Some(crate::state::messages::session_id_not_found(
                        &input.session_id,
                    )),
                    from_federation_source: None,
                },
            )
            .into());
        };
        // The only writes a read makes: the status and the states the clock had already made
        // due. The session's own status decides whether this read has a runtime to report a
        // statement of at all, so it is materialised rather than read stale.
        session.settle_if_due(now);
        session.settle_due_statements(now);

        // The statements of a session are held by the remote Spark runtime environment it
        // IS, so a session that has ENDED — its environment never came up, its own timeout
        // ended it, or a stop took it down — has no runtime a statement of it could be read
        // from, and the read is refused as invalid input rather than reporting a record no
        // runtime holds any more. The same reading `ListStatements` takes of the same
        // statuses.
        if crate::state::session_has_ended(&session.status) {
            return Err(GetStatementErrorModeled::InvalidInputException(
                InvalidInputException {
                    message: Some(crate::state::messages::session_not_ready(
                        &input.session_id,
                        &session.status,
                    )),
                    from_federation_source: None,
                },
            )
            .into());
        }

        let Some(statement) = session.statement(input.id) else {
            // Which refusal an id this session does not hold answers follows from whether
            // the id is one of this session's own at all: an `Id` the session has minted, or
            // the one it would mint next, names a statement slot of this session's runtime
            // ([`crate::state::SessionEntry::statement_id_in_live_space`]), so what the read
            // cannot serve is reported as a state of the SESSION; an id outside that space
            // names no statement of any session, which is the statement miss.
            if session.statement_id_in_live_space(input.id) {
                return Err(GetStatementErrorModeled::IllegalSessionStateException(
                    IllegalSessionStateException {
                        // The service's fixed sentence for this refusal, which has no
                        // variable part: neither the session nor the id appears in it.
                        message: Some(
                            crate::state::messages::STATEMENT_ILLEGAL_SESSION_STATUS.to_string(),
                        ),
                    },
                )
                .into());
            }
            return Err(GetStatementErrorModeled::EntityNotFoundException(
                EntityNotFoundException {
                    // The refusal names the statement id that resolved to nothing, and
                    // nothing else.
                    message: Some(crate::state::messages::statement_not_found(input.id)),
                    from_federation_source: None,
                },
            )
            .into());
        };

        // "Returns the statement" — rebuilt from the stored record, so this read reports
        // what the run wrote and what the clock has since owed it.
        Ok(GetStatementOutput {
            statement: Some(statement.to_statement()),
        })
    }
}
