/// The region every request here is signed for.
const REGION: &str = "us-east-1";

/// A well-formed Lambda execution role ARN.
const ROLE: &str = "arn:aws:iam::000000000000:role/service-role/authorizer-exec";

/// Where Lambda's `CreateFunction` is bound.
const FUNCTIONS_URI: &str = "/2015-03-31/functions";

/// The service principal AWS IoT invokes a custom authorizer's function as, which the
/// function's resource policy has to grant: "the identifier of the service that invokes the
/// function" (`AddPermission$Principal`).
///
/// `pub(crate)` for the reason [`package`] is.
pub(crate) const IOT_PRINCIPAL: &str = "iot.amazonaws.com";

/// The action a grant of an invocation names: `Invoke` "requires permission for the
/// `lambda:InvokeFunction` action".
///
/// `pub(crate)` for the reason [`package`] is.
pub(crate) const INVOKE_ACTION: &str = "lambda:InvokeFunction";

/// The module and entry point of every deployment package this suite uploads.
const HANDLER: &str = "lambda_function.lambda_handler";

/// The Lambda runtime every function here declares.
const RUNTIME: &str = "python3.12";

/// How long a function is given to reach `Active` before the suite gives up. Generous:
/// the suite waits for that CONDITION, read through the function's own configuration,
/// and never for a span of its own choosing.
const SETTLE_DEADLINE: Duration = Duration::from_secs(60);

/// How often the suite looks again while waiting for a condition to hold.
const POLL_INTERVAL: Duration = Duration::from_millis(20);

/// The authorizer function of every positive row: it computes its whole answer FROM the
/// event it was handed, and hands the event back inside the policy document, so the
/// event AWS IoT built is observable from the response.
///
/// `pub(crate)` for the reason [`package`] is.
pub(crate) const ECHO_SOURCE: &str = r#"
import json


def lambda_handler(event, context):
    token = event.get("token", "")
    return {
        "isAuthenticated": event.get("signatureVerified", False),
        "principalId": "p" + str(len(token)),
        "policyDocuments": [json.dumps(event)],
        "refreshAfterInSeconds": 100 + len(event.get("protocols", [])),
        "disconnectAfterInSeconds": 3600,
    }
"#;

/// An RSA key pair a custom authentication service signs its tokens with: the public
/// half as the PEM block `tokenSigningPublicKeys` carries, the private half to sign
/// with.
struct SigningKey {
    private_key_pkcs8: Vec<u8>,
    public_key_pem: String,
}

impl SigningKey {
    /// A fresh RSA-2048 key pair.
    fn generate() -> Self {
        let private_key =
            aws_lc_rs::rsa::PrivateDecryptingKey::generate(aws_lc_rs::rsa::KeySize::Rsa2048)
                .expect("an RSA key pair");
        let spki = private_key
            .public_key()
            .as_der()
            .expect("the public key as DER")
            .as_ref()
            .to_vec();
        let public_key_pem = SubjectPublicKeyInfoOwned::from_der(&spki)
            .expect("the SubjectPublicKeyInfo")
            .to_pem(LineEnding::LF)
            .expect("the PEM block");
        Self {
            private_key_pkcs8: private_key
                .as_der()
                .expect("the private key as PKCS#8")
                .as_ref()
                .to_vec(),
            public_key_pem,
        }
    }

    /// `token` signed with this key's private half, RSASSA-PKCS1-v1_5 over SHA-256,
    /// base-64 encoded — which is what signing a token with an RSA private key and
    /// `sha256` and then base-64 encoding it produces.
    fn sign(&self, token: &str) -> String {
        let pair = aws_lc_rs::signature::RsaKeyPair::from_pkcs8(&self.private_key_pkcs8)
            .expect("the key pair");
        let mut signature = vec![0u8; pair.public_modulus_len()];
        pair.sign(
            &aws_lc_rs::signature::RSA_PKCS1_SHA256,
            &aws_lc_rs::rand::SystemRandom::new(),
            token.as_bytes(),
            &mut signature,
        )
        .expect("the signature");
        base64::engine::general_purpose::STANDARD.encode(&signature)
    }
}

/// One response, reduced to what a client branches on.
///
/// `pub(crate)` for the reason [`package`] is: the suite that drives the same operation's
/// request and grant rules ([`crate::authorization_request_contexts`]) reads a reply the
/// same way.
#[derive(Debug)]
pub(crate) struct Reply {
    pub(crate) status: u16,
    pub(crate) error_code: Option<String>,
    pub(crate) body: Value,
}

impl Reply {
    /// The wire error SHAPE, with either namespace the wire carries stripped: the `#`
    /// prefix of a `__type` member, and the `:`-separated API doc namespace this service
    /// qualifies a shape name with in `x-amzn-errortype`. The rows below are about WHICH
    /// shape a refusal names; how this service spells that name on the wire is pinned by
    /// the suites that assert the header verbatim.
    pub(crate) fn code(&self) -> String {
        self.error_code
            .clone()
            .or_else(|| {
                self.body
                    .get("__type")
                    .and_then(Value::as_str)
                    .map(str::to_string)
            })
            .unwrap_or_default()
            .rsplit('#')
            .next()
            .unwrap_or_default()
            .split(':')
            .next()
            .unwrap_or_default()
            .to_string()
    }

    /// The `message` member of an error body.
    pub(crate) fn message(&self) -> String {
        self.body
            .get("message")
            .and_then(Value::as_str)
            .unwrap_or_default()
            .to_string()
    }

    /// The authorization event the echo function handed back inside its single policy
    /// document.
    fn echoed_event(&self) -> Value {
        let document = self.body["policyDocuments"][0]
            .as_str()
            .unwrap_or_else(|| panic!("the answer must carry one policy document, got {}", self.body));
        serde_json::from_str(document).unwrap_or_else(|error| {
            panic!("the echoed policy document must be JSON ({error}): {document}")
        })
    }
}

/// IoT and Lambda over ONE shared engine, so IoT's in-process callback reaches this very
/// Lambda.
///
/// `pub(crate)` for the reason [`package`] is.
pub(crate) fn router() -> MultiServiceRouter {
    let engine: std::sync::Arc<engine::InMemoryEngine> =
        std::sync::Arc::new(engine::InMemoryEngine::new());
    let mut router = MultiServiceRouter::new();
    router.set_request_authentication(false);
    router.register_service(IotService::new(std::sync::Arc::clone(&engine)));
    router.register_service(LambdaService::new(engine));
    router
}

/// One REST call to the service whose signing name is `signing_name`. The credential
/// scope is how the router picks the claiming service; the signature itself is never
/// checked — the harness turns request authentication off.
///
/// `pub(crate)` for the reason [`package`] is.
pub(crate) async fn rest(
    router: &MultiServiceRouter,
    signing_name: &str,
    method: &str,
    path: &str,
    body: Option<&Value>,
) -> Reply {
    let payload = body.map_or_else(Vec::new, |value| {
        serde_json::to_vec(value).expect("a request body serializes")
    });
    let request = http::Request::builder()
        .method(method)
        .uri(format!("https://{signing_name}.{REGION}.amazonaws.com{path}"))
        .header("host", format!("{signing_name}.{REGION}.amazonaws.com"))
        .header("content-type", "application/json")
        .header(
            "authorization",
            format!(
                "AWS4-HMAC-SHA256 Credential=AKIDTEST/20260101/{REGION}/{signing_name}/\
                 aws4_request, SignedHeaders=host, Signature=0000"
            ),
        )
        .body(bytes::Bytes::from(payload))
        .expect("a well-formed request");
    let response = router.dispatch(request).await;
    let status = response.status().as_u16();
    let error_code = response
        .headers()
        .get("x-amzn-errortype")
        .and_then(|value| value.to_str().ok())
        .map(str::to_string);
    let bytes = response.into_body();
    let body = if bytes.is_empty() {
        Value::Null
    } else {
        serde_json::from_slice(&bytes).unwrap_or(Value::Null)
    };
    Reply {
        status,
        error_code,
        body,
    }
}

/// A .zip deployment package holding `source` as `lambda_function.py`, written in memory
/// the way a caller uploads one.
///
/// Shared with the suites that stage a function for another half of this service to resolve
/// (`crate::dependent_resource_preflight`), so one spelling of a deployment package serves
/// them all.
pub(crate) fn package(source: &str) -> Vec<u8> {
    use std::io::Write as _;
    let mut buffer = std::io::Cursor::new(Vec::new());
    {
        let mut writer = zip::ZipWriter::new(&mut buffer);
        let options: zip::write::FileOptions<'_, '_, ()> = zip::write::FileOptions::default();
        writer
            .start_file("lambda_function.py", options)
            .expect("the entry starts");
        writer
            .write_all(source.as_bytes())
            .expect("the entry's bytes");
        writer.finish().expect("a finished archive");
    }
    buffer.into_inner()
}

/// Create a Lambda function whose code is `source` and return the ARN Lambda minted.
///
/// `pub(crate)` for the reason [`package`] is.
pub(crate) async fn create_function(
    router: &MultiServiceRouter,
    name: &str,
    source: &str,
) -> String {
    let created = rest(
        router,
        "lambda",
        "POST",
        FUNCTIONS_URI,
        Some(&json!({
            "FunctionName": name,
            "Role": ROLE,
            "Runtime": RUNTIME,
            "Handler": HANDLER,
            "Timeout": 10,
            "Code": {
                "ZipFile": base64::engine::general_purpose::STANDARD.encode(package(source)),
            },
        })),
    )
    .await;
    assert_eq!(
        created.status, 201,
        "CreateFunction {name:?} must succeed, got {} ({})",
        created.status, created.body
    );
    created.body["FunctionArn"]
        .as_str()
        .unwrap_or_else(|| panic!("CreateFunction must mint an ARN, got {}", created.body))
        .to_string()
}

/// Wait for `name` to reach `Active`, which is the state an invocation needs: the wait
/// is for that CONDITION, read through the function's own configuration.
///
/// `pub(crate)` for the reason [`package`] is.
pub(crate) async fn wait_active(router: &MultiServiceRouter, name: &str) {
    let deadline = Instant::now() + SETTLE_DEADLINE;
    loop {
        let read = rest(
            router,
            "lambda",
            "GET",
            &format!("{FUNCTIONS_URI}/{name}/configuration"),
            None,
        )
        .await;
        if read.status == 200 && read.body["State"] == json!("Active") {
            return;
        }
        assert!(
            Instant::now() < deadline,
            "the function {name:?} never became Active: {} ({})",
            read.status,
            read.body
        );
        tokio::time::sleep(POLL_INTERVAL).await;
    }
}

/// Create a Lambda function from `source`, wait it Active, grant AWS IoT the invocation of
/// it, and return its ARN.
async fn ready_function(router: &MultiServiceRouter, name: &str, source: &str) -> String {
    let arn = create_function(router, name, source).await;
    wait_active(router, name).await;
    grant_invoke(router, name, "iot-invoke", IOT_PRINCIPAL, None).await;
    arn
}

/// Grant `principal` the invocation of `name` through Lambda's own `AddPermission`, which
/// is what a client does beside creating a custom authorizer: the invocation is made by the
/// IoT service principal, so only the function's resource-based policy can admit it.
/// `source_arn` narrows the grant to one invoking resource when it is given.
///
/// `pub(crate)` for the reason [`package`] is.
pub(crate) async fn grant_invoke(
    router: &MultiServiceRouter,
    name: &str,
    statement_id: &str,
    principal: &str,
    source_arn: Option<&str>,
) {
    let mut grant = json!({
        "StatementId": statement_id,
        "Action": INVOKE_ACTION,
        "Principal": principal,
    });
    if let Some(source_arn) = source_arn {
        grant["SourceArn"] = json!(source_arn);
    }
    let granted = rest(
        router,
        "lambda",
        "POST",
        &format!("{FUNCTIONS_URI}/{name}/policy"),
        Some(&grant),
    )
    .await;
    assert_eq!(
        granted.status, 201,
        "AddPermission({name:?}, {statement_id:?}) must answer 201, got {} ({})",
        granted.status, granted.body
    );
}

