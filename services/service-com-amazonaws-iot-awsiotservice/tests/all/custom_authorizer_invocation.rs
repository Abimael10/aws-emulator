/// A token signed with ANY of the keys the authorizer registered is handed to the
/// authorizer's function; one whose signature verifies against none of them is refused.
#[tokio::test]
async fn a_token_signed_with_any_registered_key_reaches_the_authorizer_function() {
    let router = router();
    let function = ready_function(&router, "either-key-authorizer", ECHO_SOURCE).await;

    let first = SigningKey::generate();
    let second = SigningKey::generate();
    let stranger = SigningKey::generate();
    // The authorizer registers the most keys a write may state (two: a new signing key
    // published beside the old one), so "any registered key" is tested over every key
    // an authorizer can hold.
    let registered: BTreeMap<String, String> = [
        ("key1".to_string(), first.public_key_pem.clone()),
        ("key2".to_string(), second.public_key_pem.clone()),
    ]
    .into_iter()
    .collect();
    create_authorizer(&router, "eitherkey", &function, &registered, false).await;

    // A long token, to span the length `Token` admits (1..6144) rather than one size.
    let long_token = "t".repeat(6_000);
    // (case, the token presented, the signature presented, expected status)
    let rows: [(&str, String, String, u16); 7] = [
        (
            "a short token signed with the first registered key",
            "a".to_string(),
            first.sign("a"),
            200,
        ),
        (
            "a token signed with the second registered key",
            "second-key-token".to_string(),
            second.sign("second-key-token"),
            200,
        ),
        (
            "a token carrying whitespace and punctuation, signed with the first key",
            "line one\n line two\ttab {\"json\": true}".to_string(),
            first.sign("line one\n line two\ttab {\"json\": true}"),
            200,
        ),
        (
            "a 6000-character token signed with the second key",
            long_token.clone(),
            second.sign(&long_token),
            200,
        ),
        (
            "a token signed with a key the authorizer does not register",
            "stranger-token".to_string(),
            stranger.sign("stranger-token"),
            400,
        ),
        (
            "a signature made over a different token",
            "presented-token".to_string(),
            first.sign("some-other-token"),
            400,
        ),
        (
            "a base-64 value that is no signature at all",
            "unsigned-token".to_string(),
            base64::engine::general_purpose::STANDARD.encode([0u8; 256]),
            400,
        ),
    ];

    for (case, token, signature, expected_status) in rows {
        let answer = test_invoke(
            &router,
            "eitherkey",
            // Every request carries a protocol context, because an authorization request
            // without one is no authorization request at all.
            &json!({
                "token": token,
                "tokenSignature": signature,
                "mqttContext": { "clientId": "device-01" },
            }),
        )
        .await;
        assert_eq!(
            answer.status, expected_status,
            "case {case:?}: expected HTTP {expected_status}, got {} ({})",
            answer.status, answer.body
        );
        if expected_status != 200 {
            assert_eq!(
                (answer.code().as_str(), answer.message().as_str()),
                (
                    "InvalidRequestException",
                    "Token signature mismatch for authorizer eitherkey"
                ),
                "case {case:?}: expected the signature mismatch refusal, got {} ({})",
                answer.code(),
                answer.body
            );
            continue;
        }
        // The answer is the function's, computed from the event it was handed.
        assert_eq!(
            answer.body["isAuthenticated"],
            json!(true),
            "case {case:?}: expected the function's verdict, got {}",
            answer.body
        );
        assert_eq!(
            answer.body["principalId"],
            json!(format!("p{}", token.chars().count())),
            "case {case:?}: expected the principal the function computed from the token, got {}",
            answer.body
        );
        assert_eq!(
            answer.body["disconnectAfterInSeconds"],
            json!(3600),
            "case {case:?}: expected the function's disconnect window, got {}",
            answer.body
        );
        let event = answer.echoed_event();
        assert_eq!(
            event["token"],
            json!(token),
            "case {case:?}: expected the presented token in the authorizer event, got {event}"
        );
        assert_eq!(
            event["signatureVerified"],
            json!(true),
            "case {case:?}: expected a verified signature in the authorizer event, got {event}"
        );
    }
}

/// An authorizer that turns signature validation OFF is run without a signature, and
/// one that leaves it on refuses a request that presents no token or no signature over
/// it.
#[tokio::test]
async fn signature_validation_follows_the_authorizers_own_setting() {
    let router = router();
    let function = ready_function(&router, "signing-setting-authorizer", ECHO_SOURCE).await;
    let key = SigningKey::generate();
    let registered: BTreeMap<String, String> = [("key1".to_string(), key.public_key_pem.clone())]
        .into_iter()
        .collect();
    create_authorizer(&router, "signingon", &function, &registered, false).await;
    create_authorizer(&router, "signingoff", &function, &registered, true).await;

    // (case, authorizer, request body, expected status, expected code, expected message)
    //
    // Every body carries a protocol context: what varies across the rows is the token and
    // the signature, not whether there is an authorization request to test.
    let rows: [(&str, &str, Value, u16, &str, String); 6] = [
        (
            "signing off, nothing but the context presented",
            "signingoff",
            json!({ "tlsContext": { "serverName": "data.iot.example.test" } }),
            200,
            "",
            String::new(),
        ),
        (
            "signing off, a token with a signature that would not verify",
            "signingoff",
            json!({
                "token": "unverifiable",
                "tokenSignature": base64::engine::general_purpose::STANDARD.encode([7u8; 256]),
                "mqttContext": { "clientId": "device-01" },
            }),
            200,
            "",
            String::new(),
        ),
        (
            "signing off, a token with no signature",
            "signingoff",
            json!({ "token": "unsigned", "mqttContext": { "clientId": "device-01" } }),
            200,
            "",
            String::new(),
        ),
        (
            "signing on, a correctly signed token",
            "signingon",
            json!({
                "token": "signed",
                "tokenSignature": key.sign("signed"),
                "mqttContext": { "clientId": "device-01" },
            }),
            200,
            "",
            String::new(),
        ),
        (
            "signing on, no token at all",
            "signingon",
            json!({ "mqttContext": { "clientId": "device-01" } }),
            400,
            "InvalidRequestException",
            "Token is required for authorizer signingon".to_string(),
        ),
        (
            "signing on, a token with no signature over it",
            "signingon",
            json!({ "token": "signed", "mqttContext": { "clientId": "device-01" } }),
            400,
            "InvalidRequestException",
            "Token signature is required for authorizer signingon".to_string(),
        ),
    ];

    for (case, authorizer, body, expected_status, expected_code, expected_message) in rows {
        let answer = test_invoke(&router, authorizer, &body).await;
        assert_eq!(
            answer.status, expected_status,
            "case {case:?}: expected HTTP {expected_status}, got {} ({})",
            answer.status, answer.body
        );
        if expected_status != 200 {
            assert_eq!(
                (answer.code().as_str(), answer.message().as_str()),
                (expected_code, expected_message.as_str()),
                "case {case:?}: expected {expected_code} {expected_message:?}, got {}",
                answer.body
            );
            continue;
        }
        // An authorizer that validates no signature reports none as verified, which the
        // event carries and the function answered with.
        let verified = authorizer == "signingon";
        let event = answer.echoed_event();
        assert_eq!(
            event["signatureVerified"],
            json!(verified),
            "case {case:?}: expected signatureVerified {verified} in the authorizer event, got \
             {event}"
        );
        assert_eq!(
            answer.body["isAuthenticated"],
            json!(verified),
            "case {case:?}: expected the function's verdict for that event, got {}",
            answer.body
        );
    }
}

/// The authorization event names the protocols the request's own contexts named, and
/// carries each of their data.
#[tokio::test]
async fn the_event_carries_the_protocol_contexts_the_request_named() {
    let router = router();
    let function = ready_function(&router, "protocol-context-authorizer", ECHO_SOURCE).await;
    let key = SigningKey::generate();
    let registered: BTreeMap<String, String> = [("key1".to_string(), key.public_key_pem.clone())]
        .into_iter()
        .collect();
    create_authorizer(&router, "contexts", &function, &registered, false).await;

    let token = "context-token";
    let signature = key.sign(token);
    // (case, the contexts the request carries, the protocols the event must name)
    //
    // Every row carries at least one context: a request with none of them is no
    // authorization request, which `authorization_request_contexts.rs` covers.
    let rows: [(&str, Value, Value); 4] = [
        (
            "an HTTP context alone",
            json!({
                "httpContext": {
                    "headers": { "x-amz-customauthorizer-name": "contexts" },
                    "queryString": "?x-amz-customauthorizer-signature=abc",
                },
            }),
            json!(["http"]),
        ),
        (
            "an MQTT context alone",
            json!({
                "mqttContext": {
                    "username": "device-user",
                    "password": base64::engine::general_purpose::STANDARD.encode("secret"),
                    "clientId": "device-01",
                },
            }),
            json!(["mqtt"]),
        ),
        (
            "a TLS context alone",
            json!({ "tlsContext": { "serverName": "data.iot.example.test" } }),
            json!(["tls"]),
        ),
        (
            "all three contexts at once",
            json!({
                "httpContext": { "queryString": "?k=v" },
                "mqttContext": { "clientId": "device-02" },
                "tlsContext": { "serverName": "both.iot.example.test" },
            }),
            json!(["tls", "http", "mqtt"]),
        ),
    ];

    for (case, contexts, expected_protocols) in rows {
        let mut body = json!({ "token": token, "tokenSignature": signature });
        if let Value::Object(members) = contexts.clone() {
            for (member, value) in members {
                body[member] = value;
            }
        }
        let answer = test_invoke(&router, "contexts", &body).await;
        assert_eq!(
            answer.status, 200,
            "case {case:?}: expected HTTP 200, got {} ({})",
            answer.status, answer.body
        );
        let event = answer.echoed_event();
        assert_eq!(
            event["protocols"], expected_protocols,
            "case {case:?}: expected the event to name {expected_protocols}, got {event}"
        );
        // Every context the request carried is in the event's protocol data, member for
        // member — and no protocol the request did not name is.
        for (protocol, member, expected) in [
            ("http", "queryString", contexts["httpContext"]["queryString"].clone()),
            ("mqtt", "clientId", contexts["mqttContext"]["clientId"].clone()),
            ("tls", "serverName", contexts["tlsContext"]["serverName"].clone()),
        ] {
            if expected.is_null() {
                continue;
            }
            assert_eq!(
                event["protocolData"][protocol][member], expected,
                "case {case:?}: expected {protocol}.{member} to be {expected} in the event, got \
                 {event}"
            );
        }
        if let Some(password) = contexts["mqttContext"]["password"].as_str() {
            // The password is a blob, so the event carries it base-64 encoded — the same
            // encoding the request wrote it in.
            assert_eq!(
                event["protocolData"]["mqtt"]["password"],
                json!(password),
                "case {case:?}: expected the MQTT password base-64 in the event, got {event}"
            );
        }
        if let Some(headers) = contexts["httpContext"]["headers"].as_object() {
            for (name, value) in headers {
                assert_eq!(
                    event["protocolData"]["http"]["headers"][name],
                    *value,
                    "case {case:?}: expected the header {name} in the event, got {event}"
                );
            }
        }
    }
}

/// How many token signing public keys one authorizer may register is bounded, and a
/// write past the bound is refused rather than recorded — so the signature check a
/// later run does is bounded too. The rows are the ceiling itself, one short of it and
/// one past it, on both writers of an authorizer.
#[tokio::test]
async fn the_number_of_registered_signing_keys_is_bounded() {
    let router = router();
    let function = ready_function(&router, "bounded-keys-authorizer", ECHO_SOURCE).await;

    // One real key pair per slot up to the ceiling, so a row at the ceiling can still be
    // RUN with a signature made by its last key.
    let keys: Vec<SigningKey> = (0..MAX_TOKEN_SIGNING_PUBLIC_KEYS)
        .map(|_| SigningKey::generate())
        .collect();
    let registered = |count: usize| -> BTreeMap<String, String> {
        (0..count)
            .map(|index| {
                (
                    format!("key{index}"),
                    keys[index.min(keys.len() - 1)].public_key_pem.clone(),
                )
            })
            .collect()
    };

    // (case, how many keys the write registers, expected status)
    let rows: [(&str, usize, u16); 3] = [
        (
            "one key short of the ceiling",
            MAX_TOKEN_SIGNING_PUBLIC_KEYS - 1,
            200,
        ),
        ("exactly the ceiling", MAX_TOKEN_SIGNING_PUBLIC_KEYS, 200),
        (
            "one key past the ceiling",
            MAX_TOKEN_SIGNING_PUBLIC_KEYS + 1,
            400,
        ),
    ];

    for (index, (case, count, expected_status)) in rows.into_iter().enumerate() {
        let name = format!("bounded{index}");
        let created = authorizer_create(&router, &name, &function, &registered(count), false).await;
        assert_eq!(
            created.status, expected_status,
            "case {case:?}: expected HTTP {expected_status} from CreateAuthorizer, got {} ({})",
            created.status, created.body
        );
        if expected_status != 200 {
            assert_eq!(
                (created.code().as_str(), created.message().as_str()),
                (
                    "InvalidRequestException",
                    format!(
                        "Token signing keys map for authorizer {name} cannot contain more than \
                         {MAX_TOKEN_SIGNING_PUBLIC_KEYS} keys"
                    )
                    .as_str()
                ),
                "case {case:?}: expected the keys-ceiling refusal, got {}",
                created.body
            );
            // The refused create recorded nothing, so the name is still free.
            let read = rest(&router, "iot", "GET", &format!("/authorizer/{name}"), None).await;
            assert_eq!(
                read.status, 404,
                "case {case:?}: expected the refused create to record nothing, got {} ({})",
                read.status, read.body
            );
            continue;
        }
        // The last registered key still verifies a token signed with it: the ceiling
        // bounds how many keys there are, it does not change which of them is tried.
        let token = format!("token-{count}");
        let signature = keys[count - 1].sign(&token);
        let answer = test_invoke(
            &router,
            &name,
            &json!({
                "token": token,
                "tokenSignature": signature,
                "mqttContext": { "clientId": "device-01" },
            }),
        )
        .await;
        assert_eq!(
            answer.status, 200,
            "case {case:?}: expected the last registered key to verify, got {} ({})",
            answer.status, answer.body
        );
    }

    // The same ceiling on `UpdateAuthorizer`, which replaces the whole map.
    create_authorizer(&router, "boundedupdate", &function, &registered(1), false).await;
    let past_the_ceiling: serde_json::Map<String, Value> =
        registered(MAX_TOKEN_SIGNING_PUBLIC_KEYS + 1)
            .into_iter()
            .map(|(name, pem)| (name, Value::String(pem)))
            .collect();
    let refused = rest(
        &router,
        "iot",
        "PUT",
        "/authorizer/boundedupdate",
        Some(&json!({ "tokenSigningPublicKeys": past_the_ceiling })),
    )
    .await;
    assert_eq!(
        (refused.status, refused.code().as_str()),
        (400, "InvalidRequestException"),
        "case \"an update past the ceiling\": expected the keys-ceiling refusal, got {} ({})",
        refused.status,
        refused.body
    );
    // The refused update changed nothing: the authorizer still carries its one key.
    let read = rest(&router, "iot", "GET", "/authorizer/boundedupdate", None).await;
    assert_eq!(
        read.body["authorizerDescription"]["tokenSigningPublicKeys"]
            .as_object()
            .map(serde_json::Map::len),
        Some(1),
        "case \"an update past the ceiling\": expected the record to be unchanged, got {}",
        read.body
    );
}

/// A function that answers something other than an authorization answer is reported as
/// such, and a name no authorizer of the account holds is a not-found.
#[tokio::test]
async fn an_authorizer_that_answers_no_authorization_answer_is_refused() {
    let router = router();
    let key = SigningKey::generate();
    let registered: BTreeMap<String, String> = [("key1".to_string(), key.public_key_pem.clone())]
        .into_iter()
        .collect();

    // One function per way an answer can fail to be an authorization answer.
    let sources: [(&str, &str, &str); 5] = [
        (
            "notanobject",
            "answers-a-list",
            "def lambda_handler(event, context):\n    return [1, 2, 3]\n",
        ),
        (
            "noverdict",
            "answers-no-verdict",
            "def lambda_handler(event, context):\n    return {\"principalId\": \"p1\"}\n",
        ),
        (
            "verdictnotbool",
            "answers-a-string-verdict",
            "def lambda_handler(event, context):\n    return {\"isAuthenticated\": \"true\"}\n",
        ),
        (
            "badprincipal",
            "answers-an-unmodelled-principal",
            "def lambda_handler(event, context):\n    return {\"isAuthenticated\": True, \
             \"principalId\": \"not a principal\"}\n",
        ),
        (
            "raiser",
            "raises",
            "def lambda_handler(event, context):\n    raise KeyError(\"no such claim\")\n",
        ),
    ];
    for (authorizer, function_name, source) in sources {
        let arn = ready_function(&router, function_name, source).await;
        create_authorizer(&router, authorizer, &arn, &registered, false).await;
    }
    // An authorizer whose function Lambda does not hold at all: nothing grants the
    // invocation, so Lambda refuses it and no function answers.
    create_authorizer(
        &router,
        "absentfunction",
        "arn:aws:lambda:us-east-1:000000000000:function:never-created",
        &registered,
        false,
    )
    .await;

    let token = "refusal-token";
    let signature = key.sign(token);
    // (case, the authorizer, expected status, expected error code, expected message prefix)
    //
    // The prefix is what separates a function that ANSWERED something other than an
    // authorization answer from an invocation AWS Lambda refused: nothing ran for the
    // second, so its refusal must not claim its response was invalid, and it names the
    // class Lambda refused it with rather than the function it resolved.
    let rows: [(&str, &str, u16, &str, &str); 7] = [
        (
            "a function that answers a JSON list",
            "notanobject",
            400,
            "InvalidResponseException",
            "Invalid response from authorizer notanobject: ",
        ),
        (
            "a function that answers no isAuthenticated",
            "noverdict",
            400,
            "InvalidResponseException",
            "Invalid response from authorizer noverdict: ",
        ),
        (
            "a function that answers isAuthenticated as a string",
            "verdictnotbool",
            400,
            "InvalidResponseException",
            "Invalid response from authorizer verdictnotbool: ",
        ),
        (
            "a function that answers a principalId the shape does not admit",
            "badprincipal",
            400,
            "InvalidResponseException",
            "Invalid response from authorizer badprincipal: ",
        ),
        (
            "a function that raises",
            "raiser",
            400,
            "InvalidResponseException",
            "Invalid response from authorizer raiser: ",
        ),
        (
            "an authorizer naming a function Lambda does not hold",
            "absentfunction",
            400,
            "InvalidResponseException",
            "AccessDeniedException encountered when invoking lambda; requestId: ",
        ),
        (
            "a name no authorizer of this account holds",
            "neverCreated",
            404,
            "ResourceNotFoundException",
            "Authorizer neverCreated not found",
        ),
    ];

    for (case, authorizer, expected_status, expected_code, expected_prefix) in rows {
        let answer = test_invoke(
            &router,
            authorizer,
            &json!({
                "token": token,
                "tokenSignature": signature,
                "mqttContext": { "clientId": "device-01" },
            }),
        )
        .await;
        assert_eq!(
            (answer.status, answer.code().as_str()),
            (expected_status, expected_code),
            "case {case:?}: expected HTTP {expected_status} {expected_code}, got {} {} ({})",
            answer.status,
            answer.code(),
            answer.body
        );
        let message = answer.message();
        assert!(
            message.starts_with(expected_prefix),
            "case {case:?}: expected the refusal to begin {expected_prefix:?}, got {message:?}"
        );
        if expected_status == 404 {
            assert_eq!(
                message,
                format!("Authorizer {authorizer} not found"),
                "case {case:?}: expected the authorizer-family not-found wording, got {message:?}"
            );
        }
    }
}
