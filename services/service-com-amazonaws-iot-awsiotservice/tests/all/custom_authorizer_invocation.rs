//! End-to-end HTTP coverage of `TestInvokeAuthorizer`: RUNNING a custom authorizer the
//! account holds, across the two services that own the two halves — IoT holds the
//! authorizer, AWS Lambda holds the function that authorizes for it. Both are mounted on
//! ONE shared engine, exactly as the assembled emulator mounts them.
//!
//! The rule under test: `TestInvokeAuthorizer` refuses a request that carries none of the
//! three protocol contexts (`InvalidRequestException`, 400 — covered as a class in
//! `authorization_request_contexts.rs`), resolves the named authorizer (a name the
//! account does not hold is `ResourceNotFoundException`, 404) and — unless the
//! authorizer's `signingDisabled` turned signature validation off — verifies the
//! base-64 `tokenSignature` as an RSASSA-PKCS1-v1_5 SHA-256 signature over the `token`
//! against EVERY key in the authorizer's `tokenSigningPublicKeys`, accepting the token
//! when ANY of them verifies and refusing `InvalidRequestException` (400) when none
//! does; it then invokes the authorizer's Lambda function synchronously with the
//! authorization event — the token, whether its signature verified, and the protocol
//! contexts the request carried — and answers 200 with the `isAuthenticated`,
//! `principalId`, `policyDocuments`, `refreshAfterInSeconds` and
//! `disconnectAfterInSeconds` that function returned, refusing
//! `InvalidResponseException` (400) when it answered no authorization answer at all or
//! when AWS Lambda refused the invocation.
//!
//! The invocation is made by the IoT service principal, so every function the suite
//! stages is granted to it through Lambda's own `AddPermission` — the grant a client adds
//! beside a custom authorizer — and the one authorizer pointed at a function nobody holds
//! is refused for the lack of it.
//!
//! Nothing asserted here is a value baked into the IoT service: every key pair is
//! generated by the suite, every signature is made by the suite with the private half,
//! and every response member comes back out of a Lambda function whose code the suite
//! uploaded and which computes its answer FROM the event it was handed — so a row can
//! only pass if the event reached the function and the function's answer came back.
//!
//! The rows span what the rule generalises over: which of the registered keys signed the
//! token, how many keys the authorizer registered, the length and content of the token,
//! whether the presented signature is a signature at all, whether the authorizer
//! validates signatures, which protocol contexts the request carries, and what the
//! function answers.

