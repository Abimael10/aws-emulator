/// Longest region token this operation will key an account's endpoint record by.
///
/// The region comes from the caller's credential scope and names the Region whose
/// endpoint was asked for, which AWS carries as one label of that endpoint's hostname,
/// so the token is bounded like the DNS label it is (RFC 1035 §2.3.4: 63 octets).
const MAX_REGION_LENGTH: usize = 63;

/// The endpoint types `DescribeEndpoint` knows.
///
/// The catalog is the `endpointType` member's own documentation — "Valid endpoint
/// types include: `iot:Data` ... `iot:Data-ATS` ... `iot:CredentialProvider` ...
/// `iot:Jobs`" — read with:
///
/// ```text
/// smithy_query(query="doc",shape="DescribeEndpointRequest",member="endpointType",model_path="services/service-com-amazonaws-iot-awsiotservice/smithy-model/com-amazonaws-iot-awsiotservice.json")
/// ```
///
/// Knowing a type is not serving it: a type AWS has RETIRED is still a type this operation
/// recognises — it is refused by naming the type that serves its APIs now rather than as a
/// token nobody ever heard of ([`EndpointType::retirement`]).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum EndpointType {
    /// `iot:Data` — the VeriSign signed data endpoint, and the type a request that
    /// names none asks for.
    Data,
    /// `iot:Data-ATS` — the ATS signed data endpoint.
    DataAts,
    /// `iot:CredentialProvider` — the IoT credentials provider API endpoint.
    CredentialProvider,
    /// `iot:Jobs` — the IoT device management Jobs API endpoint, RETIRED: its APIs are
    /// served through the ATS data endpoint now ([`EndpointType::retirement`]).
    Jobs,
}

/// What a RETIRED endpoint type is refused by naming: the APIs it used to serve, and the
/// type that serves them now.
///
/// A retired type is one AWS no longer resolves an endpoint for, so a caller asking for it
/// cannot be handed an address: it is told which type to ask for instead, which is a
/// MIGRATION rather than a typo, and that is what separates this refusal from the one an
/// unrecognised token earns.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Retirement {
    /// The APIs the retired type's endpoints used to serve, as the refusal names them.
    pub apis: &'static str,
    /// The endpoint type those APIs are reached through now.
    pub replacement: EndpointType,
}

impl EndpointType {
    /// Every endpoint type, in the order the model documents them.
    pub const ALL: &'static [Self] = &[
        Self::Data,
        Self::DataAts,
        Self::CredentialProvider,
        Self::Jobs,
    ];

    /// The endpoint type a request asking for no particular one gets: the data
    /// endpoint. The member's documentation recommends asking for `iot:Data-ATS`
    /// *instead of* the default, which is what makes the default the plain
    /// `iot:Data` type.
    pub const DEFAULT: Self = Self::Data;

    /// The wire token for this endpoint type.
    pub const fn token(self) -> &'static str {
        match self {
            Self::Data => "iot:Data",
            Self::DataAts => "iot:Data-ATS",
            Self::CredentialProvider => "iot:CredentialProvider",
            Self::Jobs => "iot:Jobs",
        }
    }

    /// Why this type resolves no endpoint any more, or `None` for one AWS still serves.
    /// The Jobs endpoint type is retired: the Jobs and Commands APIs it used to serve are
    /// reached through the ATS data endpoint, so an account has no `iot:Jobs` endpoint to
    /// be told about at all.
    pub const fn retirement(self) -> Option<Retirement> {
        match self {
            Self::Jobs => Some(Retirement {
                apis: "IoT Jobs and Commands APIs",
                replacement: Self::DataAts,
            }),
            Self::Data | Self::DataAts | Self::CredentialProvider => None,
        }
    }

    /// Whether the address of this endpoint type is one a DEVICE opens an MQTT connection
    /// to.
    ///
    /// The data endpoints are the account's MESSAGE BROKER address: "iot:Data - Returns a
    /// VeriSign signed data endpoint. iot:Data-ATS - Returns an ATS signed data endpoint"
    /// — the host AWS serves MQTT over TLS on 8883 and the HTTPS data-plane API on 443 at.
    /// The credentials provider endpoint carries an HTTPS API alone, so nothing opens an
    /// MQTT connection to it.
    pub const fn serves_the_message_broker(self) -> bool {
        match self {
            Self::Data | Self::DataAts => true,
            Self::CredentialProvider | Self::Jobs => false,
        }
    }

    /// The endpoint type `requested` names, or `None` when it names none.
    pub fn parse(requested: &str) -> Option<Self> {
        Self::ALL
            .iter()
            .copied()
            .find(|candidate| candidate.token() == requested)
    }
}

/// How this operation refuses an `endpointType` it does not recognise: the token the
/// request carried, and the fixed clause.
///
/// The value is echoed back because it is the caller's own input and the only thing that
/// says WHICH token was not recognised; nothing of this service's state is in the
/// sentence.
#[must_use]
pub fn unrecognized_endpoint_type_message(requested: &str) -> String {
    format!("Endpoint type {requested} not recognized.")
}

/// How this operation refuses an `endpointType` AWS has RETIRED: the APIs that type used
/// to serve, the type they are reached through now, the type the request asked for, and
/// the instruction to ask for the replacement.
#[must_use]
pub fn retired_endpoint_type_message(retired: EndpointType, retirement: Retirement) -> String {
    let replacement = retirement.replacement.token();
    let apis = retirement.apis;
    let retired = retired.token();
    format!(
        "{apis} are now available through {replacement} endpoints instead of {retired} \
         endpoints. Please use {replacement}."
    )
}

/// The address this account's IoT endpoint is PUBLISHED at: the `host[:port]` a client
/// then DIALS to reach the endpoint type it asked for.
///
/// `endpointAddress` is not a label a client reads — it is the address it DIALS:
/// "Returns or creates a unique endpoint specific to the Amazon Web Services account
/// making the call", and every SDK sample builds its IoT data or credentials client with
/// that value as its endpoint, while a DEVICE opens its MQTT connection to it. So the
/// address announced has to be one THIS emulator answers the asked-for type's protocols
/// on; the host AWS names an account's endpoint resolves off this machine, and a client
/// sent there leaves the emulator entirely and reaches no data plane at all.
///
/// AWS publishes one HOST per endpoint type and serves everything that type carries on it:
/// for a data endpoint, MQTT over TLS on 8883 and the HTTPS data-plane API on 443. This
/// emulator has one host and an address it hands out has to carry a PORT, so a data
/// endpoint is published at the MESSAGE BROKER's own socket
/// ([`::service_common::iot_mqtt_broker::ensure_broker_endpoint`], opened by this call
/// — which is the call that creates the account's endpoint), and that socket serves both
/// wires: an MQTT connection and the HTTPS data plane, which it hands to this emulator's
/// own router. A client handed that address reaches the whole of what the type carries.
///
/// Every other endpoint type carries HTTPS alone, and is published at the endpoint this
/// emulator serves its whole surface at
/// ([`::service_common::data_plane_addressing::emulator_endpoint_authority`]) — which
/// binds the IoT control plane, the IoT data plane and the credentials provider, and
/// resolves a request to the service its SigV4 credential scope names. It is also the
/// address a data endpoint falls back to on an emulator that could open no socket of its
/// own, which still serves that type's HTTPS half.
///
/// Scheme and host only, no path: the value is an address a client appends the modelled
/// path to, exactly as the `identifier.iot.region.amazonaws.com` form the member
/// documents is.
async fn published_endpoint_address<Eng: Send + Sync + 'static>(
    ctx: &smithy_server_runtime::OperationContext<'_>,
    engine: &Eng,
    endpoint_type: EndpointType,
) -> String {
    if endpoint_type.serves_the_message_broker() {
        if let Some(broker) =
            ::service_common::iot_mqtt_broker::ensure_broker_endpoint(engine, ctx.callback()).await
        {
            return broker;
        }
    }
    ::service_common::data_plane_addressing::emulator_endpoint_authority(ctx)
}

/// The region whose endpoint this request asks for: the region of its SigV4 credential
/// scope ([`crate::state::request_region`], the same region this service scopes a minted
/// ARN to), lowercased because the hostname label AWS carries it as is.
///
/// A region that is not a hostname label falls back to [`crate::state::DEFAULT_REGION`]
/// rather than keying an account's endpoint by a value that names no Region.
fn endpoint_region(parts: &::http::request::Parts) -> String {
    let region = crate::state::request_region(parts).to_ascii_lowercase();
    let is_label = !region.is_empty()
        && region.len() <= MAX_REGION_LENGTH
        && region.starts_with(|c: char| c.is_ascii_alphanumeric())
        && region.ends_with(|c: char| c.is_ascii_alphanumeric())
        && region
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '-');
    if is_label {
        region
    } else {
        crate::state::DEFAULT_REGION.to_string()
    }
}

/// Emit the structured access record for one `DescribeEndpoint` call.
///
/// Called on EVERY branch this handler returns from, because one of them creates
/// state (the account's endpoint identifier) whose effect is otherwise invisible
/// after the fact. The record carries the operation, the identity the request
/// PRESENTED (the SigV4 access key id, an identifier and not a secret), the request
/// target, what was asked for and the outcome; the subscriber supplies the timestamp.
/// The endpoint address itself is NOT logged — it is what the caller is told, not
/// metadata about the call.
fn audit(
    ctx: &smithy_server_runtime::OperationContext<'_>,
    outcome: &'static str,
    endpoint_type: Option<&str>,
) {
    let parts = ctx.parts();
    tracing::info!(
        target: "emulator::audit",
        service = ctx.identity().signing_name(),
        operation = "DescribeEndpoint",
        access_key_id = %crate::state::audit_field(&::engine::extract_akid(&parts.headers)),
        request_target =
            %crate::state::audit_field(&format!("{} {}", parts.method, parts.uri.path())),
        endpoint_type = %crate::state::audit_field(endpoint_type.unwrap_or("")),
        outcome,
        "iot api call"
    );
}

