//! `pendingDeletion` with its removal recorded for that timeout after its deprecation, or
//! after this call when it carries none (202) — a command on its way out being one no new
//! execution may be created from, so scheduling a removal deprecates the command too. The
//! rule, the instant it is decided against and the removal the clock later makes due all
