/// The character that separates the fields of a continuation token's SCOPE. A control
/// character, so it is outside `ThingGroupName`'s pattern (`^[a-zA-Z0-9:_-]+$`) and
/// cannot occur inside any field it joins.
const SCOPE_SEPARATOR: char = '\u{1e}';

/// The LISTING a continuation token belongs to: the filters that decide which groups it
/// walks and therefore what "the next set of results" means.
///
/// `parentGroup` and `namePrefixFilter` are both modelled `len 1..128`, so neither can
/// be empty and an absent one cannot be confused with a supplied one. `recursive` is
/// the reading the handler acted on rather than the member as it arrived, so two
/// requests that walk the same groups share one scope and a token moves between them.
fn listing_scope(
    parent_group: Option<&str>,
    recursive: bool,
    name_prefix_filter: Option<&str>,
) -> String {
    format!(
        "thing-groups{SCOPE_SEPARATOR}{}{SCOPE_SEPARATOR}{recursive}{SCOPE_SEPARATOR}{}",
        parent_group.unwrap_or_default(),
        name_prefix_filter.unwrap_or_default()
    )
}
