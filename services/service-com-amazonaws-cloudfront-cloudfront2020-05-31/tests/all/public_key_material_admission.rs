//! The KEY MATERIAL `CreatePublicKey` admits, end to end over HTTP.
//!
//! The rule: `PublicKeyConfig$EncodedKey` is "the public key that you can use with signed
//! URLs and signed cookies, or with field-level encryption" — the RSA PUBLIC key of a key
//! pair, PEM-enveloped as an X.509 `SubjectPublicKeyInfo` — so material that is not such a
//! key is refused with the `InvalidArgument` (HTTP 400) the operation models and no key is
//! stored for it. The service decides it by DECODING the material, so what gets through is
//! what a PKCS#1 reader accepted, not what merely looks like a key: the private half of a
//! pair, a key of another algorithm, a body that is not DER and text in no envelope at all
//! are each refused.
//!
//! Why it matters: a key the control plane stored is the key a signed URL is verified
//! against, and material the control plane serves back out is read by whoever can read a
//! public key — so private key material must never be stored, let alone reported.
//!
//! The rows differ along what the rule generalises over: the KIND of material (public key,
//! private key in each of its two envelopes, another algorithm's public key, a certificate's
//! own structure, undecodable base64, no envelope, nothing at all) and, for the material that
//! IS a public key, the width of its modulus. The harness is the public key lifecycle
//! suite's, reused rather than copied.

use smithy_server_runtime::MultiServiceRouter;

use service_com_amazonaws_cloudfront_cloudfront2020_05_31::state::INVALID_ENCODED_KEY_MESSAGE;

use crate::distribution_lifecycle::{call, emulator, API_VERSION};
use crate::public_key_lifecycle::{create_key, get_key, pem, Key};

/// `GET /2020-05-31/public-key/{Id}/config`, the reader that reports the stored material
/// back.
async fn get_key_config(router: &MultiServiceRouter, id: &str) -> crate::distribution_lifecycle::Answer {
    call(
        router,
        "GET",
        &format!("/{API_VERSION}/public-key/{id}/config"),
        None,
        None,
    )
    .await
}

/// The ids `ListPublicKeys` reports, which is what says whether a refused create stored
/// anything.
async fn listed_key_ids(router: &MultiServiceRouter) -> Vec<String> {
    let listed = call(
        router,
        "GET",
        &format!("/{API_VERSION}/public-key"),
        None,
        None,
    )
    .await;
    assert_eq!(
        listed.status, 200,
        "expected HTTP 200 from ListPublicKeys, got {} with {}",
        listed.status, listed.raw
    );
    listed
        .root()
        .children_named("Items")
        .first()
        .map(|items| {
            items
                .children_named("PublicKeySummary")
                .iter()
                .filter_map(|summary| summary.text_at("Id").map(str::to_string))
                .collect()
        })
        .unwrap_or_default()
}

/// One freshly generated 2048-bit RSA pair, in the two envelopes a client holds its halves
/// in: the PEM `SubjectPublicKeyInfo` of the public half, the PEM PKCS#8 `PrivateKeyInfo` of
/// the private half, and the PEM PKCS#1 `RSAPrivateKey` inside that.
///
/// Generated by the cryptography provider this workspace builds rather than written out here,
/// so the material under test is a real key pair's.
fn generated_pair() -> (String, String, String) {
    use ::aws_lc_rs::encoding::{AsDer, Pkcs8V1Der, PublicKeyX509Der};
    use ::aws_lc_rs::signature::KeyPair as _;

    let key = ::aws_lc_rs::signature::RsaKeyPair::generate(::aws_lc_rs::rsa::KeySize::Rsa2048)
        .expect("the provider generates a 2048-bit RSA pair");
    let public: PublicKeyX509Der<'_> =
        AsDer::as_der(key.public_key()).expect("the public half encodes as an SPKI");
    let private: Pkcs8V1Der<'_> =
        AsDer::as_der(&key).expect("the private half encodes as a PKCS#8");
    let info = ::pkcs8::PrivateKeyInfo::try_from(private.as_ref())
        .expect("the generated key is a PKCS#8 PrivateKeyInfo");
    (
        envelope("PUBLIC KEY", public.as_ref().to_vec()),
        envelope("PRIVATE KEY", private.as_ref().to_vec()),
        envelope("RSA PRIVATE KEY", info.private_key.to_vec()),
    )
}

/// `der` in a PEM envelope labelled `label`, with the line ending a client's own PEM file
/// carries.
fn envelope(label: &str, der: Vec<u8>) -> String {
    ::pem::encode_config(
        &::pem::Pem::new(label.to_string(), der),
        ::pem::EncodeConfig::new().set_line_ending(::pem::LineEnding::LF),
    )
    .trim_end()
    .to_string()
}

/// A PEM `SubjectPublicKeyInfo` whose algorithm is NOT `rsaEncryption`: an Ed25519 public
/// key, whose object identifier (`1.3.101.112`) is the one RFC 8410 section 3 assigns that
/// algorithm.
fn other_algorithm_public_key() -> String {
    use ::pkcs1::der::asn1::BitString;
    use ::pkcs1::der::Encode as _;
    use ::x509_cert::spki::{AlgorithmIdentifierOwned, SubjectPublicKeyInfoOwned};

    let info = SubjectPublicKeyInfoOwned {
        algorithm: AlgorithmIdentifierOwned {
            oid: "1.3.101.112".parse().expect("the Ed25519 OID"),
            // Ed25519 states no algorithm parameters at all (RFC 8410 section 3).
            parameters: None,
        },
        subject_public_key: BitString::from_bytes(&[7u8; 32]).expect("a whole number of octets"),
    };
    envelope(
        "PUBLIC KEY",
        info.to_der().expect("a SubjectPublicKeyInfo encodes as DER"),
    )
}

/// The material every case is run over: what the row submits as `EncodedKey`, and whether
/// the service stores a key for it.
fn material_rows() -> Vec<(String, String, bool)> {
    let (public_key, pkcs8_private_key, pkcs1_private_key) = generated_pair();
    let valid = pem(4, 'M');
    vec![
        ("a generated RSA public key".to_string(), public_key, true),
        (
            "a synthesised RSA public key of a 1024-bit modulus".to_string(),
            pem(1, 'N'),
            true,
        ),
        (
            "a synthesised RSA public key of a wide modulus".to_string(),
            pem(7, 'O'),
            true,
        ),
        (
            "the private half of the pair, in its PKCS#8 envelope".to_string(),
            pkcs8_private_key,
            false,
        ),
        (
            "the private half of the pair, in its PKCS#1 envelope".to_string(),
            pkcs1_private_key,
            false,
        ),
        (
            "a public key of another algorithm".to_string(),
            other_algorithm_public_key(),
            false,
        ),
        (
            "a PUBLIC KEY envelope around base64 that is not DER".to_string(),
            envelope("PUBLIC KEY", b"not a SubjectPublicKeyInfo".to_vec()),
            false,
        ),
        (
            "the body of a public key with no envelope at all".to_string(),
            valid
                .lines()
                .filter(|line| !line.starts_with("-----"))
                .collect::<Vec<_>>()
                .join("\n"),
            false,
        ),
        (
            "a public key whose envelope has lost its closing armour".to_string(),
            valid
                .lines()
                .filter(|line| !line.starts_with("-----END"))
                .collect::<Vec<_>>()
                .join("\n"),
            false,
        ),
        ("no material at all".to_string(), String::new(), false),
        (
            "a sentence that is no key".to_string(),
            "this is not a key".to_string(),
            false,
        ),
    ]
}

/// Material that is an RSA public key is stored and round-trips through the readers; material
/// that is not is refused with `InvalidArgument` and the sentence CloudFront states for the
/// condition, and nothing is stored for it.
#[tokio::test]
async fn only_an_rsa_public_key_is_admitted_as_encoded_key() {
    let router = emulator();

    for (index, (case, material, admitted)) in material_rows().into_iter().enumerate() {
        let before = listed_key_ids(&router).await;
        let key = Key {
            case: case.clone(),
            caller_reference: format!("material-reference-{index}"),
            name: format!("material-key-{index}"),
            encoded_key: material.clone(),
            comment: Some("the material admission suite".to_string()),
        };
        let answer = create_key(&router, &key.xml()).await;
        if !admitted {
            assert_eq!(
                answer.status, 400,
                "case {case}: expected HTTP 400, got {} with {}",
                answer.status, answer.raw
            );
            assert_eq!(
                answer.error_code(),
                "InvalidArgument",
                "case {case}: expected InvalidArgument, got {:?} in {}",
                answer.error_code(),
                answer.raw
            );
            assert_eq!(
                answer.root().find_text("Message"),
                Some(INVALID_ENCODED_KEY_MESSAGE),
                "case {case}: expected the sentence {INVALID_ENCODED_KEY_MESSAGE:?}, got {:?}",
                answer.root().find_text("Message")
            );
            let after = listed_key_ids(&router).await;
            assert_eq!(
                after, before,
                "case {case}: the refused create stored a key"
            );
            // And nothing of the refused material is reported by any reader, which is what
            // matters for the private halves above.
            assert!(
                !answer.raw.contains("PRIVATE KEY"),
                "case {case}: the refusal carries the submitted material: {}",
                answer.raw
            );
            continue;
        }

        assert_eq!(
            answer.status, 201,
            "case {case}: expected HTTP 201, got {} with {}",
            answer.status, answer.raw
        );
        let id = answer
            .root()
            .find_text("Id")
            .unwrap_or_else(|| panic!("case {case}: the created key reports an id"))
            .to_string();

        // The material round-trips through both readers of the one stored record.
        let read = get_key(&router, &id).await;
        assert_eq!(
            read.status, 200,
            "case {case}: expected HTTP 200 from GetPublicKey, got {} with {}",
            read.status, read.raw
        );
        assert_eq!(
            read.root().find_text("EncodedKey"),
            Some(material.as_str()),
            "case {case}: GetPublicKey reported {:?}",
            read.root().find_text("EncodedKey")
        );
        let config = get_key_config(&router, &id).await;
        assert_eq!(
            config.root().find_text("EncodedKey"),
            Some(material.as_str()),
            "case {case}: GetPublicKeyConfig reported {:?} in {}",
            config.root().find_text("EncodedKey"),
            config.raw
        );
        let after = listed_key_ids(&router).await;
        assert!(
            after.contains(&id),
            "case {case}: ListPublicKeys does not report the stored key {id}: {after:?}"
        );
    }
}
