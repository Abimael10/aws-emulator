//! ONE country per viewer request: the code the edge REPORTS to the origin as
//! `CloudFront-Viewer-Country` is the code the distribution's `Restrictions.GeoRestriction`
//! decides that same viewer by — whichever way the restriction got there.
//!
//! RULE: the edge resolves one country for a viewer request and both readers of it see that
//! value: the origin receives it as `CloudFront-Viewer-Country` wherever the matched
//! behaviour's origin request policy names that header, and the geographic restriction is
//! evaluated against it. So a `blacklist` that names the very code the origin was told
//! refuses that viewer — `403` generated by CloudFront, `X-Cache: Error from cloudfront`,
//! none of the origin's bytes — and an `allowlist` that names it serves the viewer from the
//! origin, whether that restriction was stated by the CREATE or put there by a later UPDATE
//! which the clock has deployed.
//!
//! Every viewer here dials the address the distribution PUBLISHED, in the clear and with no
//! credential, and states NO country of its own: the country is then wholly the edge's to
//! resolve, which is the viewer a client of a running emulator is. The origin is a Lambda
//! function URL, as [`crate::edge_lambda_url_origin`]'s topology stages it, so what the
//! viewer is served says what reached the origin.
//!
//! The rows differ along what the rule generalises over: how the restriction got onto the
//! distribution (the create, and an update of a distribution that was serving), the
//! restriction type (`blacklist`, `whitelist`, `none`), whether the code it names is the one
//! the edge reported for this viewer, and how many codes it names.

use serde_json::Value;

use crate::distribution_lifecycle::{call, update_distribution, API_VERSION};
use crate::edge_lambda_url_origin::{
    Answered, Topology, ALL_VIEWER_AND_CLOUDFRONT, MISS, OPEN_PATH, ORIGIN_MARKER,
};
use crate::edge_signed_access::CACHING_DISABLED;

/// `X-Cache` for an answer CloudFront produced itself, which is what a viewer its own
/// enforcement refused is told.
const ERROR: &str = "Error from cloudfront";

/// A country code that is NOT the one the edge reports for a viewer of this emulator, used by
/// the rows whose restriction names somewhere else. Two letters ISO 3166-1 assigns to a
/// country, as a `GeoRestriction` `Location` is ("the `Location` element is a two-letter,
/// uppercase country code"), and held to differing from the reported one by the case itself.
const ELSEWHERE: &str = "DE";
/// A second such code, for the rows whose restriction names several locations.
const ALSO_ELSEWHERE: &str = "JP";

/// A `Restrictions` element of `restriction_type` over `locations`; `Quantity` is the number
/// of locations it carries, which is what the control plane checks it against.
fn restrictions(restriction_type: &str, locations: &[&str]) -> String {
    let items: String = locations
        .iter()
        .map(|location| format!("<Location>{location}</Location>"))
        .collect();
    let items = if locations.is_empty() {
        String::new()
    } else {
        format!("<Items>{items}</Items>")
    };
    format!(
        "<Restrictions><GeoRestriction>\
         <RestrictionType>{restriction_type}</RestrictionType>\
         <Quantity>{}</Quantity>{items}\
         </GeoRestriction></Restrictions>",
        locations.len()
    )
}

/// One `DistributionConfig` over the function URL `origin` carrying `restrictions`: the
/// AWS-managed `CachingDisabled` cache policy, so every viewer request below is an origin
/// fetch rather than an earlier one's cached answer, and the AWS-managed origin request
/// policy that forwards the `CloudFront-*` headers the edge generates, without which the
/// origin is told no country at all.
///
/// `PriceClass` is stated because an UPDATE submits the configuration WHOLE: a document that
/// leaves the member out is refused `IllegalUpdate`, so the rows below state it exactly as a
/// caller that read the configuration back and changed one member does.
fn config_xml(caller_reference: &str, origin: &str, restrictions: &str) -> String {
    format!(
        "<DistributionConfig xmlns=\"http://cloudfront.amazonaws.com/doc/{API_VERSION}/\">\
         <CallerReference>{caller_reference}</CallerReference>\
         <Origins><Quantity>1</Quantity><Items><Origin>\
         <Id>function-url</Id><DomainName>{origin}</DomainName>\
         <CustomOriginConfig><HTTPPort>80</HTTPPort><HTTPSPort>443</HTTPSPort>\
         <OriginProtocolPolicy>https-only</OriginProtocolPolicy>\
         <OriginSslProtocols><Quantity>1</Quantity>\
         <Items><SslProtocol>TLSv1.2</SslProtocol></Items></OriginSslProtocols>\
         </CustomOriginConfig>\
         </Origin></Items></Origins>\
         <DefaultCacheBehavior><TargetOriginId>function-url</TargetOriginId>\
         <ViewerProtocolPolicy>allow-all</ViewerProtocolPolicy>\
         <AllowedMethods><Quantity>2</Quantity>\
         <Items><Method>GET</Method><Method>HEAD</Method></Items></AllowedMethods>\
         <CachePolicyId>{CACHING_DISABLED}</CachePolicyId>\
         <OriginRequestPolicyId>{ALL_VIEWER_AND_CLOUDFRONT}</OriginRequestPolicyId>\
         </DefaultCacheBehavior>\
         <Comment>the country the edge reports and restricts by</Comment>\
         <PriceClass>PriceClass_All</PriceClass>\
         {restrictions}\
         <Enabled>true</Enabled>\
         </DistributionConfig>"
    )
}

/// The country the ORIGIN was told, read out of the answer one viewer request was served:
/// the handler reports the `CloudFront-Viewer-Country` it received, so this is the value the
/// edge resolved for that viewer.
fn country_of(case: &str, served: &Answered) -> String {
    assert_eq!(
        served.status, 200,
        "case {case:?}: expected the origin's answer through the edge, got {} with {:?}",
        served.status, served.raw
    );
    let report: Value = serde_json::from_str(&served.body).unwrap_or(Value::Null);
    let country = report["country"].as_str().unwrap_or_default().to_string();
    assert!(
        country.len() == 2 && country.chars().all(|letter| letter.is_ascii_uppercase()),
        "case {case:?}: expected the origin to be told a two-letter uppercase country code, \
         got {country:?} in {:?}",
        served.body
    );
    country
}

/// The configuration the distribution `id` is holding, as `GetDistributionConfig` reports it,
/// and the version token an update of it has to state as its `If-Match`.
///
/// This is the document a client CHANGES one member of: "the distribution configuration
/// information for your distribution" read back whole, resubmitted whole. Read here rather
/// than rebuilt, so what the update below carries is every member the service itself reports —
/// the ones the create stated and the ones it supplied.
async fn read_configuration(topology: &Topology, case: &str, id: &str) -> (String, String) {
    let read = call(
        &topology.router,
        "GET",
        &format!("/{API_VERSION}/distribution/{id}/config"),
        None,
        None,
    )
    .await;
    assert_eq!(
        read.status, 200,
        "setup {case:?}: GetDistributionConfig must answer 200, got {} with {}",
        read.status, read.raw
    );
    let etag = read.header("etag").to_string();
    assert!(
        !etag.is_empty(),
        "setup {case:?}: GetDistributionConfig reports no version token: {}",
        read.raw
    );
    assert!(
        read.raw.contains("<DistributionConfig"),
        "setup {case:?}: GetDistributionConfig must report a DistributionConfig, got {}",
        read.raw
    );
    (read.raw.clone(), etag)
}

/// The configuration `document` with its `Restrictions` member replaced by `restrictions` —
/// the one member each row changes, every other member left exactly as the service reported
/// it.
fn with_restrictions(case: &str, document: &str, restrictions: &str) -> String {
    let opening = "<Restrictions>";
    let closing = "</Restrictions>";
    let head = document.find(opening).unwrap_or_else(|| {
        panic!("case {case:?}: no Restrictions in the reported configuration: {document}")
    });
    let tail = document
        .find(closing)
        .map(|at| at + closing.len())
        .unwrap_or_else(|| {
            panic!("case {case:?}: no Restrictions in the reported configuration: {document}")
        });
    format!("{}{restrictions}{}", &document[..head], &document[tail..])
}

/// One row: how the restriction is spelled, and whether CloudFront then refuses the viewer.
struct Row {
    case: &'static str,
    restriction_type: &'static str,
    /// Whether the locations include the code the edge reported for this viewer, and which
    /// other codes they name beside it.
    names_the_reported_country: bool,
    other_locations: &'static [&'static str],
    refused: bool,
}

/// The locations one row's restriction names, with the reported country substituted where the
/// row names it — the row says WHICH countries, the edge says which one the viewer is in.
fn locations(row: &Row, reported: &str) -> Vec<String> {
    let mut out = Vec::new();
    if row.names_the_reported_country {
        out.push(reported.to_string());
    }
    out.extend(row.other_locations.iter().map(|code| (*code).to_string()));
    out
}

/// RULE: the country the edge reports to the origin as `CloudFront-Viewer-Country` is the one
/// its `Restrictions.GeoRestriction` decides the same viewer by, so a `blacklist` naming that
/// code refuses the viewer with CloudFront's own `403` and no origin request, and an
/// `allowlist` naming it serves the viewer from the origin — whether the restriction was
/// stated at the create or put there by a later update the clock has deployed.
#[tokio::test]
async fn the_country_the_edge_reports_is_the_country_it_restricts_the_viewer_by() {
    let topology = Topology::new();
    // The emulator as a started one is: served at an endpoint, so every address it publishes
    // is one a client of that process reads.
    ::emulator_server::EmulatorService::serving_at(&topology.router, "https://127.0.0.1:9297");
    let case = "the origin behind the restricted distribution";
    let announced = topology
        .public_function_url_host(case, "cf-edge-geo-reported-country")
        .await;
    // An `Origin$DomainName` carries a host and no path, so what the origin names is the
    // AUTHORITY of the published endpoint.
    let origin = announced
        .split('/')
        .next()
        .unwrap_or_default()
        .to_string();

    // The BASELINE: the same distribution with no restriction at all, which restricts nobody.
    // It is what the country the rows restrict by is read from, exactly as a client learns
    // where the edge thinks it is — from the origin it reaches through that edge.
    let reference = "edge-geo-reported-country";
    let (id, _arn, domain) = topology
        .created_distribution(case, &config_xml(reference, &origin, &restrictions("none", &[])))
        .await;
    topology.awaited_deployment(case, &id).await;
    let baseline = Answered::of_stating(case, &domain, "GET", OPEN_PATH, &[]).await;
    let reported = country_of(case, &baseline);
    assert!(
        baseline.body.contains(ORIGIN_MARKER),
        "case {case:?}: expected the function's own bytes through the edge, got {:?}",
        baseline.body
    );
    assert!(
        baseline.raw.to_ascii_lowercase().contains(&format!("x-cache: {}", MISS.to_ascii_lowercase())),
        "case {case:?}: expected the origin's answer to be reported a cache miss, got {:?}",
        baseline.raw
    );
    assert_ne!(
        reported, ELSEWHERE,
        "setup {case:?}: the row that names somewhere else needs a code the edge does not \
         report, got {reported:?}"
    );

    let rows: &[Row] = &[
        Row {
            case: "a blocklist naming the country the origin was told",
            restriction_type: "blacklist",
            names_the_reported_country: true,
            other_locations: &[],
            refused: true,
        },
        Row {
            case: "that same country last of several blocklisted ones",
            restriction_type: "blacklist",
            names_the_reported_country: true,
            other_locations: &[ELSEWHERE, ALSO_ELSEWHERE],
            refused: true,
        },
        Row {
            case: "a blocklist naming only somewhere else",
            restriction_type: "blacklist",
            names_the_reported_country: false,
            other_locations: &[ELSEWHERE, ALSO_ELSEWHERE],
            refused: false,
        },
        Row {
            case: "an allowlist naming the country the origin was told",
            restriction_type: "whitelist",
            names_the_reported_country: true,
            other_locations: &[ELSEWHERE],
            refused: false,
        },
        Row {
            case: "an allowlist naming only somewhere else",
            restriction_type: "whitelist",
            names_the_reported_country: false,
            other_locations: &[ELSEWHERE],
            refused: true,
        },
        Row {
            case: "the restriction taken off again",
            restriction_type: "none",
            names_the_reported_country: false,
            other_locations: &[],
            refused: false,
        },
    ];

    for row in rows {
        let case = row.case;
        // The restriction is put on the distribution that is already SERVING, through an
        // update at the version its caller read: the configuration a viewer is decided by is
        // the one the control plane last accepted.
        let (document, version) = read_configuration(&topology, case, &id).await;
        let named = locations(row, &reported);
        let named: Vec<&str> = named.iter().map(String::as_str).collect();
        let updated = update_distribution(
            &topology.router,
            &id,
            &with_restrictions(
                case,
                &document,
                &restrictions(row.restriction_type, &named),
            ),
            Some(&version),
        )
        .await;
        assert_eq!(
            updated.status, 200,
            "case {case:?}: UpdateDistribution must be accepted, got {} with {}",
            updated.status, updated.raw
        );
        // A configuration that has not reached the edge locations serves no viewer by it yet.
        topology.awaited_deployment(case, &id).await;

        // Every viewer request through the restricted distribution is ANSWERED, and answered
        // the same way whichever object it names: the restriction is the distribution's, so
        // the path the viewer spelled does not decide it — the root included, which is the
        // path a client handed a domain name asks for first.
        for path in ["/", OPEN_PATH] {
            let case = &format!("{case} at {path}");
            let served = Answered::of_stating(case, &domain, "GET", path, &[]).await;
            if row.refused {
                assert_eq!(
                    served.status, 403,
                    "case {case:?}: expected CloudFront's own 403 for a viewer in {reported:?}, \
                     got {} with {:?}",
                    served.status, served.raw
                );
                assert!(
                    served
                        .raw
                        .to_ascii_lowercase()
                        .contains(&format!("x-cache: {}", ERROR.to_ascii_lowercase())),
                    "case {case:?}: expected X-Cache {ERROR:?} on a refusal CloudFront \
                     produced, got {:?}",
                    served.raw
                );
                assert!(
                    !served.body.contains(ORIGIN_MARKER),
                    "case {case:?}: a refused viewer must be served none of the origin's bytes, \
                     got {:?}",
                    served.body
                );
                continue;
            }
            let country = country_of(case, &served);
            assert_eq!(
                country, reported,
                "case {case:?}: expected the origin to be told the same country as before, got \
                 {country:?} in {:?}",
                served.body
            );
            assert!(
                served.body.contains(ORIGIN_MARKER),
                "case {case:?}: expected the function's own bytes through the edge, got {:?}",
                served.body
            );
        }
    }
}
