//! The Amazon Web Services Secrets Manager secret Amazon Redshift MANAGES for a namespace's
//! admin credentials, and the minting and release a request that turns that management on or
//! off depends on.
//!
//! `manageAdminPassword` is documented as "If true, Amazon Redshift uses Secrets Manager to
//! manage the namespace's admin credentials", and `Namespace$adminPasswordSecretArn` is "the
//! Amazon Resource Name (ARN) for the namespace's admin user credentials secret". So a
//! request that turns management on makes the service do three things, and all three happen
//! here:
//!
//! 1. GENERATE the admin password. It is generated by Secrets Manager's own generator
//!    (`GetRandomPassword`), without the characters an Amazon Redshift admin password may not
//!    carry, so the generated value is one `adminUserPassword` would itself accept.
//! 2. STORE it in a secret Secrets Manager holds: `CreateSecret` under the name the service
//!    gives a secret of its own ([`namespace_admin_secret_name`]), whose value is the
//!    `{"username", "password"}` document such a secret holds. The secret is a real secret of
//!    the emulated Secrets Manager, so `GetSecretValue` on the ARN this reports answers with
//!    those credentials, and `DescribeSecret` resolves it.
//! 3. REPORT it. The ARN Secrets Manager allocated is stored on the namespace record and is
//!    what every reader of the namespace projects as `adminPasswordSecretArn`.
//!
//! A request that turns management back OFF releases that secret
//! ([`release_namespace_admin_secret`]): the namespace no longer has credentials the service
//! manages, so nothing is left holding them.
//!
//! Secrets Manager is reached the way the rest of this emulator reaches another service: the
//! AWS SDK driven over the emulator's own in-process transport, through the operation callback
//! ([`smithy_server_runtime::OperationContext::callback`]), so no socket is opened and no
//! request leaves the process.
//!
//! The generated password is never stored on this service's records and never reported: it
//! goes into the secret, and what a caller gets back is the secret's ARN.

use super::service_principal_call::ServicePrincipalCall;

/// The prefix every secret Amazon Redshift MANAGES is named under: the service's own id and
/// the character AWS reserves for a secret an Amazon Web Services service owns.
///
/// A secret in this form is not a caller's to create — the mark is not one of the characters
/// a secret name may carry, so a caller's `CreateSecret` cannot name one at all — which is
/// what makes the name itself say the secret is the service's. It is accepted from the service
/// whose own principal is making the create.
pub const MANAGED_SECRET_NAME_PREFIX: &str = "redshift!";

/// The name of the secret Amazon Redshift manages for a NAMESPACE's admin credentials:
/// `redshift!namespace-<namespaceId>`.
///
/// AWS names a secret of its own under the reserved prefix every such secret carries
/// ([`MANAGED_SECRET_NAME_PREFIX`]), then the kind of resource it belongs to, then an opaque
/// id of the account's own. The namespace's `namespaceId` is that id: it is server-minted,
/// carries nothing of the caller's input, and never changes for the life of the namespace, so
/// the secret of a namespace is still that namespace's secret and two namespaces can never be
/// given one name. It is also not what the secret is addressed by: every later call reads the
/// ARN Secrets Manager allocated, which the namespace record stores.
#[must_use]
pub fn namespace_admin_secret_name(namespace_id: &str) -> String {
    format!("{MANAGED_SECRET_NAME_PREFIX}namespace-{namespace_id}")
}

/// How long a generated admin password is. Amazon Redshift documents an admin password of 8
/// to 64 characters, so this sits well inside that range and well above its floor.
const ADMIN_PASSWORD_LENGTH: i64 = 32;

/// The characters a generated admin password leaves out: the ones an Amazon Redshift admin
/// password is documented not to accept — the single quote, the double quote, the backslash,
/// the forward slash and the at sign — so the generated value is one `adminUserPassword`
/// would itself accept. The space is excluded through `IncludeSpace` below.
const ADMIN_PASSWORD_EXCLUDED_CHARACTERS: &str = "'\"\\/@";

/// What a request that turns management on asks for: the namespace whose admin credentials the
/// secret holds, and the key to encrypt it under.
#[derive(Debug)]
pub struct AdminSecretRequest<'a> {
    /// The namespace's ARN, the resource the call is made on behalf of.
    pub namespace_arn: &'a str,
    /// The namespace's `namespaceId`, which the secret is named from.
    pub namespace_id: &'a str,
    /// `adminUsername`, the user whose password the secret holds.
    pub admin_username: Option<&'a str>,
    /// `adminPasswordSecretKmsKeyId`: "The ID of the Key Management Service (KMS) key used to
    /// encrypt and store the namespace's admin credentials secret." A request naming none
    /// leaves the choice to Secrets Manager's own default.
    pub kms_key_id: Option<&'a str>,
}

/// Mint the managed admin credentials secret `asked` describes: generate the password, store
/// it in a new Secrets Manager secret, and answer the ARN the namespace will carry.
///
/// `Err` carries the sentence to report the failure with. Every failure here is a failure of
/// this EMULATOR to do what the service does — Secrets Manager not mounted beside this
/// service, or a store that would not take the secret — never anything the request carried.
pub async fn mint_namespace_admin_secret<Eng: Send + Sync + 'static>(
    engine: &Eng,
    ctx: &smithy_server_runtime::OperationContext<'_>,
    region: &str,
    asked: &AdminSecretRequest<'_>,
) -> Result<String, String> {
    let secrets = secrets_manager_client_signed_as(ctx, region, None)
        .ok_or_else(unaskable_region_message)?;
    let password = generated_password(&secrets).await?;
    // The secret is one Amazon Redshift OWNS, so the create is made as the service's OWN
    // principal acting for the namespace the secret belongs to ([`ServicePrincipalCall`]):
    // that is what lets it be named under the reserved prefix no caller can mint and be
    // reported with `OwningService`. A call that cannot be made that way cannot create that
    // secret AT ALL, so it is reported as this emulator failing to create the secret rather
    // than quietly creating an ordinary one of the account under a name a caller could mint.
    let acting = ServicePrincipalCall::begin(engine, ctx, asked.namespace_arn)
        .ok_or_else(|| unactable_principal("created", asked.namespace_arn))?;
    let created = acting
        .secrets_manager_client(ctx, region)?
        .create_secret()
        .name(namespace_admin_secret_name(asked.namespace_id))
        .client_request_token(fresh_version_token())
        .secret_string(credentials_document(asked.admin_username, &password))
        .set_kms_key_id(asked.kms_key_id.map(str::to_string))
        .send()
        .await
        .map_err(|error| {
            format!(
                "the admin credentials secret could not be created in Amazon Web Services \
                 Secrets Manager: {}",
                ::aws_smithy_types::error::display::DisplayErrorContext(&error)
            )
        })?;
    created.arn().map(str::to_string).ok_or_else(|| {
        "Amazon Web Services Secrets Manager created the admin credentials secret without an \
         ARN"
            .to_string()
    })
}

/// Release a managed admin credentials secret: the namespace's admin password is no longer
/// managed by the service — because management was turned off, or because the namespace
/// itself is gone — so the credentials it held can no longer be read.
///
/// The delete goes through Secrets Manager's own `DeleteSecret`, which is what owns the
/// secret's lifecycle, made as the service's own principal acting for the namespace for the
/// same reason the create is: a caller's own `DeleteSecret` on such a secret is refused.
pub async fn release_namespace_admin_secret<Eng: Send + Sync + 'static>(
    engine: &Eng,
    ctx: &smithy_server_runtime::OperationContext<'_>,
    region: &str,
    namespace_arn: &str,
    secret_arn: &str,
) -> Result<(), String> {
    let acting = ServicePrincipalCall::begin(engine, ctx, namespace_arn)
        .ok_or_else(|| unactable_principal("deleted", namespace_arn))?;
    acting
        .secrets_manager_client(ctx, region)?
        .delete_secret()
        .secret_id(secret_arn)
        // The secret goes with the management rather than into a recovery window: it is the
        // service's own, so nobody but the service could take it back out of one, and its
        // NAME is the namespace's ([`namespace_admin_secret_name`]) — so a request that turns
        // the management back on for that same namespace has to be able to mint it again,
        // which a secret still occupying the name would refuse.
        .force_delete_without_recovery(true)
        .send()
        .await
        .map_err(|error| {
            format!(
                "the admin credentials secret could not be deleted in Amazon Web Services \
                 Secrets Manager: {}",
                ::aws_smithy_types::error::display::DisplayErrorContext(&error)
            )
        })?;
    Ok(())
}

/// Release a managed secret no namespace reports any more, so nothing is left behind holding
/// credentials nothing can reach: the secret of a namespace this call deleted, or one minted
/// for a namespace the call then could not store.
///
/// Best effort by design: the answer to the caller is already decided — the namespace is gone,
/// or the refusal that orphaned the secret stands — so a Secrets Manager call that fails here
/// cannot change it. It is recorded and the answer stands.
pub async fn release_orphaned_namespace_admin_secret<Eng: Send + Sync + 'static>(
    engine: &Eng,
    ctx: &smithy_server_runtime::OperationContext<'_>,
    region: &str,
    namespace_arn: &str,
    secret_arn: &str,
) {
    if let Err(message) =
        release_namespace_admin_secret(engine, ctx, region, namespace_arn, secret_arn).await
    {
        ::tracing::debug!(
            secret = secret_arn,
            %message,
            "the admin credentials secret of a namespace no caller can reach any more was not \
             deleted"
        );
    }
}

/// The admin password the service generates for a managed secret, from Secrets Manager's own
/// generator — so the value is one that service produced rather than one this crate invented.
async fn generated_password(
    secrets: &::aws_sdk_secretsmanager::Client,
) -> Result<String, String> {
    let generated = secrets
        .get_random_password()
        .password_length(ADMIN_PASSWORD_LENGTH)
        .exclude_characters(ADMIN_PASSWORD_EXCLUDED_CHARACTERS)
        .include_space(false)
        .send()
        .await
        .map_err(|error| {
            format!(
                "the admin password could not be generated in Amazon Web Services Secrets \
                 Manager: {}",
                ::aws_smithy_types::error::display::DisplayErrorContext(&error)
            )
        })?;
    generated.random_password().map(str::to_string).ok_or_else(|| {
        "Amazon Web Services Secrets Manager generated no admin password".to_string()
    })
}

/// The value a managed admin credentials secret holds: the admin user's name and the password
/// generated for it, as the JSON document a client reads the credentials out of.
fn credentials_document(username: Option<&str>, password: &str) -> String {
    let mut document = ::serde_json::Map::new();
    if let Some(username) = username {
        document.insert(
            "username".to_string(),
            ::serde_json::Value::String(username.to_string()),
        );
    }
    document.insert(
        "password".to_string(),
        ::serde_json::Value::String(password.to_string()),
    );
    ::serde_json::Value::Object(document).to_string()
}

/// A version id for the secret version this call stakes.
///
/// `ClientRequestToken` becomes the version's id, and "if you generate a raw HTTP request to
/// the Secrets Manager service endpoint, then you must generate a ClientRequestToken and
/// include it in the request" — which is the position this service is in, since it is Amazon
/// Redshift that creates the secret. A v4 UUID, the form that member documents, so two calls
/// never stake the same version.
fn fresh_version_token() -> String {
    uuid::Uuid::new_v4().to_string()
}

/// A Secrets Manager client over the IN-PROCESS callback into this same emulator: the secret
/// Amazon Redshift manages is one this emulator holds, so creating and deleting it never
/// leaves the process.
///
/// `signed_as` names the credential the call presents: the service's own principal credential
/// for a call that has to be the service's ([`ServicePrincipalCall::secrets_manager_client`]),
/// and the callback's own for a call that is nobody's in particular (generating a password,
/// which reads and writes nothing).
///
/// `region` is the request's own signing region, so the secret is created where the namespace
/// that carries it lives. The transport is in-process, so everything a network client needs
/// and this one cannot have is disabled: retries, timeouts, stalled-stream protection and
/// identity caching each need a sleep implementation the callback transport is not given, and
/// there is nothing behind it to retry.
///
/// The Region a request is signed for is CALLER-SUPPLIED text and here it ends up in an
/// endpoint URL's authority, so it is read as a Region LABEL (`service_common::arn::region_label`,
/// the one place this tree states that grammar) instead of being interpolated as given: `None`
/// for a value that would name an authority the caller chose rather than the peer service this
/// emulator asks.
pub(super) fn secrets_manager_client_signed_as(
    ctx: &smithy_server_runtime::OperationContext<'_>,
    region: &str,
    signed_as: Option<::aws_sdk_secretsmanager::config::Credentials>,
) -> Option<::aws_sdk_secretsmanager::Client> {
    let region = ::service_common::arn::region_label(region)?;
    let mut config = ::aws_sdk_secretsmanager::Config::builder()
        .behavior_version(::aws_sdk_secretsmanager::config::BehaviorVersion::latest())
        .region(::aws_sdk_secretsmanager::config::Region::new(
            region.to_string(),
        ))
        .endpoint_url(format!("https://secretsmanager.{region}.amazonaws.com"))
        .http_client(ctx.callback().http_client())
        .retry_config(::aws_sdk_secretsmanager::config::retry::RetryConfig::disabled())
        .timeout_config(::aws_sdk_secretsmanager::config::timeout::TimeoutConfig::disabled())
        .identity_cache(::aws_sdk_secretsmanager::config::IdentityCache::no_cache())
        .stalled_stream_protection(
            ::aws_sdk_secretsmanager::config::StalledStreamProtectionConfig::disabled(),
        );
    config = match signed_as {
        Some(credentials) => config.credentials_provider(credentials),
        None => config.credentials_provider(ctx.callback().aws_credentials_provider()),
    };
    Some(::aws_sdk_secretsmanager::Client::from_conf(config.build()))
}

/// The sentence a managed-secret call reports when the request's signing scope names no Region
/// this emulator can ask a peer service in: a failure of this emulator to reach the service
/// that owns the secret, like the others here.
pub(super) fn unaskable_region_message() -> String {
    "the admin credentials secret could not be reached in Amazon Web Services Secrets Manager: \
     the request's signing scope names no Amazon Web Services Region"
        .to_string()
}

/// The sentence reported when this emulator could not make the call AS the Amazon Redshift
/// service principal acting for `namespace_arn` ([`ServicePrincipalCall::begin`]).
///
/// Such a secret is the service's own — its name is not a caller's to write, and neither its
/// value nor its lifecycle is a caller's to change — so a call that cannot be made as that
/// principal does nothing. `action` is what could not be done to the secret ("created",
/// "deleted"), so one sentence serves every call made as that principal.
fn unactable_principal(action: &str, namespace_arn: &str) -> String {
    format!(
        "the admin credentials secret could not be {action} in Amazon Web Services Secrets \
         Manager: this emulator could not make the call as the Amazon Redshift service \
         principal acting for {namespace_arn}, which is the identity that owns the secret"
    )
}
