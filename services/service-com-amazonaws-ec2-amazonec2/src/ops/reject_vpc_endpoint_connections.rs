impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for RejectVpcEndpointConnections<Eng>
{
    type Input = RejectVpcEndpointConnectionsInput;
    type Output = RejectVpcEndpointConnectionsOutput;
    type Error = RejectVpcEndpointConnectionsError;

    const NAME: &'static str = "RejectVpcEndpointConnections";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::REJECT_VPC_ENDPOINT_CONNECTIONS_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::REJECT_VPC_ENDPOINT_CONNECTIONS_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // `ctx` carries request metadata only; this operation reads none of it — a service
        // and an endpoint are each named by id. The store is reached through the engine
        // held on `self`.
        let _ = ctx;
        use crate::state;

        // "The IDs of the VPC endpoints" (`VpcEndpointIds`, `@required`): the model refuses a
        // request that omits the member, and a request carrying an EMPTY list names no
        // endpoint to reject, which is the same missing parameter.
        if input.vpc_endpoint_ids.is_empty() {
            return Err(state::missing_parameter(
                "The request must contain at least one VpcEndpointId",
            ));
        }
        // The model publishes no bound on the list either, and every id costs a store lookup
        // and may add an `Unsuccessful` item to the answer, so the number of ids one request
        // may name is capped here — the same ceiling the rest of this crate puts on a
        // caller-chosen id list — before any per-id work is done.
        if input.vpc_endpoint_ids.len() > state::MAX_RESOURCE_IDS {
            return Err(state::invalid_parameter_value(format!(
                "VpcEndpointIds carries {supplied} ids, above the maximum of {maximum}",
                supplied = input.vpc_endpoint_ids.len(),
                maximum = state::MAX_RESOURCE_IDS,
            )));
        }

        // The service id's own form next: a value that is not a VPC endpoint service id at
        // all is refused as malformed, so "not an id of this kind" never reads as "no such
        // service" and is never answered by the DryRun arm below either.
        let service_id = input.service_id.as_str();
        state::require_well_formed_id(
            state::VPC_ENDPOINT_SERVICE_ID_PREFIX,
            service_id,
            state::INVALID_VPC_ENDPOINT_SERVICE_ID_MALFORMED,
        )?;

        let state_handle = state::require_service_state(&*self.engine)?;
        let mut store = state_handle.lock();
        // A connection whose own move has fallen due is already `available`, so whether each
        // rejection is admissible is asked of the state the connection is ACTUALLY in.
        store.materialize_due_transitions();

        // "Rejects VPC endpoint connection requests to YOUR VPC endpoint service": the
        // service the request names must be one of the account's own, so a `ServiceId` naming
        // none is refused outright — the whole call is about that one service, so this is not
        // a per-endpoint failure that belongs in `Unsuccessful`. Answered AHEAD of the DryRun
        // arm below, exactly as the acceptance beside it answers it.
        if !store.vpc_endpoint_services.contains_key(service_id) {
            return Err(state::invalid_vpc_endpoint_service_id_not_found(service_id));
        }

        // "Checks whether you have the required permissions for the action, WITHOUT ACTUALLY
        // MAKING THE REQUEST, and provides an error response. If you have the required
        // permissions, the error response is DryRunOperation. Otherwise, it is
        // UnauthorizedOperation" (`DryRun`): the flag asks about PERMISSION, not about the
        // endpoints named, so it is answered once the service the call is scoped to has been
        // resolved and before any connection of it is judged or moved; every caller of this
        // emulator is permitted.
        if input.dry_run.unwrap_or(false) {
            return Err(state::dry_run_operation());
        }

        // Each endpoint is judged on its own and reported in `Unsuccessful` when it cannot be
        // rejected — "information about the endpoints that were not rejected" — so one bad id
        // does not refuse the endpoints beside it. The reason carried is the code this
        // service answers that same cause with elsewhere, so a client reads one code per
        // cause whether it comes back as an error or as an unsuccessful item.
        let mut unsuccessful: Vec<UnsuccessfulItem> = Vec::new();
        let mut rejected: Vec<String> = Vec::new();
        for endpoint_id in &input.vpc_endpoint_ids {
            let refusal = if !state::vpc_endpoint_id_is_well_formed(endpoint_id) {
                Some((
                    state::INVALID_VPC_ENDPOINT_ID_MALFORMED,
                    state::invalid_id_message(endpoint_id),
                ))
            } else {
                match store.vpc_endpoint_connections.get(endpoint_id) {
                    // A connection to ANOTHER service is as absent from this service's
                    // connections as one that does not exist at all.
                    None => Some((
                        state::INVALID_VPC_ENDPOINT_ID_NOT_FOUND,
                        format!(
                            "The VPC endpoint ID '{endpoint_id}' does not name a connection to \
                             the service '{service_id}'"
                        ),
                    )),
                    Some(connection) if connection.service_id.as_deref() != Some(service_id) => {
                        Some((
                            state::INVALID_VPC_ENDPOINT_ID_NOT_FOUND,
                            format!(
                                "The VPC endpoint ID '{endpoint_id}' does not name a connection \
                                 to the service '{service_id}'"
                            ),
                        ))
                    }
                    // Only a request the owner has not answered yet can be refused: a
                    // connection already in service was accepted, and one already rejected
                    // has been answered.
                    Some(connection)
                        if connection.vpc_endpoint_state.as_deref()
                            != Some(state::VPC_ENDPOINT_STATE_PENDING_ACCEPTANCE) =>
                    {
                        Some((
                            state::INCORRECT_STATE,
                            format!(
                                "The VPC endpoint '{endpoint_id}' is in state '{current}'; only \
                                 a connection in state '{pending_acceptance}' can be rejected",
                                current = connection
                                    .vpc_endpoint_state
                                    .as_deref()
                                    .unwrap_or_default(),
                                pending_acceptance = state::VPC_ENDPOINT_STATE_PENDING_ACCEPTANCE,
                            ),
                        ))
                    }
                    Some(_) => None,
                }
            };
            match refusal {
                Some((code, message)) => unsuccessful.push(UnsuccessfulItem {
                    resource_id: Some(endpoint_id.clone()),
                    error: Some(UnsuccessfulItemError {
                        code: Some(code.to_string()),
                        message: Some(message),
                    }),
                }),
                None => rejected.push(endpoint_id.clone()),
            }
        }

        // Every refused connection, and the endpoint it is of, reach the TERMINAL `rejected`
        // at once — through the one writer of a rejection, so the state the consumer reads
        // off its endpoint and the state the owner reads off the connection cannot drift
        // apart. Nothing is owed on either afterwards: the refusal is the owner's answer
        // rather than a span of the clock.
        for endpoint_id in rejected {
            store.reject_vpc_endpoint_connection(&endpoint_id);
        }

        Ok(RejectVpcEndpointConnectionsOutput {
            unsuccessful: Some(unsuccessful),
        })
    }
}
