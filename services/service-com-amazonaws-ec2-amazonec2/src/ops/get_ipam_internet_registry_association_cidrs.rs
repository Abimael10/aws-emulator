/// Is an address range in the `ByoipCidrState` `cidr_state` one the internet registry still
/// records as the account's?
///
/// Bringing an address range to AWS is what has its registration at the registry CHECKED:
/// "before you begin, you must ensure that the address range is registered to you and that you
/// created an RPKI ROA to authorize Amazon ASNs to advertise the range" (`ProvisionByoipCidr`),
/// and AWS checks that authorization before the range leaves
/// [`crate::state::BYOIP_CIDR_STATE_PENDING_PROVISION`]. So the states that count are the ones
/// where that check has passed and the account has not finished giving the range back: a range
/// that finished provisioning ([`crate::state::BYOIP_CIDR_STATE_PROVISIONED`], or
/// [`crate::state::BYOIP_CIDR_STATE_PROVISIONED_NOT_PUBLICLY_ADVERTISABLE`] when the account
/// asked for it not to be advertised), one being or already advertised
/// ([`crate::state::BYOIP_CIDR_STATE_PENDING_ADVERTISING`],
/// [`crate::state::BYOIP_CIDR_STATE_ADVERTISED`]) or being withdrawn from advertisement
/// ([`crate::state::BYOIP_CIDR_STATE_PENDING_WITHDRAWAL`]), one whose release the account has
/// asked for but AWS has not finished ([`crate::state::BYOIP_CIDR_STATE_PENDING_DEPROVISION`]),
/// and one whose release did not complete, so the range is still the account's
/// ([`crate::state::BYOIP_CIDR_STATE_FAILED_DEPROVISION`]). Left out are the states where the
/// registration was never confirmed ([`crate::state::BYOIP_CIDR_STATE_PENDING_PROVISION`],
/// which is still being checked, and [`crate::state::BYOIP_CIDR_STATE_FAILED_PROVISION`], where
/// the check did not pass) and the one where the range has already been given back
/// (`deprovisioned`). Every word compared here is a member of the model's own `ByoipCidrState`
/// catalog (`crate::ops::types::BYOIP_CIDR_STATE_VALUES`).
fn cidr_is_held_at_the_internet_registry(cidr_state: &str) -> bool {
    matches!(
        cidr_state,
        state::BYOIP_CIDR_STATE_PROVISIONED
            | state::BYOIP_CIDR_STATE_PROVISIONED_NOT_PUBLICLY_ADVERTISABLE
            | state::BYOIP_CIDR_STATE_PENDING_ADVERTISING
            | state::BYOIP_CIDR_STATE_ADVERTISED
            | state::BYOIP_CIDR_STATE_PENDING_WITHDRAWAL
            | state::BYOIP_CIDR_STATE_PENDING_DEPROVISION
            | state::BYOIP_CIDR_STATE_FAILED_DEPROVISION
    )
}

