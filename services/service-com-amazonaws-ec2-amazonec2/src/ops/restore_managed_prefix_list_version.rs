    const NAME: &'static str = "RestoreManagedPrefixListVersion";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::RESTORE_MANAGED_PREFIX_LIST_VERSION_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::RESTORE_MANAGED_PREFIX_LIST_VERSION_OUTPUT_SCHEMA;
