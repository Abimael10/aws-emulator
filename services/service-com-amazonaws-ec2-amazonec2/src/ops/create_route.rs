/// The target `member` names, resolved against the store.
///
/// "Each route in a route table specifies a destination and a target" (Amazon VPC User
/// Guide, "Route tables"), and a target is a resource: one this account does not hold is
/// refused with that resource's own `Invalid<Kind>.NotFound`, so no route is ever stored
/// pointing at nothing. A GATEWAY target carries one rule more — it has to be attached to
/// the VPC the route table routes for, a gateway of another VPC being unreachable from this
/// one.
///
/// `member` is one of the member names the handler collected, and `value` the id it carried;
/// `route_table_id` and `vpc_id` are the table the route goes in and the VPC it routes for.
///
/// Each member resolves against the ONE resource kind it documents, and against no other: a
/// value that names a resource of a different kind names nothing this member could have meant,
/// so it is refused with that member's own refusal rather than resolved through a neighbouring
/// member's store. That is what lets a caller tell the two forms of a target apart — the same
/// VPC endpoint id is a route's target under `vpcEndpointId` and no gateway at all under
/// `gatewayId`.
///
/// Shared with [`crate::ops::replace_route`], which resolves a route's new target by exactly
/// this rule: a replacement points the route at a resource this account holds, so the two
/// operations cannot disagree about which targets are reachable from a table. Generic over the
/// error channel for that reason — every refusal it answers is one of this service's own codes,
/// which each operation's channel carries ([`crate::scaffolded::Scaffolded`]).
pub(crate) fn resolve_target<E>(
    store: &crate::state::ComAmazonawsEc2Amazonec2State,
    member: &str,
    value: &str,
    route_table_id: &str,
    vpc_id: &str,
) -> Result<crate::state::RouteTarget, crate::scaffolded::Scaffolded<E>> {
    use crate::state::{self, RouteTarget};
    match member {
        "gatewayId" => {
            // "Every route table contains a local route for communication within the VPC"
            // and that route is the table's own: `local` is not a gateway a caller can
            // point a route at.
            if value == state::LOCAL_ROUTE_GATEWAY_ID {
                return Err(state::invalid_parameter_value(format!(
                    "Value ({value}) for parameter gatewayId is invalid. \
                     The local route of a route table cannot be created."
                )));
            }
            // An internet gateway or a virtual private gateway: the two kinds this member
            // documents, told apart by the id form each kind carries. No OTHER resource is
            // reachable through this member — "the ID of an internet gateway or virtual
            // private gateway attached to your VPC" (`CreateRouteRequest$GatewayId`) — so an
            // id of any other kind, a VPC endpoint's among them, names no gateway of this
            // account and is refused as such.
            let attached_vpc = if store.internet_gateways.contains_key(value) {
                store.internet_gateway_attached_vpc(value)
            } else if let Some(vpn_gateway) = store.vpn_gateways.get(value) {
                vpn_gateway
                    .view
                    .vpc_attachments
                    .iter()
                    .flatten()
                    .find_map(|attachment| attachment.vpc_id.clone())
            } else {
                return Err(state::invalid_gateway_id_not_found(value));
            };
            // A gateway attached to another VPC — or to none — cannot carry this VPC's
            // traffic, which is the refusal EC2 answers naming both sides.
            if attached_vpc.as_deref() != Some(vpc_id) {
                return Err(belongs_to_another_network(
                    route_table_id,
                    &network_gateway_noun(value),
                ));
            }
            Ok(RouteTarget::Gateway(value.to_string()))
        }
        // "The ID of a VPC endpoint. Supported for Gateway Load Balancer endpoints only"
        // (`CreateRouteRequest$VpcEndpointId`): the endpoint target has its own member, which
        // is where an endpoint is named. That the stored route REPORTS it in `Route$GatewayId`
        // is about the modelled `Route` having no member of its own for an endpoint, and says
        // nothing about which member a request may name it in.
        "vpcEndpointId" => resolve_vpc_endpoint_target(store, value, route_table_id, vpc_id),
        "natGatewayId" => {
            // A target the account does not hold is reported by the member that carried it,
            // in the route family's own code for an unresolvable NAT gateway target
            // ([`state::invalid_nat_gateway_route_target_not_found`]) rather than in the NAT
            // gateway family's `NatGatewayNotFound`, which its own operations answer.
            if !store.nat_gateways.contains_key(value) {
                return Err(state::invalid_nat_gateway_route_target_not_found(value));
            }
            Ok(RouteTarget::NatGateway(value.to_string()))
        }
        "instanceId" => {
            if !store.instances.contains_key(value) {
                return Err(crate::scaffolded::Scaffolded::invalid_instance_id_not_found(
                    value,
                ));
            }
            Ok(RouteTarget::Instance(value.to_string()))
        }
        "networkInterfaceId" => {
            if !store.network_interfaces.contains_key(value) {
                return Err(state::invalid_network_interface_id_not_found(value));
            }
            Ok(RouteTarget::NetworkInterface(value.to_string()))
        }
        "transitGatewayId" => {
            if !store.holds_transit_gateway_in_service(value) {
                // A target the account does not hold is reported by the member that
                // carried it, like the route's other targets.
                return Err(state::transit_gateway_route_target_not_found(value));
            }
            // A transit gateway carries a VPC's traffic only through an ATTACHMENT to that
            // VPC, so a gateway with none in the route table's own VPC is as unreachable from
            // this table as a gateway attached to another network: the route would forward
            // nothing, which is the refusal EC2 answers naming both sides.
            if !store.transit_gateway_is_attached_to_vpc(value, vpc_id) {
                // A transit gateway is reached from a VPC through its ATTACHMENT to that VPC,
                // so a route table of a VPC the gateway has no attachment in resolves no
                // transit gateway at all: the member answers its own not-found, the same way
                // it answers an id the account holds no gateway for.
                return Err(state::transit_gateway_route_target_not_found(value));
            }
            Ok(RouteTarget::TransitGateway(value.to_string()))
        }
        "localGatewayId" => {
            if !store.local_gateways.contains_key(value) {
                return Err(state::invalid_local_gateway_id_not_found(value));
            }
            Ok(RouteTarget::LocalGateway(value.to_string()))
        }
        "carrierGatewayId" => {
            if !store.carrier_gateways.contains_key(value) {
                return Err(state::invalid_carrier_gateway_id_not_found(value));
            }
            Ok(RouteTarget::CarrierGateway(value.to_string()))
        }
        "vpcPeeringConnectionId" => {
            if !store.vpc_peering_connections.contains_key(value) {
                return Err(state::invalid_vpc_peering_connection_id_not_found(value));
            }
            Ok(RouteTarget::VpcPeeringConnection(value.to_string()))
        }
        "egressOnlyInternetGatewayId" => {
            // "[IPv6 traffic only] The ID of an egress-only internet gateway"
            // (`CreateRouteRequest$EgressOnlyInternetGatewayId`): a gateway of this kind is
            // attached to its VPC by its own create, so the rule a gateway target carries
            // holds for it too — one attached to another VPC cannot carry this VPC's traffic.
            let Some(attached_vpc) = store.egress_only_internet_gateway_attached_vpc(value) else {
                return Err(state::invalid_egress_only_internet_gateway_id_not_found(
                    value,
                ));
            };
            if attached_vpc != vpc_id {
                return Err(belongs_to_another_network(
                    route_table_id,
                    &network_gateway_noun(value),
                ));
            }
            Ok(RouteTarget::EgressOnlyInternetGateway(value.to_string()))
        }
        // Unreachable: each handler collects these member names itself and answers the ones
        // it holds no store for before reaching here.
        _ => Err(crate::scaffolded::Scaffolded::not_implemented(&format!(
            "a route with a {member} target"
        ))),
    }
}

/// Whether `value` is under the VPC ENDPOINT's own resource id form: that prefix, a `-`, and a
/// non-empty suffix of lowercase hexadecimal digits.
///
/// The reading [`crate::state::prefixed_id_is_well_formed`] makes, minus ONE clause: that
/// function also holds the suffix to the digit counts EC2 ISSUES, which is the reading the
/// operations resolving a `VpcEndpointId` as the SUBJECT of the call were recorded answering
/// `InvalidVpcEndpointId.Malformed` for ([`crate::state::vpc_endpoint_id_is_well_formed`], used
/// by the describes, the delete, the modify and the connection operations). The ROUTE
/// operations' own recorded refusals answer a value under this prefix whose suffix is not a
/// length EC2 issues with the endpoint's NOT-FOUND sentence instead — replaying a route-target
/// step under the stricter reading makes that recorded step diverge — so which reading an
/// operation applies is a fact of that operation's validator, read off its own recorded
/// refusal. That is the same per-operation split this crate already documents for an AMI id,
/// where the launch path decodes the id EC2 could have issued and the describes keep the wider
/// reading ([`crate::state::issued_image_id_is_well_formed`]).
///
/// The HEX suffix is what separates an endpoint id from the ids of the other resources whose
/// own prefixes extend it — an endpoint service's and a connection's carry `svc-` or `conn-`
/// first ([`crate::state::vpc_endpoint_id_is_well_formed`]'s doc) — so a value of those
/// families is no endpoint id here either, exactly as it is none there.
fn carries_vpc_endpoint_prefix(value: &str) -> bool {
    value
        .strip_prefix(crate::state::VPC_ENDPOINT_ID_PREFIX)
        .and_then(|rest| rest.strip_prefix('-'))
        .is_some_and(|suffix| {
            !suffix.is_empty()
                && suffix
                    .bytes()
                    .all(|byte| matches!(byte, b'0'..=b'9' | b'a'..=b'f'))
        })
}

/// The VPC ENDPOINT the `vpcEndpointId` target member names, resolved against the endpoints
/// this account holds.
///
/// "The ID of a VPC endpoint. Supported for Gateway Load Balancer endpoints only"
/// (`CreateRouteRequest$VpcEndpointId`): the ONE endpoint type a route may point at is the
/// Gateway Load Balancer endpoint, so this resolves an endpoint target against that type
/// alone. An endpoint of any other type is no more a target than an id nothing minted — a
/// gateway endpoint is reached through the route EC2 maintains in the tables the endpoint
/// names rather than through one a caller writes — so both answer the one refusal this service
/// words an unresolvable endpoint target with: the ENDPOINT's own not-found code and sentence
/// ([`crate::state::invalid_vpc_endpoint_route_target_not_found`]), carrying the id the REQUEST
/// named. Which is also why a resolved endpoint always holds the network interface the
/// cross-network refusal names ([`endpoint_target_noun`]).
///
/// Shared by [`crate::ops::replace_route`] through [`resolve_target`], so pointing a route at
/// an endpoint and re-pointing one answer the same way.
fn resolve_vpc_endpoint_target<E>(
    store: &crate::state::ComAmazonawsEc2Amazonec2State,
    value: &str,
    route_table_id: &str,
    vpc_id: &str,
) -> Result<crate::state::RouteTarget, crate::scaffolded::Scaffolded<E>> {
    use crate::state::{self, RouteTarget};
    // A value that is not under the VPC endpoint's own resource prefix is no endpoint id at
    // all, so it is refused for its FORM before the account is asked whether it holds such an
    // endpoint: under the endpoint id's own `Malformed` code, in the sentence the route
    // operations' recorded refusal carries
    // ([`state::invalid_vpc_endpoint_route_target_malformed`]). That keeps "this is not an
    // endpoint id" apart from "this account holds no such endpoint", which is the difference a
    // caller that mistyped a target has to be able to read. Why the suffix is read the way
    // [`carries_vpc_endpoint_prefix`] reads it is that function's own doc.
    if !carries_vpc_endpoint_prefix(value) {
        return Err(state::invalid_vpc_endpoint_route_target_malformed(value));
    }
    let endpoint = store.vpc_endpoints.get(value).filter(|endpoint| {
        endpoint.vpc_endpoint_type.as_deref() == Some(state::VPC_ENDPOINT_TYPE_GATEWAY_LOAD_BALANCER)
    });
    let Some(endpoint) = endpoint else {
        return Err(state::invalid_vpc_endpoint_route_target_not_found(value));
    };
    if endpoint.vpc_id.as_deref() != Some(vpc_id) {
        return Err(belongs_to_another_network(
            route_table_id,
            &endpoint_target_noun(endpoint, value),
        ));
    }
    // An endpoint target is reported in `Route$GatewayId`, the modelled `Route` carrying no
    // member of its own for a VPC endpoint.
    Ok(RouteTarget::Gateway(value.to_string()))
}

/// Refuse a route whose target is not reachable from the VPC the route table routes for: HTTP
/// 400 `InvalidParameterValue`, naming the table and the target.
///
/// A route carries traffic of ONE VPC, so a target that sits in another one — or in none — can
/// carry none of it, which is the refusal EC2 answers naming both sides. The ONE wording of
/// that refusal, so the target members of this operation (and of
/// [`crate::ops::replace_route`], which resolves a target through the same function) cannot
/// word one rule two ways; `target` is the target as the service names it
/// ([`network_gateway_noun`], [`endpoint_target_noun`]).
fn belongs_to_another_network<E>(
    route_table_id: &str,
    target: &str,
) -> crate::scaffolded::Scaffolded<E> {
    crate::state::invalid_parameter_value(format!(
        "route table {route_table_id} and {target} belong to different networks"
    ))
}

/// A GATEWAY target, as the refusal above names it: the gateway noun and the id the request
/// carried.
///
/// Every target that is a GATEWAY of a network is named this way, whichever kind of gateway it
/// is — an internet gateway, a virtual private gateway, an egress-only one, and a transit
/// gateway the route table's VPC has no attachment to — so one rule about a target that sits in
/// another network reads one way whatever the caller pointed the route at.
fn network_gateway_noun(gateway_id: &str) -> String {
    format!("network gateway {gateway_id}")
}

/// A VPC ENDPOINT target, as the refusal above names it: the endpoint's own network INTERFACE,
/// under the interface's id with `interface-` for its prefix.
///
/// What a route to a VPC endpoint reaches is the endpoint network interface the endpoint holds
/// in its subnet ("an endpoint network interface is created … in an Availability Zone",
/// `CreateVpcEndpointRequest$SubnetIds`), so that interface is what the cross-network refusal
/// names and what decides the network the target sits in. The endpoint's first interface is the
/// one named: a Gateway Load Balancer endpoint — the one type a route may name
/// (`CreateRouteRequest$VpcEndpointId`) — is created in a single subnet and so holds a single
/// interface.
///
/// An endpoint that holds no interface at all — one placed in no subnet — has none to name, so
/// it falls back to the gateway noun under the endpoint's own id.
fn endpoint_target_noun(endpoint: &VpcEndpoint, endpoint_id: &str) -> String {
    let Some(interface_id) = endpoint
        .network_interface_ids
        .iter()
        .flatten()
        .next()
        .map(String::as_str)
    else {
        return network_gateway_noun(endpoint_id);
    };
    // An EC2 resource id is `<prefix>-<digits>`; the interface is named by those digits under
    // the interface prefix, so the id's own prefix is replaced rather than carried.
    let digits = interface_id
        .split_once('-')
        .map_or(interface_id, |(_, digits)| digits);
    format!("interface interface-{digits}")
}
