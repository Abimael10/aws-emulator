/// Whether `event` falls in the window `[from, until]`, in milliseconds since the epoch.
///
/// `startTime` is "the start time for filtering events" and `endTime` "the end time", so
/// both bounds are inclusive: an event recorded exactly at a bound is inside the window
/// the caller named.
fn within(event: &crate::state::ServiceEventRecord, from: i64, until: i64) -> bool {
    let at = crate::state::to_date_time(event.timestamp)
        .to_millis()
        .unwrap_or_default();
    (from..=until).contains(&at)
}

/// Whether `event` is one of the types the request asked for.
///
/// `eventTypes` is "the type of events to include in the results", so a request that names
/// some reports only those and one that names none reports every type. A list that arrives
/// EMPTY names no type to narrow by and so constrains nothing, the same as an absent one.
/// The values are modelled `ServiceEventType` members, so the boundary has already refused
/// anything outside them by the time this runs.
fn wanted_type(event: &crate::state::ServiceEventRecord, wanted: Option<&[String]>) -> bool {
    match wanted {
        None => true,
        Some([]) => true,
        Some(types) => types.iter().any(|kind| kind == &event.event_type),
    }
}

