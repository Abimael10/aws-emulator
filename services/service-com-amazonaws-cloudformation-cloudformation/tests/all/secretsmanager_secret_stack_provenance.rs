//! What a stack's provisioning records ON the AWS Secrets Manager secret it declares, read
//! back through that service's own API, with Secrets Manager mounted beside CloudFormation on
//! one engine.
//!
//! RULE: a resource CloudFormation provisions carries, in the service that owns it, the
//! stack-level `Tags` the stack operation supplied PLUS the three tags CloudFormation records
//! itself — `aws:cloudformation:stack-name` (the stack's name),
//! `aws:cloudformation:stack-id` (its id) and `aws:cloudformation:logical-id` (the resource's
//! logical id in the template) — and a key the resource's own declaration states keeps that
//! declaration's value, except those three, which are CloudFormation's to set whatever a
//! declaration spells. For a secret that set is what `DescribeSecret` answers in `Tags`.
//!
//! Those three tags are the secret-to-stack reverse lookup: a client holding only a secret id
//! uses them to discover the stack that owns it, to tell a stack-managed secret from a
//! hand-made one, and to attribute cost or scope policy over secrets by stack. A secret
//! provisioned without them answers `DescribeSecret` with no stack attribution at all.
//!
//! The rows differ along what the rule generalises over: where the secret's NAME comes from
//! (spelled by the declaration, or generated by CloudFormation for a declaration that states
//! none), the FORM the value is stated in (`SecretString` verbatim, and a
//! `GenerateSecretString` document), and what the declaration's own `Tags` ask for (none, one
//! of its own, a key the stack also states, and a key that is CloudFormation's own). Every
//! secret is a resource of ONE stack, so the two stack-level tags are the same across the rows
//! while `aws:cloudformation:logical-id` differs per resource. Every expected value is
//! computed from what the row declares plus the stack id `DescribeStacks` reports — never read
//! back out of the answer being checked.

use std::collections::BTreeMap;

use serde_json::{json, Value};
use smithy_server_runtime::MultiServiceRouter;

use crate::stack_lifecycle::{create_stack, member, output_value, router, xml_text};
use crate::stack_owned_secret_teardown::{poll_to_terminal, secretsmanager};
use crate::stack_tag_propagation::expected_tags;

/// The stack every row is deployed in: one provisioning is what the rule is about, so the
/// rows are resources of ONE stack rather than a stack each.
const STACK: &str = "secret-stack-provenance";

/// The stack-level `Tags` the `CreateStack` call supplies, which every resource of the stack
/// must carry beside CloudFormation's own three.
const STACK_TAGS: &[(&str, &str)] = &[("team", "platform"), ("owner", "the-stack")];

/// One declared secret of the stack.
#[derive(Debug, Clone, Copy)]
struct Row {
    case: &'static str,
    /// The logical id the template declares it under, which also names its output.
    logical_id: &'static str,
    /// The `Name` the declaration states, or `""` for the row that states none and so is
    /// created under the name CloudFormation generates.
    declared_name: &'static str,
    /// The declaration's value properties, as the JSON text the template carries.
    value: &'static str,
    /// The `Tags` the declaration asks for.
    declared_tags: &'static [(&'static str, &'static str)],
    /// The declared tags that must read back under their declared value: every one whose key
    /// is the declaration's own to set, which is every one outside the three CloudFormation
    /// records itself.
    kept_tags: &'static [(&'static str, &'static str)],
}

const ROWS: &[Row] = &[
    Row {
        // The recorded shape: a named secret holding a credential document stated verbatim,
        // declaring no tags of its own, so the stack's two tags and CloudFormation's three
        // are the whole set.
        case: "a named secret declaring no tags of its own",
        logical_id: "Named",
        declared_name: "secret-stack-provenance-named",
        value: r#"{"SecretString": "{\"username\":\"probeadmin\",\"password\":\"declared\"}"}"#,
        declared_tags: &[],
        kept_tags: &[],
    },
    Row {
        // No `Name` at all, and the value GENERATED into a declared document: the rule holds
        // whichever way the secret is identified and the value stated.
        case: "a generated password in a declared document, under a generated name",
        logical_id: "Generated",
        declared_name: "",
        value: r#"{"GenerateSecretString": {
            "SecretStringTemplate": "{\"username\":\"probeadmin\"}",
            "GenerateStringKey": "password",
            "PasswordLength": 24
        }}"#,
        declared_tags: &[("workload", "generated")],
        kept_tags: &[("workload", "generated")],
    },
    Row {
        // A key the stack ALSO states: the declaration is the more specific statement about
        // this one resource, so its value is the one the secret carries.
        case: "a declared tag whose key the stack states too",
        logical_id: "Collides",
        declared_name: "secret-stack-provenance/collides",
        value: r#"{"SecretString": "a-plain-text-value"}"#,
        declared_tags: &[("owner", "the-resource"), ("retention-days", "7")],
        kept_tags: &[("owner", "the-resource"), ("retention-days", "7")],
    },
    Row {
        // A declaration that spells one of CloudFormation's OWN three keys does not displace
        // it: those three are CloudFormation's to set, wherever they are written.
        case: "a declaration that spells aws:cloudformation:logical-id itself",
        logical_id: "Claimed",
        declared_name: "secret-stack-provenance.claimed+v2",
        value: r#"{"SecretString": "another-plain-text-value"}"#,
        declared_tags: &[
            ("aws:cloudformation:logical-id", "NotThisOne"),
            ("workload", "claimed"),
        ],
        // Only the key that is CloudFormation's own is overridden; the ordinary declared tag
        // stands.
        kept_tags: &[("workload", "claimed")],
    },
];

/// The `Properties` a row declares.
fn properties(row: &Row) -> Value {
    let mut properties = match serde_json::from_str(row.value) {
        Ok(Value::Object(members)) => members,
        other => panic!("case {:?}: a row's value properties are an object, got {other:?}", row.case),
    };
    if !row.declared_name.is_empty() {
        properties.insert("Name".to_string(), json!(row.declared_name));
    }
    if !row.declared_tags.is_empty() {
        properties.insert(
            "Tags".to_string(),
            Value::Array(
                row.declared_tags
                    .iter()
                    .map(|(key, value)| json!({"Key": key, "Value": value}))
                    .collect(),
            ),
        );
    }
    Value::Object(properties)
}

/// The template declaring every row, and publishing each secret's ARN as an output — "Ref
/// returns the ARN of the secret", which is the handle every Secrets Manager call takes.
fn template() -> String {
    let mut resources = serde_json::Map::new();
    let mut outputs = serde_json::Map::new();
    for row in ROWS {
        resources.insert(
            row.logical_id.to_string(),
            json!({
                "Type": "AWS::SecretsManager::Secret",
                "Properties": properties(row),
            }),
        );
        outputs.insert(arn_output(row), json!({"Value": {"Ref": row.logical_id}}));
    }
    json!({"Resources": resources, "Outputs": outputs}).to_string()
}

/// The output key a row's ARN is published under.
fn arn_output(row: &Row) -> String {
    format!("{}Arn", row.logical_id)
}

/// The `Tags.member.N.Key`/`Value` request members the stack-level tag list is.
fn stack_tag_members() -> Vec<(String, String)> {
    let mut members = Vec::new();
    for (index, (key, value)) in STACK_TAGS.iter().enumerate() {
        let position = index + 1;
        members.push(member(&format!("Tags.member.{position}.Key"), key));
        members.push(member(&format!("Tags.member.{position}.Value"), value));
    }
    members
}

/// What `DescribeSecret` answers for `secret_id`: the status, and its `Tags` as the map a
/// client reads them as, beside the whole answer.
async fn described(
    router: &MultiServiceRouter,
    secret_id: &str,
) -> (u16, Value, BTreeMap<String, String>) {
    let (status_code, answered) =
        secretsmanager(router, "DescribeSecret", &json!({"SecretId": secret_id})).await;
    let held = answered
        .get("Tags")
        .and_then(Value::as_array)
        .map(|tags| {
            tags.iter()
                .filter_map(|tag| {
                    let key = tag.get("Key").and_then(Value::as_str)?;
                    Some((
                        key.to_string(),
                        tag.get("Value")
                            .and_then(Value::as_str)
                            .unwrap_or_default()
                            .to_string(),
                    ))
                })
                .collect()
        })
        .unwrap_or_default();
    (status_code, answered, held)
}

#[tokio::test]
async fn a_stacks_secret_carries_the_stacks_tags_and_cloudformations_own_records() {
    let router = router();
    let (status_code, body) =
        create_stack(&router, STACK, &template(), &stack_tag_members()).await;
    assert_eq!(
        status_code, 200,
        "CreateStack must answer 200, got {status_code} {body}"
    );
    let stack_described = poll_to_terminal(&router, "the stack", STACK).await;
    assert_eq!(
        xml_text(&stack_described, "StackStatus").as_deref(),
        Some("CREATE_COMPLETE"),
        "expected the create to complete, got {stack_described}"
    );
    let stack_id = xml_text(&stack_described, "StackId").unwrap_or_default();
    assert!(
        !stack_id.is_empty(),
        "expected the stack to report its id, got {stack_described}"
    );

    for row in ROWS {
        let case = row.case;
        let arn = output_value(&stack_described, &arn_output(row)).unwrap_or_else(|| {
            panic!("case {case:?}: the stack published no ARN in {stack_described}")
        });

        let (status_code, answered, held) = described(&router, &arn).await;
        assert_eq!(
            status_code, 200,
            "case {case:?}: expected Secrets Manager to hold the secret the stack created, got \
             {status_code} {answered}"
        );
        let name = answered
            .get("Name")
            .and_then(Value::as_str)
            .unwrap_or_else(|| panic!("case {case:?}: no Name in {answered}"));
        if row.declared_name.is_empty() {
            assert!(
                name.starts_with(STACK) && name.len() > STACK.len(),
                "case {case:?}: expected a generated name built on the stack's, got {name:?}"
            );
        } else {
            assert_eq!(
                name, row.declared_name,
                "case {case:?}: expected the secret to be created under the declared name, got \
                 {name:?}"
            );
        }

        let expected = expected_tags(STACK_TAGS, row.kept_tags, STACK, &stack_id, row.logical_id);
        assert_eq!(
            held, expected,
            "case {case:?}: expected the stack's tags and CloudFormation's own three on \
             {arn:?}, got {held:?}"
        );

        // The same set is reported for the secret addressed by its NAME, which is the other
        // handle a `SecretId` takes: the tags are the secret's own state, not something one
        // form of the id computes.
        let (status_code, answered, by_name) = described(&router, name).await;
        assert_eq!(
            status_code, 200,
            "case {case:?}: expected the secret to answer by name too, got {status_code} \
             {answered}"
        );
        assert_eq!(
            by_name, expected,
            "case {case:?}: expected the same tag set whichever handle names the secret, got \
             {by_name:?}"
        );
    }
}
