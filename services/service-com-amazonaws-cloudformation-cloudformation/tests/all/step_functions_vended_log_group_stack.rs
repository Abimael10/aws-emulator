const STACK: &str = "sfn-vended-log-stack";

/// The service principal a state machine's execution role is trusted by
/// (`states.amazonaws.com`), which is what lets Step Functions act as that role to set the log
/// delivery up.
const SFN_SERVICE_PRINCIPAL: &str = "states.amazonaws.com";

