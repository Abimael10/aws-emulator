//! The canonical Step Functions LOGGING stack — a vended log group, the execution role that
//! delivers to it, and the state machine whose `LoggingConfiguration` names it — deploys end
//! to end, with Amazon CloudWatch Logs, AWS IAM and AWS Step Functions mounted beside
//! CloudFormation on one engine.
//!
//! RULE under test: **a stack whose declared state machine carries a `LoggingConfiguration`
//! whose destination is a log group the same stack declares, and whose `RoleArn` is a role the
//! same stack declares that is trusted by the Step Functions service principal and allowed any
//! of the CloudWatch Logs delivery actions that service's logging guidance publishes for that
//! role, creates all three resources in the service that OWNS each and reaches
//! `CREATE_COMPLETE`** — a role that CAN deliver to the destination is never a reason to
//! refuse the create, and the handles the stack publishes are the ones those services really
//! hold. Run backwards, the same rule is the other half: a role allowed NONE of those actions
//! on the destination cannot deliver, so that create is refused, the resource records
//! `CREATE_FAILED` with the owning service's own sentence and the stack rolls back — which is
//! what keeps the completion above from being unconditional.
//!
//! Why it matters: this template is the shape every client deploys Step Functions logging
//! with. A stack that cannot create it reaches `ROLLBACK_COMPLETE`, so its outputs, its
//! resource ids and any drift check over that estate are all unreachable before a client's own
//! subject is even exercised.
//!
//! The rows differ along what the rule generalises over: the workflow TYPE (`STANDARD` and
//! `EXPRESS`), the log LEVEL (`ALL`, `ERROR`, `FATAL` — every value of the enum that logs) and
//! whether execution data is included, where the names come from (spelled by the template or
//! generated by CloudFormation), the group's retention, the FORM the role's grant takes (the
//! action list the recorded template carries, every action the guidance publishes, a single
//! action spelled as one string, and a grant scoped to the destination group rather than to
//! every resource) and how the trust document spells the service principal (one string, or a
//! list). Every expected value is computed from what the row declares, never read back out of
//! the answer being checked.

