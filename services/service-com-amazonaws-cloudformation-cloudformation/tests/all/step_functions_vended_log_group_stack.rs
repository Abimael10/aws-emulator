/// The error code of a Step Functions refusal, as that service's awsJson envelope carries it
/// (`__type`, or the `code` member some refusals spell).
fn error_code(refused: &Value) -> String {
    for member in ["__type", "code", "Code"] {
        if let Some(value) = refused.get(member).and_then(Value::as_str) {
            return value.rsplit('#').next().unwrap_or(value).to_string();
        }
    }
    String::new()
}

/// The other half of the rule: a role allowed NONE of the delivery actions on the destination
/// cannot deliver, so the machine's create is refused, the resource says why, and the stack
/// rolls back — which is what keeps the completion above from being unconditional.
#[tokio::test]
async fn a_role_that_cannot_deliver_to_the_destination_fails_the_stack() {
    for row in DENIED_ROWS {
        let case = row.case;
        let router = router();
        let (code, created) = create_stack(
            &router,
            row.stack,
            &denied_template(row),
            &acknowledging_iam(&[]),
        )
        .await;
        assert_eq!(
            code, 200,
            "case {case:?}: CreateStack must answer 200, got {code} {created}"
        );
        let described = settled_stack(&router, case, row.stack).await;
        assert_eq!(
            xml_text(&described, "StackStatus").as_deref(),
            Some(ROLLBACK_COMPLETE),
            "case {case:?}: expected the refused create to be rolled back, got {described}"
        );

        let reason =
            failed_resource_reason(case, &router, REGION, row.stack, "Machine", CREATE_FAILED)
                .await;
        assert!(
            reason.contains(LOG_DESTINATION_ACCESS_DENIED),
            "case {case:?}: expected the failed machine to report \
             {LOG_DESTINATION_ACCESS_DENIED:?}, got {reason:?}"
        );

        // Nothing was left behind in Step Functions under the name the declaration spelled.
        let machine_arn = expected_machine_arn(row.machine_name);
        let (code, refused) = sfn_json(
            &router,
            "DescribeStateMachine",
            &json!({"stateMachineArn": machine_arn}),
        )
        .await;
        assert_eq!(
            (code, error_code(&refused).as_str()),
            (400, STATE_MACHINE_DOES_NOT_EXIST),
            "case {case:?}: expected Step Functions to hold no machine at {machine_arn:?}, got \
             {code} {refused}"
        );
    }
}
