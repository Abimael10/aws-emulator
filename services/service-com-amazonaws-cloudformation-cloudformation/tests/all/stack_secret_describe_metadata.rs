//! What the OWNING service's own read reports of a secret a stack created, end to end over
//! the wire, with AWS Secrets Manager mounted beside CloudFormation on one engine.
//!
//! RULE: a resource CloudFormation provisions is an ordinary resource of the service that
//! owns it, so that service's own read answers it in full — for a secret, `DescribeSecret`
//! answers 200 with the ARN the service minted for it
//! (`arn:<partition>:secretsmanager:<region>:<account>:secret:<name>-<six characters the
//! service draws per secret>`, the ARN the stack publishes for `Ref`), the `Name` it was
//! created under, the `Description` the declaration stated, a `CreatedDate` and a
//! `LastChangedDate`, and its tags including the three records CloudFormation stamps on what
//! it creates.
//!
//! A stack that reported a secret created while the owning service holds nothing publishes an
//! ARN that resolves to nothing: every consumer of a template-provisioned secret starts with
//! `DescribeSecret`, so a refusal there makes the stack's secret unusable and hides the stack
//! attribution that routes a secret back to the stack that owns it.
//!
//! The rows differ along what the rule generalises over: where the secret's NAME comes from
//! (spelled by the declaration, or generated by CloudFormation for a declaration that states
//! none), the SHAPE of that name (flat, hierarchical, and one carrying the other characters a
//! secret's name admits), the FORM the value is stated in (`SecretString` verbatim, and a
//! password generated into a declared document) and whether the declaration states a
//! `Description` at all — a member Secrets Manager reports only when it has a value.
//!
//! Every expected value is computed from what the row declares plus the stack name and the
//! stack id `DescribeStacks` reports; nothing is read back out of the answer being checked.
//!
//! This suite holds the members the read reports BESIDE the tag set: the ARN's form, the
//! `Description` (and its absence), and the two dates. The tag set itself — the stack's own
//! tags, a declaration's own keys, and which of them CloudFormation's three records displace —
//! is [`crate::stack_tag_propagation`]'s rule, held of a secret by
//! [`crate::secretsmanager_secret_stack_provenance`]; the three records are asserted here only
//! as part of one whole report, so the two suites stay separate rules rather than one.

use serde_json::{json, Value};
use smithy_server_runtime::MultiServiceRouter;

use crate::stack_lifecycle::{create_stack, output_value, router, xml_text, ACCOUNT_ID, REGION};
use crate::stack_owned_secret_teardown::{poll_to_terminal, secretsmanager};
use crate::stack_tag_propagation::{LOGICAL_ID_TAG, STACK_ID_TAG, STACK_NAME_TAG};

/// The stack every row is deployed in: one provisioning is what the rule is about, so the
/// rows are resources of ONE stack rather than a stack each.
const STACK: &str = "secret-describe-metadata";

/// The service an ARN of this kind names, which is the Secrets Manager endpoint prefix its
/// model publishes (`com.amazonaws.secretsmanager#secretsmanager`).
const ARN_SERVICE: &str = "secretsmanager";

/// The resource type a secret's ARN names, as AWS publishes it:
/// `arn:<partition>:secretsmanager:<region>:<account>:secret:<name>-<suffix>`.
const ARN_RESOURCE_TYPE: &str = "secret";

/// How many characters Secrets Manager draws per secret to end its ARN with — six, as the
/// documented ARN form has it.
const ARN_SUFFIX_LEN: usize = 6;

/// One declared secret of the stack.
#[derive(Debug, Clone, Copy)]
struct Row {
    case: &'static str,
    /// The logical id the template declares it under, which also names its output and is the
    /// value of the logical-id record CloudFormation stamps.
    logical_id: &'static str,
    /// The `Name` the declaration states, or `""` for the row that states none and so is
    /// created under the name CloudFormation generates.
    declared_name: &'static str,
    /// The `Description` the declaration states, or `""` for a row that states none — which
    /// the read then omits, because "Secrets Manager only returns fields that have a value".
    declared_description: &'static str,
    /// The declaration's value properties, as the JSON text the template carries.
    value: &'static str,
}

const ROWS: &[Row] = &[
    Row {
        // The recorded shape: a named secret holding a credential document stated verbatim,
        // with a description of its own.
        case: "a named secret with a description, value stated verbatim",
        logical_id: "Named",
        declared_name: "secret-describe-metadata-named",
        declared_description: "the master credentials of the cluster",
        value: r#"{"SecretString": "{\"username\":\"probeadmin\",\"password\":\"declared\"}"}"#,
    },
    Row {
        // No `Name` at all, and the value GENERATED into a declared document: the rule holds
        // whichever way the secret is identified and the value stated.
        case: "a generated password in a declared document, under a generated name",
        logical_id: "Generated",
        declared_name: "",
        declared_description: "generated under the name CloudFormation computed",
        value: r#"{"GenerateSecretString": {
            "SecretStringTemplate": "{\"username\":\"probeadmin\"}",
            "GenerateStringKey": "password",
            "PasswordLength": 24
        }}"#,
    },
    Row {
        // A declaration that states NO description: the member has no value, so the read
        // leaves it out rather than reporting an empty one.
        case: "a hierarchical name and no description at all",
        logical_id: "Undescribed",
        declared_name: "describe-metadata/team/db-credentials",
        declared_description: "",
        value: r#"{"SecretString": "a-plain-text-value"}"#,
    },
    Row {
        // The other characters a secret's name admits ("/_+=.@-"), on a plain-text value.
        case: "a name of the other admitted characters, with a description",
        logical_id: "Dotted",
        declared_name: "describe-metadata.api_token+v2",
        declared_description: "the token the application reads at boot",
        value: r#"{"SecretString": "another-plain-text-value"}"#,
    },
];

/// The `Properties` a row declares.
fn properties(row: &Row) -> Value {
    let mut properties = match serde_json::from_str(row.value) {
        Ok(Value::Object(members)) => members,
        other => panic!(
            "case {:?}: a row's value properties are an object, got {other:?}",
            row.case
        ),
    };
    if !row.declared_name.is_empty() {
        properties.insert("Name".to_string(), json!(row.declared_name));
    }
    if !row.declared_description.is_empty() {
        properties.insert("Description".to_string(), json!(row.declared_description));
    }
    Value::Object(properties)
}

/// The template declaring every row, and publishing each secret's ARN as an output — "Ref
/// returns the ARN of the secret", which is the handle every Secrets Manager call takes.
fn template() -> String {
    let mut resources = serde_json::Map::new();
    let mut outputs = serde_json::Map::new();
    for row in ROWS {
        resources.insert(
            row.logical_id.to_string(),
            json!({
                "Type": "AWS::SecretsManager::Secret",
                "Properties": properties(row),
            }),
        );
        outputs.insert(arn_output(row), json!({"Value": {"Ref": row.logical_id}}));
    }
    json!({"Resources": resources, "Outputs": outputs}).to_string()
}

/// The output key a row's ARN is published under.
fn arn_output(row: &Row) -> String {
    format!("{}Arn", row.logical_id)
}

/// What `DescribeSecret` answers for `secret_id`.
async fn described(router: &MultiServiceRouter, secret_id: &str) -> (u16, Value) {
    secretsmanager(router, "DescribeSecret", &json!({"SecretId": secret_id})).await
}

/// A required string member of an answer.
fn text(case: &str, answered: &Value, member: &str) -> String {
    answered
        .get(member)
        .and_then(Value::as_str)
        .unwrap_or_else(|| panic!("case {case:?}: no {member} in {answered}"))
        .to_string()
}

/// A timestamp member of an answer, as the epoch seconds the wire carries it as.
fn instant(case: &str, answered: &Value, member: &str) -> f64 {
    answered
        .get(member)
        .and_then(Value::as_f64)
        .unwrap_or_else(|| panic!("case {case:?}: no {member} timestamp in {answered}"))
}

/// The value the secret's tags hold for `key`, if any.
fn tag(answered: &Value, key: &str) -> Option<String> {
    answered
        .get("Tags")
        .and_then(Value::as_array)?
        .iter()
        .find(|entry| entry.get("Key").and_then(Value::as_str) == Some(key))
        .map(|entry| {
            entry
                .get("Value")
                .and_then(Value::as_str)
                .unwrap_or_default()
                .to_string()
        })
}

/// Assert `arn` is the ARN Secrets Manager mints for a secret named `name`: the canonical
/// segments, and a resource part that is the name plus the six characters the service draws
/// per secret.
fn assert_secret_arn(case: &str, arn: &str, name: &str) {
    let segments: Vec<&str> = arn.split(':').collect();
    assert_eq!(
        segments.len(),
        7,
        "case {case:?}: expected a secret ARN of seven colon-separated segments, got {arn:?}"
    );
    assert_eq!(
        segments[0], "arn",
        "case {case:?}: expected an ARN, got {arn:?}"
    );
    assert!(
        !segments[1].is_empty(),
        "case {case:?}: expected a partition in {arn:?}"
    );
    assert_eq!(
        (segments[2], segments[3], segments[4], segments[5]),
        (ARN_SERVICE, REGION, ACCOUNT_ID, ARN_RESOURCE_TYPE),
        "case {case:?}: expected the secret's ARN to name this service, region, account and \
         resource type, got {arn:?}"
    );
    let resource = segments[6];
    let suffix = resource
        .strip_prefix(&format!("{name}-"))
        .unwrap_or_else(|| {
            panic!(
                "case {case:?}: expected the ARN's resource part to be the secret's name plus \
                 the characters the service draws, got {resource:?} for name {name:?}"
            )
        });
    assert_eq!(
        suffix.chars().count(),
        ARN_SUFFIX_LEN,
        "case {case:?}: expected {ARN_SUFFIX_LEN} characters after the name in {arn:?}, got \
         {suffix:?}"
    );
    assert!(
        suffix.chars().all(|character| character.is_ascii_alphanumeric()),
        "case {case:?}: expected the ARN's trailing characters to be letters and digits, got \
         {suffix:?}"
    );
}

#[tokio::test]
async fn a_stacks_secret_is_described_in_full_by_the_service_that_owns_it() {
    let router = router();
    let (status_code, body) = create_stack(&router, STACK, &template(), &[]).await;
    assert_eq!(
        status_code, 200,
        "CreateStack must answer 200, got {status_code} {body}"
    );
    let stack_described = poll_to_terminal(&router, "the stack", STACK).await;
    assert_eq!(
        xml_text(&stack_described, "StackStatus").as_deref(),
        Some("CREATE_COMPLETE"),
        "expected the create to complete, got {stack_described}"
    );
    let stack_id = xml_text(&stack_described, "StackId").unwrap_or_default();
    assert!(
        !stack_id.is_empty(),
        "expected the stack to report its id, got {stack_described}"
    );

    for row in ROWS {
        let case = row.case;
        let published = output_value(&stack_described, &arn_output(row)).unwrap_or_else(|| {
            panic!("case {case:?}: the stack published no ARN in {stack_described}")
        });

        let (status_code, answered) = described(&router, &published).await;
        assert_eq!(
            status_code, 200,
            "case {case:?}: expected the owning service to describe the secret the stack \
             created, got {status_code} {answered}"
        );

        // The name: the declaration's own, or the one CloudFormation generated for a
        // declaration that states none.
        let name = text(case, &answered, "Name");
        if row.declared_name.is_empty() {
            assert!(
                name.starts_with(STACK) && name.len() > STACK.len(),
                "case {case:?}: expected a generated name built on the stack's, got {name:?}"
            );
        } else {
            assert_eq!(
                name, row.declared_name,
                "case {case:?}: expected the secret to be created under the declared name, got \
                 {name:?}"
            );
        }

        // The ARN: the one the service minted, which is the one the stack published.
        let arn = text(case, &answered, "ARN");
        assert_eq!(
            arn, published,
            "case {case:?}: expected the described ARN to be the one the stack published \
             ({published:?}), got {arn:?}"
        );
        assert_secret_arn(case, &arn, &name);

        // The description: the declaration's, and absent for a declaration that states none.
        let description = answered.get("Description").and_then(Value::as_str);
        if row.declared_description.is_empty() {
            assert_eq!(
                description, None,
                "case {case:?}: expected no Description for a declaration that states none, got \
                 {description:?}"
            );
        } else {
            assert_eq!(
                description,
                Some(row.declared_description),
                "case {case:?}: expected the declared Description, got {description:?}"
            );
        }

        // The two dates every secret carries, with the create no later than the last change
        // it is the first of.
        let created = instant(case, &answered, "CreatedDate");
        let last_changed = instant(case, &answered, "LastChangedDate");
        assert!(
            created > 0.0,
            "case {case:?}: expected a CreatedDate after the epoch, got {created}"
        );
        assert!(
            last_changed >= created,
            "case {case:?}: expected LastChangedDate ({last_changed}) at or after CreatedDate \
             ({created})"
        );

        // The three records CloudFormation stamps on what it creates, which are what routes a
        // secret back to the stack that owns it.
        for (key, expected) in [
            (STACK_NAME_TAG, STACK),
            (STACK_ID_TAG, stack_id.as_str()),
            (LOGICAL_ID_TAG, row.logical_id),
        ] {
            assert_eq!(
                tag(&answered, key).as_deref(),
                Some(expected),
                "case {case:?}: expected {key} = {expected:?} on the stack's secret, got \
                 {answered}"
            );
        }

        // The same report for the secret addressed by its NAME, the other handle a `SecretId`
        // takes — and a read leaves what a later caller sees unchanged, so the identity and
        // the dates are the ones the first read gave.
        let (status_code, again) = described(&router, &name).await;
        assert_eq!(
            status_code, 200,
            "case {case:?}: expected the secret to answer by name too, got {status_code} {again}"
        );
        assert_eq!(
            (
                again.get("ARN"),
                again.get("Name"),
                again.get("Description"),
                again.get("CreatedDate"),
                again.get("LastChangedDate"),
                again.get("Tags"),
            ),
            (
                answered.get("ARN"),
                answered.get("Name"),
                answered.get("Description"),
                answered.get("CreatedDate"),
                answered.get("LastChangedDate"),
                answered.get("Tags"),
            ),
            "case {case:?}: expected the same report whichever handle names the secret and \
             however often it is read, got {again} after {answered}"
        );
    }
}
