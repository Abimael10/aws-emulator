//! The AWS CodePipeline WEBHOOK a stack declares: `AWS::CodePipeline::Webhook`, created in
//! CodePipeline itself through that service's own `PutWebhook`, read back through
//! `ListWebhooks` and removed by `DeleteWebhook`.
//!
//! One file of [`super`]'s per-type arms, beside the pipeline and custom-action-type arms the
//! same owning service has ([`super::application_services`]): a webhook is a resource of its
//! own in that API — `ListWebhooks` reports one, `DeleteWebhook` takes its name, and the
//! trigger URL it is created with is minted in that service's store — so its create, delete
//! and read live together here.
//!
//! What the type declares and what the API takes differ in three ways, which is why the
//! request is mapped member by member rather than re-cased wholesale ([`camel_cased`] would
//! rewrite the members CodePipeline spells with a capital initial):
//!
//! * `WebhookAuthConfiguration`'s own members ARE capitalised in that model
//!   (`AllowedIPRange`, `SecretToken`), exactly as the template spells them, so that
//!   configuration is carried through verbatim;
//! * `TargetPipelineVersion` is CloudFormation's own — `WebhookDefinition` has no such
//!   member, a webhook being defined over the pipeline's NAME — so it takes no part in the
//!   definition;
//! * `RegisterWithThirdParty` is a deployment instruction rather than part of the webhook:
//!   it asks for the connection `RegisterWebhookWithThirdParty` makes, which is a call of its
//!   own made after the webhook exists.

use super::*;

/// The three properties that make up the webhook's own DEFINITION beside the filters and the
/// authentication, as (property, member): `WebhookDefinition`'s `name` is the one
/// CloudFormation decides, so it is written by [`webhook_definition`] rather than copied.
///
/// Source: `WebhookDefinition`'s members in CodePipeline's own model (`name`,
/// `targetPipeline`, `targetAction`, `filters`, `authentication`,
/// `authenticationConfiguration`, every one of them `@required`) against the property names
/// the type spells — which differ from those members only in the initial letter.
const WEBHOOK_MEMBERS: &[(&str, &str)] = &[
    ("TargetPipeline", "targetPipeline"),
    ("TargetAction", "targetAction"),
    ("Authentication", "authentication"),
];

/// The property that carries the webhook's filter rules, and the member `WebhookDefinition`
/// takes them as: a list of `WebhookFilterRule`, whose own members (`jsonPath`,
/// `matchEquals`) differ from the template's spelling in the initial letter too.
const WEBHOOK_FILTERS_PROPERTY: &str = "Filters";
/// See [`WEBHOOK_FILTERS_PROPERTY`].
const WEBHOOK_FILTERS_MEMBER: &str = "filters";

/// The property that carries the authentication configuration, and the member it is taken
/// as. The members INSIDE it are capitalised in that model (`AllowedIPRange`,
/// `SecretToken`), so the document itself is carried through as the template states it.
const WEBHOOK_AUTH_CONFIGURATION_PROPERTY: &str = "AuthenticationConfiguration";
/// See [`WEBHOOK_AUTH_CONFIGURATION_PROPERTY`].
const WEBHOOK_AUTH_CONFIGURATION_MEMBER: &str = "authenticationConfiguration";

/// The property that asks for the connection to the external tool the webhook is for:
/// "configures a connection between the webhook that was created and the external tool",
/// which is `RegisterWebhookWithThirdParty`'s business and not part of the definition.
const WEBHOOK_REGISTER_WITH_THIRD_PARTY: &str = "RegisterWithThirdParty";

/// The member `PutWebhook` takes the webhook in, and the one its answer reports it under
/// (`PutWebhook$webhook`, `PutWebhookOutput$webhook`).
const WEBHOOK_MEMBER: &str = "webhook";

/// The member a `ListWebhookItem` carries the webhook's own definition in, and the one it
/// carries the URL CodePipeline generated in ("A unique URL generated by CodePipeline").
const WEBHOOK_DEFINITION_MEMBER: &str = "definition";
/// See [`WEBHOOK_DEFINITION_MEMBER`].
const WEBHOOK_URL_MEMBER: &str = "url";

/// The `Fn::GetAtt` attribute an `AWS::CodePipeline::Webhook` publishes the generated trigger
/// URL under, as the type's "Return values" section spells it.
const WEBHOOK_URL_ATTRIBUTE: &str = "Url";

/// The member `ListWebhooks` reports the account's webhooks in, and the member a page cursor
/// is carried under in both directions (`ListWebhooks$NextToken`).
const WEBHOOK_LIST_MEMBER: &str = "webhooks";
/// See [`WEBHOOK_LIST_MEMBER`].
const WEBHOOK_NEXT_TOKEN: &str = "NextToken";

/// How many pages of `ListWebhooks` one read walks before it gives up.
///
/// The read is bounded because the page cursor comes from the called service rather than from
/// this module. It names no `MaxResults`, so each page is as large as that service's own
/// listing makes it (`MAX_WEBHOOKS_PER_PAGE`, the model's `@range(min: 1, max: 100)`
/// maximum), and the whole of a bounded store (`MAX_WEBHOOKS_PER_ACCOUNT`) is therefore far
/// inside this many pages: a webhook the account holds is always found within the bound, and a
/// service answering an endless run of cursors cannot hold a deployment open.
const WEBHOOK_PAGES_MAX: usize = 64;

/// Create the webhook an `AWS::CodePipeline::Webhook` declares — so the trigger the stack
/// reported created really exists in CodePipeline: `ListWebhooks` reports it, a POST to its
/// URL starts the pipeline it targets, and `DeleteWebhook` has something to remove.
///
/// The webhook is created under the name CloudFormation decided (the declared `Name`, or the
/// `<stack>-<logical id>-<unique id>` name it generated), carrying the pipeline and the
/// action it targets, its filter rules and its authentication exactly as the declaration
/// states them ([`webhook_definition`]) — CodePipeline's own validation of those values is
/// what judges them, so a filter pattern or an authentication configuration it refuses leaves
/// the stack `CREATE_FAILED` rather than a webhook triggering differently from the template.
///
/// The webhook carries the tags the declaration asks for beside the ones CloudFormation gives
/// the resource ([`tags_of`]), as the list CodePipeline's own `Tag` shape spells in lower
/// camel case.
///
/// What comes back is the URL that service generated for the webhook, which carries a token
/// minted in its own store and no naming rule could compute: it is this type's one published
/// `Fn::GetAtt` attribute, so it is reported off the create's answer.
pub(super) async fn put_webhook(
    ctx: &smithy_server_runtime::OperationContext<'_>,
    region: &str,
    resource: &StoredResource,
    propagated: &[(String, String)],
) -> Result<Created, Refusal> {
    let mut request = Map::new();
    request.insert(
        WEBHOOK_MEMBER.to_string(),
        Value::Object(webhook_definition(resource)?),
    );
    let tags = tags_of(&resource.properties, propagated);
    if !tags.is_empty() {
        request.insert("tags".to_string(), tags_as_list(&tags, LOWER_CASED_TAG));
    }
    let answered = call_codepipeline(ctx, region, "PutWebhook", &Value::Object(request)).await?;
    // The connection to the external tool the declaration asks for is a call of its own,
    // made once the webhook exists: a stack that declared it and never made it would report a
    // webhook as registered with a third party that nothing registered.
    if asks_for_third_party_registration(&resource.properties) {
        call_codepipeline(
            ctx,
            region,
            "RegisterWebhookWithThirdParty",
            &serde_json::json!({ "webhookName": resource.physical_resource_id }),
        )
        .await?;
    }
    Ok(Created::attributes(reported_attributes(
        &reported_member(&answered, WEBHOOK_MEMBER),
        &[(WEBHOOK_URL_ATTRIBUTE, WEBHOOK_URL_MEMBER)],
    )))
}

/// Remove the webhook a stack created, by the name it was created under — the one value
/// `DeleteWebhook` takes.
///
/// That call models no does-not-exist error ("if a webhook name is not specified, … the
/// webhook is deleted" is the whole of its contract): a webhook CodePipeline no longer holds
/// is already in the state the delete asks for, and the delete is answered rather than
/// refused.
pub(super) async fn delete_webhook(
    ctx: &smithy_server_runtime::OperationContext<'_>,
    region: &str,
    physical_resource_id: &str,
) -> Result<(), Refusal> {
    call_codepipeline(
        ctx,
        region,
        "DeleteWebhook",
        &serde_json::json!({ "name": physical_resource_id }),
    )
    .await?;
    Ok(())
}

/// The webhook's definition as CodePipeline reports it, for drift detection, under the
/// property names the type declares — so a declared member is compared against the member of
/// the same name that service answers with.
///
/// `ListWebhooks` reports the webhooks the account holds rather than refusing a read of one
/// it does not, so an answer that lists no webhook of this name is that service saying it no
/// longer holds the resource — the `DELETED` drift status.
pub(super) async fn describe_webhook(
    ctx: &smithy_server_runtime::OperationContext<'_>,
    region: &str,
    physical_resource_id: &str,
) -> Result<Option<Value>, Refusal> {
    let Some(item) = held_webhook(ctx, region, physical_resource_id).await? else {
        return Ok(None);
    };
    let definition = reported_member(&item, WEBHOOK_DEFINITION_MEMBER);
    let mut reported = match reported_as_properties(&definition, WEBHOOK_MEMBERS) {
        Value::Object(members) => members,
        _ => Map::new(),
    };
    // The two documents whose own members are spelled differently from the properties they
    // came from: the filters are re-cased back, and the authentication configuration's
    // members are spelled the same way on both sides.
    if let Some(filters) = definition.get(WEBHOOK_FILTERS_MEMBER) {
        reported.insert(
            WEBHOOK_FILTERS_PROPERTY.to_string(),
            upper_initialled(filters, 0)?,
        );
    }
    if let Some(configuration) = definition.get(WEBHOOK_AUTH_CONFIGURATION_MEMBER) {
        reported.insert(
            WEBHOOK_AUTH_CONFIGURATION_PROPERTY.to_string(),
            configuration.clone(),
        );
    }
    Ok(Some(Value::Object(reported)))
}

/// The webhook of this name as CodePipeline's own `ListWebhooks` reports it, or `None` for a
/// webhook that service does not hold.
///
/// The listing is PAGED, so every page is walked until the webhook is found or the run of
/// pages ends ([`WEBHOOK_PAGES_MAX`]): a webhook on a later page is one the account holds,
/// and reading only the first page would report a deployed resource as deleted.
async fn held_webhook(
    ctx: &smithy_server_runtime::OperationContext<'_>,
    region: &str,
    name: &str,
) -> Result<Option<Value>, Refusal> {
    let mut cursor: Option<String> = None;
    for _ in 0..WEBHOOK_PAGES_MAX {
        let mut request = Map::new();
        if let Some(token) = &cursor {
            request.insert(
                WEBHOOK_NEXT_TOKEN.to_string(),
                Value::String(token.clone()),
            );
        }
        let answered =
            call_codepipeline(ctx, region, "ListWebhooks", &Value::Object(request)).await?;
        let listed = answered
            .get(WEBHOOK_LIST_MEMBER)
            .and_then(Value::as_array)
            .map(|items| items.to_vec())
            .unwrap_or_default();
        if let Some(found) = listed.into_iter().find(|item| {
            item.pointer(&format!("/{WEBHOOK_DEFINITION_MEMBER}/name"))
                .and_then(Value::as_str)
                == Some(name)
        }) {
            return Ok(Some(found));
        }
        cursor = answered
            .get(WEBHOOK_NEXT_TOKEN)
            .and_then(Value::as_str)
            .map(ToString::to_string);
        if cursor.is_none() {
            return Ok(None);
        }
    }
    Ok(None)
}

/// The `WebhookDefinition` one declaration states: the name CloudFormation decided, the
/// members the type spells with a capital initial ([`WEBHOOK_MEMBERS`]), the filter rules
/// re-cased to the members `WebhookFilterRule` takes, and the authentication configuration as
/// the declaration states it.
///
/// A property the declaration leaves out is left out of the definition: every member of that
/// shape is `@required`, so CodePipeline's own validation of the request is what reports a
/// definition that states too little, rather than a value invented here.
fn webhook_definition(resource: &StoredResource) -> Result<Map<String, Value>, Refusal> {
    let mut definition = Map::new();
    definition.insert(
        "name".to_string(),
        Value::String(resource.physical_resource_id.clone()),
    );
    if let Some(declared) = resource.properties.as_object() {
        copy_members(declared, WEBHOOK_MEMBERS, &mut definition);
    }
    if let Some(filters) = resource.properties.get(WEBHOOK_FILTERS_PROPERTY) {
        definition.insert(
            WEBHOOK_FILTERS_MEMBER.to_string(),
            camel_cased(filters, 0)?,
        );
    }
    if let Some(configuration) = resource.properties.get(WEBHOOK_AUTH_CONFIGURATION_PROPERTY) {
        definition.insert(
            WEBHOOK_AUTH_CONFIGURATION_MEMBER.to_string(),
            configuration.clone(),
        );
    }
    Ok(definition)
}

/// Whether the declaration asks for the webhook to be registered with the external tool it
/// is for: `RegisterWithThirdParty`, read as the boolean the property is, in either of the
/// spellings a template may state it in (a JSON `true`, or the string a parameter resolves
/// to).
fn asks_for_third_party_registration(properties: &Value) -> bool {
    properties
        .get(WEBHOOK_REGISTER_WITH_THIRD_PARTY)
        .and_then(scalar_text)
        .is_some_and(|asked| asked.eq_ignore_ascii_case("true"))
}

/// The same document with every object KEY's initial letter UPPER-cased, which turns the
/// members a CodePipeline answer carries back into the property names the type spells them
/// with (`jsonPath` -> `JsonPath`) — the inverse of [`camel_cased`], which lives beside it
/// ([`upper_initialled`]).
/// Call one webhook operation of AWS CodePipeline on the awsJson1_1 wire its model declares.
async fn call_codepipeline(
    ctx: &smithy_server_runtime::OperationContext<'_>,
    region: &str,
    operation: &str,
    request: &Value,
) -> Result<Value, Refusal> {
    call_json_rpc(
        ctx,
        CODEPIPELINE_SIGNING_NAME,
        region,
        AWS_JSON_1_1,
        &format!("{CODEPIPELINE_TARGET_PREFIX}.{operation}"),
        request,
    )
    .await
}
