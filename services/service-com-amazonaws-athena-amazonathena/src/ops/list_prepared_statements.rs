        // modelled maximum of `MaxPreparedStatementsCount`, which is also the page a
        // request naming none gets and the most `PreparedStatementsList` can carry.
        let page_size = usize::try_from(input.max_results.unwrap_or(MAX_PAGE_STATEMENTS))
            .unwrap_or(0)
            .min(usize::try_from(MAX_PAGE_STATEMENTS).unwrap_or(0));

        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(ListPreparedStatementsErrorModeled::InternalServerException(
                InternalServerException {
                    message: Some("Athena state is not reachable on this engine".to_string()),
                },
            )
            .into());
        };
        // A read: nothing below writes the store.
        let store = state.lock();

        // The statements a listing reports are the workgroup's, so a workgroup this account
        // does not hold has none to list rather than an empty list.
        if !store.holds_work_group(&input.work_group) {
            return Err(invalid_request(crate::state::WORK_GROUP_NOT_FOUND));
        }

        // "A token generated by the Athena service": a value this store did not mint names
        // no page of this listing, which is a bad request rather than an empty page.
        let position = match input.next_token.as_deref() {
            None => 0,
            Some(token) => {
                let Some(position) = store
                    .prepared_statements_page_position(&input.work_group, token)
                else {
                    return Err(invalid_request(crate::state::page_token_malformed(token)));
                };
                position
            }
        };

        // In name order, which is the order the registry holds one workgroup's statements
        // in and therefore the order every page of this listing walks.
        let summaries = store.prepared_statements.summaries_in(&input.work_group);
        let end = position.saturating_add(page_size).min(summaries.len());
        let page = summaries.get(position..end).unwrap_or_default().to_vec();

        // A token only where this page reported something and statements remain behind it,
        // so a caller following tokens always makes progress and the last page of a listing
        // hands back none.
        let more = !page.is_empty() && end < summaries.len();
