impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for ListNotebookMetadata<Eng>
{
    type Input = ListNotebookMetadataInput;
    type Output = ListNotebookMetadataOutput;
    type Error = ListNotebookMetadataError;

    const NAME: &'static str = "ListNotebookMetadata";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::LIST_NOTEBOOK_METADATA_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::LIST_NOTEBOOK_METADATA_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        // The notebooks of a workgroup are read with access to that workgroup, which is the
        // IAM resource this action is scoped by. See `crate::state::authorization`.
        crate::state::authorization::authorize(
            &*self.engine,
            ctx,
            Self::NAME,
            &crate::state::authorization::work_group_arn(ctx, &input.work_group),
        )
        .map_err(ListNotebookMetadataError::AccessDenied)?;

        // "Specifies the maximum number of results to return", bounded by the modelled
        // maximum of `MaxNotebooksCount`, which is also the page a request naming none gets.
        let page_size = usize::try_from(input.max_results.unwrap_or(MAX_PAGE_NOTEBOOKS))
            .unwrap_or(0)
            .min(usize::try_from(MAX_PAGE_NOTEBOOKS).unwrap_or(0));

        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(ListNotebookMetadataErrorModeled::InternalServerException(
                InternalServerException {
                    message: Some("Athena state is not reachable on this engine".to_string()),
                },
            )
            .into());
        };
        // A read: nothing below writes the store. The position a `NextToken` resumes at
        // travels inside the token, so no page is kept on the side either.
        let store = state.lock();

        // A notebook lives in a workgroup, so one this account does not hold holds none:
        // the refusal every operation of this service that resolves a `WorkGroup` states.
        if !store.holds_work_group(&input.work_group) {
            return Err(invalid_request(crate::state::WORK_GROUP_NOT_FOUND));
        }
        // "The name of the Spark enabled workgroup to retrieve notebook metadata for": an
        // Athena SQL workgroup runs no notebook engine and holds no notebook files, and
        // Athena's own default workgroup — the one the registry holds no record for — is
        // one of those.
        let spark_enabled = store
            .work_groups
            .get(&input.work_group)
            .is_some_and(crate::state::is_spark_enabled);
        if !spark_enabled {
            return Err(invalid_request(
                crate::state::WORK_GROUP_ENGINE_VERSION_NOT_SPARK,
            ));
        }

        // "A token generated by the Athena service": a value this store did not mint for
        // THIS workgroup's listing names no page of it, which is a bad request rather than
        // an empty page.
        let position = match input.next_token.as_deref() {
            None => 0,
            Some(token) => {
                let Some(position) =
                    store.notebook_metadata_page_position(&input.work_group, token)
                else {
                    return Err(invalid_request(crate::state::INVALID_NEXT_TOKEN));
                };
                position
            }
        };

        // The workgroup's notebooks the request's search reports, in the order the registry
        // projects them — the one projection every reader of a workgroup's notebooks takes.
        let searched = input
            .filters
            .as_ref()
            .and_then(|filters| filters.name.as_deref());
        let found = store.notebooks.notebooks_in(&input.work_group, searched);
        let end = position.saturating_add(page_size).min(found.len());
        let page: Vec<NotebookMetadata> = found
            .get(position..end)
            .unwrap_or_default()
            .iter()
            .map(|record| record.to_notebook_metadata())
            .collect();

        // A token only where this page reported something and notebooks remain behind it,
        // so a caller following tokens always makes progress and the last page of a listing
        // hands back none.
        let more = !page.is_empty() && end < found.len();
        Ok(ListNotebookMetadataOutput {
            notebook_metadata_list: Some(page),
            next_token: more.then(|| store.notebook_metadata_page_token(&input.work_group, end)),
        })
    }
}

