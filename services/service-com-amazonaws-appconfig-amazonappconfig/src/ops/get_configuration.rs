impl<Eng: ::std::marker::Send + ::std::marker::Sync + 'static> smithy_server_runtime::Operation
    for GetConfiguration<Eng>
{
    type Input = GetConfigurationInput;
    type Output = GetConfigurationOutput;
    type Error = GetConfigurationError;

    const NAME: &'static str = "GetConfiguration";
    const INPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_CONFIGURATION_INPUT_SCHEMA;
    const OUTPUT_SCHEMA: &'static ::aws_smithy_schema::Schema = super::types::GET_CONFIGURATION_OUTPUT_SCHEMA;
    const SUCCESS_STATUS: u16 = 200u16;

    async fn handle(
        &self,
        input: Self::Input,
        ctx: &smithy_server_runtime::OperationContext<'_>,
    ) -> Result<Self::Output, Self::Error> {
        let Some(state) = crate::state::service_state(&*self.engine) else {
            return Err(internal("AppConfig state is not reachable on this engine"));
        };
        let now = std::time::SystemTime::now();
        // The Region this read was signed for, which is the endpoint a configuration
        // profile's EXTERNAL source is resolved through (`crate::state::request_region`).
        let region = crate::state::request_region(ctx.parts());
        // A deployment whose environment's monitored CloudWatch alarms have already made a
        // rollback due is rolled back before the configuration in force is read: that breach
        // fell due at an instant that has passed, so this materialises only what the clock
        // had already made true — and a rolled-back deployment serves no target, which is
        // what puts the previous version back in force here.
        crate::state::alarm_monitors::settle(&*self.engine, now);
        let mut store = state.lock();

        // `ClientId` identifies the client asking, which is what AppConfig paces a
        // gradual rollout by: the member's own doc is "a unique, user-specified ID to
        // identify the client for the configuration. This ID enables AppConfig to deploy
        // the configuration in intervals, as defined in the deployment strategy". So the
        // client id is this caller's position in the rollout — where it stands among the
        // targets a deployment's `PercentageComplete` has reached — and a deployment
        // still rolling out is in force for this caller only once the rollout has passed
        // that position, while a caller it has not reached is served what was in force
        // before (`crate::state::RolloutBucket`). The position is derived from the id and
        // from nothing else, so the same client keeps it across its polls; nothing about
        // the client is stored — a read records no caller.
        let target = crate::state::RolloutBucket::of_key(&input.client_id);

        // Each of the three path members is documented as "the <level> name or the
        // <level> ID", so each resolves either way, and the (Application, Configuration)
        // pair is resolved FIRST — before the environment — because that pair is the
        // configuration profile this path reads a configuration out of, and the only
        // thing it reports as a profile it could not find
        // ([`configuration_profile_not_found`]), naming each level by the id it resolved
        // to from there on.
        let Some(application_id) = store.resolve_application_id(&input.application) else {
            return Err(configuration_profile_not_found(
                &input.application,
                &input.configuration,
            ));
        };
        let Some(application) = store.application_mut(&application_id) else {
            return Err(internal(
                "The application could not be re-read while reading its configuration",
            ));
        };
        let Some(profile_id) = application
            .resolve_profile(&input.configuration)
            .map(|profile| profile.id.clone())
        else {
            return Err(configuration_profile_not_found(
                &application_id,
                &input.configuration,
            ));
        };
        // From here the profile is there, so nothing below it can be reported as that
        // profile missing: the environment is the key the DEPLOYMENT that serves this
        // profile is looked up by, and a label no environment resolves holds no
        // deployment, which is the same condition as a resolvable environment nothing was
        // deployed into ([`no_deployed_version`]).
        let Some(environment_id) = application
            .resolve_environment(&input.environment)
            .map(|environment| environment.id.clone())
        else {
            return Err(no_deployed_version(
                &input.application,
                &input.environment,
                &input.configuration,
            ));
        };

        // The environment is brought up to the state the CLOCK already owes it before
        // its deployments are read: a deployment whose rollout window and bake time have
        // both elapsed is `COMPLETE` whether or not anybody called, and a rollback a
        // caller started has finished once its own window has passed. Nothing else about
        // the environment is written, so this read leaves every record where the clock
        // had already put it.
        let Some(environment) = application.environments.get_mut(&environment_id) else {
            return Err(internal(
                "The environment could not be re-read while reading its configuration",
            ));
        };
        environment.materialize(now);
        let in_force = environment
            .in_force_deployment(&profile_id, target)
            .map(|deployment| deployment.configuration_version.clone());
        let Some(deployed_version) = in_force else {
            return Err(no_deployed_version(
                &input.application,
                &input.environment,
                &input.configuration,
            ));
        };

        let Some(profile) = application.profiles.get(&profile_id) else {
            return Err(internal(
                "The configuration profile could not be re-read while reading its \
                 configuration",
            ));
        };
        // WHICH STORE the deployed bytes live in is the profile's own `LocationUri`: the
        // hosted versions this service holds for a `hosted` profile, and the named source's
        // own store for a profile pointing at one
        // (`crate::state::configuration_sources`). Read here, so the answer below comes out
        // of the store the profile actually uses.
        let external = match crate::state::configuration_sources::source_of(&profile.location_uri)
        {
            crate::state::configuration_sources::ConfigurationSource::Hosted => None,
            _ => Some(profile.location_uri.clone()),
        };
        // The deployment records the version it deployed as the caller spelled it — a
        // hosted version number or that version's label — so it is resolved through the
        // profile's own lookup, the one every reader of a deployed configuration uses.
        //
        // `ConfigurationVersion` identifies the version this answer carries, and
        // `ClientConfigurationVersion` is "the configuration version returned in the most
        // recent GetConfiguration response", so the two are the same spelling: the stored
        // version number.
        //
        // What the stored bytes MEAN is the profile's `Type`, so the content served is the
        // profile's own projection of them rather than the bytes themselves — the same
        // projection the `appconfigdata` poll serves for the same deployment.
        let hosted = profile.resolve_hosted_version(&deployed_version).map(|version| {
            (
                version.version_number.to_string(),
                version.content_type.clone(),
                profile.served_content(&version.content),
            )
        });
        // This store's guard is released before any other is read, so the two are taken one
        // at a time, never nested.
        drop(store);
        let (configuration_version, content_type, content) = match external {
            // A `hosted` profile whose deployed version this store does not hold serves no
            // version here, so it is the same deployment-level refusal rather than a claim
            // about the profile, which resolved.
            None => {
                let Some(hosted) = hosted else {
                    return Err(no_deployed_version(
                        &input.application,
                        &input.environment,
                        &input.configuration,
                    ));
                };
                hosted
            }
            // A profile pointing at another store is served the content THAT store holds
            // for the version the deployment named, with the media type describing it; the
            // deployed version stays pinned, because a later write at the source mints a
            // new version and leaves the deployed one where it was. A source holding no such
            // version has nothing in force to report, which is the same deployment-level
            // refusal.
            Some(location_uri) => {
                let Ok(source) = crate::state::configuration_sources::source_configuration(
                    &*self.engine,
                    &region,
                    &location_uri,
                    &deployed_version,
                ) else {
                    return Err(no_deployed_version(
                        &input.application,
                        &input.environment,
                        &input.configuration,
                    ));
                };
                (deployed_version.clone(), source.content_type, source.content)
            }
        };

        // "The Content attribute only contains data if the system finds new or updated
        // configuration data. If there is no new or updated data and
        // ClientConfigurationVersion matches the version of the current configuration …
        // the Content value will be empty." The comparison is between two stored values:
        // the version the client says it holds and the one in force now.
        let client_holds_this_version =
            input.client_configuration_version.as_deref() == Some(configuration_version.as_str());

        Ok(GetConfigurationOutput {
            // Empty rather than absent when the client already holds this version: the
            // member is the response's `@httpPayload`, so an absent one would leave the
            // protocol's JSON object as the body where AppConfig sends no content at all.
            // The accompanying HTTP 204 is not reachable from a handler — the status is
            // this operation's modelled `@http(code: 200)` and the `Configuration` shape
            // binds no `@httpResponseCode` member for a handler to answer through.
            content: Some(if client_holds_this_version {
                Vec::new()
            } else {
                content
            }),
            configuration_version: Some(configuration_version),
            content_type: Some(content_type),
        })
    }
}
